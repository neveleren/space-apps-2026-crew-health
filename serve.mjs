// A simple local server: no internet, no outside packages.
// NASA's ISS research software rules ask for installers that need no internet, say simple
// server implementations work best, and ask that data be kept in plain files with no personal
// information in file names. This file needs only Node.js.
// It serves the pages and keeps the events (readings, reviews, messages to a doctor) in app/data, one plain file
// per person, named by the person's id. A message to a doctor is also queued in app/data/outbox with its text sealed
// for the flight surgeon's key: the hand-over point for the station's downlink. Nothing leaves this computer.
// The protection rules, with their sources, are in src/security.js; docs/SECURITY.md says what is protected and what is not.
// Run: node serve.mjs   then open http://127.0.0.1:8080/
// Settings: PORT; HOST, the address to listen on; HOSTS, more host names to answer to (comma-separated);
// DATA_DIR, another data folder (the automatic checks use a throwaway one); OUTBOX_KEY_FILE, the flight surgeon's public key.
// Code generated by Claude (Anthropic), an AI system.
import { createServer } from 'node:http';
import { createCipheriv, createHash, createPublicKey, diffieHellman, generateKeyPairSync, hkdfSync, randomBytes } from 'node:crypto';
import { appendFile, mkdir, readdir, readFile, realpath, rename, stat, writeFile } from 'node:fs/promises';
import { extname, isAbsolute, join, normalize, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SHIP } from './src/config.js';
import { LIMITS, LOCAL_HOSTS, PERSON_ID, allowedHosts, cleanEvent, eventProblem, hostName, isJson, isPrivatePath, sameOrigin, securityHeaders, siteAllowed } from './src/security.js';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)));
// The name the disk itself uses for the app folder (true letter case, long names), to compare real paths with.
const REAL_ROOT = await realpath(ROOT);
const DATA = process.env.DATA_DIR ? resolve(process.env.DATA_DIR) : join(ROOT, 'data');
const OUTBOX = join(DATA, 'outbox');
const HOST = process.env.HOST || '127.0.0.1';
const PORT = Number(process.env.PORT) || 8080;
const HOSTS = allowedHosts({ host: HOST, hosts: process.env.HOSTS || '' });
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.woff2': 'font/woff2',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.txt': 'text/plain; charset=utf-8',
  '.md': 'text/markdown; charset=utf-8',
  '.wasm': 'application/wasm', // the camera models' runtime (vendor/mediapipe)
  '.task': 'application/octet-stream', // the camera models themselves
  '.mp4': 'video/mp4', // the Earth break's videos (assets/breathe)
  '.mp3': 'audio/mpeg', // the Earth break's sounds
};
const isMedia = (type) => type.startsWith('video/') || type.startsWith('audio/');

// One byte range of a video or sound (RFC 9110, section 14): browsers ask for parts of a video to start it, loop
// it and jump in it, and some play video only from a server that answers such a request. Returns null to send the
// whole file (no header, several ranges, or a form this server does not read), 'bad' when the range lies outside
// the file, else { start, end } with end included.
function byteRange(header, size) {
  const m = /^bytes=(\d*)-(\d*)$/.exec(String(header || '').trim());
  if (!m || (m[1] === '' && m[2] === '')) return null;
  let start;
  let end;
  if (m[1] === '') {
    const n = Number(m[2]);
    if (n === 0) return 'bad';
    start = Math.max(0, size - n);
    end = size - 1;
  } else {
    start = Number(m[1]);
    end = m[2] === '' ? size - 1 : Math.min(Number(m[2]), size - 1);
  }
  if (!Number.isSafeInteger(start) || !Number.isSafeInteger(end) || start >= size || start > end) return 'bad';
  return { start, end };
}
const TEXT = 'text/plain; charset=utf-8';
const JSON_TYPE = 'application/json; charset=utf-8';

// ---------- answers ----------
// Every answer carries the security headers; our own answers are never kept in a cache.
function send(res, code, body = '', type = TEXT, extra = {}, headOnly = false) {
  const headers = { ...securityHeaders(), 'Cache-Control': 'no-store', ...extra };
  if (code === 204) {
    res.writeHead(code, headers);
    res.end();
    return;
  }
  res.writeHead(code, { ...headers, 'Content-Type': type, 'Content-Length': Buffer.byteLength(body) });
  res.end(headOnly ? undefined : body);
}
const json = (res, code, value, headOnly = false) => send(res, code, JSON.stringify(value), JSON_TYPE, {}, headOnly);
const notFound = (res) => send(res, 404, 'Not found');

// ---------- files ----------
// The hash of each inline <script> of a page, so the policy allows exactly those scripts and nothing injected.
// The browser hashes the script text after turning CR LF into LF (HTML parsing), so the same is done here.
function inlineScriptHashes(html) {
  const out = [];
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
    if (/\bsrc\s*=/i.test(m[1])) continue;
    out.push(createHash('sha256').update(m[2].replace(/\r\n?/g, '\n'), 'utf8').digest('base64'));
  }
  return out;
}

// True when a real path lies in the data folder. DATA_DIR may put that folder inside the app folder under any
// name (DATA_DIR=./records), where the name rules above would not know it.
async function inData(real) {
  let data;
  try {
    data = await realpath(DATA);
  } catch {
    return false; // no data folder yet: nothing can be served from it
  }
  const r = relative(data, real);
  return r === '' || (r !== '..' && !r.startsWith(`..${sep}`) && !isAbsolute(r));
}

async function serveFile(req, res, path) {
  // Back slashes, colons and NUL never appear in this program's addresses; on Windows they would mean another
  // folder, a drive or a hidden stream.
  if (/[\\:\0]/.test(path)) return notFound(res);
  if (path.endsWith('/')) path += 'index.html';
  const file = resolve(ROOT, `.${normalize(path)}`);
  if (!file.startsWith(ROOT + sep) || isPrivatePath(relative(ROOT, file))) return notFound(res);
  let real;
  let body;
  try {
    // Checked again under the name the disk uses, which also catches short names such as DEMO-K~1.
    real = await realpath(file);
    if (!real.startsWith(REAL_ROOT + sep) || isPrivatePath(relative(REAL_ROOT, real)) || (await inData(real))) return notFound(res);
    if (!(await stat(real)).isFile()) return notFound(res);
    body = await readFile(real);
  } catch {
    return notFound(res);
  }
  const type = TYPES[extname(real).toLowerCase()] || 'application/octet-stream';
  const hashes = type.startsWith('text/html') ? inlineScriptHashes(body.toString('utf8')) : [];
  const headers = {
    ...securityHeaders(hashes),
    'Content-Type': type,
    'Content-Length': body.length,
    // Third-party files never change, so the browser may keep them; our own files are always fresh.
    'Cache-Control': relative(REAL_ROOT, real).split(sep)[0].toLowerCase() === 'vendor' ? 'public, max-age=86400' : 'no-store',
  };
  if (isMedia(type)) {
    headers['Accept-Ranges'] = 'bytes';
    const range = byteRange(req.headers.range, body.length);
    if (range === 'bad') {
      res.writeHead(416, { ...headers, 'Content-Range': `bytes */${body.length}`, 'Content-Length': 0 });
      res.end();
      return;
    }
    if (range) {
      const part = body.subarray(range.start, range.end + 1);
      res.writeHead(206, { ...headers, 'Content-Range': `bytes ${range.start}-${range.end}/${body.length}`, 'Content-Length': part.length });
      res.end(req.method === 'HEAD' ? undefined : part);
      return;
    }
  }
  res.writeHead(200, headers);
  res.end(req.method === 'HEAD' ? undefined : body);
}

// ---------- events ----------
async function readBody(req) {
  if (Number(req.headers['content-length']) > LIMITS.bodyBytes) throw new Error('too big');
  const chunks = [];
  let size = 0;
  for await (const chunk of req) {
    size += chunk.length;
    if (size > LIMITS.bodyBytes) throw new Error('too big');
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString('utf8');
}

// Whose events a request may read: one person together with the ship's cabin readings (the crew screen), or
// everyone with ?all=1 (the technical view: the engineering view, which a real deployment would restrict).
function scopeOf(query) {
  const person = query.get('person');
  if (person !== null) return PERSON_ID.test(person) ? { person } : null;
  return query.get('all') === '1' ? { all: true } : null;
}

async function peopleWithFiles() {
  try {
    return (await readdir(DATA)).filter((f) => f.endsWith('.jsonl')).map((f) => f.slice(0, -6)).filter((id) => PERSON_ID.test(id));
  } catch {
    return [];
  }
}

// Only the files of the people asked for are opened. A line that is damaged, no longer valid or filed under
// another person is skipped; the rest is kept.
async function readEvents(ids) {
  const events = [];
  for (const id of ids) {
    let text = '';
    try {
      text = await readFile(join(DATA, `${id}.jsonl`), 'utf8');
    } catch {
      continue; // nobody saved anything for this person yet
    }
    for (const line of text.split('\n')) {
      if (!line.trim()) continue;
      try {
        const e = JSON.parse(line);
        if (!eventProblem(e, { checkFuture: false }) && e.person === id) events.push(cleanEvent(e));
      } catch {
        // a damaged line is skipped
      }
    }
  }
  return events.sort((a, b) => Date.parse(a.time) - Date.parse(b.time));
}

async function getEvents(req, res, query) {
  const scope = scopeOf(query);
  if (!scope) return json(res, 400, { error: 'say whose events: ?person=<id>, or ?all=1 for the technical view' });
  const ids = scope.all ? await peopleWithFiles() : [...new Set([scope.person, SHIP.id])];
  let events = await readEvents(ids);
  // Crew alarms reach every crewmate: only the alarm line, never the rest of the other person's record.
  if (!scope.all) {
    const others = (await peopleWithFiles()).filter((id) => !ids.includes(id));
    events = [...events, ...(await readEvents(others)).filter((e) => e.kind === 'alarm')].sort((a, b) => Date.parse(a.time) - Date.parse(b.time));
  }
  json(res, 200, events, req.method === 'HEAD');
}

async function postEvent(req, res) {
  if (!sameOrigin(req.headers.origin, req.headers.host)) return json(res, 403, { error: "only this program's own pages may save" });
  if (!isJson(req.headers['content-type'])) return json(res, 415, { error: 'send the event as Content-Type: application/json' });
  let event;
  try {
    event = JSON.parse(await readBody(req));
  } catch (err) {
    if (err.message === 'too big') return send(res, 413, JSON.stringify({ error: `at most ${LIMITS.bodyBytes} bytes` }), JSON_TYPE, { Connection: 'close' });
    return json(res, 400, { error: 'not readable JSON' });
  }
  const problem = eventProblem(event);
  if (problem) return json(res, 400, { error: `not a valid event: ${problem}` });
  const clean = cleanEvent(event);
  // A message is queued first: if that fails, nothing is kept and the screen says so, so it can be sent again.
  // Without a key on this computer, a message to the doctor on board is still kept (that doctor reads it here);
  // only a message to Earth, which cannot reach the ground without the key, is refused.
  let outbox = null;
  if (clean.kind === 'report') {
    if (OUTBOX_KEY) outbox = await queueMessage(clean);
    else if (clean.report.to !== 'doctor-onboard') return json(res, 503, { error: 'no outbox key on this computer: the message was not queued' });
  }
  await mkdir(DATA, { recursive: true });
  await appendFile(join(DATA, `${clean.person}.jsonl`), `${JSON.stringify(clean)}\n`, 'utf8');
  if (outbox) return json(res, 201, { outbox });
  send(res, 204);
}

// ---------- the outbox ----------
// The flight surgeon's public key. A real deployment points OUTBOX_KEY_FILE at a file with only kid and publicJwk;
// this version ships a DEMO key pair in demo-keys/ (never a real key) so the demonstration and the checks can open
// the messages. Only the public part is read here.
async function loadOutboxKey() {
  const file = process.env.OUTBOX_KEY_FILE ? resolve(process.env.OUTBOX_KEY_FILE) : join(ROOT, 'demo-keys', 'DEMO-flight-surgeon-keypair.json');
  try {
    const k = JSON.parse(await readFile(file, 'utf8'));
    const { kty, crv, x, y } = k.publicJwk;
    if (kty !== 'EC' || crv !== 'P-256') throw new Error('the key must be an EC P-256 public key');
    return { kid: String(k.kid || 'unnamed'), demo: k.demo === true, publicKey: createPublicKey({ key: { kty, crv, x, y }, format: 'jwk' }) };
  } catch (err) {
    console.error(`No outbox key in ${file} (${err.message}): messages to a doctor cannot be queued.`);
    return null;
  }
}
const OUTBOX_KEY = await loadOutboxKey();
const OUTBOX_ALG = 'ECDH-ES P-256 + HKDF-SHA-256 + AES-256-GCM';
const OUTBOX_INFO = Buffer.from('jff-outbox-v1', 'utf8');
// The readable fields are bound to the sealed text: changing who it is for or when breaks the seal.
const outboxAad = (m) => Buffer.from(JSON.stringify([m.v, m.id, m.to, m.person, m.time, m.kid]), 'utf8');

// Sealed for the public key: a fresh key pair per message and ECDH on P-256 (NIST SP 800-56A, one-pass
// Diffie-Hellman), HKDF-SHA-256 (RFC 5869) for a 256-bit key, AES-256-GCM with a random 96-bit IV (NIST SP 800-38D).
// Only the holder of the private key can open it (as EveryWear does on Artemis II, ESA 2026).
function seal(text, aad) {
  const once = generateKeyPairSync('ec', { namedCurve: 'prime256v1' });
  const shared = diffieHellman({ privateKey: once.privateKey, publicKey: OUTBOX_KEY.publicKey });
  const salt = randomBytes(16);
  const key = Buffer.from(hkdfSync('sha256', shared, salt, OUTBOX_INFO, 32));
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', key, iv, { authTagLength: 16 });
  cipher.setAAD(aad);
  const ciphertext = Buffer.concat([cipher.update(text, 'utf8'), cipher.final()]);
  const { kty, crv, x, y } = once.publicKey.export({ format: 'jwk' });
  return { alg: OUTBOX_ALG, epk: { kty, crv, x, y }, salt: salt.toString('base64url'), iv: iv.toString('base64url'), ciphertext: ciphertext.toString('base64url'), tag: cipher.getAuthTag().toString('base64url') };
}

// How a file is named on the screen: inside the app folder as "data/outbox/...", elsewhere in full.
function shown(path) {
  const r = relative(ROOT, path);
  return r.startsWith('..') || isAbsolute(r) ? path : r.split(sep).join('/');
}

// One file per message in data/outbox: the hand-over point for the station's downlink (the link itself is not
// part of this program; a downlink job would send the file and set status to "sent"). The name is the time and a
// random number: no personal information in file names. Written whole, then renamed, so it is never seen half-done.
async function queueMessage(event) {
  const id = `${event.time.replace(/[-:.]/g, '')}-${randomBytes(4).toString('hex')}`;
  const head = { v: 1, id, to: event.report.to, person: event.person, time: event.time, kid: OUTBOX_KEY.kid };
  const entry = {
    ...head,
    status: 'queued',
    queuedAt: new Date().toISOString(),
    encrypted: true,
    ...(OUTBOX_KEY.demo ? { keyNote: 'Sealed for the DEMO key pair in demo-keys/: anyone with that file can open it. Not a real key.' } : {}),
    body: seal(event.report.text, outboxAad(head)),
  };
  await mkdir(OUTBOX, { recursive: true });
  const file = join(OUTBOX, `${id}.json`);
  await writeFile(`${file}.tmp`, `${JSON.stringify(entry, null, 2)}\n`, 'utf8');
  await rename(`${file}.tmp`, file);
  return { id, file: shown(file), to: head.to, status: 'queued', encrypted: true, kid: head.kid, demoKey: OUTBOX_KEY.demo };
}

// What waits in the outbox, without the sealed text: for the screen to show "queued for the downlink".
async function getOutbox(req, res, query) {
  const scope = scopeOf(query);
  if (!scope) return json(res, 400, { error: 'say whose messages: ?person=<id>, or ?all=1 for the technical view' });
  let names = [];
  try {
    names = (await readdir(OUTBOX)).filter((f) => f.endsWith('.json')).sort();
  } catch {
    // nothing queued yet
  }
  const items = [];
  for (const name of names) {
    try {
      const m = JSON.parse(await readFile(join(OUTBOX, name), 'utf8'));
      if (scope.all || m.person === scope.person) {
        items.push({ id: m.id, file: shown(join(OUTBOX, name)), to: m.to, person: m.person, time: m.time, status: m.status, encrypted: m.encrypted === true, kid: m.kid });
      }
    } catch {
      // a damaged file is skipped
    }
  }
  json(res, 200, items, req.method === 'HEAD');
}

// ---------- the API ----------
async function api(req, res, path, query) {
  if (!siteAllowed(req.headers['sec-fetch-site'], req.method)) return json(res, 403, { error: "only this program's own pages may use the API" });
  const read = req.method === 'GET' || req.method === 'HEAD';
  if (path === '/api/events') {
    if (read) return getEvents(req, res, query);
    if (req.method === 'POST') return postEvent(req, res);
    return send(res, 405, '', TEXT, { Allow: 'GET, HEAD, POST' });
  }
  if (path === '/api/outbox') {
    if (read) return getOutbox(req, res, query);
    return send(res, 405, '', TEXT, { Allow: 'GET, HEAD' });
  }
  return json(res, 404, { error: 'no such API' });
}

async function handle(req, res) {
  // DNS rebinding: a page on another site that points its own name at this computer arrives with that name.
  if (!HOSTS.has(hostName(req.headers.host))) {
    return send(res, 403, `Unknown host name. Open http://127.0.0.1:${PORT}/ or add the name to HOSTS.`);
  }
  const url = new URL(req.url, 'http://localhost');
  let path;
  try {
    path = decodeURIComponent(url.pathname);
  } catch {
    return send(res, 400, 'Bad address');
  }
  if (path.startsWith('/api/')) return api(req, res, path, url.searchParams);
  if (req.method !== 'GET' && req.method !== 'HEAD') return send(res, 405, '', TEXT, { Allow: 'GET, HEAD' });
  return serveFile(req, res, path);
}

const server = createServer(async (req, res) => {
  try {
    await handle(req, res);
  } catch (err) {
    console.error(`Request failed: ${err.message}`); // never the request body: it may hold health data
    if (!res.headersSent) send(res, 500, 'Something went wrong on this computer.');
    else res.end();
  }
});

server.listen(PORT, HOST, () => {
  const at = HOST.includes(':') ? `[${HOST}]` : HOST;
  console.log(`Skeleton running at http://${at}:${PORT}/ (no internet needed). Data: ${DATA}. Stop with Ctrl+C.`);
  console.log(`Answers only to the host names ${[...HOSTS].join(', ')}. Messages to a doctor are queued in ${OUTBOX}${OUTBOX_KEY ? `, sealed for key "${OUTBOX_KEY.kid}"${OUTBOX_KEY.demo ? ' (a DEMO key, not a real one)' : ''}` : ', but there is no outbox key'}.`);
  if (!LOCAL_HOSTS.includes(hostName(at))) console.log('Note: listening beyond this computer. There is no sign-in: anyone on the network who uses a name from HOSTS can read every person\'s data (/api/events?all=1).');
});
