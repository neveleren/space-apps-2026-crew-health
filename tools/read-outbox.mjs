// The ground side of the outbox, for the demonstration: opens the messages in data/outbox with the flight
// surgeon's private key and prints them. On a real mission this runs on the ground, where the private key stays.
// Run: node tools/read-outbox.mjs [outbox folder or one message file] [key file]
// The default key is the DEMO key pair in demo-keys/ (not a real key).
// The format, as serve.mjs writes it: ECDH on P-256 between a key made for this one message (body.epk) and the
// flight surgeon's key, HKDF-SHA-256 (salt body.salt, info "jff-outbox-v1") for a 256-bit key, then AES-256-GCM
// (body.iv, body.tag) over the text, with the readable fields [v, id, to, person, time, kid] bound as extra data.
// Code generated by Claude (Anthropic), an AI system.
import { createDecipheriv, createPrivateKey, createPublicKey, diffieHellman, hkdfSync } from 'node:crypto';
import { readdir, readFile, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const APP = fileURLToPath(new URL('..', import.meta.url));
const INFO = Buffer.from('jff-outbox-v1', 'utf8');
const unb64 = (s) => Buffer.from(String(s), 'base64url');

// Returns the text of one outbox entry. Throws if the key is wrong or anything in the entry was changed.
export function openMessage(entry, privateJwk) {
  const b = entry.body;
  const privateKey = createPrivateKey({ key: privateJwk, format: 'jwk' });
  const once = createPublicKey({ key: { kty: b.epk.kty, crv: b.epk.crv, x: b.epk.x, y: b.epk.y }, format: 'jwk' });
  const shared = diffieHellman({ privateKey, publicKey: once });
  const key = Buffer.from(hkdfSync('sha256', shared, unb64(b.salt), INFO, 32));
  const decipher = createDecipheriv('aes-256-gcm', key, unb64(b.iv), { authTagLength: 16 });
  decipher.setAAD(Buffer.from(JSON.stringify([entry.v, entry.id, entry.to, entry.person, entry.time, entry.kid]), 'utf8'));
  decipher.setAuthTag(unb64(b.tag));
  return Buffer.concat([decipher.update(unb64(b.ciphertext)), decipher.final()]).toString('utf8');
}

async function main() {
  const target = resolve(process.argv[2] || join(APP, 'data', 'outbox'));
  const keyFile = resolve(process.argv[3] || join(APP, 'demo-keys', 'DEMO-flight-surgeon-keypair.json'));
  const key = JSON.parse(await readFile(keyFile, 'utf8'));
  if (!key.privateJwk) throw new Error(`${keyFile} holds no private key`);
  if (key.demo) console.log('Using the DEMO key pair (not a real key).\n');
  const files = (await stat(target)).isDirectory()
    ? (await readdir(target)).filter((f) => f.endsWith('.json')).sort().map((f) => join(target, f))
    : [target];
  if (!files.length) console.log(`Nothing in ${target}.`);
  for (const file of files) {
    const entry = JSON.parse(await readFile(file, 'utf8'));
    let text;
    try {
      text = openMessage(entry, key.privateJwk);
    } catch {
      text = '(cannot be opened with this key, or the file was changed)';
    }
    console.log(`${entry.id}  to ${entry.to}  from ${entry.person}  at ${entry.time}  [${entry.status}]\n${text}\n`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
