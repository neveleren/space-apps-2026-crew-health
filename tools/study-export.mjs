// The study export of an analog test (for example NASA's HERA): reads every person's file in the data folder and
// writes two CSV files, the steps of each alert (study-alerts.csv) and a summary per subject (study-subjects.csv):
// counts, time to acknowledge, false alarms, drills and Bedford workload ratings, by id only. No names, no measures,
// no values, no text of any alert or message, and no alert about the mind, the cycle, symptoms or medicines
// (src/alert-log.js studyRows, subjectRows). Each line is checked with the server's own rules first (src/security.js),
// as the server reads it back; a damaged line, or one filed under another person, is left out.
// Run: node tools/study-export.mjs [--data <folder>] [--out <folder>] [--real-only]
//   --data       the data folder (default: DATA_DIR, else data/ of the app)
//   --out        where the two files go (default: <data folder>/study, which the server never serves)
//   --real-only  leave out the alerts of the made-up example flight
// Code generated by Claude (Anthropic), an AI system.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { eventProblem, cleanEvent, PERSON_ID } from '../src/security.js';
import { studyRows, subjectRows, toCsv, ALERT_COLUMNS, SUBJECT_COLUMNS } from '../src/alert-log.js';

const APP = fileURLToPath(new URL('..', import.meta.url));

// Every checked event of every person's file, as serve.mjs reads them back (readEvents).
export async function readAll(dataDir) {
  let names = [];
  try { names = (await readdir(dataDir)).filter((f) => f.endsWith('.jsonl')); } catch { return []; }
  const events = [];
  for (const name of names.sort()) {
    const id = name.slice(0, -6);
    if (!PERSON_ID.test(id)) continue;
    const text = await readFile(join(dataDir, name), 'utf8');
    for (const line of text.split('\n')) {
      if (!line.trim()) continue;
      try {
        const e = JSON.parse(line);
        if (!eventProblem(e, { checkFuture: false }) && e.person === id) events.push(cleanEvent(e));
      } catch {
        // a damaged line is left out
      }
    }
  }
  return events;
}

// The two tables from the events of all subjects.
export function studyTables(events, { realOnly = false } = {}) {
  const rows = studyRows(events, { realOnly });
  const subjects = subjectRows(rows, realOnly ? events.filter((e) => !e.example) : events);
  return { rows, subjects, alertsCsv: toCsv(rows, ALERT_COLUMNS), subjectsCsv: toCsv(subjects, SUBJECT_COLUMNS) };
}

function option(args, name) {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : null;
}

export async function main(args = process.argv.slice(2)) {
  const data = resolve(option(args, '--data') || process.env.DATA_DIR || join(APP, 'data'));
  const out = resolve(option(args, '--out') || join(data, 'study'));
  const realOnly = args.includes('--real-only');
  const events = await readAll(data);
  const t = studyTables(events, { realOnly });
  await mkdir(out, { recursive: true });
  await writeFile(join(out, 'study-alerts.csv'), t.alertsCsv, 'utf8');
  await writeFile(join(out, 'study-subjects.csv'), t.subjectsCsv, 'utf8');
  console.log(`Read ${events.length} checked events from ${data}.`);
  console.log(`Wrote ${t.rows.length} alert rows and ${t.subjects.length} subject rows to ${out}${realOnly ? ' (example data left out)' : ''}.`);
  console.log('By id only: no names, measures, values or texts, and no alert about the mind, the cycle, symptoms or medicines.');
  return { data, out, ...t };
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main().catch((err) => { console.error(`Study export failed: ${err.message}`); process.exit(1); });
}
