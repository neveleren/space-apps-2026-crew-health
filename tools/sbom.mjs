const sha256 = async (path) => createHash('sha256').update(await readFile(join(APP, path))).digest('hex');
const md5 = async (path) => createHash('md5').update(await readFile(join(APP, path))).digest('hex');

// Every file in vendor/ and fonts/, with forward slashes, in a fixed order.
export async function listFiles() {
  const out = [];
  const walk = async (dir) => {
    for (const entry of await readdir(join(APP, dir), { withFileTypes: true })) {
      const path = `${dir}/${entry.name}`;
      if (entry.isDirectory()) await walk(path);
      else if (entry.isFile()) out.push(path);
    }
  };
  for (const f of FOLDERS) await walk(f);
  return out.sort();
}

async function component(p) {
  const c = { type: p.type, 'bom-ref': p.ref, supplier: p.supplier };
  if (p.authors) c.authors = p.authors;
  if (p.group) c.group = p.group;
  Object.assign(c, { name: p.name, version: p.version, description: p.description, licenses: p.licenses, purl: p.purl });
  if (p.location) c.hashes = [{ alg: 'SHA-256', content: await sha256(p.location) }, ...(p.md5 ? [{ alg: 'MD5', content: p.md5 }] : [])];
  else c.hashes = p.hashes;
  c.externalReferences = p.links.map(([type, url]) => ({ type, url }));
  const places = [...(p.location ? [p.location] : []), ...(p.occurrences || [])];
  if (places.length) c.evidence = { occurrences: places.map((location) => ({ location })) };
  if (p.files.length) {
    c.components = await Promise.all(p.files.map(async (f) => ({
      type: 'file', 'bom-ref': `file:${f.path}`, name: f.path, ...(f.note ? { description: f.note } : {}),
      hashes: [{ alg: 'SHA-256', content: await sha256(f.path) }], evidence: { occurrences: [{ location: f.path }] },
    })));
  }
  return c;
}

export async function buildSbom(now = new Date()) {
  const pkg = JSON.parse(await readFile(join(APP, 'package.json'), 'utf8'));
  const team = { name: 'Team Just For Fun (NASA Space Apps Challenge 2026)' };
  return {
    bomFormat: 'CycloneDX',
    specVersion: '1.6',
    serialNumber: `urn:uuid:${randomUUID()}`,
    version: 1,
    metadata: {
      timestamp: now.toISOString(),
      authors: [{ name: 'Claude (Anthropic), an AI system, for team Just For Fun' }],
      tools: { components: [{ type: 'application', name: 'tools/sbom.mjs', description: 'writes this file from the files themselves' }] },
      component: { type: 'application', 'bom-ref': 'app', supplier: team, name: pkg.name, version: pkg.version, description: 'Crew Health Console', licenses: [{ license: { id: pkg.license } }] },
      supplier: team,
      properties: [{ name: 'note', value: 'Hashes of local files are SHA-256 of the files exactly as kept in this folder (.gitattributes keeps them byte for byte); SHA256SUMS lists every file of vendor/ and fonts/. The program itself has no npm dependencies.' }],
    },
    components: await Promise.all(PARTS.map(component)),
    dependencies: [{ ref: 'app', dependsOn: PARTS.map((p) => p.ref) }, ...PARTS.map((p) => ({ ref: p.ref, dependsOn: [] }))],
    compositions: [{ aggregate: 'complete', assemblies: ['app'] }],
  };
}

export async function buildSums() {
  const lines = [];
  for (const path of await listFiles()) lines.push(`${await sha256(path)}  ${path}`);
  return `${lines.join('\n')}\n`;
}

// What no longer matches between the files and SBOM.json and SHA256SUMS; an empty list when all is well.
export async function checkSupply() {
  const problems = [];
  const files = await listFiles();
  let sums = '';
  try {
    sums = await readFile(join(APP, 'SHA256SUMS'), 'utf8');
  } catch {
    return ['SHA256SUMS is missing: run node tools/sbom.mjs'];
  }
  const listed = new Map();
  for (const line of sums.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const m = /^([0-9a-f]{64}) [ *](.+)$/.exec(line);
    if (!m) problems.push(`SHA256SUMS: unreadable line "${line.slice(0, 80)}"`);
    else listed.set(m[2], m[1]);
  }
  for (const path of files) {
    if (!listed.has(path)) problems.push(`SHA256SUMS does not list ${path}`);
    else if (listed.get(path) !== await sha256(path)) problems.push(`${path} does not match its SHA-256 in SHA256SUMS`);
  }
  for (const path of listed.keys()) if (!files.includes(path)) problems.push(`SHA256SUMS lists ${path}, which is not there`);

  let sbom;
  try {
    sbom = JSON.parse(await readFile(join(APP, 'SBOM.json'), 'utf8'));
  } catch {
    return [...problems, 'SBOM.json is missing or unreadable: run node tools/sbom.mjs'];
  }
  if (sbom.bomFormat !== 'CycloneDX' || !sbom.specVersion) problems.push('SBOM.json is not a CycloneDX document');
  if (!sbom.metadata || !sbom.metadata.timestamp || !(sbom.metadata.authors || []).length) problems.push('SBOM.json lacks the author or the timestamp');
  const refs = new Set();
  const checkOne = async (c, top) => {
    refs.add(c['bom-ref']);
    const label = c['bom-ref'] || c.name;
    if (top) {
      if (!c.supplier || !c.supplier.name) problems.push(`${label}: no supplier`);
      if (!c.name || !c.version) problems.push(`${label}: no name or version`);
      if (!c.purl) problems.push(`${label}: no unique identifier (purl)`);
      if (!(c.licenses || []).length) problems.push(`${label}: no licence`);
    }
    if (!(c.hashes || []).length) problems.push(`${label}: no hash`);
    const place = c.evidence && c.evidence.occurrences && c.evidence.occurrences[0] && c.evidence.occurrences[0].location;
    if (place && files.includes(place)) {
      const sha = (c.hashes || []).find((h) => h.alg === 'SHA-256');
      if (!sha || sha.content !== await sha256(place)) problems.push(`${label}: SHA-256 does not match ${place}`);
      const m = (c.hashes || []).find((h) => h.alg === 'MD5');
      if (m && m.content !== await md5(place)) problems.push(`${label}: MD5 does not match ${place}`);
    }
    for (const sub of c.components || []) await checkOne(sub, false);
  };
  for (const c of sbom.components || []) await checkOne(c, true);
  for (const p of PARTS) if (!refs.has(p.ref)) problems.push(`SBOM.json lacks ${p.ref}`);
  const deps = new Map((sbom.dependencies || []).map((d) => [d.ref, d.dependsOn || []]));
  for (const p of PARTS) if (!(deps.get('app') || []).includes(p.ref)) problems.push(`SBOM.json: the program's dependencies lack ${p.ref}`);
  const covered = new Set([...refs].filter((r) => r && r.startsWith('file:')).map((r) => r.slice(5)));
  for (const p of PARTS) if (p.location) covered.add(p.location);
  const own = ['vendor/mediapipe/NOTICE.md', 'vendor/web-llm/NOTICE.md', 'fonts/fonts.css']; // the team's own notes about the parts, not third-party files
  for (const path of files) if (!covered.has(path) && !own.includes(path)) problems.push(`SBOM.json does not name ${path}`);
  return problems;
}

async function main() {
  if (process.argv.includes('--check')) {
    const problems = await checkSupply();
    for (const p of problems) console.log(p);
    console.log(problems.length ? `${problems.length} problems.` : 'SBOM.json and SHA256SUMS match the files.');
    process.exit(problems.length ? 1 : 0);
  }
  await writeFile(join(APP, 'SBOM.json'), `${JSON.stringify(await buildSbom(), null, 2)}\n`, 'utf8');
  await writeFile(join(APP, 'SHA256SUMS'), await buildSums(), 'utf8');
  console.log(`Wrote SBOM.json and SHA256SUMS in ${APP}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
