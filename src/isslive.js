// Real ISS cabin air from NASA's public ISSLive! feed: an Earth demo, off by default, that needs the internet.
// On board, the same cells would be fed by the station's own sensors (planned); the program works offline without it.
//
// What the feed is: NASA JSC's ISSLive! project releases a subset of station telemetry for the public ("Public Use
// Permitted", NTRS 20130013825: https://ntrs.nasa.gov/citations/20130013825), relayed by Lightstreamer on
// https://push.lightstreamer.com with the adapter set ISSLIVE (Lightstreamer's own example client, lsClient.ts and
// Subscriber.ts: https://github.com/Lightstreamer/Lightstreamer-example-ISSLive-client-javascript). No written terms
// of use were found; credit "NASA ISSLive, relayed by Lightstreamer"; not for operational decisions.
// Protocol: TLCP 2.4.0, Lightstreamer's plain text protocol over HTTP, polling mode, no library
// (https://lightstreamer.com/sdks/ls-generic-client/2.4.0/TLCP%20Specifications.pdf): create_session, control (add a
// MERGE subscription with snapshot), bind_session to read the U lines, control (destroy). LS_cid must be the fixed
// string the specification gives for custom clients. The server answers CORS for any page origin (tested tonight
// from Node with Origin http://127.0.0.1:8080: Access-Control-Allow-Origin echoed back).
// Items and units: the 2011 public item list (PUIList.xml in the Lightstreamer example) names the items; it labels
// the pressures PSI or PSIA, but the values fit torr (about 758 for a cabin at sea-level pressure), and the open
// source ISS Mimic labels them torr (https://github.com/ISS-Mimic/Mimic, docs/index.html). Status.Class "24" on the
// time item means signal acquired (ISS Mimic). TimeStamp is hours counted as day of the year x 24 plus the GMT hour
// (ISS Mimic and the Lightstreamer example split it this way).
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".

export const ISSLIVE = {
  server: 'https://push.lightstreamer.com/lightstreamer',
  adapterSet: 'ISSLIVE',
  protocol: 'TLCP-2.4.0',
  cid: 'mgQkwtwdysogQz2BJ4Ji kOj2Bg', // TLCP spec, create_session: "Must be set with the special string ... for all custom developed clients"
  schema: ['TimeStamp', 'Value', 'Status.Class', 'CalibratedData'],
  credit: 'NASA ISSLive, relayed by Lightstreamer',
  sources: [
    { title: 'NASA ISS Live! (NTRS 20130013825)', url: 'https://ntrs.nasa.gov/citations/20130013825' },
    { title: 'Lightstreamer ISSLive example client', url: 'https://github.com/Lightstreamer/Lightstreamer-example-ISSLive-client-javascript' },
    { title: 'TLCP 2.4.0 specification', url: 'https://lightstreamer.com/sdks/ls-generic-client/2.4.0/TLCP%20Specifications.pdf' },
    { title: 'ISS Mimic (item units)', url: 'https://github.com/ISS-Mimic/Mimic' },
  ],
};

// The cabin items, all in the life support group (ETHOS). CO2 and O2 come from the Major Constituent Analyzer; since
// January 2026 newer commercial sensors are the station's main air monitor and they are not in the public list
// (NASA ICES-2026-379: https://ntrs.nasa.gov/api/citations/20260003280/downloads/ISS%20ECLSS%20Testbed%202026_final_A.pdf),
// which fits the CO2 and O2 values being about 12 days old tonight.
export const CABIN_ITEMS = [
  { item: 'TIME_000001', name: 'Station clock (shows whether the station is in contact)', unit: 'ms' },
  { item: 'USLAB000058', name: 'US Lab cabin pressure', unit: 'torr', indicator: 'cabinPressure' },
  { item: 'USLAB000059', name: 'US Lab cabin temperature', unit: '°C', indicator: 'cabinTemp' },
  { item: 'USLAB000055', name: 'US Lab CO2 partial pressure (Major Constituent Analyzer)', unit: 'torr', indicator: 'co2' },
  { item: 'USLAB000053', name: 'US Lab O2 partial pressure (Major Constituent Analyzer)', unit: 'torr', indicator: 'cabinO2' },
  { item: 'NODE3000003', name: 'Node 3 CO2 partial pressure (Major Constituent Analyzer)', unit: 'torr' },
  { item: 'NODE3000001', name: 'Node 3 O2 partial pressure (Major Constituent Analyzer)', unit: 'torr' },
];

// ISS Mimic's list of Status.Class values (docs/index.html).
const STATUS_CLASS = { 0: 'overridden', 1: 'missing', 2: 'dead', 3: 'off-scale high', 4: 'off-scale low', 5: 'out of limit high', 6: 'out of limit low', 7: 'out of calibration', 8: 'overscaling', 9: 'static', 24: 'default' };

// A value older than this is shown as not live.
export const FRESH_MINUTES = 60;

// ---------- unit conversions ----------
// 1 torr = 101325/760 Pa = 133.3224 Pa; 1 mmHg = 133.3224 Pa to the same 7 digits (NIST SP 811 Appendix B.8:
// https://www.nist.gov/pml/special-publication-811/nist-guide-si-appendix-b-conversion-factors/nist-guide-si-appendix-b8).
export const KPA_PER_TORR = 101.325 / 760;
export const torrToKpa = (torr) => torr * KPA_PER_TORR;
// Inspired O2 pressure, as NASA-STD-3001 Vol 2 Rev F [V2 6003] defines it: PIO2 = (PB - 47 mmHg) x FIO2, with
// FIO2 = ppO2 / PB (https://standards.nasa.gov/system/files/tmp/NASA-STD-3001%20Vol%202%20Rev%20F.pdf). The
// program's cabin oxygen cell is this inspired pressure, not the cabin's partial pressure.
export const inspiredO2 = (ppO2Torr, cabinTorr) => (cabinTorr - 47) * (ppO2Torr / cabinTorr);

// ---------- time ----------
// TimeStamp in hours: day of the year x 24 + GMT hour, with 1 January as day 1 (7656.6 is 15 November 00:36 GMT).
// The year is not sent: it is taken from now, and a time more than two days ahead belongs to last year.
export function issTime(timeStamp, now = new Date()) {
  const h = Number(timeStamp);
  if (!Number.isFinite(h) || h <= 0) return null;
  const year = new Date(now).getUTCFullYear();
  let t = Date.UTC(year, 0, 0) + h * 3600000;
  if (t - new Date(now).getTime() > 2 * 86400000) t = Date.UTC(year - 1, 0, 0) + h * 3600000;
  return new Date(Math.round(t));
}

// ---------- TLCP text ----------
// One response body into messages: { tag, args } per line; an update keeps its values unsplit (they may hold commas).
export function parseTlcp(text) {
  const out = [];
  for (const line of String(text || '').split(/\r?\n/)) {
    if (!line) continue;
    if (line.startsWith('U,')) {
      const a = line.indexOf(',');
      const b = line.indexOf(',', a + 1);
      const c = line.indexOf(',', b + 1);
      out.push({ tag: 'U', subId: Number(line.slice(a + 1, b)), item: Number(line.slice(b + 1, c)), values: line.slice(c + 1) });
    } else {
      const parts = line.split(',');
      out.push({ tag: parts[0], args: parts.slice(1) });
    }
  }
  return out;
}

// The field values of one update, by the specification's decoding rules: empty = unchanged, "#" = null,
// "$" = empty string, "^n" = n unchanged fields, "^P" and "^T" = a diff on the previous value (not used here: a
// snapshot never carries one), anything else is percent-encoded text.
export function decodeValues(values, previous = []) {
  const out = [...previous];
  let i = 0;
  for (const tok of String(values).split('|')) {
    if (tok === '') { i += 1; continue; }
    if (tok === '#') { out[i] = null; i += 1; continue; }
    if (tok === '$') { out[i] = ''; i += 1; continue; }
    if (tok[0] === '^') {
      if (/^\^\d+$/.test(tok)) { i += Number(tok.slice(1)); continue; }
      i += 1; // a diff: keep the previous value
      continue;
    }
    try { out[i] = decodeURIComponent(tok); } catch { out[i] = tok; }
    i += 1;
  }
  return out;
}

// ---------- the request ----------
const form = (obj) => Object.entries(obj).map(([k, v]) => `${k}=${encodeURIComponent(v)}`).join('&');

async function post(fetchFn, path, body, timeoutMs) {
  const ctl = typeof AbortController !== 'undefined' ? new AbortController() : null;
  const timer = ctl ? setTimeout(() => ctl.abort(), timeoutMs) : null;
  try {
    const res = await fetchFn(`${ISSLIVE.server}/${path}?LS_protocol=${ISSLIVE.protocol}`, { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' }, body, signal: ctl ? ctl.signal : undefined });
    if (!res.ok) throw new Error(`ISSLive answered HTTP ${res.status}`);
    return await res.text();
  } finally {
    if (timer) clearTimeout(timer);
  }
}

// What the program can save from one set of item values: { readings, items, signal }.
// values: { [item]: [TimeStamp, Value, Status.Class, CalibratedData] } as decoded from the feed.
// skip: cells not to fill (for example ['cabinO2'] if the team keeps the partial pressure out of the inspired-O2 cell).
export function cabinReadings(values, now = new Date(), { skip = [] } = {}) {
  const nowMs = new Date(now).getTime();
  const items = [];
  const byItem = {};
  for (const def of CABIN_ITEMS) {
    const v = values[def.item];
    if (!v) continue;
    const time = issTime(v[0], now);
    const raw = v[1] === null || v[1] === undefined || v[1] === '' ? null : Number(v[1]);
    const entry = {
      item: def.item,
      name: def.name,
      unit: def.unit,
      value: Number.isFinite(raw) ? raw : null,
      text: v[3] ?? null,
      time: time ? time.toISOString() : null,
      ageMinutes: time ? Math.max(0, Math.round((nowMs - time.getTime()) / 60000)) : null,
      statusClass: v[2] ?? null,
      status: STATUS_CLASS[v[2]] || (v[2] ? `class ${v[2]}` : null),
    };
    items.push(entry);
    byItem[def.item] = entry;
  }
  const clock = byItem.TIME_000001;
  const signal = !clock ? 'unknown' : clock.statusClass === '24' ? 'acquired' : 'lost';
  const readings = [];
  const add = (indicator, value, unit, from, how, digits = 2) => {
    if (!Number.isFinite(value) || !from.time || skip.includes(indicator)) return;
    readings.push({
      source: 'isslive',
      person: 'ship',
      indicator,
      value: Number(value.toFixed(digits)),
      unit,
      time: from.time,
      ageMinutes: from.ageMinutes,
      stale: from.ageMinutes > FRESH_MINUTES,
      item: from.item,
      how,
    });
  };
  const p = byItem.USLAB000058;
  if (p && p.value !== null) add('cabinPressure', torrToKpa(p.value), 'kPa', p, `${p.item}: ${p.value.toFixed(2)} torr x 0.133322 = ${torrToKpa(p.value).toFixed(2)} kPa`);
  const t = byItem.USLAB000059;
  if (t && t.value !== null) add('cabinTemp', t.value, '°C', t, `${t.item}: degrees C as sent`, 1);
  const co2 = byItem.USLAB000055;
  if (co2 && co2.value !== null) add('co2', co2.value, 'mmHg', co2, `${co2.item}: torr, the same as mmHg to 7 digits`);
  const o2 = byItem.USLAB000053;
  if (o2 && o2.value !== null && p && p.value) add('cabinO2', inspiredO2(o2.value, p.value), 'mmHg', o2, `${o2.item}: ppO2 ${o2.value.toFixed(2)} torr, as inspired O2 = (${p.value.toFixed(2)} - 47) x ${o2.value.toFixed(2)} / ${p.value.toFixed(2)} (NASA-STD-3001 Vol 2, V2 6003), with the cabin pressure of ${p.time}`, 1);
  return { readings, items, signal };
}

// Reads the first values of the cabin items once and closes the session.
// Returns { ok: true, source: 'isslive', fetchedAt, signal, items, readings, credit, earthDemo: true }
// or { ok: false, error, source: 'isslive' } (no internet, the feed is down, or the protocol was refused).
// readings: { source: 'isslive', person: 'ship', indicator, value, unit, time, ageMinutes, stale, item, how }.
// skip: cells not to fill, as in cabinReadings().
export async function readCabinAir({ fetch: fetchFn = globalThis.fetch, now = () => new Date(), timeoutMs = 10000, binds = 4, skip = [] } = {}) {
  if (typeof fetchFn !== 'function') return { ok: false, source: 'isslive', error: 'This browser cannot fetch.' };
  let session = null;
  try {
    const created = parseTlcp(await post(fetchFn, 'create_session.txt', form({ LS_adapter_set: ISSLIVE.adapterSet, LS_cid: ISSLIVE.cid, LS_polling: 'true', LS_polling_millis: '0', LS_idle_millis: '0' }), timeoutMs));
    const ok = created.find((m) => m.tag === 'CONOK');
    if (!ok) {
      const err = created.find((m) => m.tag === 'CONERR' || m.tag === 'END' || m.tag === 'ERROR');
      throw new Error(err ? `ISSLive refused the session: ${err.args.join(' ')}` : 'ISSLive did not open a session');
    }
    session = ok.args[0];
    const items = CABIN_ITEMS.map((d) => d.item);
    const sub = parseTlcp(await post(fetchFn, 'control.txt', form({ LS_session: session, LS_reqId: '1', LS_op: 'add', LS_subId: '1', LS_mode: 'MERGE', LS_group: items.join(' '), LS_schema: ISSLIVE.schema.join(' '), LS_snapshot: 'true' }), timeoutMs));
    const refused = sub.find((m) => m.tag === 'REQERR' || m.tag === 'ERROR');
    if (refused) throw new Error(`ISSLive refused the subscription: ${refused.args.join(' ')}`);
    const fields = {};
    for (let n = 0; n < binds && Object.keys(fields).length < items.length; n += 1) {
      const msgs = parseTlcp(await post(fetchFn, 'bind_session.txt', form({ LS_session: session, LS_polling: 'true', LS_polling_millis: '0', LS_idle_millis: '3000' }), timeoutMs));
      for (const m of msgs) {
        if (m.tag === 'U' && m.subId === 1) {
          const name = items[m.item - 1];
          if (name) fields[name] = decodeValues(m.values, fields[name]);
        }
        if (m.tag === 'END' || m.tag === 'CONERR') throw new Error(`ISSLive closed the session: ${m.args.join(' ')}`);
      }
    }
    const at = now();
    const { readings, items: list, signal } = cabinReadings(fields, at, { skip });
    if (!list.length) throw new Error('ISSLive sent no values');
    return { ok: true, source: 'isslive', fetchedAt: new Date(at).toISOString(), signal, items: list, readings, credit: ISSLIVE.credit, earthDemo: true };
  } catch (err) {
    const msg = err && err.name === 'AbortError' ? 'ISSLive did not answer in time' : (err && err.message) || String(err);
    return { ok: false, source: 'isslive', error: msg };
  } finally {
    if (session) {
      try { await post(fetchFn, 'control.txt', form({ LS_session: session, LS_reqId: '2', LS_op: 'destroy' }), timeoutMs); } catch { /* the session ends by itself */ }
    }
  }
}
