// The alert log, for an analog test such as NASA's HERA: each step in the life of an alert on a person's screens
// (shown, acknowledged, read, cleared, called off as a false alarm, rated for workload) is saved in that person's own
// record as one event of kind "alert", one per alert and step. Every screen of the person reads these back, so all of
// them show the same read and acknowledged state and an acknowledged alarm does not sound again; the time to
// acknowledge is worked out from them; and the study export counts them for every subject by id only, leaving out
// each alert about the mind, the cycle, symptoms or medicines (src/crew.js writes the steps; tools/study-export.mjs
// and the technical view export them). Crewmates never get these events: the server gives others only alarm lines.
// NASA-STD-3001 Vol 2 Rev F: alert events are still logged when an alert is suppressed (10177, rationale); automated
// systems record operational and performance data and make them available to crew and ground (10163); the alerts
// display shows each event's acknowledge state (Appendix F.6.4 f). The workload rating is the Bedford scale, which
// NASA names for crew interfaces [V2 5007], in the words of NASA's own figure (NASA/TP-2014-218556, Figure 4.3.2-1).
// Code generated by Claude (Anthropic), an AI system.
import { CELLS } from './config.js';

// The steps of an alert's life. "acknowledged" is the first acknowledgement of its sound or of the alert; "read" is
// Mark as read or Mark all as read, which acknowledges too; "false-alarm" is "I am okay: false alarm".
export const LOG_STEPS = Object.freeze(['shown', 'acknowledged', 'read', 'cleared', 'false-alarm', 'rated']);
// How it was acknowledged: Mark as read on one message, Mark all as read, the Messages key (status line or the key
// bar), Silence on the alarm banner, "Silence all sounds" on Messages.
export const ACK_WAYS = Object.freeze(['mark-read', 'mark-all-read', 'messages-key', 'banner-silence', 'silence-all']);
// What the alert is about, without the measure: the person's body, mind, the camera, the Help key, the ship's cabin
// air, or a crewmate's alarm line.
export const SYSTEMS = Object.freeze(['body', 'mind', 'camera', 'help-key', 'ship', 'crew']);
// The ids the crew screen gives its alerts: "crew-1|red|spo2|3|2026-11-15", "line|crew-2|crew-1|<time>", ...
export const ALERT_ID = /^[A-Za-z0-9][A-Za-z0-9|:._-]{0,159}$/;
export const LEVEL_WORDS = Object.freeze(['fine', 'attention', 'needs action', 'urgent']);

// The measures that are private to the person by default: an alert about one of them, or about the mind, is marked
// private, and the study export leaves it out.
const PRIVATE = new Set(CELLS.filter((c) => c.private).map((c) => c.indicator));
const SYSTEM_OF = { Body: 'body', Mind: 'mind', Camera: 'camera', 'Help key': 'help-key', Ship: 'ship' };
const msOf = (t) => (typeof t === 'number' ? t : t instanceof Date ? t.getTime() : Date.parse(t));

// ---------- what is logged ----------
// The facts of one alert of the Messages list (src/crew.js alertsFor): id, level, system, private, drill, example.
export function ownFacts(x, { example = false } = {}) {
  if (!x || typeof x.id !== 'string') return null;
  const system = SYSTEM_OF[x.system] || 'body';
  return { id: x.id, level: x.level, system, private: system === 'mind' || PRIVATE.has(x.indicator), drill: x.drill || null, example: Boolean(example) };
}
// The facts of a crewmate's alarm line on the banner (src/crew.js crewAlerts): always urgent, never private (the line
// is shared by design), made up when it comes from the example flight.
export function lineFacts(l) {
  if (!l || typeof l.id !== 'string') return null;
  return { id: l.id, level: 3, system: 'crew', private: false, drill: l.drill || null, example: l.id.startsWith('example|') };
}

// One step as an event for the person's record. drill: the drill the alert belongs to (src/drill.js), not the switch.
export function logEvent(facts, step, { person, time = new Date().toISOString(), how = null, rating = null } = {}) {
  const alert = { id: facts.id, step, level: facts.level, system: facts.system };
  if (facts.private) alert.private = true;
  if (how) alert.how = how;
  if (step === 'rated') alert.rating = rating;
  const e = { v: 1, kind: 'alert', time, person, alert };
  if (facts.drill) e.drill = facts.drill;
  if (facts.example) e.example = true;
  return e;
}

// ---------- reading the log back ----------
// What the log of one person says about each alert, by id: the first time of each step (two screens can log the same
// step; the earliest counts), how it was first acknowledged, the rating, and the time to acknowledge in seconds: from
// the first time any screen showed it to the first acknowledgement anywhere (acknowledged, read or false alarm).
export function logState(events, person) {
  const out = new Map();
  for (const e of Array.isArray(events) ? events : []) {
    if (!e || e.kind !== 'alert' || !e.alert || (person && e.person !== person)) continue;
    const a = e.alert;
    const t = msOf(e.time);
    if (!Number.isFinite(t) || typeof a.id !== 'string') continue;
    let s = out.get(a.id);
    if (!s) {
      s = { id: a.id, person: e.person, level: a.level, system: a.system, private: a.private === true, drill: e.drill || null, example: e.example === true };
      out.set(a.id, s);
    }
    if (e.drill && !s.drill) s.drill = e.drill;
    const first = (k, how) => { if (s[k] === undefined || t < s[k]) { s[k] = t; if (how !== undefined) s[`${k}How`] = how; } };
    if (a.step === 'shown') first('shown');
    else if (a.step === 'acknowledged') first('acknowledged', a.how || null);
    else if (a.step === 'read') first('read', a.how || null);
    else if (a.step === 'cleared') first('cleared');
    else if (a.step === 'false-alarm') first('falseAlarm');
    else if (a.step === 'rated' && (s.rated === undefined || t < s.rated)) { s.rated = t; s.rating = a.rating; }
  }
  for (const s of out.values()) {
    const acks = [['acknowledged', s.acknowledgedHow], ['read', s.readHow], ['falseAlarm', 'false-alarm']].filter(([k]) => s[k] !== undefined).sort((x, y) => s[x[0]] - s[y[0]]);
    s.ackAt = acks.length ? s[acks[0][0]] : undefined;
    s.ackHow = acks.length ? acks[0][1] || null : null;
    s.timeToAck = s.ackAt !== undefined && s.shown !== undefined ? Math.round((s.ackAt - s.shown) / 100) / 10 : null;
  }
  return out;
}

// Which alerts the log says are read (so they no longer count as new) and acknowledged (so they do not sound again).
export function readAndAcked(state) {
  const read = new Set();
  const acked = new Set();
  for (const s of state.values()) {
    if (s.read !== undefined || s.falseAlarm !== undefined) read.add(s.id);
    if (s.ackAt !== undefined) acked.add(s.id);
  }
  return { read, acked };
}

// ---------- which steps are due ----------
// current and previous: Map id -> facts of the alerts on the screen now and at the last look (previous null when the
// screen just opened or the example flight was switched, so nothing counts as cleared then). Returns [facts, step].
export function shownAndCleared({ current, previous = null, state }) {
  const out = [];
  for (const [id, f] of current) if (!(state.get(id) || {}).shown) out.push([f, 'shown']);
  if (previous) {
    for (const [id, f] of previous) {
      if (current.has(id)) continue;
      const s = state.get(id);
      if (s && s.shown !== undefined && s.cleared === undefined) out.push([f, 'cleared']);
    }
  }
  return out;
}
// The alerts an acknowledgement covers that the log does not yet hold as acknowledged.
export const ackDue = (facts, state) => facts.filter((f) => f && (state.get(f.id) || {}).ackAt === undefined);
// The alerts a "Mark as read" covers that the log does not yet hold as read.
export const readDue = (facts, state) => facts.filter((f) => f && (state.get(f.id) || {}).read === undefined);

// Own log events that a look at the station computer brings and this screen does not have yet (another device of
// the same person wrote them). key: the same key the screen uses for every event (src/crew-alarm.js eventKey).
export function newOwnLog(fetched, have, person, key) {
  const known = new Set((have || []).map(key));
  const out = [];
  for (const e of Array.isArray(fetched) ? fetched : []) {
    if (!e || e.kind !== 'alert' || e.person !== person) continue;
    const k = key(e);
    if (known.has(k)) continue;
    known.add(k);
    out.push(e);
  }
  return out;
}

// ---------- the workload rating ----------
// The Bedford workload scale, as NASA's figure gives it: three questions, answered from the bottom up, lead to a group
// of levels, and the person picks the level whose words fit best. NASA-STD-3001 Vol 2 Rev F [V2 5007]: crew interfaces
// that result in Bedford ratings of 3 or less for nominal tasks and 6 or less under degraded system conditions.
export const BEDFORD = Object.freeze({
  levels: Object.freeze([
    { n: 1, text: 'Workload insignificant' },
    { n: 2, text: 'Workload low' },
    { n: 3, text: 'Enough spare capacity for all desirable additional tasks' },
    { n: 4, text: 'Insufficient spare capacity for easy attention to additional tasks' },
    { n: 5, text: 'Reduced spare capacity: additional tasks cannot be given the desired amount of attention' },
    { n: 6, text: 'Little spare capacity: level of effort allows little attention to additional tasks' },
    { n: 7, text: 'Very little spare capacity, but maintenance of effort in the primary tasks not in question' },
    { n: 8, text: 'Very high workload with almost no spare capacity. Difficult in maintaining level of effort' },
    { n: 9, text: 'Extremely high workload. No spare capacity. Serious doubts as to ability to maintain level of effort' },
    { n: 10, text: 'Tasks abandoned. Pilot unable to apply sufficient effort' },
  ]),
  questions: Object.freeze([
    { id: 'complete', text: 'Was it possible to complete the task?', no: [10] },
    { id: 'tolerable', text: 'Was workload tolerable for the task?', no: [7, 8, 9] },
    { id: 'satisfactory', text: 'Was workload satisfactory without reduction?', no: [4, 5, 6], yes: [1, 2, 3] },
  ]),
  limits: Object.freeze({ nominal: 3, degraded: 6 }),
  task: 'answering this alarm, from its first sound until you acknowledged it',
  sources: Object.freeze([
    { name: 'NASA/TP-2014-218556, Human Integration Design Processes, 2014, Figure 4.3.2-1 The Bedford Scale', year: 2014, url: 'https://www.nasa.gov/wp-content/uploads/2015/03/human_integration_design_processes.pdf' },
    { name: 'NASA-STD-3001 Vol 2 Rev F, 2026, [V2 5007] Cognitive Workload', year: 2026, url: 'https://standards.nasa.gov/system/files/tmp/NASA-STD-3001%20Vol%202%20Rev%20F.pdf' },
    { name: 'NASA OCHMO-TB-032 Rev C, Cognitive Workload Assessment Methods, 2023', year: 2023, url: 'https://www.nasa.gov/wp-content/uploads/2023/12/ochmo-tb-032-cognitive-workload.pdf' },
  ]),
});

// Where the answers so far lead: the next question, or the levels to choose from. answers: true for yes, false for no.
export function bedfordChoices(answers = []) {
  const qs = BEDFORD.questions;
  for (let i = 0; i < qs.length; i += 1) {
    if (answers[i] === undefined) return { next: qs[i], levels: [] };
    if (answers[i] === false) return { next: null, levels: qs[i].no };
  }
  return { next: null, levels: qs[qs.length - 1].yes };
}
export const bedfordText = (n) => (BEDFORD.levels.find((l) => l.n === n) || { text: '' }).text;
export const isBedford = (n) => Number.isInteger(n) && n >= 1 && n <= 10;

// Which alerts ask for a rating (a draft): an urgent one, once it was acknowledged or called off, until it is rated.
export const WORKLOAD_RULES = Object.freeze({ minLevel: 3, draft: true, note: 'Which alerts ask for a workload rating is a draft: the team decides.' });
export function asksWorkload(x, state) {
  if (!x || x.level < WORKLOAD_RULES.minLevel) return false;
  const s = state.get(x.id);
  return Boolean(s && s.ackAt !== undefined && s.rating === undefined);
}

// ---------- the study export ----------
// One row per alert of each subject, by id only: no name, no measure, no value, no text of any alert or message, and
// no alert about the mind, the cycle, symptoms or medicines. Times are GMT (ISO 8601), durations in seconds.
export const ALERT_COLUMNS = Object.freeze(['subject', 'alert', 'about', 'system', 'level', 'drill', 'example', 'shown_gmt', 'acknowledged_gmt', 'acknowledged_by', 'time_to_ack_s', 'read_gmt', 'cleared_gmt', 'false_alarm', 'bedford', 'reach_s']);
export const SUBJECT_COLUMNS = Object.freeze(['subject', 'alerts', 'urgent_alerts', 'acknowledged', 'not_acknowledged', 'median_time_to_ack_s', 'longest_time_to_ack_s', 'false_alarms', 'drills', 'drill_alerts', 'median_drill_time_to_ack_s', 'crewmate_lines', 'median_reach_s', 'bedford_ratings', 'median_bedford', 'bedford_above_3', 'bedford_above_6']);

const iso = (t) => (t === undefined || t === null ? '' : new Date(t).toISOString());
const median = (xs) => {
  const v = xs.filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
  if (!v.length) return '';
  const m = Math.floor(v.length / 2);
  return Math.round((v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2) * 10) / 10;
};
// Who a crewmate line is about, and when the line was written: from its id, "line|<viewer>|<person>|<time>".
function lineParts(id) {
  const p = String(id).split('|');
  if (p[0] === 'line') return { about: p[2] || '', at: msOf(p[3]) };
  if (p[0] === 'example') return { about: p[2] || '', at: NaN };
  return null;
}

export function studyRows(events, { realOnly = false } = {}) {
  const people = [...new Set((Array.isArray(events) ? events : []).filter((e) => e && e.kind === 'alert').map((e) => e.person))].sort();
  const rows = [];
  for (const person of people) {
    const list = [...logState(events, person).values()]
      .filter((s) => !s.private && SYSTEMS.includes(s.system) && s.system !== 'mind' && !(realOnly && s.example))
      .sort((a, b) => (a.shown ?? a.ackAt ?? a.cleared ?? 0) - (b.shown ?? b.ackAt ?? b.cleared ?? 0));
    list.forEach((s, i) => {
      const line = s.system === 'crew' ? lineParts(s.id) : null;
      const reach = line && Number.isFinite(line.at) && s.shown !== undefined ? Math.round((s.shown - line.at) / 100) / 10 : '';
      rows.push({
        subject: person,
        alert: `A${i + 1}`,
        about: line ? line.about : s.system === 'ship' ? 'ship' : 'own',
        system: s.system,
        level: LEVEL_WORDS[s.level] || '',
        drill: s.drill || '',
        example: s.example ? 'yes' : 'no',
        shown_gmt: iso(s.shown),
        acknowledged_gmt: iso(s.ackAt),
        acknowledged_by: s.ackHow || '',
        time_to_ack_s: s.timeToAck === null ? '' : s.timeToAck,
        read_gmt: iso(s.read),
        cleared_gmt: iso(s.cleared),
        false_alarm: s.falseAlarm !== undefined ? 'yes' : 'no',
        bedford: s.rating ?? '',
        reach_s: reach,
      });
    });
  }
  return rows;
}

// One row per subject. drills: the drills the subject's own events belong to (every kind of event counts).
export function subjectRows(rows, events = []) {
  const drillsOf = new Map();
  for (const e of Array.isArray(events) ? events : []) {
    if (!e || typeof e.drill !== 'string' || !e.drill) continue;
    if (!drillsOf.has(e.person)) drillsOf.set(e.person, new Set());
    drillsOf.get(e.person).add(e.drill);
  }
  const subjects = [...new Set([...rows.map((r) => r.subject), ...drillsOf.keys()])].sort();
  return subjects.map((subject) => {
    const mine = rows.filter((r) => r.subject === subject);
    const tta = mine.map((r) => r.time_to_ack_s).filter((x) => x !== '');
    const drill = mine.filter((r) => r.drill);
    const lines = mine.filter((r) => r.system === 'crew');
    const ratings = mine.map((r) => r.bedford).filter((x) => x !== '');
    return {
      subject,
      alerts: mine.length,
      urgent_alerts: mine.filter((r) => r.level === 'urgent').length,
      acknowledged: mine.filter((r) => r.acknowledged_gmt).length,
      not_acknowledged: mine.filter((r) => !r.acknowledged_gmt).length,
      median_time_to_ack_s: median(tta),
      longest_time_to_ack_s: tta.length ? Math.max(...tta) : '',
      false_alarms: mine.filter((r) => r.false_alarm === 'yes').length,
      drills: (drillsOf.get(subject) || new Set()).size,
      drill_alerts: drill.length,
      median_drill_time_to_ack_s: median(drill.map((r) => r.time_to_ack_s).filter((x) => x !== '')),
      crewmate_lines: lines.length,
      median_reach_s: median(lines.map((r) => r.reach_s).filter((x) => x !== '')),
      bedford_ratings: ratings.length,
      median_bedford: median(ratings),
      bedford_above_3: ratings.filter((x) => x > BEDFORD.limits.nominal).length,
      bedford_above_6: ratings.filter((x) => x > BEDFORD.limits.degraded).length,
    };
  });
}

// CSV (RFC 4180): quotes where needed; a text cell that starts with = + - or @ gets a leading apostrophe, so a
// spreadsheet never runs it as a formula (OWASP, CSV injection).
const cell = (v) => {
  if (typeof v === 'number') return String(v);
  let s = String(v ?? '');
  if (/^[=+\-@]/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
export function toCsv(rows, columns) {
  return `${[columns.join(','), ...rows.map((r) => columns.map((c) => cell(r[c])).join(','))].join('\r\n')}\r\n`;
}

