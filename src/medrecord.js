function alertRows({ person, history, events, statusOf, ship, words }) {
  const out = [];
  for (const cell of CELLS) {
    if (cell.section === 'env' || !(cell.red || []).length) continue;
    (history(person.id, cell.indicator) || []).forEach((x, i) => {
      if (!x.red) return;
      const v = readingVerdict(cell, x);
      out.push({ kind: 'entry', key: `a:red:${cell.indicator}:${iso(x.time)}:${i}`, icon: v.level >= LEVEL.URGENT ? 'octagon-alert' : 'triangle-alert', level: v.level, tag: 'Red limit', title: `${cell.label}: ${words(cell.indicator, x.value)} ${cell.unit || ''}`.trim(), detail: v.text, time: iso(x.time), source: sourceWords(x, cell.indicator), example: Boolean(x.example), link: { to: 'measure', indicator: cell.indicator } });
    });
  }
  (history(person.id, 'camera') || []).forEach((x, i) => {
    if (x.value === 'sleeping') return;
    const helpKey = x.source === 'help-key';
    const okay = x.value === 'chest_grab_ok';
    const falseAlarm = okay && x.source === 'false-alarm';
    const title = helpKey ? 'Help key held: you called for help' : falseAlarm ? 'You pressed "I am okay: false alarm"' : CAMERA_TITLE[x.value] || `Camera: ${String(x.value)}`;
    const detail = x.status === STATUS.OUT ? 'An urgent alarm, raised by the automation without the AI.' : falseAlarm ? 'This called off the alarm before it; the alarm stays in the record.' : okay ? 'No alarm was raised.' : '';
    out.push({ kind: 'entry', key: `a:cam:${iso(x.time)}:${i}`, icon: okay ? 'circle-check' : 'octagon-alert', level: x.status === STATUS.OUT ? LEVEL.URGENT : LEVEL.FINE, tag: falseAlarm ? 'False alarm' : okay ? 'Answer' : helpKey ? 'Help key' : 'Camera', title, detail, time: iso(x.time), source: sourceWords(x, 'camera'), example: Boolean(x.example), link: { to: 'messages' } });
  });
  for (const e of events || []) {
    if (!e || e.person !== person.id) continue;
    if (e.kind === 'alarm' && e.alarm && typeof e.alarm.text === 'string') {
      const clear = Boolean(e.alarm.clear);
      out.push({ kind: 'entry', key: `a:line:${e.time}:${clear ? 'clear' : 'open'}`, icon: clear ? 'circle-check' : 'users', level: clear ? LEVEL.FINE : LEVEL.URGENT, tag: clear ? 'All clear' : 'Crew line', title: clear ? `All clear for the crew: "${e.alarm.text}"` : `Crew line: "${e.alarm.text}"`, detail: lineWords(statusOf(e), clear), time: iso(e.time), source: 'Written by the program', example: false, link: { to: 'messages' } });
    }
    if (e.kind === 'report' && e.report && (e.report.topic === 'alarm' || e.report.topic === 'alarm-clear')) {
      const where = e.report.to === 'doctor-onboard' ? 'the doctor on board' : 'the doctor on Earth';
      const clear = e.report.topic === 'alarm-clear';
      const st = statusOf(e);
      out.push({ kind: 'entry', key: `a:report:${e.time}:${e.report.topic}`, icon: 'send', level: LEVEL.FINE, tag: 'Message to the doctor', title: `Automatic ${clear ? 'all clear' : 'alarm message'} to ${where}`, detail: `${sentChip(st, ship).text}. ${firstWords(bodyOfAlarm(e.report.text), 220)}`.trim(), time: iso(e.time), source: 'Written by the program', example: false, link: { to: 'messages' } });
    }
  }
  return out.sort(newestFirst);
}
// The program's alarm message starts with the same two sentences every time; the rest says what happened.
const bodyOfAlarm = (text) => String(text || '').replace(/^Automatic message from the Crew Health Console \([^)]*\)\.\s*/, '');
const firstWords = (text, max) => { const s = String(text || '').replace(/\s+/g, ' ').trim(); return s.length > max ? `${s.slice(0, max - 4).replace(/\s+\S*$/, '')} ...` : s; };

// The person's own messages to a doctor, the weekly conference summaries and the requests for a private call; the
// automatic alarm messages are under the alerts. Messages that were not saved are listed as "Not sent".
const MIND_TOPICS = new Set(['letter-to-psychologist', 'talk-request', 'mind-checkins']);
export function messageTitle(report) {
  const where = report.to === 'doctor-onboard' ? 'the doctor on board' : 'the doctor on Earth';
  if (isTalkRequest(report)) return 'Request for a private call, to Earth';
  if (isLetter(report)) return 'Private letter for your psychologist, to Earth';
  if (report.topic === 'pmc') return `Summary for the private medical conference, to ${where}`;
  if (report.topic === 'mind-checkins') return `Your check-ins, to ${where}`;
  return `Message to ${where}`;
}
function encounterRows({ person, events, unsent, statusOf, ship }) {
  const out = [];
  const one = (e, st, why = '') => {
    if (!e || e.kind !== 'report' || e.person !== person.id || !e.report) return;
    if (e.report.topic === 'alarm' || e.report.topic === 'alarm-clear') return;
    const mind = MIND_TOPICS.has(e.report.topic) || isTalkRequest(e.report) || isLetter(e.report);
    const chip = sentChip(st, ship);
    out.push({ kind: 'entry', key: `m:${e.time}:${st === 'unsent' ? 'unsent' : 'kept'}`, icon: st === 'unsent' ? 'circle-alert' : 'message-square', level: LEVEL.FINE, tag: mind ? 'Private: mind' : null, private: mind, title: messageTitle(e.report), detail: `${chip.text}${why ? `: ${why}` : ''}. ${firstWords(e.report.text, 160)}`.trim(), status: st, time: iso(e.time), source: 'Sent by you', example: false, link: { to: 'messages' } });
  };
  for (const e of events || []) one(e, statusOf(e));
  for (const u of unsent || []) one(u && u.event, 'unsent', u && u.why ? String(u.why).replace(/^not saved:\s*/, '') : '');
  return out.sort(newestFirst);
}

// The daily check-ins of the last days, one row a GMT day, newest first, with the mind rule's own low day (a bad mood,
// or energy at the Samn-Perelli step that counts as low; state-levels.js).
export function checkinDays({ person, history, now, days = RECORD_RULES.mindDays }) {
  const since = ms(now) - days * DAY;
  const byDay = new Map();
  const put = (ind, x) => {
    if (ms(x.time) < since || ms(x.time) > ms(now) + DAY) return;
    const d = iso(x.time).slice(0, 10);
    if (!byDay.has(d)) byDay.set(d, { day: d, mood: null, energy: null, sleep: null, low: false });
    const row = byDay.get(d);
    if (ind === 'mood') { row.mood = String(x.value); if (x.value === 'bad') row.low = true; }
    if (ind === 'attitude') { const n = fatigueStep(x.value); row.energy = Number.isFinite(n) ? `${n} of 7` : String(x.value); if (isLowEnergy(x.value)) row.low = true; }
    if (ind === 'sleepQuality') row.sleep = `${x.value} of 7`;
  };
  for (const ind of ['mood', 'attitude', 'sleepQuality']) for (const x of history(person.id, ind) || []) put(ind, x);
  return [...byDay.values()].sort((a, b) => b.day.localeCompare(a.day));
}

function cyclePart({ person, history, now }) {
  const list = history(person.id, 'cycle') || [];
  if (!list.length && person.sex !== 'F') return null;
  const s = cycleSummary(list, now);
  const facts = [];
  if (s.suppressed) facts.push('You chose to suppress your periods. The choice is yours and your flight surgeon\'s.');
  else if (s.cycleDay) facts.push(`Cycle day ${s.cycleDay}${s.average ? `; average cycle ${s.average} days` : ''}${s.periodDays ? `; period about ${s.periodDays} days` : ''}${s.nextExpected ? `; next period expected around ${fmtDay(s.nextExpected)} (a plain average of your last cycles, not a medical model)` : ''}.`);
  else facts.push('No period logged yet.');
  if (Array.isArray(s.lengths) && s.lengths.length) facts.push(`Cycle lengths, oldest first: ${s.lengths.slice(-6).join(', ')} days.`);
  // The same checked flags and words as the cycle card on All measures (crew.js cycleCard, src/cycle.js).
  const flags = Array.isArray(s.flags) ? s.flags : [];
  if (flags.includes('long-cycles')) facts.push(`The last cycles were longer than ${CYCLE_RULES.longCycleDays} days. The Endocrine Society advises a check-up when cycles are consistently that long.`);
  if (flags.includes('no-period')) facts.push('No period for more than 3 months. The Endocrine Society advises a check-up, after other causes are ruled out.');
  if (flags.includes('cycle-outside-range')) facts.push(`The last cycle was outside the usual ${CYCLE_RULES.normalMin} to ${CYCLE_RULES.normalMax} days (ACOG).`);
  if (flags.includes('cycle-varies')) facts.push(`Your recent cycles differ by more than ${CYCLE_RULES.varyMax} days; ACOG counts that as irregular.`);
  if (flags.includes('long-period')) facts.push(`The last period lasted more than ${CYCLE_RULES.periodMax} days; ACOG counts that as abnormal bleeding.`);
  return { facts, flags: [...flags] };
}

// ---------- the whole record ----------
// buildRecord({ person, history, events, unsent, statusOf, now, mission, flightDay, today, flagged, notes, storeKind, ship,
//               valueText }) -> { header, today, sections, notHeld, sources }
// - person: the signed-in person ({ id, name, sex, real, code }); history(id, indicator): the machine's readings
// - events: what the screen holds (saved events and those waiting for the server); unsent: [{ event, why }]
// - statusOf(event): what became of a message or a crew line ('queued', 'onboard', 'shared', 'local', ...)
// - today: { sentence, body, mind, ship, stale: [text], alerts: [{ id, level, title, text, time, indicator, system }] }
// - flagged: { indicator: level } from today's levels; notes: { indicator: words } such as "Common in flight"
// - storeKind: 'server', 'browser', 'memory' or 'waiting'
// - mission: { name, launch, landing, example } or null; flightDay: { words } or null; ship: the simulation switches
// - valueText(indicator, value): the screen's own words for a value (valueWords by default)
export function buildRecord({ person, history, events = [], unsent = [], statusOf = () => null, now = new Date(), mission = null, flightDay = null, today = null, flagged = {}, notes = {}, storeKind = 'memory', ship = {}, valueText = null } = {}) {
  if (!person || !person.id) throw new TypeError('buildRecord needs the signed-in person');
  if (typeof history !== 'function') throw new TypeError('buildRecord needs history(personId, indicator)');
  if (person.vehicle) throw new Error('The ship has no medical record: cabin air belongs to the whole crew.');
  const words = (ind, v) => (ind === 'weighing' || ind === 'cycle' || typeof valueText !== 'function' ? valueWords(ind, v) : valueText(ind, v));
  const mine = (events || []).filter((e) => e && e.person === person.id);
  const ctx = { person, history, words, now, flagged: flagged || {}, notes: notes || {}, events: mine, statusOf, ship };

  const sections = [];
  const add = (id, items, extra = {}) => sections.push({ id, ...SECTION_INFO[id], private: Boolean(SECTION_INFO[id].private), count: items.length, items, ...extra });

  if (person.real) {
    add('labs', labDraws(person, history), { empty: 'No lab results.' });
    add('documents', [
      { kind: 'doc', key: 'doc:osdr', id: 'osdr', title: 'The source data at NASA OSDR', detail: 'OSD-575 (metabolic panel) and OSD-569 (complete blood count): real, de-identified data of the Inspiration4 crew, kept in this program as a saved copy.', links: INSPIRATION4.source.urls.map((url, i) => ({ name: i === 0 ? 'OSD-575' : 'OSD-569', url })) },
      { kind: 'doc', key: 'doc:fhir', id: 'fhir', title: 'Export for medical records (HL7 FHIR R4)', detail: 'Not for this record: the real Inspiration4 records are NASA\'s data and are not exported as a patient record.', unavailable: true },
    ]);
  } else {
    const BODY_NUMBERS = CELLS.filter((c) => c.section === 'body' && c.kind === KIND.NUMBER).map((c) => c.indicator);
    const EYES = ['octChange', 'visionCheck', 'eyePressure', 'octScan', 'xray', 'ecg', 'ultrasound'];
    add('vitals', measureRows(VITAL_SIGNS, ctx), { empty: 'No vital signs yet.' });
    add('measures', measureRows(BODY_NUMBERS.filter((i) => !VITAL_SIGNS.includes(i) && !EYES.includes(i)), ctx), { empty: 'No other measures yet.' });
    add('labs', labDraws(person, history), { empty: 'No lab results in this record. The real blood tests of the Inspiration4 crew are under their own sign-in cards.' });
    add('eyes', entryRows(EYES, ctx), { empty: 'No eye checks, images or tracings yet.' });
    add('medicines', entryRows(['medicines'], ctx), { empty: 'No medicines logged.' });
    add('symptoms', entryRows(['symptoms'], ctx), { empty: 'No symptoms logged.' });
    add('alerts', alertRows(ctx), { empty: 'No alarm and no red limit crossed.', note: "Crewmates' screens got only the crew line, never the rest of this record (14 CFR 1214.403)." });
    add('encounters', encounterRows({ ...ctx, events: mine, unsent: (unsent || []).filter((u) => u && u.event && u.event.person === person.id) }), { empty: 'No messages sent.', note: 'Crewmates\' screens never get these. The automatic alarm messages are under "Alerts and what happened".' });
    const mind = measureRows(['mood', 'attitude', 'sleepQuality', 'cognition', 'reaction'], ctx);
    for (const r of mind) {
      const last = (history(person.id, r.indicator) || []).slice(-1)[0];
      // The mind rule's own low day (state-levels.js), a draft: a bad mood, or energy at the step that counts as low.
      if (r.indicator === 'mood' && last && last.value === 'bad') r.verdict = 'A low day for the mind rule (a draft)';
      if (r.indicator === 'attitude' && last && isLowEnergy(last.value)) r.verdict = 'A low day for the mind rule (a draft)';
      if (r.indicator !== 'reaction') continue;
      const ev = mine.filter((e) => e.kind === 'reading' && e.reading && e.reading.indicator === 'reaction' && e.reading.detail).sort((a, b) => ms(b.time) - ms(a.time))[0];
      if (ev && Number.isFinite(Number(ev.reading.detail.lapses))) r.verdict = `Median of your last test; ${plural(Number(ev.reading.detail.lapses), 'lapse')} (a response of 355 ms or more, PVT-B). Compared only with your own runs.`;
      else r.verdict = 'Median of your last test. Compared only with your own runs.';
    }
    // What was weighing on the person: the topics of the check-ins, by the days they were marked (support.js).
    const topics = topicCounts(history(person.id, 'weighing') || [], now, RECORD_RULES.mindDays);
    const mindFacts = topics.length ? [`What was weighing on you, the last ${RECORD_RULES.mindDays} days: ${topics.map((x) => `${x.label} (${plural(x.days, 'day')})`).join(', ')}.`] : [];
    add('mind', mind, { empty: 'No check-ins or tests yet.', facts: mindFacts, table: checkinDays({ person, history, now }), note: 'Your private journal and your plan for hard days are not part of this record: they stay in this browser (Mind support).' });
    const cycle = cyclePart(ctx);
    if (cycle) add('cycle', entryRows(['cycle'], ctx), { empty: 'Nothing logged.', facts: cycle.facts, flags: cycle.flags });
    add('documents', [
      { kind: 'doc', key: 'doc:fhir', id: 'fhir', title: 'Export for medical records (HL7 FHIR R4)', detail: 'Your number readings of the last 30 days, with LOINC codes and UCUM units, the way medical record systems read them; made-up data carry the HTEST test label. The private logs (medicines, symptoms, mind, cycle) are not in it.', action: 'Show the FHIR file' },
      { kind: 'doc', key: 'doc:copy', id: 'copy', title: 'A copy of all your records', detail: 'Every reading, answer and message of yours, and the ship\'s cabin readings, as one file (JSON lines). It holds the private parts too, so keep it safe. The made-up example flight is not part of it.', action: 'Save a copy' },
    ]);
  }
  sections.sort((a, b) => SECTION_ORDER.indexOf(a.id) - SECTION_ORDER.indexOf(b.id));

  return {
    header: headerOf({ person, history, mine, mission, flightDay, storeKind }),
    today: person.real ? realToday(person) : today ? { ...today, alerts: [...(today.alerts || [])] } : null,
    sections,
    notHeld: { text: NOT_HELD_TEXT, items: NOT_HELD, connection: CONNECTIONS.find((c) => c.id === NOT_HELD_CONNECTION) || null },
    sources: RECORD_SOURCES,
    privateNote: PRIVATE_NOTE,
  };
}

const SAVED = {
  server: 'Kept on the station computer, in one file named by this id.',
  browser: 'Kept in this browser only: this copy runs without the station server.',
  memory: 'Kept only until this page closes: this browser blocks storage.',
  waiting: 'The station server is not answering: what you enter now waits in this browser until it is back.',
};
function headerOf({ person, history, mine, mission, flightDay, storeKind }) {
  let readings = 0;
  let made = 0;
  if (!person.real) {
    for (const c of CELLS) {
      if (c.section === 'env') continue;
      for (const x of history(person.id, c.indicator) || []) { readings += 1; if (x.example) made += 1; }
    }
  }
  const messages = mine.filter((e) => e.kind === 'report').length;
  const lines = mine.filter((e) => e.kind === 'alarm').length;
  const sex = person.sex === 'F' ? 'Female' : person.sex === 'M' ? 'Male' : 'Not set';
  if (person.real) {
    const s = INSPIRATION4.subjects[person.code];
    const n = s ? INSPIRATION4.timepoints.filter((tp) => (s.panels[tp] || []).length).length : 0;
    return {
      name: person.name, kind: 'real', kindText: 'A real person, de-identified by NASA (OSDR)',
      facts: [
        ['Mission', `Inspiration4: launch ${fmtDay(I4_DATES.launch)}, return ${fmtDay(I4_DATES.landing)} (NASA OSDR)`],
        ['Sex', `${sex} (as NASA OSDR gives it)`],
        ['Record', `${person.code}: a saved copy of NASA OSDR data in this program (OSD-575, OSD-569)`],
        ['In this record', `${plural(n, 'blood draw')}; no other kind of data`],
      ],
    };
  }
  const missionText = mission
    ? `${mission.name || 'Our mission'}: launch ${fmtDay(mission.launch)}, landing ${fmtDay(mission.landing)}${mission.example ? '' : ' (GMT, set on this device)'}${flightDay && flightDay.words ? `. ${flightDay.words}` : ''}`
    : 'No mission is set on this device.';
  const counts = [
    readings ? `${thousands(readings)} ${readings === 1 ? 'reading' : 'readings'}${made ? `, ${made === readings ? 'all' : thousands(made)} of them made-up example data` : ''}` : 'no readings yet',
    plural(messages, 'message'),
    plural(lines, 'crew line'),
  ];
  return {
    name: person.name, kind: 'example', kindText: 'Example crew member: a made-up person',
    facts: [
      ['Mission', missionText],
      ['Sex', person.sex ? sex : 'Not set in this example'],
      ['Record', `${person.id}. ${SAVED[storeKind] || SAVED.memory}`],
      ['In this record', counts.join('; ')],
    ],
  };
}

function realToday(person) {
  const s = INSPIRATION4.subjects[person.code];
  const tps = s ? INSPIRATION4.timepoints.filter((tp) => (s.panels[tp] || []).length) : [];
  const last = tps.length ? (s.panels[tps[tps.length - 1]] || []).map(labValue).filter((x) => x.value !== null) : [];
  const outNow = last.filter((x) => x.out).length;
  return { real: true, sentence: 'Blood tests alone do not tell the condition of body and mind, so there is no status message here.', outNow, lastDraw: tps.length ? drawWords(tps[tps.length - 1]) : null, alerts: [] };
}
