// The topics of "What is weighing on you?", by their names on the check-in.
export function topicWords(value) {
  const ids = Array.isArray(value) ? value : typeof value === 'string' ? value.split(',') : [];
  const names = ids.map((x) => CHECKIN_TOPICS.find((t) => t.id === String(x).trim() || t.label.toLowerCase() === String(x).trim().toLowerCase())).filter(Boolean).map((t) => t.label);
  return names.length ? names.join(', ') : 'Nothing chosen';
}
// One cycle log entry. A value this module does not know (a newer kind of cycle entry) is still listed, never dropped.
export function cycleWords(value) {
  if (typeof value === 'string' && CYCLE_WORDS[value]) return CYCLE_WORDS[value];
  if (typeof value === 'string' && value.trim()) return `Cycle entry: ${value.trim().replace(/_/g, ' ')}`;
  return 'Cycle entry';
}

// A value in plain words, the same way the crew screen writes it (crew.js valueText), plus the topics and the cycle.
export function valueWords(indicator, value) {
  if (value === null || value === undefined) return '';
  if (indicator === 'weighing') return topicWords(value);
  if (indicator === 'cycle') return cycleWords(value);
  const logged = logText(indicator, value);
  if (logged !== null && logged !== undefined) return logged;
  if (indicator === 'cognition' && typeof value === 'number') return `${Math.round(value)} ms`;
  if (indicator === 'bp' && value && typeof value === 'object') return `${value.sys}/${value.dia}`;
  if (indicator === 'camera') return CAMERA_WORDS[value] || String(value);
  if (indicator === 'attitude') return fatigueWords(value);
  if (indicator === 'bone' && value && typeof value === 'object') return `${value.hipSpine}% and ${value.neck}%`;
  if (typeof value === 'object') return 'A value of several parts';
  const n = Number(value);
  return Number.isFinite(n) && String(value).trim() !== '' ? String(Math.round(n * 10) / 10) : String(value);
}

// Where one reading came from, in a few words: a device, a file, a feed, the person, NASA's data, or made-up example.
const OWN_LOGS = new Set(['symptoms', 'medicines', 'cycle']);
export function sourceWords(entry, indicator = null) {
  if (!entry) return '';
  if (entry.example) return 'Made-up example data';
  if (entry.source === 'help-key') return 'The Help key';
  if (entry.source === 'false-alarm') return 'Your own answer';
  const info = sourceInfo(entry.source);
  if (info.origin === 'self') return OWN_LOGS.has(indicator) ? 'Your own entry' : 'Your own answer';
  if (info.origin === 'typed') return 'Typed in by hand';
  if (info.origin === 'dataset') return 'NASA OSDR, Inspiration4 (real data)';
  if (info.origin === 'unknown') return 'Source not recorded';
  return info.label;
}

const limitWords = (red) => `${({ atOrBelow: 'at or below', atOrAbove: 'at or above', below: 'below', above: 'above' })[red.when] || red.when} ${red.value}`;
// What one reading of a number measure was, against its norm, its red limits and, for the OCT, NASA's two levels.
export function readingVerdict(cell, entry) {
  if (!cell || !entry) return { text: '', level: LEVEL.FINE, out: null };
  if (entry.red) {
    const level = RED_LEVEL[entry.red.level] || LEVEL.ACTION;
    return { level, out: entry.side || null, text: `${cap(limitWords(entry.red))}${entry.red.part ? ` (${entry.red.part === 'sys' ? 'systolic' : 'diastolic'})` : ''}: past the ${level >= LEVEL.URGENT ? 'urgent' : 'needs-action'} limit (a draft; ${entry.red.source})` };
  }
  if (cell.thresholds && Number.isFinite(Number(entry.value))) {
    const v = Number(entry.value);
    const steps = [...cell.thresholds].sort((a, b) => b.min - a.min);
    const hit = steps.find((t) => v >= t.min);
    const low = steps[steps.length - 1];
    return { level: LEVEL.FINE, out: hit ? 'above' : null, text: hit ? `At or above ${hit.min} ${cell.unit}: NASA's ${hit.text} (a draft)` : `Below ${low.min} ${cell.unit}, NASA's ${low.text} (a draft)` };
  }
  if (entry.context === 'exercise' && entry.status !== STATUS.OUT) return { level: LEVEL.FINE, out: null, text: 'Taken during exercise: recorded, not judged' };
  if (cell.normType === 'baseline-percent') {
    const words = `${cell.norm.minPercent}% of your own pre-flight level (NASA standard)`;
    return entry.status === STATUS.OUT ? { level: LEVEL.FINE, out: 'below', text: `Below ${words}` } : entry.status === STATUS.OK ? { level: LEVEL.FINE, out: null, text: `At or above ${words}` } : { level: LEVEL.FINE, out: null, text: 'Recorded' };
  }
  if (cell.normType === 'min-parts') return entry.status === STATUS.OUT ? { level: LEVEL.FINE, out: 'below', text: 'Below the NASA minimum' } : { level: LEVEL.FINE, out: null, text: 'At or above the NASA minimum' };
  if (entry.status === STATUS.OUT) return { level: LEVEL.FINE, out: entry.side || null, text: entry.side === 'below' ? 'Below the normal range' : 'Above the normal range' };
  if (entry.status === STATUS.OK) return { level: LEVEL.FINE, out: null, text: 'Within the normal range' };
  return { level: LEVEL.FINE, out: null, text: 'Recorded' };
}

// ---------- the parts of the record ----------
const newestFirst = (a, b) => ms(b.time) - ms(a.time) || String(a.key).localeCompare(String(b.key));
const hasCell = (ind) => Boolean(cellOf[ind]);

// One row per measure: its latest reading, how many there are, where the latest came from, and today's level.
// A plain "within the normal range" or "recorded" is left out, as on All measures, where a fine row carries no word;
// notes: today's own words for a measure (common in flight, watched, a forecast), from the crew screen's levels.
const PLAIN = new Set(['Within the normal range', 'Recorded']);
function measureRows(indicators, { person, history, words, flagged, notes = {} }) {
  const rows = [];
  for (const ind of indicators) {
    if (!hasCell(ind)) continue;
    const cell = cellOf[ind];
    const list = history(person.id, ind) || [];
    if (!list.length) continue;
    const last = list[list.length - 1];
    const v = cell.kind === KIND.NUMBER ? readingVerdict(cell, last) : { text: '', level: LEVEL.FINE, out: null };
    // A word answer starts with a capital letter, as on the measure's own page; the sleep rating is "6 of 7".
    const raw = words(ind, last.value);
    const value = ind === 'sleepQuality' ? `${raw} of 7` : cell.kind === KIND.NUMBER ? raw : cap(String(raw));
    rows.push({
      kind: 'measure', key: `m:${ind}`, indicator: ind, title: cell.label, value, unit: cell.kind === KIND.NUMBER ? (cell.unit || '') : '',
      time: iso(last.time), source: sourceWords(last, ind), example: Boolean(last.example), count: list.length,
      out: v.out, verdict: [PLAIN.has(v.text) ? '' : v.text, notes[ind] || ''].filter(Boolean).join('; '), level: flagged[ind] || LEVEL.FINE,
      link: { to: 'measure', indicator: ind },
    });
  }
  return rows.sort(newestFirst);
}

// Every entry of some measures, newest first: for the eyes, images and the private logs. Shorter names for the list.
const ENTRY_TITLE = { octChange: 'OCT: retinal thickness change', octScan: 'OCT image of the retina', eyePressure: 'Eye pressure' };
function entryRows(indicators, { person, history, words }) {
  const out = [];
  for (const ind of indicators) {
    if (!hasCell(ind)) continue;
    const cell = cellOf[ind];
    (history(person.id, ind) || []).forEach((x, i) => {
      const base = { kind: 'entry', key: `e:${ind}:${iso(x.time)}:${i}`, indicator: ind, time: iso(x.time), source: sourceWords(x, ind), example: Boolean(x.example) };
      if (cell.kind === KIND.COMPLEX) {
        out.push({ ...base, icon: ind === 'ecg' ? 'chart-line' : 'scan-line', title: `${ENTRY_TITLE[ind] || cell.label}: received`, detail: 'Needs analysis by the AI or a doctor; which one, and when, is the team\'s open question.', link: { to: 'complex', indicator: ind } });
      } else if (ind === 'visionCheck') {
        const a = (cell.answers || []).find((y) => y.value === x.value);
        const tell = cell.tellDoctor && cell.tellDoctor.values.includes(x.value);
        out.push({ ...base, icon: 'eye', title: `Eye self-check: ${a ? a.short : String(x.value)}`, detail: tell ? 'Worth telling your flight surgeon (a draft rule).' : '', out: tell ? 'changed' : null, link: { to: 'measure', indicator: ind } });
      } else if (cell.kind === KIND.NUMBER) {
        const v = readingVerdict(cell, x);
        const value = ind === 'octChange' && Number(x.value) > 0 ? `+${words(ind, x.value)}` : words(ind, x.value);
        out.push({ ...base, icon: 'eye', title: `${ENTRY_TITLE[ind] || cell.label}: ${value} ${cell.unit || ''}`.trim(), detail: v.text, out: v.out, level: x.red ? v.level : LEVEL.FINE, link: { to: 'measure', indicator: ind } });
      } else {
        out.push({ ...base, icon: ind === 'medicines' ? 'pill' : ind === 'symptoms' ? 'stethoscope' : 'calendar-heart', title: words(ind, x.value), detail: '', link: { to: ind === 'cycle' ? 'cycle' : 'measure', indicator: ind } });
      }
    });
  }
  return out.sort(newestFirst);
}

// The Inspiration4 blood draws: dates from NASA OSDR's own record of OSD-575 ("Mission Start 09/16/2021", "Mission
// End 09/18/2021"), counted from midday, the same dates as src/crew.js. Each value against the lab range of its row.
export const I4_DATES = Object.freeze({ launch: '2021-09-16T12:00:00Z', landing: '2021-09-18T12:00:00Z' });
const TEST_NAMES = { CMP: 'Metabolic panel (CMP, OSD-575)', CBC: 'Complete blood count (CBC, OSD-569)' };
export function drawTime(tp) {
  const m = /^([LR])([+-])(\d+)$/.exec(String(tp));
  if (!m) return null;
  return iso(ms(m[1] === 'L' ? I4_DATES.launch : I4_DATES.landing) + (m[2] === '+' ? 1 : -1) * Number(m[3]) * DAY);
}
export function drawWords(tp) {
  const m = /^([LR])([+-])(\d+)$/.exec(String(tp));
  if (!m) return String(tp);
  return m[1] === 'L' ? `${plural(Number(m[3]), 'day')} before launch` : `${plural(Number(m[3]), 'day')} after return`;
}
const outOfRange = (v, min, max) => (min !== null && min !== undefined && v < min ? 'below' : max !== null && max !== undefined && v > max ? 'above' : null);
const labValue = (a) => {
  const v = Number(a.value);
  return { code: a.code, name: a.nameEn || a.name, test: a.test || '', value: Number.isFinite(v) ? v : null, units: a.units || '', min: a.min ?? null, max: a.max ?? null, out: Number.isFinite(v) ? outOfRange(v, a.min, a.max) : null };
};
function labDraws(person, history) {
  const draws = [];
  if (person.real && person.code && INSPIRATION4.subjects[person.code]) {
    const s = INSPIRATION4.subjects[person.code];
    for (const tp of INSPIRATION4.timepoints) {
      const values = (s.panels[tp] || []).map(labValue).filter((x) => x.value !== null);
      if (!values.length) continue;
      draws.push({ kind: 'draw', key: `d:${tp}`, time: drawTime(tp), title: `Blood draw, ${drawWords(tp)}`, timepoint: tp, values, groups: groupTests(values), outCount: values.filter((x) => x.out).length, source: 'NASA OSDR, Inspiration4 (real data)', example: false, link: { to: 'blood' } });
    }
  }
  // A blood panel sent for a crew member (the technical view can send one): the same shape, from the machine.
  (history(person.id, 'blood') || []).forEach((x, i) => {
    const values = (x.value && Array.isArray(x.value.analytes) ? x.value.analytes : []).map(labValue).filter((y) => y.value !== null);
    if (!values.length) return;
    draws.push({ kind: 'draw', key: `d:m:${iso(x.time)}:${i}`, time: iso(x.time), title: `Blood test${x.value.timepoint ? `, ${drawWords(x.value.timepoint)}` : ''}`, values, groups: groupTests(values), outCount: values.filter((y) => y.out).length, source: sourceWords(x, 'blood'), example: Boolean(x.example), link: null });
  });
  return draws.sort(newestFirst);
}
function groupTests(values) {
  const map = new Map();
  for (const v of values) {
    const k = v.test || 'other';
    if (!map.has(k)) map.set(k, { test: k, title: TEST_NAMES[k] || (v.test ? `Test ${v.test}` : 'Other values'), values: [] });
    map.get(k).values.push(v);
  }
  return [...map.values()];
}

