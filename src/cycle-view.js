// The cycle log on the crew screen: a month calendar of the logged days (move between months), the day editor (how
// much bleeding, which symptoms, for today or any day back to the limit, never a future day), the cycle history
// with its averages, and where the rules come from. The rules live in src/cycle-log.js and src/cycle.js.
// Framework-free, like src/quicklog.js: it draws plain DOM with the crew screen's classes (the calendar's own in
// cycle.css) into a host element and calls onSave(value) to save a day. Colour never carries the meaning alone:
// each day says in words what was logged (its label for a screen reader, the word under the number on a wide
// screen) and shows marks of different shapes, explained in the legend under the calendar.
// What the person picked but has not saved stays with that person only while they are signed in (resetCycleView).
// Code generated by Claude (Anthropic), an AI system.
import { FLOWS, CYCLE_SYMPTOMS, LOG_RULES, LOG_SOURCES, WEEKDAYS, MONTHS, dayOf, dayMs, dayWords, monthOf, addMonths, addDays, monthGrid, editWindow, dayProblem, suppressedOn, flowOf, entryWords, cycleValue } from './cycle-log.js';

// Person id -> what the calendar shows: { month, day (the day in the editor), focus (the day the keyboard is on),
// draft (unsaved choices for day), status, all (the whole history), ctx (the latest drawing's inputs) }.
const views = new Map();
export function resetCycleView() { views.clear(); }

const SHORT_WORD = { spotting: 'Spot', light: 'Light', medium: 'Medium', heavy: 'Heavy' };
const HISTORY_ROWS = 6;

function make(doc, tag, props = {}, ...kids) {
  const node = doc.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v === null || v === undefined || v === false) continue;
    if (k === 'class') node.className = v;
    else if (k === 'hidden') node.hidden = true;
    else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2), v);
    else node.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of kids.flat()) {
    if (c === null || c === undefined || c === false) continue;
    node.append(typeof c === 'string' ? doc.createTextNode(c) : c);
  }
  return node;
}

const sameList = (a, b) => a.length === b.length && a.every((x, i) => x === b[i]);
// 0 for Monday to 6 for Sunday.
const weekday = (day) => (new Date(dayMs(day)).getUTCDay() + 6) % 7;
const monthShort = (month) => MONTHS[Number(month.slice(5)) - 1].slice(0, 3);

// host: the element to draw into. person: { id }. summary: cycleSummary(...) of the person's log. now: the screen's
// time. onSave(value) saves one day and resolves to { ok, waiting }; it may throw. icon(name, opts): optional, the
// crew screen's icons. Returns { redraw }.
export function drawCycleLog(host, { person, summary, now, onSave, icon = null }) {
  if (typeof onSave !== 'function') throw new TypeError('drawCycleLog needs onSave');
  const w = editWindow(now);
  let st = views.get(person.id);
  if (!st) {
    st = { month: monthOf(w.today), day: w.today, focus: w.today, draft: null, status: '', all: false, sourcesOpen: false };
    views.set(person.id, st);
  }
  st.ctx = { host, summary, now, onSave, icon };
  const redraw = (focusKey = null) => draw(st, focusKey);
  st.redraw = redraw;
  draw(st);
  return { redraw };
}

function draw(st, focusKey = null) {
  const { host, summary, now, icon } = st.ctx;
  const doc = host.ownerDocument;
  const active = doc.activeElement;
  const inside = active && typeof host.contains === 'function' && host.contains(active);
  const key = focusKey || (inside && typeof active.getAttribute === 'function' ? active.getAttribute('data-fk') : null);
  host.replaceChildren(calendar(doc, st, summary, now, icon), editor(doc, st, summary, now), history(doc, st, summary), sources(doc, st));
  if (key && typeof host.querySelector === 'function') {
    const el = host.querySelector(`[data-fk="${key}"]`);
    if (el && typeof el.focus === 'function') el.focus({ preventScroll: true });
  }
}

// ---------- the month ----------
function monthRange(summary, w) {
  const logged = [...summary.log.days.keys()].sort();
  const min = [monthOf(w.first), logged.length ? monthOf(logged[0]) : monthOf(w.first)].sort()[0];
  const est = summary.nextExpected ? dayOf(summary.nextExpected) : null;
  const next = addMonths(monthOf(w.today), 1);
  const max = est && monthOf(est) >= next ? next : monthOf(w.today);
  return { min, max };
}

function calendar(doc, st, summary, now, icon) {
  const w = editWindow(now);
  const range = monthRange(summary, w);
  if (st.month < range.min) st.month = range.min;
  if (st.month > range.max) st.month = range.max;
  const grid = monthGrid(st.month);
  const est = summary.nextExpected && !summary.suppressed ? dayOf(summary.nextExpected) : null;
  const inMonth = (d) => d && monthOf(d) === st.month;
  // The one day of the month the Tab key lands on (a roving tab stop): the keyboard's day, else the editor's day,
  // else today, else the last day of the month that can be chosen.
  const choosable = grid.weeks.flat().filter((d) => d && d <= w.today);
  const tabDay = [st.focus, st.day, w.today].find((d) => inMonth(d) && d <= w.today) || choosable[choosable.length - 1] || null;
  const move = (n) => {
    const m = addMonths(st.month, n);
    if (m < range.min || m > range.max) return;
    st.month = m;
    st.redraw(n < 0 ? 'cyc:prev' : 'cyc:next');
  };
  const navBtn = (n, label, m) => make(doc, 'button', {
    type: 'button', class: 'btn secondary small', 'data-fk': n < 0 ? 'cyc:prev' : 'cyc:next',
    'aria-label': `${label}: ${monthGrid(m).title}`, 'aria-disabled': m < range.min || m > range.max ? 'true' : null, onclick: () => move(n),
  }, n < 0 && icon ? icon('chevron-left', { size: 18 }) : null, monthShort(m), n > 0 && icon ? icon('chevron-right', { size: 18 }) : null);

  const cell = (day) => {
    if (!day) return make(doc, 'td', { class: 'cyc-empty' });
    const n = String(Number(day.slice(8)));
    // A day still to come cannot be pressed; the estimated start of the next period is marked on it.
    if (day > w.today) {
      return make(doc, 'td', {}, make(doc, 'span', { class: `cyc-day cyc-future${day === est ? ' cyc-est' : ''}` }, make(doc, 'span', { class: 'cyc-n' }, n),
        day === est ? make(doc, 'span', { class: 'cyc-w', 'aria-hidden': 'true' }, 'Est.') : null,
        day === est ? make(doc, 'span', { class: 'sr-only' }, ', the estimated start of your next period, a plain average') : null));
    }
    const entry = summary.log.days.get(day) || null;
    const suppressed = suppressedOn(day, summary.log.suppression);
    const flow = entry ? entry.flow : undefined;
    const blood = entry && flow !== 'none';
    const classes = ['cyc-day'];
    if (blood && suppressed) classes.push('cyc-btb');
    else if (blood && flow !== 'spotting') classes.push('cyc-bleed');
    if (flow === 'spotting') classes.push('cyc-spot');
    if (entry && flow === null) classes.push('cyc-old');
    if (entry && entry.symptoms.length) classes.push('cyc-sym');
    if (day === w.today) classes.push('cyc-today');
    if (day === est) classes.push('cyc-est');
    if (day < w.first) classes.push('cyc-locked');
    const words = [dayWords(day, { long: true }), day === w.today ? 'today' : null, entry ? entryWords(entry, { suppressed }) : 'nothing logged', day === est ? 'estimated start of your next period (a plain average)' : null, day < w.first ? `not within the last ${LOG_RULES.backDays} days, cannot be changed` : null].filter(Boolean);
    const marks = make(doc, 'span', { class: 'cyc-marks', 'aria-hidden': 'true' });
    if (entry && flow === null) marks.append(make(doc, 'span', { class: 'cyc-bar' }));
    else if (flow === 'spotting') marks.append(make(doc, 'span', { class: 'cyc-ring' }));
    else if (entry && flowOf(flow) && flowOf(flow).marks) for (let i = 0; i < flowOf(flow).marks; i += 1) marks.append(make(doc, 'span', { class: 'cyc-drop' }));
    const word = entry && flow === null ? 'Period' : SHORT_WORD[flow] || (day === est ? 'Est.' : day === w.today ? 'Today' : '');
    return make(doc, 'td', {}, make(doc, 'button', {
      type: 'button', class: classes.join(' '), 'data-fk': `cyc:day:${day}`, tabindex: day === tabDay ? '0' : '-1',
      'aria-pressed': String(day === st.day), 'aria-current': day === w.today ? 'date' : null, 'aria-label': words.join(', '),
      onclick: () => choose(st, day), onkeydown: (e) => keyMove(st, e, day, w, range),
    }, make(doc, 'span', { class: 'cyc-n', 'aria-hidden': 'true' }, n), marks, word ? make(doc, 'span', { class: 'cyc-w', 'aria-hidden': 'true' }, word) : null));
  };

  const shownSuppressed = grid.weeks.flat().some((d) => d && d <= w.today && suppressedOn(d, summary.log.suppression));
  const legend = make(doc, 'ul', { class: 'cyc-legend' },
    make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key', 'aria-hidden': 'true' }, make(doc, 'span', { class: 'cyc-drop' })), '1, 2 or 3 drops: light, medium or heavy flow'),
    make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key', 'aria-hidden': 'true' }, make(doc, 'span', { class: 'cyc-ring' })), 'ring: spotting'),
    make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key', 'aria-hidden': 'true' }, make(doc, 'span', { class: 'cyc-bar' })), 'bar: a period day of the old buttons, flow not logged'),
    make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key cyc-sym', 'aria-hidden': 'true' }), 'dot in the corner: symptoms'),
    make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key cyc-today', 'aria-hidden': 'true' }), 'frame: today'),
    est ? make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key cyc-est', 'aria-hidden': 'true' }), 'dashed frame: the estimated start of your next period, a plain average') : null,
    shownSuppressed ? make(doc, 'li', {}, make(doc, 'span', { class: 'cyc-key cyc-btb', 'aria-hidden': 'true' }), 'stripes: bleeding while your periods were suppressed') : null);

  return make(doc, 'section', { class: 'cyc-cal', 'aria-labelledby': 'cyc-month' },
    make(doc, 'div', { class: 'cyc-head' },
      navBtn(-1, 'Previous month', addMonths(st.month, -1)),
      make(doc, 'h3', { id: 'cyc-month' }, grid.title),
      navBtn(1, 'Next month', addMonths(st.month, 1))),
    make(doc, 'table', { class: 'cyc-grid', 'aria-labelledby': 'cyc-month' },
      make(doc, 'thead', {}, make(doc, 'tr', {}, ...WEEKDAYS.map((d) => make(doc, 'th', { scope: 'col', abbr: d }, d.slice(0, 3))))),
      make(doc, 'tbody', {}, ...grid.weeks.map((week) => make(doc, 'tr', {}, ...week.map(cell))))),
    make(doc, 'p', { class: 'note' }, `Press a day to log it: today and the ${LOG_RULES.backDays - 1} days before (a draft limit), never a day still to come. Arrow keys move between days.`),
    legend);
}

// Arrow keys move the keyboard between days, Page Up and Page Down by a month, Home and End to the week's ends;
// Enter or Space opens the day in the editor. A day still to come is never reached.
function keyMove(st, e, day, w, range) {
  const steps = { ArrowLeft: -1, ArrowRight: 1, ArrowUp: -7, ArrowDown: 7 };
  let target = null;
  if (steps[e.key]) target = addDays(day, steps[e.key]);
  else if (e.key === 'Home') target = addDays(day, -weekday(day));
  else if (e.key === 'End') target = addDays(day, 6 - weekday(day));
  else if (e.key === 'PageUp' || e.key === 'PageDown') {
    const m = addMonths(monthOf(day), e.key === 'PageUp' ? -1 : 1);
    const last = Number(addDays(`${addMonths(m, 1)}-01`, -1).slice(8));
    target = `${m}-${String(Math.min(Number(day.slice(8)), last)).padStart(2, '0')}`;
  } else return;
  if (e.preventDefault) e.preventDefault();
  if (target > w.today) target = w.today;
  if (monthOf(target) < range.min) return;
  st.focus = target;
  st.month = monthOf(target);
  st.redraw(`cyc:day:${target}`);
}

function choose(st, day) {
  if (day === st.day) return;
  const dirty = st.draft && st.draft.day === st.day && changed(st, st.ctx.summary);
  st.status = dirty ? `Your choice for ${dayWords(st.day)} was not saved.` : '';
  st.day = day;
  st.focus = day;
  st.draft = null;
  st.redraw(`cyc:day:${day}`);
}

// ---------- the day editor ----------
const savedOf = (summary, day) => summary.log.days.get(day) || null;
function current(st, summary) {
  if (st.draft && st.draft.day === st.day) return st.draft;
  const saved = savedOf(summary, st.day);
  return { day: st.day, flow: saved ? saved.flow : null, symptoms: saved ? [...saved.symptoms] : [] };
}
function changed(st, summary) {
  const saved = savedOf(summary, st.day);
  const c = current(st, summary);
  return !saved ? c.flow !== null || c.symptoms.length > 0 : c.flow !== saved.flow || !sameList(c.symptoms, saved.symptoms);
}

function editor(doc, st, summary, now) {
  const day = st.day;
  const why = dayProblem(day, now);
  const saved = savedOf(summary, day);
  const suppressed = suppressedOn(day, summary.log.suppression);
  const today = day === dayOf(now);
  const title = make(doc, 'h3', { id: 'cyc-edit' }, dayWords(day, { long: true }), today ? make(doc, 'span', { class: 'muted' }, ' (today)') : null);
  const savedLine = make(doc, 'p', { class: 'note' }, saved ? `Logged: ${entryWords(saved, { suppressed })}.` : 'Nothing logged for this day.',
    saved && saved.flow === null ? ' It was marked with the old buttons "Period started today" and "Period ended today", which did not ask for the flow.' : '');
  if (why) {
    return make(doc, 'section', { class: 'cyc-edit', 'aria-labelledby': 'cyc-edit' }, title, savedLine,
      make(doc, 'p', { class: 'note' }, why === 'too-old' ? `This day is not within the last ${LOG_RULES.backDays} days: it stays as logged and can no longer be changed here (a draft limit).` : 'This day cannot be logged.'));
  }
  const c = current(st, summary);
  const setDraft = (next) => { st.draft = { day, ...next }; st.status = ''; };
  const flowBtn = (f) => make(doc, 'div', { class: 'seg' }, make(doc, 'button', {
    type: 'button', 'aria-pressed': String(c.flow === f.key), 'data-fk': `cyc:flow:${f.key}`,
    onclick: () => { setDraft({ flow: c.flow === f.key ? null : f.key, symptoms: c.symptoms }); st.redraw(`cyc:flow:${f.key}`); },
  }, c.flow === f.key && st.ctx.icon ? st.ctx.icon('check', { size: 16 }) : null, f.label));
  const symBtn = (s) => {
    const on = c.symptoms.includes(s.key);
    return make(doc, 'div', { class: 'seg' }, make(doc, 'button', {
      type: 'button', 'aria-pressed': String(on), 'data-fk': `cyc:sym:${s.key}`, 'aria-label': s.hint ? `${s.label}, ${s.hint}` : null,
      onclick: () => { setDraft({ flow: c.flow, symptoms: CYCLE_SYMPTOMS.map((x) => x.key).filter((k) => (k === s.key ? !on : c.symptoms.includes(k))) }); st.redraw(`cyc:sym:${s.key}`); },
    }, on && st.ctx.icon ? st.ctx.icon('check', { size: 16 }) : null, s.label));
  };
  const heavyNote = c.flow === 'heavy' || c.symptoms.includes('clots')
    ? make(doc, 'p', { class: 'note' }, 'CDC lists as signs of heavy menstrual bleeding: a new pad or tampon after less than 2 hours, clots the size of a quarter or larger, a period of more than 7 days. ', make(doc, 'a', { href: LOG_SOURCES.cdcHeavy.url, target: '_blank', rel: 'noopener' }, LOG_SOURCES.cdcHeavy.name))
    : null;
  const save = async () => {
    const value = cycleValue({ day, flow: c.flow, symptoms: c.symptoms }, new Date());
    if (c.flow === null) { st.status = 'Choose how much you bled first, or "No bleeding".'; st.redraw('cyc:save'); return; }
    if (!value) { st.status = 'This day can no longer be logged.'; st.redraw('cyc:save'); return; }
    if (!changed(st, summary)) { st.status = `Nothing changed for ${dayWords(day)}.`; st.redraw('cyc:save'); return; }
    await send(st, value, `Saved ${dayWords(day)}: ${entryWords(value, { suppressed })}.`);
  };
  const clear = async () => { await send(st, { day, flow: 'none', symptoms: [] }, `Cleared ${dayWords(day)}: nothing logged for it now.`); };
  return make(doc, 'section', { class: 'cyc-edit', 'aria-labelledby': 'cyc-edit' }, title, savedLine,
    make(doc, 'div', { class: 'q' },
      make(doc, 'div', { class: 'q-label', id: 'cyc-flow' }, suppressed ? 'Bleeding while your periods are suppressed ' : 'Bleeding ', make(doc, 'span', {}, 'one a day: the heavier one if there were two')),
      make(doc, 'div', { class: 'chips', role: 'group', 'aria-labelledby': 'cyc-flow' }, ...FLOWS.map(flowBtn)),
      make(doc, 'p', { class: 'note' }, 'Spotting: a few drops, no pad, tampon or cup needed. Light, medium and heavy: compared with your own usual flow (Creinin and others, 2022).'),
      suppressed ? make(doc, 'p', { class: 'note' }, 'Bleeding now is breakthrough bleeding, which hormones can cause (ACOG). It is worth logging: the US systems on the ISS that reclaim water from urine were not designed for menstrual blood (Jain and Wotring, 2016).') : null),
    make(doc, 'div', { class: 'q' },
      make(doc, 'div', { class: 'q-label', id: 'cyc-sym' }, 'Symptoms ', make(doc, 'span', {}, 'pick any; mood and energy come from your check-in')),
      make(doc, 'div', { class: 'chips', role: 'group', 'aria-labelledby': 'cyc-sym' }, ...CYCLE_SYMPTOMS.map(symBtn))),
    heavyNote,
    make(doc, 'div', { class: 'actions' },
      make(doc, 'button', { type: 'button', class: 'btn primary', 'data-fk': 'cyc:save', onclick: save }, `Save ${dayWords(day).split(' ').slice(0, 3).join(' ')}`),
      saved ? make(doc, 'button', { type: 'button', class: 'btn secondary', 'data-fk': 'cyc:clear', onclick: clear }, 'Clear this day') : null),
    st.status ? make(doc, 'p', { class: 'note cyc-status' }, st.status) : null);
}

let busy = false;
async function send(st, value, doneText) {
  if (busy) return;
  busy = true;
  try {
    const res = await st.ctx.onSave(value);
    if (res && res.ok === false) throw new Error('not saved');
    st.draft = null;
    st.status = `${doneText}${res && res.waiting ? ' Kept in this browser until the station server answers.' : ''} Private: not sent to anyone.`;
  } catch {
    st.status = 'Not saved. Your choice is kept: try again.';
  } finally {
    busy = false;
  }
  st.redraw('cyc:save');
}

// ---------- the history ----------
function history(doc, st, summary) {
  const periods = [...summary.periods].reverse();
  const shown = st.all ? periods : periods.slice(0, HISTORY_ROWS);
  const head = make(doc, 'h3', { id: 'cyc-hist' }, 'Your periods');
  if (!periods.length) return make(doc, 'section', { class: 'cyc-hist', 'aria-labelledby': 'cyc-hist' }, head, make(doc, 'p', { class: 'note' }, 'No period logged yet. A period starts on its first day of bleeding; spotting alone does not start one.'));
  const length = (p) => (p.length !== null ? `${p.length} ${p.length === 1 ? 'day' : 'days'}` : p.ongoing ? `${p.soFar} ${p.soFar === 1 ? 'day' : 'days'} so far` : 'end not logged');
  // The newest period has no next one yet: its cycle is still going on.
  const cycle = (p, i) => {
    if (i === 0) return summary.cycleDay ? `day ${summary.cycleDay}, going on` : summary.suppressedSince ? 'suppression began after it' : '';
    return p.acrossSuppression ? 'not counted: suppression in between' : `${p.cycle} days`;
  };
  const avg = [
    summary.average ? `Average cycle ${summary.average} days (the last ${Math.min(6, summary.lengths.length)} counted)` : 'An average cycle needs two periods in a row',
    summary.periodDays ? `period about ${summary.periodDays} days` : null,
    summary.nextExpected ? `next period expected around ${dayWords(dayOf(summary.nextExpected))}: a plain average, not a medical model` : null,
  ].filter(Boolean).join(' · ');
  return make(doc, 'section', { class: 'cyc-hist', 'aria-labelledby': 'cyc-hist' }, head,
    make(doc, 'p', { class: 'note' }, `${avg}.`),
    make(doc, 'div', { class: 'table-wrap' }, make(doc, 'table', {},
      make(doc, 'caption', { class: 'sr-only' }, 'Your periods, newest first: the first day, how long it lasted, and the cycle to the next period'),
      make(doc, 'thead', {}, make(doc, 'tr', {}, make(doc, 'th', { scope: 'col' }, 'Started'), make(doc, 'th', { scope: 'col' }, 'Period'), make(doc, 'th', { scope: 'col' }, 'Cycle'))),
      make(doc, 'tbody', {}, ...shown.map((p, i) => make(doc, 'tr', {}, make(doc, 'td', {}, dayWords(p.start)), make(doc, 'td', {}, length(p)), make(doc, 'td', {}, cycle(p, i))))))),
    periods.length > HISTORY_ROWS ? make(doc, 'div', { class: 'actions' }, make(doc, 'button', {
      type: 'button', class: 'btn secondary small', 'data-fk': 'cyc:all', 'aria-expanded': String(st.all), onclick: () => { st.all = !st.all; st.redraw('cyc:all'); },
    }, st.all ? `Show the last ${HISTORY_ROWS}` : `Show all ${periods.length}`)) : null);
}

// ---------- where the rules come from ----------
function sources(doc, st) {
  const list = [LOG_SOURCES.acogAub, LOG_SOURCES.creinin, LOG_SOURCES.acogPms, LOG_SOURCES.acogPain, LOG_SOURCES.owhPms, LOG_SOURCES.medlinePms, LOG_SOURCES.cdcHeavy, LOG_SOURCES.jain2016, LOG_SOURCES.floFlow, LOG_SOURCES.floSpotting, LOG_SOURCES.floEdit];
  const box = make(doc, 'details', { class: 'more', open: st.sourcesOpen ? true : null, ontoggle: (e) => { st.sourcesOpen = Boolean(e.target && e.target.open); } },
    make(doc, 'summary', {}, st.ctx.icon ? st.ctx.icon('chevron-right', { size: 18 }) : null, 'Where the log and its rules come from'),
    make(doc, 'div', {},
      make(doc, 'p', { class: 'note' }, `Drafts for the team and the flight surgeons: a day can be logged back to ${LOG_RULES.backDays - 1} days before today; bleeding or spotting days with at most ${LOG_RULES.gapDays} day without either between them count as one episode (2 full days end it); a period starts on its first day of bleeding and lasts to its last day of bleeding or spotting; spotting apart from periods is noted; while periods are suppressed, bleeding is counted over the last ${LOG_RULES.referenceDays} days. There are no fertility or ovulation features.`),
      make(doc, 'ul', { class: 'links' }, ...list.map((s) => make(doc, 'li', {}, make(doc, 'a', { href: s.url, target: '_blank', rel: 'noopener' }, s.name))))));
  return box;
}
