// Space weather from NOAA's public Space Weather Prediction Center: an Earth demo, off by default, that needs the
// internet. It shows the solar radiation storm level (NOAA S-scale) and the latest alert. It is a public measurement
// from a GOES satellite, not the crew's own dose: on board, the station's radiation instruments and the crew's
// dosimeters come first (NASA's radiation team, SRAG, combines NOAA forecasts with them:
// https://srag.jsc.nasa.gov/spaceradiation/how/how.cfm). Nothing here is saved as a reading.
//
// Data, keyless JSON, CORS open to any page (tested tonight: Access-Control-Allow-Origin "*"):
// - GOES integral protons, last day, 5-minute values per energy:
//   https://services.swpc.noaa.gov/json/goes/primary/integral-protons-1-day.json
// - Alerts, watches and warnings as issued: https://services.swpc.noaa.gov/products/alerts.json
// - NOAA's own current scale levels: https://services.swpc.noaa.gov/products/noaa-scales.json
// S-scale: solar radiation storms by the flux of particles of 10 MeV or more: S1 Minor at 10, S2 Moderate at 100,
// S3 Strong at 1,000, S4 Severe at 10,000, S5 Extreme at 100,000 (NOAA Space Weather Scales,
// https://www.swpc.noaa.gov/noaa-scales-explanation , now served from https://www.spaceweather.gov/noaa-scales-explanation).
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".

export const SWPC = {
  protons: 'https://services.swpc.noaa.gov/json/goes/primary/integral-protons-1-day.json',
  alerts: 'https://services.swpc.noaa.gov/products/alerts.json',
  scales: 'https://services.swpc.noaa.gov/products/noaa-scales.json',
  scalePage: 'https://www.swpc.noaa.gov/noaa-scales-explanation',
  credit: 'NOAA Space Weather Prediction Center',
};

// NOAA's biological effects text for astronauts, from the same scales page.
export const S_SCALE = [
  { level: 1, name: 'Minor', pfu: 10, astronauts: 'None.' },
  { level: 2, name: 'Moderate', pfu: 100, astronauts: 'Passengers and crew in high-flying aircraft at high latitudes may be exposed to elevated radiation risk.' },
  { level: 3, name: 'Strong', pfu: 1000, astronauts: 'Radiation hazard avoidance recommended for astronauts on EVA.' },
  { level: 4, name: 'Severe', pfu: 10000, astronauts: 'Unavoidable radiation hazard to astronauts on EVA.' },
  { level: 5, name: 'Extreme', pfu: 100000, astronauts: 'Unavoidable high radiation hazard to astronauts on EVA.' },
];

// The S level for a flux of protons of 10 MeV or more, in pfu (particles per cm2, second and steradian): 0 to 5.
export function sLevel(flux) {
  const f = Number(flux);
  if (!Number.isFinite(f)) return null;
  let level = 0;
  for (const s of S_SCALE) if (f >= s.pfu) level = s.level;
  return level;
}

// The newest value of one energy band: { flux, time, satellite } or null.
export function latestProtonFlux(rows, energy = '>=10 MeV') {
  let best = null;
  for (const r of Array.isArray(rows) ? rows : []) {
    if (!r || r.energy !== energy || !Number.isFinite(Number(r.flux))) continue;
    if (!best || String(r.time_tag) > String(best.time_tag)) best = r;
  }
  return best ? { flux: Number(best.flux), time: new Date(best.time_tag).toISOString(), satellite: best.satellite ?? null, energy } : null;
}

// One SWPC message: issue time (given in UTC), its code, serial number and first line, for example
// "ALERT: Type II Radio Emission".
export function parseAlert(a) {
  if (!a || typeof a.message !== 'string') return null;
  const lines = a.message.split(/\r?\n/).map((l) => l.trim());
  const code = (lines.find((l) => l.startsWith('Space Weather Message Code:')) || '').replace('Space Weather Message Code:', '').trim() || null;
  const serial = (lines.find((l) => l.startsWith('Serial Number:')) || '').replace('Serial Number:', '').trim() || null;
  const title = lines.find((l) => /^(CONTINUED |EXTENDED |CANCEL )?(ALERT|WARNING|WATCH|SUMMARY)\b/.test(l)) || lines.find((l) => l && !/^(Space Weather Message Code|Serial Number|Issue Time):/.test(l)) || null;
  const iso = a.issue_datetime ? new Date(`${String(a.issue_datetime).trim().replace(' ', 'T')}Z`) : null;
  return { id: a.product_id || null, code, serial, time: iso && Number.isFinite(iso.getTime()) ? iso.toISOString() : null, title, text: a.message.replace(/\r\n/g, '\n').trim() };
}

export function latestAlert(alerts, test = () => true) {
  const list = (Array.isArray(alerts) ? alerts : []).map(parseAlert).filter((x) => x && x.time && test(x));
  list.sort((x, y) => (x.time < y.time ? 1 : -1));
  return list[0] || null;
}

const isProton = (x) => /proton/i.test(x.title || '');

async function getJson(fetchFn, url, timeoutMs) {
  const ctl = typeof AbortController !== 'undefined' ? new AbortController() : null;
  const timer = ctl ? setTimeout(() => ctl.abort(), timeoutMs) : null;
  try {
    const res = await fetchFn(url, { headers: { Accept: 'application/json' }, signal: ctl ? ctl.signal : undefined });
    if (!res.ok) throw new Error(`${url} answered HTTP ${res.status}`);
    return await res.json();
  } finally {
    if (timer) clearTimeout(timer);
  }
}

// From the three answers to one summary (also used by the tests with saved copies).
export function summarize({ protons, alerts, scales = null }) {
  const p = latestProtonFlux(protons);
  const level = p ? sLevel(p.flux) : null;
  const scale = level ? S_SCALE[level - 1] : null;
  const now = scales && scales['0'] ? scales['0'] : null;
  return {
    level,
    name: level === null ? null : level === 0 ? 'no solar radiation storm' : `S${level} ${scale.name}`,
    astronauts: scale ? scale.astronauts : null,
    flux: p ? p.flux : null,
    energy: '>=10 MeV',
    time: p ? p.time : null,
    satellite: p ? p.satellite : null,
    latestAlert: latestAlert(alerts),
    latestProtonAlert: latestAlert(alerts, isProton),
    noaa: now && now.S ? { s: now.S.Scale === null ? null : Number(now.S.Scale), text: now.S.Text, time: `${now.DateStamp}T${now.TimeStamp}Z` } : null,
  };
}

// Reads NOAA's public data once. Returns { ok: true, source: 'noaa-swpc', earthDemo: true, level, name, astronauts,
// flux, energy, time, satellite, latestAlert, latestProtonAlert, noaa, credit, note } or { ok: false, error }.
// level is the S-scale level (0 = no storm) computed here from the newest >=10 MeV flux; noaa is NOAA's own
// current S level, for comparison.
export async function readSpaceWeather({ fetch: fetchFn = globalThis.fetch, timeoutMs = 10000 } = {}) {
  if (typeof fetchFn !== 'function') return { ok: false, source: 'noaa-swpc', error: 'This browser cannot fetch.' };
  try {
    const [protons, alerts, scales] = await Promise.all([
      getJson(fetchFn, SWPC.protons, timeoutMs),
      getJson(fetchFn, SWPC.alerts, timeoutMs).catch(() => []),
      getJson(fetchFn, SWPC.scales, timeoutMs).catch(() => null),
    ]);
    const s = summarize({ protons, alerts, scales });
    if (s.flux === null) throw new Error('NOAA sent no proton values');
    return { ok: true, source: 'noaa-swpc', earthDemo: true, ...s, credit: SWPC.credit, note: 'A public measurement from a GOES satellite near Earth, not the crew\'s own dose.' };
  } catch (err) {
    const msg = err && err.name === 'AbortError' ? 'NOAA did not answer in time' : (err && err.message) || String(err);
    return { ok: false, source: 'noaa-swpc', error: msg };
  }
}
