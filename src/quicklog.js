// Quick logs for the crew screen: a symptom in about ten seconds, a medicine in two taps. Both answer the two NASA
// panel reviews of 15 Nov 2026: the commonest in-flight medical problems are symptoms the app could not record, and
// when ISS crew logged their medicines in an app they logged more than ten times the use their medical records
// showed (Dose Tracker). The lists and their sources live in config.js, in the cells "Symptoms" and "Medicines taken".
//
// Framework-free: each builder gets a host element and callbacks and draws plain DOM with the crew screen's own
// classes (questions, q, q-label, chips, seg, custom, actions, btn primary, btn secondary, note). No colour carries
// meaning: a choice shows as pressed (aria-pressed), which the screen draws as a ring and bold text. Every button
// sits in a .seg group or is a .btn, both at least 48 px high on that screen.
// The entries are private by default: the forms only hand them to onSave, and who sees them is the screen's choice.
// kitFindings() checks medicine entries against the kit list's own printed rules (more tablets every 24 hours than
// its limit, a sleep medicine together with another one); the levels (state-levels.js) turn a finding into a
// private "attention" item that quotes the kit list. The medicine form shows the kit list's note of the medicine chosen.
// Code generated by Claude (Anthropic), an AI system. Idea and logic: the human member of team "Just For Fun".
import { CELLS } from './config.js';

const cellOf = (indicator) => CELLS.find((c) => c.indicator === indicator);
const HOUR = 60 * 60 * 1000;
const NOTE_MAX = 200; // a few words, not a diary
const NAME_MAX = 60;
const AMOUNT_MAX = 10; // more than 10 tablets at once is not a plausible entry
const FUTURE_SLACK = 5 * 60 * 1000; // clocks differ a little; a time more than 5 minutes ahead is refused
export const HOURS_AGO = [0, 1, 2, 4, 8]; // the "When did you take it?" choices; 0 is now
export const PRIVATE_NOTE = 'Private: not sent to anyone unless you choose to.';

// ---------- checking and wording, no DOM ----------

// One symptom entry, tidied, or null when it cannot be read: a symptom from the list, a whole number on the
// 0 to 10 scale, and a short note, which "Something else" needs.
export function symptomValue(v, cell = cellOf('symptoms')) {
  if (!v || typeof v !== 'object' || Array.isArray(v)) return null;
  const pick = cell.symptoms.find((s) => s.key === v.symptom);
  const { min, max } = cell.severity;
  if (!pick || !Number.isInteger(v.severity) || v.severity < min || v.severity > max) return null;
  const note = typeof v.note === 'string' ? v.note.trim().slice(0, NOTE_MAX) : '';
  if (pick.needsNote && !note) return null;
  return note ? { symptom: pick.key, severity: v.severity, note } : { symptom: pick.key, severity: v.severity };
}

// One medicine entry, tidied, or null: a kit medicine (name, strength and unit then come from the kit list) or
// "other" with a name; a positive amount up to 10; takenAt, when given, a real time that is not in the future.
export function medicineValue(v, { cell = cellOf('medicines'), now = new Date() } = {}) {
  if (!v || typeof v !== 'object' || Array.isArray(v)) return null;
  if (typeof v.amount !== 'number' || !Number.isFinite(v.amount) || v.amount <= 0 || v.amount > AMOUNT_MAX) return null;
  let out;
  if (v.medicine === 'other') {
    const name = typeof v.name === 'string' ? v.name.trim().slice(0, NAME_MAX) : '';
    if (!name) return null;
    out = { medicine: 'other', name, amount: v.amount, unit: 'dose' };
  } else {
    const k = cell.kit.find((x) => x.key === v.medicine);
    if (!k) return null;
    out = { medicine: k.key, name: k.name, strength: k.strength, amount: v.amount, unit: k.unit };
  }
  if (v.takenAt !== undefined && v.takenAt !== null) {
    const t = typeof v.takenAt === 'string' || typeof v.takenAt === 'number' ? new Date(v.takenAt).getTime() : NaN;
    if (!Number.isFinite(t) || t > new Date(now).getTime() + FUTURE_SLACK) return null;
    out.takenAt = new Date(t).toISOString();
  }
  return out;
}

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

// "half a tablet", "1 tablet", "2 tablets".
export function amountText(amount, unit = 'tablet') {
  if (amount === 0.5) return `half a ${unit}`;
  return `${amount} ${amount === 1 ? unit : `${unit}s`}`;
}

// GMT day of the year and time, as on the ISS and on the crew screen: "GMT 318/22:10".
const two = (n) => String(n).padStart(2, '0');
export function gmtText(t) {
  const d = new Date(t);
  const day = Math.floor((Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()) - Date.UTC(d.getUTCFullYear(), 0, 0)) / (24 * HOUR));
  return `GMT ${day}/${two(d.getUTCHours())}:${two(d.getUTCMinutes())}`;
}

// One plain line for a logged entry, for lists, "?" cards and the doctor's summary: "Headache, 4 of 10",
// "Melatonin 3 mg, 1 tablet". null for measures this module does not log, so a caller can fall back.
export function logText(indicator, value) {
  if (indicator === 'symptoms') {
    const cell = cellOf('symptoms');
    const s = value && typeof value === 'object' ? cell.symptoms.find((x) => x.key === value.symptom) : null;
    // A stored entry with no number would read "undefined of 10".
    if (!s || !Number.isFinite(value.severity)) return 'Unreadable symptom entry';
    return `${s.label}, ${value.severity} of ${cell.severity.max}${value.note ? `: ${value.note}` : ''}`;
  }
  if (indicator === 'medicines') {
    // A stored entry with no amount would read "undefined tablets".
    if (!value || typeof value !== 'object' || !value.name || !(Number(value.amount) > 0)) return 'Unreadable medicine entry';
    const what = [value.name, value.strength].filter(Boolean).join(' ');
    return `${what}, ${amountText(value.amount, value.unit)}${value.takenAt ? `, taken ${gmtText(value.takenAt)}` : ''}`;
  }
  if (indicator === 'visionCheck') {
    const a = cellOf('visionCheck').answers.find((x) => x.value === value);
    return a ? a.label : String(value);
  }
  return null;
}

// ---------- the kit list's own rules ----------
// The rules are data on each kit medicine in config.js (max24h, sleepMed, notWithSleepMeds), taken by hand from the
// kit list's printed comments; nothing is read from the comment text here, it is only quoted. KIT_HOURS is the kit
// list's own "every 24 hours". nightHours, how far apart two medicines still count as "one night", is a draft of the
// levels (state-levels.js RULES.kitNightHours) and is passed in.
export const KIT_HOURS = 24;
const iso = (t) => new Date(t).toISOString();

// When a logged medicine was taken: takenAt when the entry has it, otherwise the time of the entry.
function takenMs(x) {
  const at = x && x.value && typeof x.value.takenAt === 'string' ? Date.parse(x.value.takenAt) : NaN;
  return Number.isFinite(at) ? at : new Date(x && x.time).getTime();
}

// Medicine entries ({ time, value }, as the machine keeps them) checked against the kit list, newest first:
//   { rule: 'max', medicine, total, max, unit, note, time }: more tablets of one medicine in the last 24 hours than
//     the kit list's "No more than N tablets every 24 hours";
//   { rule: 'night', medicines: [earlier, later], times, hours, notes: [{ medicine, note }], time }: a sleep medicine
//     within `hours` of another sleep medicine, or of a medicine whose kit note says not to use it with sleep meds.
// time is when the later entry was taken (ISO). Only an entry of the last 24 hours raises a finding; "another
// medicine" and unreadable entries are left out. Two doses of the same medicine are never a "night" finding.
export function kitFindings(entries, { now = new Date(), nightHours = 12, cell = cellOf('medicines') } = {}) {
  const t0 = new Date(now).getTime();
  const kit = new Map(cell.kit.map((k) => [k.key, k]));
  const list = (Array.isArray(entries) ? entries : [])
    .map((x) => ({ k: x && x.value && typeof x.value === 'object' ? kit.get(x.value.medicine) : undefined, amount: x && x.value ? Number(x.value.amount) : NaN, t: takenMs(x) }))
    .filter((x) => x.k && x.amount > 0 && Number.isFinite(x.t) && t0 - x.t <= (KIT_HOURS + nightHours) * HOUR)
    .sort((a, b) => a.t - b.t);
  const recent = (x) => t0 - x.t <= KIT_HOURS * HOUR;
  const out = [];
  for (const k of cell.kit.filter((x) => Number.isFinite(x.max24h))) {
    const mine = list.filter((x) => x.k === k && recent(x));
    const total = mine.reduce((sum, x) => sum + x.amount, 0);
    if (total > k.max24h) out.push({ rule: 'max', medicine: k.key, total, max: k.max24h, unit: k.unit, note: k.kitNote, time: iso(mine[mine.length - 1].t) });
  }
  const clash = (a, b) => a.k !== b.k && Boolean((a.k.sleepMed && b.k.notWithSleepMeds) || (b.k.sleepMed && a.k.notWithSleepMeds));
  const pairs = new Map(); // one finding per pair of medicines: the newest
  for (let j = 0; j < list.length; j += 1) {
    if (!recent(list[j])) continue;
    for (let i = 0; i < j; i += 1) {
      const [a, b] = [list[i], list[j]];
      if (b.t - a.t <= nightHours * HOUR && clash(a, b)) pairs.set([a.k.key, b.k.key].sort().join('+'), [a, b]);
    }
  }
  for (const [a, b] of pairs.values()) {
    const notes = [a.k, b.k].filter((k) => k.notWithSleepMeds && k.kitNote).map((k) => ({ medicine: k.key, note: k.kitNote }));
    out.push({ rule: 'night', medicines: [a.k.key, b.k.key], times: [iso(a.t), iso(b.t)], hours: nightHours, notes, time: iso(b.t) });
  }
  return out.sort((x, y) => Date.parse(y.time) - Date.parse(x.time));
}

// One finding in plain words, quoting the kit list; kitFindingShort() gives it in one short line for Today.
export function kitFindingText(f, cell = cellOf('medicines')) {
  const k = (key) => cell.kit.find((x) => x.key === key);
  const named = (key) => `${k(key).name} ${k(key).strength}`;
  if (f.rule === 'max') return `${named(f.medicine)}: ${amountText(f.total, f.unit)} in the last ${KIT_HOURS} hours. The kit list says: "${f.note}"`;
  const same = new Set(f.notes.map((n) => n.note)).size === 1;
  const quote = same ? `The kit list says: "${f.notes[0].note}"` : `The kit list says of ${f.notes.map((n) => `${k(n.medicine).name}: "${n.note}"`).join(' Of ')}`;
  return `${named(f.medicines[0])} (${gmtText(f.times[0])}) and ${named(f.medicines[1])} (${gmtText(f.times[1])}), within ${f.hours} hours of each other. ${quote}`;
}
export function kitFindingShort(f, cell = cellOf('medicines')) {
  const name = (key) => cell.kit.find((x) => x.key === key).name;
  if (f.rule === 'max') return `${name(f.medicine)}: ${amountText(f.total, f.unit)} in ${KIT_HOURS} hours, more than the kit list's ${f.max}`;
  return `${name(f.medicines[0])} with ${name(f.medicines[1])}: the kit list says not together`;
}

// ---------- the forms ----------

let uid = 0;
const nextId = (name) => `ql-${name}-${(uid += 1)}`;

// A small element maker like the screens' h(): props set attributes, on* props add listeners, text sets text.
function make(doc, tag, props = {}, ...kids) {
  const node = doc.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v === null || v === undefined || v === false) continue;
    if (k === 'class') node.className = v;
    else if (k === 'hidden') node.hidden = true;
    else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2), v);
    else node.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of kids.flat()) {
    if (c === null || c === undefined || c === false) continue;
    node.append(typeof c === 'string' ? doc.createTextNode(c) : c);
  }
  return node;
}

// A row of choices that look like chips. Buttons are grouped into .seg boxes (one button each unless sizes says
// otherwise), so the screen draws them 48 px high and shows the pressed one by a ring and bold text.
function choiceRow(doc, labelId, options, onPick, sizes = null) {
  const buttons = options.map((o) => make(doc, 'button', {
    type: 'button', 'aria-pressed': 'false', 'data-value': String(o.value), 'aria-label': o.aria || null, onclick: () => onPick(o.value),
  }, o.label));
  const boxes = [];
  let at = 0;
  for (const n of sizes || buttons.map(() => 1)) { boxes.push(make(doc, 'div', { class: 'seg' }, buttons.slice(at, at + n))); at += n; }
  const row = make(doc, 'div', { class: 'chips', role: 'group', 'aria-labelledby': labelId }, boxes);
  const press = (value) => buttons.forEach((b, i) => b.setAttribute('aria-pressed', String(options[i].value === value)));
  return { row, press, buttons };
}

const label = (doc, id, text, hint) => make(doc, 'div', { class: 'q-label', id }, hint ? `${text} ` : text, hint ? make(doc, 'span', {}, hint) : null);

// The symptom log: pick one symptom, rate it from 0 to 10, add a note if you like, save.
// host: the element to draw into. onSave(entry) gets { indicator: 'symptoms', value, time } and may return a
// promise; when it fails, the choice stays so the person can try again. onCancel() is optional.
// Returns { form, reset }.
export function symptomLog(host, { onSave, onCancel = null, now = () => new Date(), privacy = PRIVATE_NOTE } = {}) {
  if (typeof onSave !== 'function') throw new TypeError('symptomLog needs onSave');
  const cell = cellOf('symptoms');
  const doc = host.ownerDocument;
  const { min, max, minText, maxText } = cell.severity;
  const ids = { what: nextId('what'), how: nextId('how'), note: nextId('note') };
  const pick = { symptom: null, severity: null };
  let busy = false;

  const status = make(doc, 'p', { class: 'note', role: 'status', 'aria-live': 'polite' });
  const noteHint = make(doc, 'span', {}, 'optional, a few words');
  const noteLabel = make(doc, 'label', { class: 'q-label', for: ids.note }, 'Note ', noteHint);
  const noteInput = make(doc, 'input', { id: ids.note, type: 'text', maxlength: NOTE_MAX, autocomplete: 'off', class: 'ql-note' });
  // "Something else" needs a few words, so the note's label says so while it is chosen.
  const needsNote = () => Boolean(pick.symptom && cell.symptoms.find((s) => s.key === pick.symptom).needsNote);
  const showNoteLabel = () => {
    noteLabel.replaceChildren(doc.createTextNode(needsNote() ? 'What is it? ' : 'Note '), noteHint);
    noteHint.textContent = needsNote() ? 'a few words' : 'optional, a few words';
  };

  const what = choiceRow(doc, ids.what, cell.symptoms.map((s) => ({ value: s.key, label: s.label })), (key) => {
    if (busy) return;
    pick.symptom = pick.symptom === key ? null : key;
    what.press(pick.symptom);
    showNoteLabel();
    status.textContent = '';
  });
  const scale = [];
  for (let n = min; n <= max; n += 1) scale.push({ value: n, label: String(n), aria: n === min ? `${n}, ${minText}` : n === max ? `${n}, ${maxText}` : null });
  // Two joined boxes (0 to 5, 6 to 10) fit a phone and the side panel without breaking the scale apart.
  const how = choiceRow(doc, ids.how, scale, (n) => {
    if (busy) return;
    pick.severity = pick.severity === n ? null : n;
    how.press(pick.severity);
    status.textContent = '';
  }, [Math.ceil(scale.length / 2), Math.floor(scale.length / 2)]);

  function reset() {
    pick.symptom = null;
    pick.severity = null;
    what.press(null);
    how.press(null);
    noteInput.value = '';
    showNoteLabel();
    status.textContent = '';
  }

  async function submit(ev) {
    if (ev && ev.preventDefault) ev.preventDefault();
    if (busy) return;
    if (pick.symptom === null || pick.severity === null) { status.textContent = 'Choose what you feel and how strong it is.'; return; }
    const value = symptomValue({ symptom: pick.symptom, severity: pick.severity, note: noteInput.value }, cell);
    if (!value) { status.textContent = 'Write a few words about it.'; return; }
    busy = true;
    try {
      await onSave({ indicator: 'symptoms', value, time: new Date(now()).toISOString() });
      reset();
      status.textContent = `Saved: ${logText('symptoms', value)}.`;
    } catch {
      status.textContent = 'Could not save. Your choice is kept: try again.';
    } finally {
      busy = false;
    }
  }

  const form = make(doc, 'form', { class: 'questions quicklog', 'aria-label': 'Log a symptom', novalidate: true, onsubmit: submit },
    privacy ? make(doc, 'p', { class: 'note' }, privacy) : null,
    make(doc, 'div', { class: 'q' }, label(doc, ids.what, 'What do you feel?', 'pick one'), what.row),
    make(doc, 'div', { class: 'q' }, label(doc, ids.how, 'How strong is it?', `${min} ${minText}, ${max} ${maxText}`), how.row),
    make(doc, 'div', { class: 'q' }, noteLabel, make(doc, 'div', { class: 'custom' }, noteInput)),
    make(doc, 'div', { class: 'actions' },
      make(doc, 'button', { type: 'submit', class: 'btn primary' }, 'Save'),
      onCancel ? make(doc, 'button', { type: 'button', class: 'btn secondary', onclick: () => onCancel() }, 'Cancel') : null),
    status);
  host.replaceChildren(form);
  return { form, reset };
}

// The medicine log: tap the medicine, then tap how much, and it is saved; "When did you take it?" stays on "Now"
// unless the person changes it. host, onSave, onCancel as in symptomLog; onSave gets
// { indicator: 'medicines', value, time }, where time is when it was taken. Returns { form, reset }.
export function medicineLog(host, { onSave, onCancel = null, now = () => new Date(), privacy = PRIVATE_NOTE } = {}) {
  if (typeof onSave !== 'function') throw new TypeError('medicineLog needs onSave');
  const cell = cellOf('medicines');
  const doc = host.ownerDocument;
  const pick = { medicine: null, hoursAgo: 0 };
  let busy = false;
  const status = make(doc, 'p', { class: 'note', role: 'status', 'aria-live': 'polite' });

  // One row per use (sleep, pain and so on) in the kit list's order, then "Something else".
  const groups = Object.entries(cell.uses)
    .map(([use, title]) => ({ title, options: cell.kit.filter((k) => k.use === use).map((k) => ({ value: k.key, label: `${k.name} ${k.strength}` })) }))
    .filter((g) => g.options.length);
  groups.push({ title: 'Something else', options: [{ value: 'other', label: 'Another medicine' }] });
  const rows = groups.map((g) => {
    const id = nextId('use');
    const r = choiceRow(doc, id, g.options, (key) => choose(key));
    return { ...g, ...r, block: make(doc, 'div', { class: 'q' }, label(doc, id, g.title), r.row) };
  });

  const ids = { when: nextId('when'), much: nextId('much'), name: nextId('name') };
  const when = choiceRow(doc, ids.when, HOURS_AGO.map((h) => ({ value: h, label: h === 0 ? 'Now' : `${h} h ago` })), (h) => {
    if (busy) return;
    pick.hoursAgo = h;
    when.press(h);
  });
  const nameInput = make(doc, 'input', { id: ids.name, type: 'text', maxlength: NAME_MAX, autocomplete: 'off', class: 'ql-name' });
  const nameQ = make(doc, 'div', { class: 'q', hidden: true },
    make(doc, 'label', { class: 'q-label', for: ids.name }, 'Which medicine? ', make(doc, 'span', {}, 'name and strength')),
    make(doc, 'div', { class: 'custom' }, nameInput));
  const amounts = make(doc, 'div', { class: 'chips', role: 'group', 'aria-labelledby': ids.much });
  // The kit list's own note on the medicine chosen (for example its limit every 24 hours), right under its row.
  const kitLine = make(doc, 'p', { class: 'note', hidden: true });
  const details = make(doc, 'div', { class: 'questions', hidden: true },
    kitLine,
    make(doc, 'div', { class: 'q' }, label(doc, ids.when, 'When did you take it?'), when.row),
    nameQ,
    make(doc, 'div', { class: 'q' }, label(doc, ids.much, 'How much?', 'tap to save'), amounts));
  const kitSrc = cell.kitSrc;
  const form = make(doc, 'form', { class: 'questions quicklog', 'aria-label': 'Log a medicine', novalidate: true, onsubmit: (ev) => ev.preventDefault() },
    privacy ? make(doc, 'p', { class: 'note' }, privacy) : null,
    ...rows.map((g) => g.block),
    details,
    kitSrc ? make(doc, 'p', { class: 'note' }, 'A short list from the ', make(doc, 'a', { href: kitSrc.url, target: '_blank', rel: 'noopener' }, kitSrc.name), ', released in 2016; the kit flying now may differ. A draft: the flight surgeons set the real list.') : null,
    onCancel ? make(doc, 'div', { class: 'actions' }, make(doc, 'button', { type: 'button', class: 'btn secondary', onclick: () => onCancel() }, 'Cancel')) : null,
    status);

  function choose(key) {
    if (busy) return;
    pick.medicine = pick.medicine === key ? null : key;
    rows.forEach((g) => g.press(pick.medicine));
    status.textContent = '';
    if (!pick.medicine) { details.hidden = true; return; }
    const kitEntry = key === 'other' ? null : cell.kit.find((k) => k.key === key);
    kitLine.textContent = kitEntry && kitEntry.kitNote ? `The kit list says: "${kitEntry.kitNote}"` : '';
    kitLine.hidden = !(kitEntry && kitEntry.kitNote);
    const unit = kitEntry ? kitEntry.unit : 'dose';
    amounts.replaceChildren(...cell.amounts.map((a) => make(doc, 'div', { class: 'seg' },
      make(doc, 'button', { type: 'button', 'data-value': String(a), onclick: () => save(a) }, cap(amountText(a, unit))))));
    nameQ.hidden = key !== 'other';
    details.hidden = false;
    // The questions move right under the row just used, so the second tap is close to the first.
    const block = rows.find((g) => g.options.some((o) => o.value === key)).block;
    const ref = block.nextSibling === details ? details.nextSibling : block.nextSibling;
    form.insertBefore(details, ref);
    if (typeof details.scrollIntoView === 'function') details.scrollIntoView({ block: 'nearest' });
  }

  function reset() {
    pick.medicine = null;
    pick.hoursAgo = 0;
    rows.forEach((g) => g.press(null));
    when.press(0);
    nameInput.value = '';
    nameQ.hidden = true;
    kitLine.textContent = '';
    kitLine.hidden = true;
    details.hidden = true;
    status.textContent = '';
  }

  async function save(amount) {
    if (busy || !pick.medicine) return;
    const taken = new Date(new Date(now()).getTime() - pick.hoursAgo * HOUR);
    const raw = { medicine: pick.medicine, amount, name: nameInput.value };
    if (pick.hoursAgo > 0) raw.takenAt = taken.toISOString();
    const value = medicineValue(raw, { cell, now: now() });
    if (!value) { status.textContent = pick.medicine === 'other' ? 'Write the name of the medicine first.' : 'This entry cannot be read.'; return; }
    busy = true;
    try {
      await onSave({ indicator: 'medicines', value, time: taken.toISOString() });
      reset();
      status.textContent = `Saved: ${logText('medicines', value)}.`;
    } catch {
      status.textContent = 'Could not save. Your choice is kept: try again.';
    } finally {
      busy = false;
    }
  }

  when.press(0);
  host.replaceChildren(form);
  return { form, reset };
}
