// An optional PIN per person for the crew screen, so a crewmate at the same computer cannot open someone's
// measures, mind, cycle or messages by chance. The ISS crew code of conduct (14 CFR 1214.403) says other
// crewmembers may not use or disclose a crewmember's medical information without consent.
// Only a salted PBKDF2 hash of the PIN is kept (Web Crypto), never the PIN itself. It works in the browser and in
// Node 18 or newer, so the automatic checks can test it.
// Honest limits: the hash is kept in this browser's storage, on this computer only. Someone with the browser's
// developer tools can delete it, and a short PIN can be found from a copied hash by trying every number, so this
// is a privacy screen against a glance, not a lock against an attacker. docs/SECURITY.md says the same.
// The numbers are drafts: the team and the flight surgeons decide.
// Code generated by Claude (Anthropic), an AI system.

const REFS = {
  nist: { name: 'NIST SP 800-63B-4, 3.2.10 Activation secrets', url: 'https://pages.nist.gov/800-63-4/sp800-63b.html' },
  owasp: { name: 'OWASP Password Storage Cheat Sheet (PBKDF2)', url: 'https://cheatsheetseries.owasp.org/cheatsheets/Password_Storage_Cheat_Sheet.html' },
  salt: { name: 'NIST SP 800-132, 5.1 The Salt', url: 'https://nvlpubs.nist.gov/nistpubs/Legacy/SP/nistspecialpublication800-132.pdf' },
  cfr: { name: '14 CFR 1214.403, ISS crew code of conduct (CFR 2026)', url: 'https://www.govinfo.gov/content/pkg/CFR-2026-title14-vol5/pdf/CFR-2026-title14-vol5-sec1214-403.pdf' },
};

export const PIN_RULES = Object.freeze({
  minDigits: 4, // NIST: activation secrets "SHALL" be at least 4 characters
  suggestedDigits: 6, // NIST: they "SHOULD" be at least 6
  maxDigits: 12,
  maxTries: 10, // NIST: no more than 10 consecutive failed attempts, then the authenticator is disabled
  hash: 'SHA-256',
  iterations: 600000, // OWASP: PBKDF2-HMAC-SHA256, 600,000 iterations (recommended)
  minIterations: 200000, // a stored record with fewer is not trusted
  saltBytes: 16, // NIST SP 800-132: a random salt of at least 128 bits
  hashBytes: 32,
  draft: true,
  rules: [
    { text: 'The PIN is optional. It keeps a crewmate at the same computer out of this person\'s screen.', src: REFS.cfr },
    { text: 'A PIN has 4 to 12 digits; 6 or more is better.', src: REFS.nist },
    { text: 'After 10 wrong PINs in a row the PIN is locked until it is reset.', src: REFS.nist },
    { text: 'Only a hash is kept: PBKDF2-HMAC-SHA256, 600,000 iterations, a random 16-byte salt.', src: REFS.owasp, src2: REFS.salt },
  ],
});

const PERSON_ID = /^[a-z0-9][a-z0-9-]{0,31}$/;
const recordKey = (id) => `jff-pin-v1:${id}`;

// Where the records live: the browser's own storage when there is one, otherwise memory (this page only).
// usePinStorage swaps it, for the automatic checks or for a store on the server later.
const memory = new Map();
const memoryStorage = {
  getItem: (k) => (memory.has(k) ? memory.get(k) : null),
  setItem: (k, v) => { memory.set(k, String(v)); },
  removeItem: (k) => { memory.delete(k); },
};
let storage = null;
function box() {
  if (storage) return storage;
  try {
    if (globalThis.localStorage) {
      globalThis.localStorage.getItem(recordKey('probe'));
      storage = globalThis.localStorage;
      return storage;
    }
  } catch {
    // storage blocked: memory only
  }
  storage = memoryStorage;
  return storage;
}
export function usePinStorage(adapter) {
  storage = adapter || null;
}

function checkId(id) {
  if (typeof id !== 'string' || !PERSON_ID.test(id)) throw new TypeError('id must be a person id such as crew-1');
}
function read(id) {
  checkId(id);
  try {
    const r = JSON.parse(box().getItem(recordKey(id)) || 'null');
    return r && r.v === 1 && typeof r.hash === 'string' && typeof r.salt === 'string' ? r : null;
  } catch {
    return null;
  }
}
const write = (id, r) => box().setItem(recordKey(id), JSON.stringify(r));

const toB64 = (bytes) => btoa(String.fromCharCode(...bytes));
const fromB64 = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
// The same time for every wrong PIN, whatever its digits.
function sameBytes(a, b) {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i += 1) diff |= a[i] ^ b[i];
  return diff === 0;
}

// Web Crypto exists only on secure pages: http://127.0.0.1, http://localhost or https. On a plain http address
// of a local network there is none, and the screen should not offer a PIN.
export function pinAvailable() {
  return Boolean(globalThis.crypto && globalThis.crypto.subtle && globalThis.crypto.getRandomValues);
}

async function derive(pin, salt, iterations) {
  if (!pinAvailable()) throw new Error('No Web Crypto on this page: open the program at http://127.0.0.1 or over https to use a PIN.');
  const subtle = globalThis.crypto.subtle;
  const base = await subtle.importKey('raw', new TextEncoder().encode(pin), 'PBKDF2', false, ['deriveBits']);
  const bits = await subtle.deriveBits({ name: 'PBKDF2', hash: PIN_RULES.hash, salt, iterations }, base, PIN_RULES.hashBytes * 8);
  return new Uint8Array(bits);
}

// Why a PIN cannot be used, in a sentence for the screen, or null when it is fine.
export function pinProblem(pin) {
  if (typeof pin !== 'string' || !/^[0-9]+$/.test(pin)) return 'A PIN is made of digits only.';
  if (pin.length < PIN_RULES.minDigits) return `A PIN needs at least ${PIN_RULES.minDigits} digits.`;
  if (pin.length > PIN_RULES.maxDigits) return `A PIN has at most ${PIN_RULES.maxDigits} digits.`;
  return null;
}

export function hasPin(id) {
  return read(id) !== null;
}

export async function setPin(id, pin) {
  checkId(id);
  const why = pinProblem(pin);
  if (why) throw new Error(why);
  const salt = globalThis.crypto.getRandomValues(new Uint8Array(PIN_RULES.saltBytes));
  const hash = await derive(pin, salt, PIN_RULES.iterations);
  write(id, { v: 1, kdf: `PBKDF2-HMAC-${PIN_RULES.hash}`, iterations: PIN_RULES.iterations, salt: toB64(salt), hash: toB64(hash), fails: 0, set: new Date().toISOString() });
}

// True only for the person's own PIN. Every wrong try counts; once the tries are used up, it answers false
// without checking until clearPin. With no PIN set it answers false: the screen asks hasPin first.
export async function checkPin(id, pin) {
  const r = read(id);
  if (!r) return false;
  const fails = Number.isInteger(r.fails) ? r.fails : PIN_RULES.maxTries;
  if (fails >= PIN_RULES.maxTries) return false;
  let ok = false;
  if (!pinProblem(pin) && Number.isInteger(r.iterations) && r.iterations >= PIN_RULES.minIterations && r.iterations <= 10 * PIN_RULES.iterations) {
    ok = sameBytes(await derive(pin, fromB64(r.salt), r.iterations), fromB64(r.hash));
  }
  // Read again before writing: the PIN may have been changed or cleared while the hash was being worked out.
  const now = read(id);
  if (now && now.hash === r.hash) write(id, { ...now, fails: ok ? 0 : (Number.isInteger(now.fails) ? now.fails : 0) + 1 });
  return ok;
}

export function pinTriesLeft(id) {
  const r = read(id);
  if (!r) return PIN_RULES.maxTries;
  return Math.max(0, PIN_RULES.maxTries - (Number.isInteger(r.fails) ? r.fails : PIN_RULES.maxTries));
}

export function pinLocked(id) {
  return hasPin(id) && pinTriesLeft(id) === 0;
}

// Removes the PIN (and so the lock). The screen asks for the current PIN first, or leaves a reset to the crew
// medical officer; this file cannot tell who is at the keyboard.
export function clearPin(id) {
  checkId(id);
  box().removeItem(recordKey(id));
}
