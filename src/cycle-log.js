// The menstrual cycle log, day by day: "like Flo, but for astronauts" (the team's words). For today and any day back
// to a limit, never a future day, the person logs how much they bled (no bleeding, spotting, light, medium or heavy)
// and which symptoms they had. This file holds the rules and reads the log, with no screen: src/cycle-view.js draws
// it, and src/cycle.js turns the periods found here into the summary and its flags.
//
// Sources, each opened by Claude (Anthropic, an AI system) on 15 Nov 2026:
// - ACOG patient FAQ095, Abnormal Uterine Bleeding (updated December 2021, reviewed August 2025): note "the dates,
//   length, and type (light, medium, heavy, or spotting) of your bleeding on a calendar"; a menstrual cycle runs from
//   "the first day of menstrual bleeding of one cycle to the first day of menstrual bleeding of the next cycle";
//   hormonal birth control can cause "breakthrough bleeding (bleeding at a time other than your period)"; bleeding
//   or spotting between periods is listed among the kinds of abnormal uterine bleeding.
// - Creinin, Vieira, Westhoff and Mansour, Recommendations for standardization of bleeding data analyses in
//   contraceptive studies, Contraception 112:14-22 (2022): spotting is "light flow with no menstrual product use";
//   an episode is bordered by 2 full days without bleeding or spotting (the Mishell criteria); on a day with two
//   flows the heavier one counts; bleeding on methods without a planned bleed (hormonal IUD, implant, pills taken
//   without a break) is described over 90-day reference periods (the WHO's Belsey periods of 1986): no bleeding or
//   spotting, infrequent (2 episodes or fewer), normal frequency (3 or 4) or frequent (more than 4); an episode of
//   more than 7 days is prolonged.
// - Flo Health help centre: one flow a day, "light, medium, heavy, or blood clots" (2025); spotting, "light bleeding
//   that occurs outside of your normal period", is logged apart from the period (2021); past periods are added and
//   edited in the calendar (2025).
// - Jain and Wotring, Medically induced amenorrhea in female astronauts, npj Microgravity 2:16008 (2016): the US
//   waste systems of the ISS that reclaim water from urine "were not designed to handle menstrual blood", so keeping
//   breakthrough bleeding low during suppression matters; with the pill taken without a break, breakthrough bleeding
//   comes "particularly in initial phase".
// The symptom list and its sources are below. Every rule here is a draft for the team and the flight surgeons.
// There are no fertility or ovulation features.
// Code generated by Claude (Anthropic), an AI system.

const DAY = 24 * 60 * 60 * 1000;

// Drafts for the team and the flight surgeons.
// - backDays: today and the days before it that can be logged or changed, 90 in all. No standard sets this; 90 days
//   is the WHO's reference period for bleeding patterns (Creinin 2022) and the 3 months of the Endocrine Society's
//   "no period" check, and ACOG FAQ057 asks for a daily record for 2 to 3 months.
// - gapDays: days without bleeding or spotting that still keep one episode together; 2 full days end it (Mishell
//   criteria, Creinin 2022).
// - referenceDays, prolongedDays, infrequentMax, frequentOver: the 90-day summary of bleeding while periods are
//   suppressed, in the words of Creinin 2022 (Table 3). They describe; they are not a diagnosis.
// - oldPairMaxDays: an old "Period ended today" more than 14 days after its start is not paired with it, as the
//   summary before the day log did (it counted only periods of 1 to 14 days).
