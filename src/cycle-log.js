// What the screens saved before the day log, still read: the two buttons and the suppression switch.
export const OLD_VALUES = Object.freeze(['period_start', 'period_end', 'suppression_on', 'suppression_off']);

// ---------- days, in GMT as on the ISS ----------
export const MONTHS = Object.freeze(['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']);
export const WEEKDAYS = Object.freeze(['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday']);
const msOf = (t) => (t instanceof Date ? t.getTime() : typeof t === 'number' ? t : typeof t === 'string' ? Date.parse(t) : NaN);
const isObj = (x) => x !== null && typeof x === 'object' && !Array.isArray(x);

// The GMT day of a time, written YYYY-MM-DD, or null.
export function dayOf(t) {
  const v = msOf(t);
  return Number.isFinite(v) && Math.abs(v) <= 8.64e15 ? new Date(v).toISOString().slice(0, 10) : null;
}
export const dayMs = (day) => Date.parse(`${day}T00:00:00Z`);
// A real calendar day written YYYY-MM-DD (so 2026-02-30 is not one).
export function isDay(s) {
  return typeof s === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(s) && dayOf(dayMs(s)) === s;
}
export const addDays = (day, n) => dayOf(dayMs(day) + n * DAY);
export const daysBetween = (from, to) => Math.round((dayMs(to) - dayMs(from)) / DAY);
export const monthOf = (day) => day.slice(0, 7);
export function addMonths(month, n) {
  const [y, m] = month.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1 + n, 1)).toISOString().slice(0, 7);
}

// "Tue 3 Nov 2026", or with long: true "Tuesday 3 November 2026".
export function dayWords(day, { long = false } = {}) {
  const d = new Date(dayMs(day));
  const weekday = WEEKDAYS[(d.getUTCDay() + 6) % 7];
  const month = MONTHS[d.getUTCMonth()];
  return long ? `${weekday} ${d.getUTCDate()} ${month} ${d.getUTCFullYear()}` : `${weekday.slice(0, 3)} ${d.getUTCDate()} ${month.slice(0, 3)} ${d.getUTCFullYear()}`;
}

// The days a person may log or change: today and the days before it, backDays in all. Never a future day.
export function editWindow(now) {
  const today = dayOf(now);
  return { today, first: today ? addDays(today, -(LOG_RULES.backDays - 1)) : null };
}
// null when the day can be logged now, otherwise 'not-a-day', 'future' or 'too-old'.
export function dayProblem(day, now) {
  const w = editWindow(now);
  if (!isDay(day) || !w.today) return 'not-a-day';
  if (day > w.today) return 'future';
  if (day < w.first) return 'too-old';
  return null;
}

// ---------- one saved value ----------
// A day of the log is { day: 'YYYY-MM-DD', flow, symptoms: [keys] }; flow 'none' with no symptoms clears the day.
// time: the event's own time; the day may not be after it, nor more than backDays before it, so a saved line keeps
// passing this check when it is read back later. Returns a short reason, or null when the value may be saved.
export function cycleValueProblem(v, time = null) {
  if (typeof v === 'string') return OLD_VALUES.includes(v) ? null : `must be ${OLD_VALUES.join(', ')} or a day of the log`;
  if (!isObj(v)) return 'must be a day of the log { day, flow, symptoms }';
  if (Object.keys(v).some((k) => !['day', 'flow', 'symptoms'].includes(k))) return 'a day of the log may hold only day, flow and symptoms';
  if (!isDay(v.day)) return 'day must be a calendar day written YYYY-MM-DD';
  if (!FLOW_KEYS.includes(v.flow)) return `flow must be one of ${FLOW_KEYS.join(', ')}`;
  if (v.symptoms !== undefined && !(Array.isArray(v.symptoms) && new Set(v.symptoms).size === v.symptoms.length && v.symptoms.every((k) => SYMPTOM_KEYS.includes(k)))) {
    return `symptoms must be a list without repeats from: ${SYMPTOM_KEYS.join(', ')}`;
  }
  if (time !== null && time !== undefined) {
    const why = dayProblem(v.day, time);
    if (why === 'future') return 'day is after the day it was logged';
    if (why === 'too-old') return `day is not within the ${LOG_RULES.backDays} days that end on the day it was logged`;
    if (why) return 'the time of the entry cannot be read';
  }
  return null;
}
// The tidy copy that is kept: the symptoms in the list's order. null when it cannot be saved.
export function cycleValue(v, time = null) {
  if (cycleValueProblem(v, time)) return null;
  if (typeof v === 'string') return v;
  return { day: v.day, flow: v.flow, symptoms: SYMPTOM_KEYS.filter((k) => (v.symptoms || []).includes(k)) };
}

// ---------- reading the log ----------
const isBleeding = (d) => d.flow === null || Boolean((FLOWS.find((f) => f.key === d.flow) || {}).bleeding);
const isBloodDay = (d) => isBleeding(d) || d.flow === 'spotting';

// events: the cycle log as the machine keeps it, [{ time, value }], in any order. Returns
//   days: Map of day -> { day, flow, symptoms, from, at, start?, end?, open? }. from 'old': a day marked by the old
//         buttons "Period started today" and "Period ended today", flow null (not logged). from 'day': a day logged
//         in the calendar. at: the time the day starts the cycle (an old start keeps its own time).
//   suppression: [{ day, at, on }] in time order.
// A day logged in the calendar always wins over the old marks, and the newest entry for a day wins. Values that
// cannot be read are left out.
export function readLog(events) {
  const list = [...(events || [])].map((e) => ({ t: msOf(e && e.time), value: e && e.value })).filter((e) => Number.isFinite(e.t)).sort((a, b) => a.t - b.t);
  const days = new Map();
  const suppression = [];
  let open = null;
  for (const e of list) {
    if (e.value === 'suppression_on' || e.value === 'suppression_off') {
      suppression.push({ day: dayOf(e.t), at: e.t, on: e.value === 'suppression_on' });
    } else if (e.value === 'period_start') {
      open = { day: dayOf(e.t), at: e.t };
      days.set(open.day, { day: open.day, flow: null, symptoms: [], from: 'old', at: e.t, start: true, open: true });
    } else if (e.value === 'period_end' && open) {
      const end = dayOf(e.t);
      const length = daysBetween(open.day, end) + 1;
      if (length >= 1 && length <= LOG_RULES.oldPairMaxDays) {
        for (let d = open.day; d <= end; d = addDays(d, 1)) {
          days.set(d, { day: d, flow: null, symptoms: [], from: 'old', at: d === open.day ? open.at : dayMs(d), start: d === open.day, end: d === end, open: false });
        }
      }
      open = null;
    }
  }
  for (const e of list) {
    const v = e.value;
    if (!isObj(v) || !isDay(v.day) || !FLOW_KEYS.includes(v.flow)) continue;
    const symptoms = SYMPTOM_KEYS.filter((k) => Array.isArray(v.symptoms) && v.symptoms.includes(k));
    if (v.flow === 'none' && !symptoms.length) days.delete(v.day);
    else days.set(v.day, { day: v.day, flow: v.flow, symptoms, from: 'day', at: dayMs(v.day), time: e.t });
  }
  return { days, suppression };
}

// Were periods suppressed on this day? The last switch on or before the day decides (the same day counts).
export function suppressedOn(day, suppression) {
  let on = false;
  for (const s of suppression) {
    if (s.day > day) break;
    on = s.on;
  }
  return on;
}

// Episodes: days of bleeding or spotting, kept together across at most gapDays days without either (Mishell).
// start: the first day of bleeding (not spotting), which starts a cycle (ACOG FAQ095); null for spotting only.
export function episodesOf(log) {
  const blood = [...log.days.values()].filter(isBloodDay).sort((a, b) => (a.day < b.day ? -1 : a.day > b.day ? 1 : 0));
  const out = [];
  for (const d of blood) {
    const last = out[out.length - 1];
    if (last && daysBetween(last.last, d.day) <= LOG_RULES.gapDays + 1) { last.days.push(d); last.last = d.day; } else out.push({ first: d.day, last: d.day, days: [d] });
  }
  return out.map((e) => {
    const bleeding = e.days.filter(isBleeding);
    const start = bleeding.length ? bleeding[0].day : null;
    return { ...e, start, bleedingDays: bleeding.length, spottingDays: e.days.length - bleeding.length, heavyDays: e.days.filter((d) => d.flow === 'heavy').length, suppressed: suppressedOn(start || e.first, log.suppression) };
  });
}

// The periods: episodes with bleeding while periods were not suppressed. A period runs from its first day of
// bleeding to its last day of bleeding or spotting. Its length is known once 2 full days without either have passed
// (or the old "Period ended today" closed it); before that it is ongoing, and an old start with no end stays open.
export function periodsOf(log, now) {
  const today = dayOf(now);
  return episodesOf(log).filter((e) => e.start && !e.suppressed).map((e) => {
    const first = log.days.get(e.start);
    const last = log.days.get(e.last);
    const open = Boolean(last.open);
    const ended = Boolean(last.end) || (today !== null && daysBetween(e.last, today) > LOG_RULES.gapDays + 1);
    const soFar = daysBetween(e.start, e.last) + 1;
    return { start: e.start, startAt: first.at, last: e.last, soFar, length: !open && ended ? soFar : null, ongoing: !open && !ended, open, heavyDays: e.heavyDays, spottingDays: e.spottingDays, days: e.days };
  });
}

// Spotting apart from the periods, while periods were not suppressed: episodes with no day of bleeding.
export function spottingApart(log) {
  return episodesOf(log).filter((e) => !e.start && !e.suppressed);
}

// Bleeding and spotting while periods were suppressed, over the last referenceDays days (Creinin 2022, Table 3).
// pattern is given only when suppression was on for the whole window, as the words are defined for a full period:
// 'none' (no bleeding or spotting), 'infrequent', 'normal' (normal frequency) or 'frequent'.
export function bleedingSummary(log, now, { days = LOG_RULES.referenceDays } = {}) {
  const today = dayOf(now);
  const from = addDays(today, -(days - 1));
  let suppressedDays = 0;
  for (let d = from; d <= today; d = addDays(d, 1)) if (suppressedOn(d, log.suppression)) suppressedDays += 1;
  const episodes = episodesOf(log)
    .map((e) => e.days.filter((d) => d.day >= from && d.day <= today && suppressedOn(d.day, log.suppression)))
    .filter((list) => list.length)
    .map((list) => ({ first: list[0].day, last: list[list.length - 1].day, days: list }));
  const all = episodes.flatMap((e) => e.days);
  const n = episodes.length;
  const full = suppressedDays === days;
  return {
    from, to: today, days, suppressedDays, full,
    bleedingDays: all.filter(isBleeding).length,
    spottingDays: all.filter((d) => d.flow === 'spotting').length,
    heavyDays: all.filter((d) => d.flow === 'heavy').length,
    episodes: n,
    prolonged: episodes.some((e) => daysBetween(e.first, e.last) + 1 > LOG_RULES.prolongedDays),
    lastDay: all.length ? all[all.length - 1].day : null,
    pattern: !full ? null : n === 0 ? 'none' : n <= LOG_RULES.infrequentMax ? 'infrequent' : n <= LOG_RULES.frequentOver ? 'normal' : 'frequent',
  };
}
export const PATTERN_WORDS = Object.freeze({
  none: 'no bleeding or spotting',
  infrequent: `infrequent: ${LOG_RULES.infrequentMax} episodes or fewer in ${LOG_RULES.referenceDays} days`,
  normal: `normal frequency: ${LOG_RULES.infrequentMax + 1} or ${LOG_RULES.frequentOver} episodes in ${LOG_RULES.referenceDays} days`,
  frequent: `frequent: more than ${LOG_RULES.frequentOver} episodes in ${LOG_RULES.referenceDays} days`,
});

// ---------- the month on the calendar ----------
// Weeks start on Monday (ISO 8601). Each week holds 7 days, null where the day belongs to another month.
export function monthGrid(month) {
  const [y, m] = month.split('-').map(Number);
  const first = Date.UTC(y, m - 1, 1);
  const count = new Date(Date.UTC(y, m, 0)).getUTCDate();
  const lead = (new Date(first).getUTCDay() + 6) % 7;
  const cells = [...Array(lead).fill(null), ...Array.from({ length: count }, (_, i) => dayOf(first + i * DAY))];
  while (cells.length % 7) cells.push(null);
  const weeks = [];
  for (let i = 0; i < cells.length; i += 7) weeks.push(cells.slice(i, i + 7));
  return { month, title: `${MONTHS[m - 1]} ${y}`, weeks };
}

// ---------- words ----------
export const flowOf = (key) => FLOWS.find((f) => f.key === key) || null;
export const symptomLabel = (key) => (CYCLE_SYMPTOMS.find((s) => s.key === key) || { label: key }).label;
// "medium flow", "spotting", "light breakthrough bleeding", "period, flow not logged", "no bleeding".
export function flowWords(flow, { suppressed = false } = {}) {
  if (flow === null || flow === undefined) return 'period, flow not logged';
  if (flow === 'none') return 'no bleeding';
  if (flow === 'spotting') return 'spotting';
  return suppressed ? `${flow} breakthrough bleeding` : `${flow} flow`;
}
// "medium flow; cramps, back pain", or "nothing logged".
export function entryWords(entry, { suppressed = false } = {}) {
  if (!entry) return 'nothing logged';
  const parts = [flowWords(entry.flow, { suppressed })];
  if (entry.symptoms && entry.symptoms.length) parts.push(entry.symptoms.map((k) => symptomLabel(k).toLowerCase()).join(', '));
  return parts.join('; ');
}
