// The doctor's summary: the draft for the weekly private medical conference ("Prepare" on Today) and the draft of
// "Message the doctor", written from one person's records. The NASA-style review of 15 Nov 2026 (PO-7) found that
// the weekly draft held only seven vital signs and the mood and energy counts, and the message draft only the flagged
// items: a 10 of 10 symptom, two medicines the kit list says not to take together and more tablets than its limit
// every 24 hours were all left out, and so were exercise, the reaction test and the eye checks. This module writes
// them in plain words: symptoms with their scores (a headache with the cabin CO2 before it, src/nasa-rules.js),
// medicines with any kit list finding (src/quicklog.js kitFindings), exercise minutes, reaction tests against the
// person's own runs (src/reaction-test.js compareToOwn), the eye self-check answers and the OCT change.
// The person sees and edits every word before anything is sent (src/crew.js); the symptom and medicine logs are
// private, so they come under a heading of their own that the person can delete.
// Pure functions, no DOM. input: { name, flightDay, now, get, co2, runs, flagged, nightHours, launch }, where
// get(indicator) gives the person's readings of one measure as the machine keeps them, co2 the ship's CO2 readings,
// runs the person's reaction test results ({ time, median, lapses, falseStarts, mode, beforeFlight, example }).
// Code generated by Claude (Anthropic), an AI system. Idea and logic: the human member of team "Just For Fun".
import { CELLS } from './config.js';
import { STATUS } from './engine.js';
import { kitFindings, kitFindingText, logText, gmtText, amountText, KIT_HOURS } from './quicklog.js';
import { fatigueStep, FATIGUE_RULE } from './fatigue.js';
import { compareToOwn } from './reaction-test.js';
import { co2Around, co2Short, co2Link } from './nasa-rules.js';

const cellOf = (indicator) => CELLS.find((c) => c.indicator === indicator);
const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const ms = (t) => (t instanceof Date ? t.getTime() : new Date(t).getTime());
const fmt = (v) => String(Math.round(Number(v) * 10) / 10);
const big = (x) => (Math.abs(x) >= 100 ? String(Math.round(x)) : fmt(x));
const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const tidy = (s) => s.replace(/ +\./g, '.').replace(/ +,/g, ',');

// Drafts of this app, for the team: one week, as the weekly conference; an eye check older than the week is still
// named, with its date, when it is at most rareDays old (the self-check is monthly, the OCT about every two months);
// at most this many lines of each kind, so the draft stays short enough to read and to send (crew.js sends at most
// 4,000 characters of a message and 6,000 of the conference summary).
export const SUMMARY_RULES = { days: 7, rareDays: 60, maxSymptoms: 10, maxMedicines: 8, maxFindings: 4, maxRuns: 3, draft: true };

// The window of a draft: readings from `since` up to `now`.
const inWindow = (x, since, now) => ms(x.time) >= since && ms(x.time) <= now;
const recentOf = (get, ind, since, now) => (typeof get === 'function' ? get(ind) || [] : []).filter((x) => x && inWindow(x, since, now));

// ---------- numbers and check-ins (the part the weekly draft always had) ----------
export const VITALS = ['pulse', 'bp', 'spo2', 'temp', 'resp', 'sleep', 'fluid'];

export function vitalLines(get, since, now) {
  const lines = [];
  for (const ind of VITALS) {
    const cell = cellOf(ind);
    const list = recentOf(get, ind, since, now);
    if (!cell || !list.length) continue;
    const out = list.some((x) => x.status === STATUS.OUT) ? ', some outside the normal range' : '';
    if (ind === 'bp') {
      const sys = list.map((x) => Number(x.value && x.value.sys)).filter(Number.isFinite);
      const dia = list.map((x) => Number(x.value && x.value.dia)).filter(Number.isFinite);
      if (!sys.length || !dia.length) continue;
      const span = sys.length === 1 && dia.length === 1 ? `${sys[0]}/${dia[0]}` : `${Math.min(...sys)}/${Math.min(...dia)} to ${Math.max(...sys)}/${Math.max(...dia)}`;
      lines.push(`- Blood pressure: ${plural(list.length, 'reading')}, ${span} mmHg${out}.`);
      continue;
    }
    const v = list.map((x) => Number(x.value)).filter(Number.isFinite);
    if (!v.length) continue;
    if (v.length === 1) { lines.push(tidy(`- ${cell.label}: 1 reading, ${big(v[0])} ${cell.unit || ''}${out ? ', outside the normal range' : ''}.`)); continue; }
    const avg = v.reduce((s, x) => s + x, 0) / v.length;
    lines.push(tidy(`- ${cell.label}: ${plural(v.length, 'reading')}, average ${big(avg)} ${cell.unit || ''}, from ${big(Math.min(...v))} to ${big(Math.max(...v))}${out}.`));
  }
  return lines;
}

export function checkinLines(get, since, now) {
  const mood = recentOf(get, 'mood', since, now);
  const moods = ['good', 'fair', 'bad'].map((v) => `${mood.filter((x) => x.value === v).length} ${v}`).join(', ');
  const steps = recentOf(get, 'attitude', since, now).map((x) => fatigueStep(x.value)).filter(Number.isFinite);
  const energy = steps.length ? `energy ${steps.filter((n) => n >= FATIGUE_RULE.lowFrom).length} of ${steps.length} answers at ${FATIGUE_RULE.lowFrom} or more (1 fully alert, 7 completely exhausted)` : 'energy not answered';
  const lines = [`- Check-ins: mood ${moods}; ${energy}.`];
  // NASA's medical standard asks for a daily sleep assessment, reviewed weekly in the private medical conference.
  const sleep = recentOf(get, 'sleepQuality', since, now).map((x) => Number(x.value)).filter(Number.isFinite);
  if (sleep.length) lines.push(`- Sleep rating (1 bad, 7 great): ${fmt(sleep.reduce((s, x) => s + x, 0) / sleep.length)} of 7 on average over ${plural(sleep.length, 'night')}, from ${Math.min(...sleep)} to ${Math.max(...sleep)}.`);
  return lines;
}

// ---------- exercise, reaction tests and the eyes ----------
export function exerciseLines(get, since, now) {
  const v = recentOf(get, 'exercise', since, now).map((x) => Number(x.value)).filter(Number.isFinite);
  if (!v.length) return [];
  const days = new Set(recentOf(get, 'exercise', since, now).map((x) => new Date(ms(x.time)).toISOString().slice(0, 10))).size;
  const avg = v.reduce((s, x) => s + x, 0) / v.length;
  return [`- Exercise: ${Math.round(avg)} minutes a day on average over ${plural(days, 'day')}, from ${Math.round(Math.min(...v))} to ${Math.round(Math.max(...v))} (recorded, not judged: each prescription is personal).`];
}

// Each reaction test of the window, newest first, against the person's own earlier runs (before flight first).
export function reactionLines(runs, since, now, max = SUMMARY_RULES.maxRuns) {
  const all = (Array.isArray(runs) ? runs : []).filter((r) => r && Number.isFinite(Number(r.median)) && Number.isFinite(ms(r.time))).map((r) => ({ ...r, median: Number(r.median) }));
  const mine = all.filter((r) => inWindow(r, since, now)).sort((a, b) => ms(b.time) - ms(a.time));
  const lines = mine.slice(0, max).map((r) => {
    const cmp = compareToOwn(r, all.filter((x) => x !== r && ms(x.time) < ms(r.time)));
    const length = (r.mode || 'full') === 'demo' ? '30 seconds' : '3 minutes';
    const counts = [Number.isFinite(r.lapses) ? plural(r.lapses, 'lapse') : null, Number.isFinite(r.falseStarts) ? plural(r.falseStarts, 'false start') : null].filter(Boolean).join(', ');
    const against = cmp.state === 'first' || cmp.state === 'none' ? 'nothing of my own to compare with yet'
      : `${({ slower: 'slower than', similar: 'about the same as', faster: 'faster than' })[cmp.state]} ${String(cmp.basis).replace(/^your /, 'my ')} (median ${cmp.baseline} ms, ${plural(cmp.runs, 'run')})`;
    return `- Reaction test, ${gmtText(r.time)}, ${length}: median ${Math.round(r.median)} ms${counts ? `, ${counts}` : ''}; ${against}.`;
  });
  if (mine.length > max) lines.push(`- And ${plural(mine.length - max, 'more reaction test')}.`);
  return lines;
}

// The eye self-check answers of the window, or the latest one within rareDays with its date; the latest OCT change
// likewise, against NASA's two levels (config.js thresholds, drafts).
export function eyeLines(get, since, now, rareDays = SUMMARY_RULES.rareDays) {
  const lines = [];
  const ago = (t) => { const d = Math.floor((now - ms(t)) / DAY); return d >= 1 ? `, ${plural(d, 'day')} ago` : ''; };
  const all = (ind) => (typeof get === 'function' ? get(ind) || [] : []).filter((x) => x && ms(x.time) <= now);
  const vision = cellOf('visionCheck');
  const answer = (v) => { const a = (vision.answers || []).find((x) => x.value === v); return a ? a.short || a.label : String(v); };
  const checks = all('visionCheck');
  const inWeek = checks.filter((x) => ms(x.time) >= since);
  if (inWeek.length) lines.push(`- Eye self-check (SANS): ${inWeek.map((x) => `"${answer(x.value)}" (${gmtText(x.time)})`).join('; ')}.`);
  else if (checks.length && now - ms(checks[checks.length - 1].time) <= rareDays * DAY) {
    const x = checks[checks.length - 1];
    lines.push(`- Eye self-check (SANS), the last one, ${gmtText(x.time)}${ago(x.time)}: "${answer(x.value)}".`);
  }
  const oct = cellOf('octChange');
  const results = all('octChange');
  const last = results[results.length - 1];
  if (last && now - ms(last.time) <= Math.max(rareDays, SUMMARY_RULES.days) * DAY && Number.isFinite(Number(last.value))) {
    const v = Number(last.value);
    const levels = [...(oct.thresholds || [])].sort((a, b) => b.min - a.min);
    const hit = levels.find((t) => v >= t.min);
    const low = levels[levels.length - 1];
    const where = hit ? `at or above ${hit.min} µm, NASA's ${hit.text} (a draft line here)` : low ? `below NASA's ${low.min} µm ${low.text} (a draft line here)` : '';
    lines.push(`- Retinal thickness change (OCT), ${gmtText(last.time)}${ago(last.time)}: ${v > 0 ? '+' : ''}${fmt(v)} µm${where ? `, ${where}` : ''}.`);
  }
  return lines;
}

// ---------- the private logs: symptoms and medicines ----------
// When a logged medicine was taken: takenAt when the entry has it, otherwise the time of the entry (as quicklog.js).
const takenMs = (x) => { const at = x && x.value && typeof x.value.takenAt === 'string' ? Date.parse(x.value.takenAt) : NaN; return Number.isFinite(at) ? at : ms(x && x.time); };

// The symptom entries of the window, newest first; a headache carries the cabin CO2 before it. skip: entry times
// (ISO) already written elsewhere in the draft (a flagged item), left out here.
export function symptomLines(get, since, now, { co2 = [], skip = [], max = SUMMARY_RULES.maxSymptoms } = {}) {
  const link = co2Link();
  const left = new Set(skip.map((t) => ms(t)));
  const list = recentOf(get, 'symptoms', since, now).filter((x) => !left.has(ms(x.time))).sort((a, b) => ms(b.time) - ms(a.time));
  const lines = list.slice(0, max).map((x) => {
    const air = link && x.value && x.value.symptom === link.symptom ? `; ${co2Short(co2Around(co2, x.time, { link }))}` : '';
    return `- Symptom: ${logText('symptoms', x.value)}, ${gmtText(x.time)}${air}.`;
  });
  if (list.length > max) lines.push(`- And ${plural(list.length - max, 'more symptom entry', 'more symptom entries')}.`);
  return lines;
}

// The medicines of the window, one line per medicine: how much in all, in how many entries, from when to when.
export function medicineLines(get, since, now, max = SUMMARY_RULES.maxMedicines) {
  const list = (typeof get === 'function' ? get('medicines') || [] : []).filter((x) => x && x.value && takenMs(x) >= since && takenMs(x) <= now);
  const groups = new Map();
  for (const x of list.sort((a, b) => takenMs(a) - takenMs(b))) {
    const key = x.value.medicine === 'other' ? `other:${String(x.value.name).toLowerCase()}` : x.value.medicine;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(x);
  }
  const rows = [...groups.values()].sort((a, b) => takenMs(b[b.length - 1]) - takenMs(a[a.length - 1]));
  const lines = rows.slice(0, max).map((g) => {
    const v = g[0].value;
    if (g.length === 1) return `- Medicine: ${logText('medicines', { ...v, takenAt: undefined })}, ${gmtText(takenMs(g[0]))}.`;
    const total = g.reduce((s, x) => s + (Number(x.value.amount) || 0), 0);
    const what = [v.name, v.strength].filter(Boolean).join(' ');
    // Entries logged within the same minute read "at GMT 319/07:15", not "GMT 319/07:15 to GMT 319/07:15".
    const [from, to] = [gmtText(takenMs(g[0])), gmtText(takenMs(g[g.length - 1]))];
    return `- Medicine: ${what}, ${amountText(total, v.unit || 'dose')} in ${g.length} entries, ${from === to ? `at ${from}` : `${from} to ${to}`}.`;
  });
  if (rows.length > max) lines.push(`- And ${plural(rows.length - max, 'more medicine')}.`);
  return lines;
}

// Every kit list finding of the window (quicklog.js kitFindings looks at the 24 hours before one time, so it is
// asked at the time of each entry): one finding per medicine for each run of 24 hours past its limit, the largest
// total kept, and each pair of medicines taken too close together.
export function weekFindings(get, since, now, { nightHours = 12, cell = cellOf('medicines') } = {}) {
  const list = (typeof get === 'function' ? get('medicines') || [] : []).filter((x) => x && x.value && takenMs(x) <= now).sort((a, b) => takenMs(a) - takenMs(b));
  const out = [];
  for (const e of list) {
    const t = takenMs(e);
    if (t < since) continue;
    for (const f of kitFindings(list.filter((x) => takenMs(x) <= t), { now: new Date(t), nightHours, cell })) {
      if (Date.parse(f.time) !== t) continue; // a finding this entry completes; earlier ones were found at their own time
      if (f.rule === 'max') {
        const same = out.find((x) => x.rule === 'max' && x.medicine === f.medicine && t - Date.parse(x.time) <= KIT_HOURS * HOUR);
        if (same) { if (f.total >= same.total) Object.assign(same, f); continue; }
      } else if (out.some((x) => x.rule === 'night' && x.time === f.time && x.medicines.join() === f.medicines.join())) continue;
      out.push({ ...f });
    }
  }
  return out.sort((a, b) => Date.parse(b.time) - Date.parse(a.time));
}

const findingKey = (f) => (f.rule === 'max' ? `max|${f.medicine}|${f.time}` : `night|${f.medicines.join('+')}|${f.time}`);

export function findingLines(get, since, now, { nightHours = 12, skip = [], max = SUMMARY_RULES.maxFindings } = {}) {
  const cell = cellOf('medicines');
  const left = new Set(skip.map(findingKey));
  const found = weekFindings(get, since, now, { nightHours, cell }).filter((f) => !left.has(findingKey(f)));
  const name = (key) => { const k = cell.kit.find((x) => x.key === key); return `${k.name} ${k.strength}`; };
  const lines = found.slice(0, max).map((f) => (f.rule === 'max'
    ? `- Kit list: ${name(f.medicine)}, ${amountText(f.total, f.unit)} within ${KIT_HOURS} hours, up to ${gmtText(f.time)}. The kit list says: "${f.note}"`
    : `- Kit list: ${kitFindingText(f, cell)}`));
  if (found.length > max) lines.push(`- And ${plural(found.length - max, 'more kit list finding')}.`);
  return lines;
}

// The private part of a draft: symptoms, medicines and kit list findings of the window.
export function privateLines(input, since, now, { skipSymptoms = [], skipFindings = [] } = {}) {
  return [
    ...symptomLines(input.get, since, now, { co2: input.co2, skip: skipSymptoms }),
    ...medicineLines(input.get, since, now),
    ...findingLines(input.get, since, now, { nightHours: input.nightHours, skip: skipFindings }),
  ];
}

// What the window holds no reading of, said in one line, so a gap is not read as "nothing to report".
function missingLine(have) {
  const gone = [['exercise', 'exercise minutes'], ['reaction', 'a reaction test'], ['eyes', 'an eye self-check or OCT result']].filter(([k]) => !have[k]).map(([, w]) => w);
  return gone.length ? [`- Nothing logged in these days: ${gone.join(', ')}.`] : [];
}

// Says when the draft holds made-up example data, so a sent copy never passes for a real record.
function exampleLine(input, since, now) {
  const inds = [...VITALS, 'mood', 'attitude', 'sleepQuality', 'exercise', 'visionCheck', 'octChange', 'symptoms', 'medicines'];
  const made = inds.some((ind) => recentOf(input.get, ind, since, now).some((x) => x.example)) || (input.runs || []).some((r) => r && r.example && inWindow(r, since, now));
  return made ? ['', 'Note: this summary includes made-up example data (the example flight is on).'] : [];
}

// ---------- the two drafts ----------
// The weekly private medical conference: the numbers, the check-ins, exercise, reaction tests and the eyes, what the
// program flagged (input.flagged: short titles), then the private logs under their own heading, then room for the
// person's own words.
export function pmcDraft(input) {
  const now = ms(input.now);
  const since = now - SUMMARY_RULES.days * DAY;
  const ex = exerciseLines(input.get, since, now);
  const rt = reactionLines(input.runs, since, now);
  const eyes = eyeLines(input.get, since, now);
  const lines = [`For my private medical conference. ${input.name}${input.flightDay ? `, ${input.flightDay}` : ''}, the last ${SUMMARY_RULES.days} days:`,
    ...vitalLines(input.get, since, now), ...checkinLines(input.get, since, now), ...ex, ...rt, ...eyes,
    ...missingLine({ exercise: ex.length, reaction: rt.length, eyes: eyes.length })];
  if (input.flagged && input.flagged.length) lines.push(`- Flagged by the program: ${input.flagged.join('; ')}.`);
  const priv = privateLines(input, since, now);
  if (priv.length) lines.push('', `From my private log of the last ${SUMMARY_RULES.days} days:`, ...priv);
  lines.push(...exampleLine(input, since, now));
  lines.push('', 'What I want to talk about:', '');
  return lines.join('\n');
}

// The sections "Message the doctor" adds to the flagged items (src/crew.js summaryFor): all of them from Today, or
// only the measure's own from its page. skip: what the flagged items already say ({ symptoms: [times], findings }).
// Returns lines, or [] for a measure with no section of its own.
export const SECTIONS_FOR = { symptoms: ['private-symptoms'], medicines: ['private-medicines'], exercise: ['exercise'], reaction: ['reaction'], visionCheck: ['eyes'], octChange: ['eyes'], octScan: ['eyes'] };
export function doctorSections(input, { indicator = null, skip = {} } = {}) {
  const now = ms(input.now);
  const since = now - SUMMARY_RULES.days * DAY;
  const want = indicator ? SECTIONS_FOR[indicator] || [] : ['exercise', 'reaction', 'eyes', 'private-symptoms', 'private-medicines'];
  if (!want.length) return [];
  const has = (k) => want.includes(k);
  const week = [...(has('exercise') ? exerciseLines(input.get, since, now) : []), ...(has('reaction') ? reactionLines(input.runs, since, now) : []), ...(has('eyes') ? eyeLines(input.get, since, now) : [])];
  const priv = [
    ...(has('private-symptoms') ? symptomLines(input.get, since, now, { co2: input.co2, skip: skip.symptoms || [] }) : []),
    ...(has('private-medicines') ? [...medicineLines(input.get, since, now), ...findingLines(input.get, since, now, { nightHours: input.nightHours, skip: skip.findings || [] })] : []),
  ];
  const out = [];
  if (week.length) out.push(`My last ${SUMMARY_RULES.days} days:`, ...week);
  if (priv.length) out.push(...(out.length ? [''] : []), `From my private log of the last ${SUMMARY_RULES.days} days:`, ...priv);
  if (out.length) out.push(...exampleLine(input, since, now));
  return out;
}
