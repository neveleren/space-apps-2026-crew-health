// Export for medical records: one person's number readings as an HL7 FHIR R4 Bundle with LOINC codes and UCUM
// units. Replaces fhirBundle() in crew.js with the fixes the night research found (same inputs: the machine's
// history, the person, the period, the example flag). Canada's space medical module prototypes (CSA C2M2) keep
// their records in HL7 FHIR (https://publications.spaceops.org/2025/download_by_id.php?id=0092); NASA has not
// published the format of its own crew medical record, so this file is an offer, not a link to a NASA system.
//
// Rules followed, with their sources:
// - Bundle of type "collection"; every entry gets fullUrl "urn:uuid:..." and references point to those fullUrls
//   ("Where a resource is not assigned a persistent identity that can be used in the Bundle, a UUID should be used
//   (urn:uuid:...)", and a reference that is a URN resolves to the entry with that fullUrl):
//   https://hl7.org/fhir/R4/bundle.html
// - Vital signs: category "vital-signs", the LOINC codes the profile fixes, UCUM units; oxygen saturation is
//   2708-6, and 59408-5 "MAY be included as an additional observation code"; blood pressure is the 85354-9 panel
//   with 8480-6 and 8462-4 components: https://hl7.org/fhir/R4/observation-vitalsigns.html
// - Categories laboratory (specimen results) and activity ("laps swum, steps, sleep data"), exam (simple instruments
//   on the body): https://hl7.org/fhir/R4/codesystem-observation-category.html
// - Observation.device, "The device used to generate the observation data": https://hl7.org/fhir/R4/observation-definitions.html
// - Provenance (target, recorded, agent with type and who, entity, reason): https://hl7.org/fhir/R4/provenance.html
//   with agent types from http://terminology.hl7.org/CodeSystem/provenance-participant-type (author, enterer)
// - Made-up data carry the security label HTEST "test health data":
//   https://terminology.hl7.org/CodeSystem-v3-ActReason.json
// - Every LOINC code below was looked up tonight in NLM's LOINC table
//   (https://clinicaltables.nlm.nih.gov/api/loinc_items/v3/search?terms=<code>); the names are LOINC's.
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".
