export const LOINC_SOURCES = Object.values(MEASURES).flatMap((m) => [...m.codes, ...Object.values(m.parts || {})]).map(([code, name]) => ({ code, name, url: LOOKUP(code) }));

const labelOf = Object.fromEntries(CELLS.map((c) => [c.indicator, c.label]));
const DAY = 86400000;
const ms = (t) => (t instanceof Date ? t.getTime() : new Date(t).getTime());

export function newUuid() {
  const c = globalThis.crypto;
  if (c && typeof c.randomUUID === 'function') return c.randomUUID();
  const b = new Uint8Array(16);
  if (c && typeof c.getRandomValues === 'function') c.getRandomValues(b);
  else for (let i = 0; i < 16; i += 1) b[i] = Math.floor(Math.random() * 256);
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = [...b].map((x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

const coding = (system, code, display) => ({ system, code, display });
const quantity = (value, m) => ({ value: Number(value), unit: m.unit, system: UCUM, code: m.ucum });

// What each kind of origin looks like in Provenance: the agent type, what was done, and whether the data are made up.
const ORIGIN = {
  device: { agent: ['author', 'Author'], activity: 'Measured by a device and received by the program', test: false },
  import: { agent: ['author', 'Author'], activity: 'Measured by a device and imported from its exported file', test: false },
  feed: { agent: ['author', 'Author'], activity: 'Read from a public data feed', test: false },
  typed: { agent: ['enterer', 'Enterer'], activity: 'Typed in by hand', test: false },
  dataset: { agent: ['author', 'Author'], activity: 'Taken from NASA\'s Open Science Data Repository', test: false },
  simulated: { agent: ['author', 'Author'], activity: 'Simulated: a button on the technical view imitated a device', test: true },
  example: { agent: ['author', 'Author'], activity: 'Made up for the example flight, shaped like published flight studies', test: true },
  unknown: { agent: ['author', 'Author'], activity: 'Origin not recorded', test: false },
};

// fhirBundle({ machine | history, person, from, to | days, example, now, uuid }) -> { bundle, count, skipped, period }
// - machine: the engine's machine (its history(personId, indicator) is used), or history: that function itself
// - person: the person object (or its id); the ship and the real Inspiration4 people are refused
// - from and to: the period (Date, ISO text or ms); without from, the last `days` days up to `to` (default now)
// - example: the example flight switch; when on, the person and every reading carry HTEST
export function fhirBundle({ machine = null, history = null, person, from = null, to = null, days = 30, example = false, now = new Date(), uuid = newUuid } = {}) {
  const hist = history || (machine ? (id, ind) => machine.history(id, ind) : null);
  if (typeof hist !== 'function') throw new TypeError('fhirBundle needs machine or history');
  const p = typeof person === 'string' ? { id: person } : person;
  if (!p || !p.id) throw new TypeError('fhirBundle needs a person');
  if (p.vehicle) throw new Error('Cabin air belongs to the ship, not to a person\'s medical record.');
  if (p.real) throw new Error('The real Inspiration4 records are NASA\'s data and are not exported as a patient record.');
  const end = to == null ? ms(now) : ms(to);
  const start = from == null ? end - days * DAY : ms(from);
  if (!Number.isFinite(start) || !Number.isFinite(end)) throw new RangeError('fhirBundle: the period is not a time');
  const recorded = new Date(now).toISOString();
  const security = (on) => (on ? { security: [HTEST] } : undefined);

  const patientUrl = `urn:uuid:${uuid()}`;
  const patient = { fullUrl: patientUrl, resource: { resourceType: 'Patient', meta: security(example), identifier: [{ system: 'urn:just-for-fun:crew', value: p.id }], active: true } };
  const devices = new Map(); // origin key -> device entry
  const groups = new Map(); // origin key -> { info, refs, first, last }
  const observations = [];
  const skipped = [];

  const deviceFor = (info) => {
    if (info.origin === 'typed') return null;
    if (!devices.has(info.key)) {
      const url = `urn:uuid:${uuid()}`;
      const notes = [{ text: info.text }];
      devices.set(info.key, { fullUrl: url, resource: { resourceType: 'Device', meta: security(example || ORIGIN[info.origin].test), deviceName: [{ name: info.label, type: 'user-friendly-name' }], ...(info.standard ? { type: { text: info.standard } } : {}), note: notes } });
    }
    return devices.get(info.key).fullUrl;
  };

  for (const [indicator, m] of Object.entries(MEASURES)) {
    for (const x of hist(p.id, indicator)) {
      const t = ms(x.time);
      if (!(t >= start && t <= end)) continue;
      const isBp = indicator === 'bp';
      const ok = isBp ? x.value && Number.isFinite(Number(x.value.sys)) && Number.isFinite(Number(x.value.dia)) : Number.isFinite(Number(x.value));
      if (!ok) { skipped.push({ indicator, time: new Date(t).toISOString(), reason: 'not a number' }); continue; }
      const info = sourceInfo(x.source, { example: x.example });
      const origin = ORIGIN[info.origin] || ORIGIN.unknown;
      const url = `urn:uuid:${uuid()}`;
      const deviceUrl = deviceFor(info);
      const resource = {
        resourceType: 'Observation',
        meta: security(example || origin.test),
        status: 'final',
        ...(m.category ? { category: [{ coding: [coding(CATEGORY, m.category, m.category === 'vital-signs' ? 'Vital Signs' : m.category[0].toUpperCase() + m.category.slice(1))] }] } : {}),
        code: { coding: m.codes.map(([code, display]) => coding(LOINC, code, display)), text: labelOf[indicator] || m.codes[0][1] },
        subject: { reference: patientUrl },
        effectiveDateTime: new Date(t).toISOString(),
        ...(info.origin === 'typed' ? { performer: [{ reference: patientUrl }] } : {}),
        ...(isBp
          ? { component: [
            { code: { coding: [coding(LOINC, ...m.parts.sys)] }, valueQuantity: quantity(x.value.sys, m) },
            { code: { coding: [coding(LOINC, ...m.parts.dia)] }, valueQuantity: quantity(x.value.dia, m) },
          ] }
          : { valueQuantity: quantity(x.value, m) }),
        ...(deviceUrl ? { device: { reference: deviceUrl, display: info.label } } : {}),
      };
      observations.push({ fullUrl: url, resource });
      if (!groups.has(info.key)) groups.set(info.key, { info, refs: [], first: t, last: t });
      const g = groups.get(info.key);
      g.refs.push({ reference: url });
      g.first = Math.min(g.first, t);
      g.last = Math.max(g.last, t);
    }
  }

  // One Provenance per origin: who or what produced these values, and how.
  const provenances = [...groups.values()].map((g) => {
    const origin = ORIGIN[g.info.origin] || ORIGIN.unknown;
    const who = g.info.origin === 'typed' ? { reference: patientUrl, display: 'the person, typing the value in' } : { reference: devices.get(g.info.key).fullUrl, display: g.info.label };
    return {
      fullUrl: `urn:uuid:${uuid()}`,
      resource: {
        resourceType: 'Provenance',
        meta: security(example || origin.test),
        target: g.refs,
        occurredPeriod: { start: new Date(g.first).toISOString(), end: new Date(g.last).toISOString() },
        recorded,
        ...(example || origin.test ? { reason: [{ coding: [HTEST] }] } : {}),
        activity: { text: origin.activity },
        agent: [{ type: { coding: [coding(PARTICIPANT, ...origin.agent)] }, who }],
        ...(g.info.origin === 'import' ? { entity: [{ role: 'source', what: { display: g.info.label } }] } : {}),
      },
    };
  });

  const bundle = {
    resourceType: 'Bundle',
    meta: security(example),
    identifier: { system: 'urn:ietf:rfc:3986', value: `urn:uuid:${uuid()}` },
    type: 'collection',
    timestamp: recorded,
    entry: [patient, ...devices.values(), ...observations, ...provenances],
  };
  return { bundle: JSON.parse(JSON.stringify(bundle)), count: observations.length, skipped, period: { start: new Date(start).toISOString(), end: new Date(end).toISOString() } };
}

export const fhirFileName = (personId, now = new Date()) => `fhir-${personId}-${new Date(now).toISOString().slice(0, 10)}.json`;

// A structural self-check (not the official HL7 validator): the problems found, an empty list when none.
// Checks: Bundle type, unique urn:uuid fullUrls, every reference resolves inside the Bundle, the fields R4 requires
// for Observation (status, code, subject, a value or components), Device and Provenance (target, recorded, agent.who),
// vital-signs category and UCUM units on vital signs, and 2708-6 with 59408-5 on oxygen saturation.
export function checkBundle(bundle) {
  const problems = [];
  if (!bundle || bundle.resourceType !== 'Bundle') return ['not a Bundle'];
  if (bundle.type !== 'collection') problems.push(`Bundle.type is ${bundle.type}`);
  const entries = Array.isArray(bundle.entry) ? bundle.entry : [];
  const urls = new Set();
  for (const e of entries) {
    if (!/^urn:uuid:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(e.fullUrl || '')) problems.push(`fullUrl is not a urn:uuid: ${e.fullUrl}`);
    if (urls.has(e.fullUrl)) problems.push(`fullUrl twice: ${e.fullUrl}`);
    urls.add(e.fullUrl);
  }
  const refs = [];
  const walk = (node, path) => {
    if (Array.isArray(node)) node.forEach((n, i) => walk(n, `${path}[${i}]`));
    else if (node && typeof node === 'object') for (const [k, v] of Object.entries(node)) { if (k === 'reference' && typeof v === 'string') refs.push({ path, ref: v }); else walk(v, `${path}.${k}`); }
  };
  for (const e of entries) {
    const r = e.resource || {};
    walk(r, r.resourceType);
    if (r.resourceType === 'Observation') {
      if (!r.status || !r.code || !r.subject) problems.push('Observation without status, code or subject');
      if (!r.valueQuantity && !(Array.isArray(r.component) && r.component.length)) problems.push('Observation without a value');
      const codes = (r.code && r.code.coding ? r.code.coding : []).map((c) => c.code);
      const vital = (r.category || []).some((c) => (c.coding || []).some((x) => x.code === 'vital-signs'));
      if (['8867-4', '9279-1', '8310-5', '2708-6', '85354-9'].some((c) => codes.includes(c)) && !vital) problems.push(`vital sign ${codes[0]} without the vital-signs category`);
      if (codes.includes('59408-5') && !codes.includes('2708-6')) problems.push('oxygen saturation without 2708-6');
      const qs = [r.valueQuantity, ...(r.component || []).map((c) => c.valueQuantity)].filter(Boolean);
      for (const q of qs) if (q.system !== UCUM || !q.code || !Number.isFinite(q.value)) problems.push(`value without a UCUM unit in ${codes[0]}`);
    }
    if (r.resourceType === 'Provenance') {
      if (!Array.isArray(r.target) || !r.target.length || !r.recorded) problems.push('Provenance without target or recorded');
      if (!Array.isArray(r.agent) || !r.agent.length || r.agent.some((a) => !a.who)) problems.push('Provenance agent without who');
    }
  }
  for (const { path, ref } of refs) if (!urls.has(ref)) problems.push(`${path} points outside the Bundle: ${ref}`);
  return problems;
}
