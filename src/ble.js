// Standard Bluetooth health devices, read in the browser (Web Bluetooth): a thermometer, a blood pressure cuff and a
// pulse oximeter, next to the heart rate strap. The same path as connectHeartRate() in crew.js: the browser shows its
// own device chooser, the device sends each measurement, the program keeps it. Works in Chrome or Edge on a computer;
// not in Firefox, not in Safari, not on iPads (MDN browser data: https://github.com/mdn/browser-compat-data/blob/main/api/Bluetooth.json).
//
// Formats (every one is a Bluetooth SIG standard, all values least significant octet first):
// - GATT Specification Supplement, version 2026-09-09:
//   https://btprodspecificationrefs.blob.core.windows.net/gatt-specification-supplement/GATT_Specification_Supplement.pdf
//   section 3.239 Temperature Measurement, 3.242 Temperature Type, 3.34 Blood Pressure Measurement,
//   3.126 Heart Rate Measurement, 3.80 Date Time, Table 2.1 special FLOAT and SFLOAT values.
// - Pulse Oximeter Service 1.0.1, sections 1.7, 3.1 (spot-check), 3.2 (continuous), Tables 3.4 and 3.5 (status bits):
//   https://www.bluetooth.com/wp-content/uploads/Files/Specification/HTML/PLXS_v1.0.1/out/en/index-en.html
// - FLOAT (8-bit exponent, 24-bit mantissa) and SFLOAT (4-bit exponent, 12-bit mantissa), base 10, two's complement,
//   with the worked examples 36.4 = 0xFF00016C and 114 = 0x0072: Bluetooth SIG, Personal Health Devices Transcoding
//   white paper v16, section 2.2: https://www.bluetooth.com/wp-content/uploads/2019/03/PHD_Transcoding_WP_v16.pdf
// - Service and characteristic names for Web Bluetooth: https://github.com/WebBluetoothCG/registries
// Not tried with a real thermometer, cuff or oximeter yet: the parsers pass the byte examples of the specifications
// (tests/integrations.test.js). Glucose meters and scales are left out on purpose: a glucose meter needs bonding and a
// record access procedure, and a scale does not work in weightlessness.
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".
import { isPlausible } from './csv-import.js';

// ---------- numbers in the IEEE 11073-20601 formats ----------
// GSS Table 2.1: the five reserved special values.
const SPECIAL_SFLOAT = { 0x07ff: 'NaN', 0x0800: 'NRes', 0x07fe: '+INF', 0x0802: '-INF', 0x0801: 'reserved' };
const SPECIAL_FLOAT = { 0x007fffff: 'NaN', 0x00800000: 'NRes', 0x007ffffe: '+INF', 0x00800002: '-INF', 0x00800001: 'reserved' };

// mantissa x 10^exponent, rounded to the precision the exponent gives (so 364 x 10^-1 is 36.4, not 36.400000000000006).
// toFixed takes at most 100 digits; a FLOAT exponent can reach -128, which would throw on a malformed value.
const scaled = (mantissa, exponent) => (exponent < 0 ? Number((mantissa * 10 ** exponent).toFixed(Math.min(-exponent, 100))) : mantissa * 10 ** exponent);

// SFLOAT (medfloat16): 4-bit signed exponent in the top bits, 12-bit signed mantissa below.
export function decodeSfloat(raw) {
  const u = raw & 0xffff;
  if (SPECIAL_SFLOAT[u]) return { value: null, special: SPECIAL_SFLOAT[u] };
  let mantissa = u & 0x0fff;
  let exponent = u >> 12;
  if (mantissa >= 0x0800) mantissa -= 0x1000;
  if (exponent >= 0x8) exponent -= 0x10;
  return { value: scaled(mantissa, exponent), special: null };
}

// FLOAT (medfloat32): 8-bit signed exponent in the top octet, 24-bit signed mantissa below.
export function decodeFloat(raw) {
  const u = raw >>> 0;
  const low = u & 0x00ffffff;
  const top = u >>> 24;
  if (top === 0 && SPECIAL_FLOAT[low]) return { value: null, special: SPECIAL_FLOAT[low] };
  const mantissa = low >= 0x800000 ? low - 0x1000000 : low;
  const exponent = top >= 0x80 ? top - 0x100 : top;
  return { value: scaled(mantissa, exponent), special: null };
}

// Accepts a DataView (what Web Bluetooth gives), an ArrayBuffer, a typed array or a plain array of bytes.
export function toView(x) {
  if (x instanceof DataView) return x;
  if (x instanceof ArrayBuffer) return new DataView(x);
  if (ArrayBuffer.isView(x)) return new DataView(x.buffer, x.byteOffset, x.byteLength);
  if (Array.isArray(x)) return new DataView(Uint8Array.from(x).buffer);
  throw new TypeError('expected bytes');
}

function need(dv, end, what) {
  if (dv.byteLength < end) throw new RangeError(`${what}: ${dv.byteLength} bytes, at least ${end} needed`);
}

// GSS 3.80 Date Time: year (uint16), month, day, hours, minutes, seconds. It carries no time zone, and device clocks
// are often wrong, so the program keeps it only as "the device's own clock" and stamps each reading with the time it
// arrived. A 0 in year, month or day means "not known".
function dateTime(dv, o) {
  need(dv, o + 7, 'Date Time');
  const t = { year: dv.getUint16(o, true), month: dv.getUint8(o + 2), day: dv.getUint8(o + 3), hours: dv.getUint8(o + 4), minutes: dv.getUint8(o + 5), seconds: dv.getUint8(o + 6) };
  const p = (n) => String(n).padStart(2, '0');
  t.text = t.year && t.month && t.day ? `${t.year}-${p(t.month)}-${p(t.day)} ${p(t.hours)}:${p(t.minutes)}:${p(t.seconds)}` : null;
  return t;
}

const bitsOn = (value, names) => names.map((name, bit) => (name && value & (1 << bit) ? name : null)).filter(Boolean);

// ---------- Health Thermometer: Temperature Measurement (GSS 3.239) ----------
// GSS 3.242.1 Temperature Type values.
export const TEMPERATURE_TYPES = { 1: 'armpit', 2: 'body (general)', 3: 'ear (usually earlobe)', 4: 'finger', 5: 'gastrointestinal tract', 6: 'mouth', 7: 'rectum', 8: 'toe', 9: 'tympanum (ear drum)' };

export function parseTemperature(bytes) {
  const dv = toView(bytes);
  need(dv, 5, 'Temperature Measurement');
  const flags = dv.getUint8(0);
  const fahrenheit = Boolean(flags & 0x01); // bit 0: 0 = Celsius, 1 = Fahrenheit
  const f = decodeFloat(dv.getUint32(1, true));
  let o = 5;
  let deviceTime = null;
  if (flags & 0x02) { deviceTime = dateTime(dv, o); o += 7; } // bit 1: Time Stamp present
  let type = null;
  if (flags & 0x04) { need(dv, o + 1, 'Temperature Type'); type = dv.getUint8(o); o += 1; } // bit 2: Temperature Type present
  const celsius = f.value === null ? null : fahrenheit ? Number((((f.value - 32) * 5) / 9).toFixed(2)) : f.value;
  return { celsius, sent: { value: f.value, unit: fahrenheit ? '°F' : '°C' }, special: f.special, deviceTime, type, typeName: TEMPERATURE_TYPES[type] || null };
}

// ---------- Blood Pressure: Blood Pressure Measurement (GSS 3.34) ----------
// 1 kPa = 7.50062 mmHg (1 mmHg = 133.322 Pa, NIST SP 811 Appendix B.8:
// https://www.nist.gov/pml/special-publication-811/nist-guide-si-appendix-b-conversion-factors/nist-guide-si-appendix-b8).
export const MMHG_PER_KPA = 1000 / 133.322387415;

export function parseBloodPressure(bytes) {
  const dv = toView(bytes);
  need(dv, 7, 'Blood Pressure Measurement');
  const flags = dv.getUint8(0);
  const kpa = Boolean(flags & 0x01); // bit 0: 0 = mmHg, 1 = kPa
  const sys = decodeSfloat(dv.getUint16(1, true));
  const dia = decodeSfloat(dv.getUint16(3, true));
  const map = decodeSfloat(dv.getUint16(5, true));
  let o = 7;
  let deviceTime = null;
  if (flags & 0x02) { deviceTime = dateTime(dv, o); o += 7; } // bit 1: Time Stamp
  let pulse = null;
  if (flags & 0x04) { need(dv, o + 2, 'Pulse Rate'); pulse = decodeSfloat(dv.getUint16(o, true)).value; o += 2; } // bit 2: Pulse Rate
  let userId = null;
  if (flags & 0x08) { need(dv, o + 1, 'User ID'); userId = dv.getUint8(o); o += 1; } // bit 3: User ID (255 = unknown user)
  let status = null;
  if (flags & 0x10) { // bit 4: Measurement Status, GSS 3.34.3
    need(dv, o + 2, 'Measurement Status');
    const s = dv.getUint16(o, true);
    o += 2;
    const range = (s >> 3) & 0x03;
    status = {
      bodyMovement: Boolean(s & 0x01),
      cuffTooLoose: Boolean(s & 0x02),
      irregularPulse: Boolean(s & 0x04),
      pulseRange: ['within', 'above the upper limit', 'below the lower limit', null][range],
      improperPosition: Boolean(s & 0x20),
    };
  }
  const mm = (v) => (v === null ? null : kpa ? Number((v * MMHG_PER_KPA).toFixed(1)) : v);
  const special = sys.special || dia.special || null;
  return { sys: mm(sys.value), dia: mm(dia.value), map: mm(map.value), sent: { unit: kpa ? 'kPa' : 'mmHg', sys: sys.value, dia: dia.value, map: map.value }, pulse, userId, status, deviceTime, special };
}

// ---------- Pulse Oximeter: PLX Spot-check and PLX Continuous Measurement (PLXS 1.0.1, 3.1 and 3.2) ----------
// PLXS Table 3.4 (bits 0 to 4 reserved) and Table 3.5.
const PLX_MEASUREMENT_STATUS = [null, null, null, null, null, 'measurement ongoing', 'early estimated data', 'validated data', 'fully qualified data', 'data from measurement storage', 'data for demonstration', 'data for testing', 'calibration ongoing', 'measurement unavailable', 'questionable measurement detected', 'invalid measurement detected'];
const PLX_DEVICE_STATUS = ['extended display update ongoing', 'equipment malfunction detected', 'signal processing irregularity detected', 'inadequate signal detected', 'poor signal detected', 'low perfusion detected', 'erratic signal detected', 'non-pulsatile signal detected', 'questionable pulse detected', 'signal analysis ongoing', 'sensor interference detected', 'sensor unconnected to user', 'unknown sensor connected', 'sensor displaced', 'sensor malfunctioning', 'sensor disconnected'];
// A value the device itself calls unavailable, invalid, questionable, demonstration or test data is not kept as a reading.
const PLX_NOT_REAL = ['measurement unavailable', 'invalid measurement detected', 'questionable measurement detected', 'data for demonstration', 'data for testing', 'early estimated data', 'measurement ongoing'];
const PLX_BAD_SENSOR = ['equipment malfunction detected', 'sensor unconnected to user', 'sensor displaced', 'sensor malfunctioning', 'sensor disconnected', 'unknown sensor connected'];

function plxTail(dv, o, flags, bits) {
  const out = { measurementStatus: [], deviceStatus: [], pai: null };
  if (flags & bits.measurement) { need(dv, o + 2, 'Measurement Status'); out.measurementStatus = bitsOn(dv.getUint16(o, true), PLX_MEASUREMENT_STATUS); o += 2; }
  if (flags & bits.device) { need(dv, o + 3, 'Device and Sensor Status'); out.deviceStatus = bitsOn(dv.getUint16(o, true) | (dv.getUint8(o + 2) << 16), PLX_DEVICE_STATUS); o += 3; }
  if (flags & bits.pai) { need(dv, o + 2, 'Pulse Amplitude Index'); out.pai = decodeSfloat(dv.getUint16(o, true)).value; o += 2; }
  return out;
}

function plxQuality(spo2, pr, tail) {
  const why = [];
  if (spo2.special) why.push(`SpO2 ${spo2.special}`);
  if (pr.special) why.push(`pulse rate ${pr.special}`);
  for (const s of tail.measurementStatus) if (PLX_NOT_REAL.includes(s)) why.push(s);
  for (const s of tail.deviceStatus) if (PLX_BAD_SENSOR.includes(s)) why.push(s);
  return { ok: why.length === 0, why };
}

export function parsePlxSpotCheck(bytes) {
  const dv = toView(bytes);
  need(dv, 5, 'PLX Spot-check Measurement');
  const flags = dv.getUint8(0);
  const spo2 = decodeSfloat(dv.getUint16(1, true));
  const pr = decodeSfloat(dv.getUint16(3, true));
  let o = 5;
  let deviceTime = null;
  if (flags & 0x01) { deviceTime = dateTime(dv, o); o += 7; } // bit 0: Timestamp
  const tail = plxTail(dv, o, flags, { measurement: 0x02, device: 0x04, pai: 0x08 }); // bits 1, 2, 3
  return { mode: 'spot-check', spo2: spo2.value, pulse: pr.value, deviceTime, clockNotSet: Boolean(flags & 0x10), ...tail, quality: plxQuality(spo2, pr, tail) };
}

export function parsePlxContinuous(bytes) {
  const dv = toView(bytes);
  need(dv, 5, 'PLX Continuous Measurement');
  const flags = dv.getUint8(0);
  const spo2 = decodeSfloat(dv.getUint16(1, true)); // SpO2PR-Normal
  const pr = decodeSfloat(dv.getUint16(3, true));
  let o = 5;
  let fast = null;
  let slow = null;
  if (flags & 0x01) { need(dv, o + 4, 'SpO2PR-Fast'); fast = { spo2: decodeSfloat(dv.getUint16(o, true)).value, pulse: decodeSfloat(dv.getUint16(o + 2, true)).value }; o += 4; } // bit 0
  if (flags & 0x02) { need(dv, o + 4, 'SpO2PR-Slow'); slow = { spo2: decodeSfloat(dv.getUint16(o, true)).value, pulse: decodeSfloat(dv.getUint16(o + 2, true)).value }; o += 4; } // bit 1
  const tail = plxTail(dv, o, flags, { measurement: 0x04, device: 0x08, pai: 0x10 }); // bits 2, 3, 4
  return { mode: 'continuous', spo2: spo2.value, pulse: pr.value, fast, slow, ...tail, quality: plxQuality(spo2, pr, tail) };
}

// ---------- Heart Rate Measurement (GSS 3.126), the same format connectHeartRate() reads ----------
export function parseHeartRate(bytes) {
  const dv = toView(bytes);
  need(dv, 2, 'Heart Rate Measurement');
  const flags = dv.getUint8(0);
  const wide = Boolean(flags & 0x01); // bit 0: value is uint16
  need(dv, wide ? 3 : 2, 'Heart Rate Measurement');
  const bpm = wide ? dv.getUint16(1, true) : dv.getUint8(1);
  let o = wide ? 3 : 2;
  const contact = flags & 0x04 ? Boolean(flags & 0x02) : null; // bit 2: contact feature supported, bit 1: contact detected
  if (flags & 0x08) o += 2; // bit 3: Energy Expended present (skipped: the program does not use it)
  const rr = [];
  if (flags & 0x10) for (; o + 2 <= dv.byteLength; o += 2) rr.push(Math.round((dv.getUint16(o, true) / 1024) * 1000)); // 1/1024 s, kept in ms
  return { bpm, contact, rr };
}

// ---------- the four kinds the screen can connect ----------
// stream: the device sends values continuously (once a second or so), so only one reading a minute is kept, as for
// the heart rate strap. A thermometer, a cuff or a spot-check is one measurement at a time and is always kept.
export const DEVICE_KINDS = {
  'heart-rate': { label: 'heart rate monitor', service: 'heart_rate', characteristics: [{ name: 'heart_rate_measurement', parse: parseHeartRate, stream: true }], source: 'ble-heart-rate' },
  thermometer: { label: 'thermometer', service: 'health_thermometer', characteristics: [{ name: 'temperature_measurement', parse: parseTemperature, stream: false }], source: 'ble-thermometer' },
  'blood-pressure': { label: 'blood pressure monitor', service: 'blood_pressure', characteristics: [{ name: 'blood_pressure_measurement', parse: parseBloodPressure, stream: false }], source: 'ble-bp' },
  'pulse-oximeter': { label: 'pulse oximeter', service: 'pulse_oximeter', characteristics: [{ name: 'plx_continuous_measurement', parse: parsePlxContinuous, stream: true }, { name: 'plx_spot_check_measurement', parse: parsePlxSpotCheck, stream: false }], source: 'ble-oximeter' },
};

// One parsed measurement into the program's readings {source, indicator, value, time, unit}. Values the device marks
// as not real, special values and values outside the plausibility limits are left out, with the reason.
export function toReadings(kind, parsed, time = new Date()) {
  const k = DEVICE_KINDS[kind];
  if (!k) throw new Error(`unknown device kind: ${kind}`);
  const at = new Date(time).toISOString();
  const out = [];
  const skipped = [];
  const add = (indicator, value, unit) => {
    if (value === null || value === undefined) return;
    if (!isPlausible(indicator, value)) { skipped.push({ indicator, value, reason: 'outside the plausibility limits' }); return; }
    out.push({ source: k.source, indicator, value, unit, time: at });
  };
  if (kind === 'heart-rate') {
    // A strap that reports no skin contact sends noise (often 0 bpm), which must never raise the crew.
    if (parsed.contact === false) skipped.push({ indicator: 'pulse', reason: 'the strap has no skin contact' });
    else add('pulse', parsed.bpm || null, 'bpm');
  }
  else if (kind === 'thermometer') {
    if (parsed.special) skipped.push({ indicator: 'temp', reason: `the device sent ${parsed.special}` });
    add('temp', parsed.celsius, '°C');
  } else if (kind === 'blood-pressure') {
    if (parsed.special) skipped.push({ indicator: 'bp', reason: `the device sent ${parsed.special}` });
    if (parsed.sys !== null && parsed.dia !== null) add('bp', { sys: parsed.sys, dia: parsed.dia }, 'mmHg');
    add('pulse', parsed.pulse, 'bpm');
  } else if (kind === 'pulse-oximeter') {
    if (!parsed.quality.ok) { skipped.push({ indicator: 'spo2', reason: parsed.quality.why.join(', ') }); return { readings: out, skipped }; }
    add('spo2', parsed.spo2, '%');
    add('pulse', parsed.pulse, 'bpm');
  }
  return { readings: out, skipped };
}

// Connects one device and calls onReading(reading) for each reading to keep. Mirrors connectHeartRate() in crew.js:
// the browser's chooser, the standard service, notifications (Web Bluetooth's startNotifications also subscribes to
// indications, which thermometers and cuffs use). Must be called from a button press.
// Returns null when the person closes the chooser, or a handle { kind, name, characteristics, disconnect() }.
// options: onLive(parsed, readings, skipped) for every value (for a live number on screen), onDisconnect(),
// minIntervalMs for streaming values (default one a minute), bluetooth (for tests), now().
export async function connectHealthDevice(kind, onReading, options = {}) {
  const k = DEVICE_KINDS[kind];
  if (!k) throw new Error(`unknown device kind: ${kind}`);
  const bluetooth = options.bluetooth || (typeof navigator !== 'undefined' ? navigator.bluetooth : undefined);
  if (!bluetooth) {
    const err = new Error('This browser has no Bluetooth: use Chrome or Edge on a computer.');
    err.name = 'NoBluetooth';
    throw err;
  }
  const now = options.now || (() => new Date());
  const minInterval = options.minIntervalMs ?? 60 * 1000;
  let device;
  try {
    device = await bluetooth.requestDevice({ filters: [{ services: [k.service] }] });
  } catch (err) {
    if (err && err.name === 'NotFoundError') return null; // the person closed the chooser
    throw err;
  }
  const server = await device.gatt.connect();
  const service = await server.getPrimaryService(k.service);
  const lastKept = {};
  const subscribed = [];
  for (const c of k.characteristics) {
    let ch;
    try { ch = await service.getCharacteristic(c.name); } catch { continue; } // an optional characteristic this device does not have
    ch.addEventListener('characteristicvaluechanged', (ev) => {
      let parsed;
      try { parsed = c.parse(ev.target.value); } catch (err) { if (options.onLive) options.onLive(null, [], [{ reason: `could not read the value: ${err.message}` }]); return; }
      const t = now();
      const ms = new Date(t).getTime();
      const { readings, skipped } = toReadings(kind, parsed, t);
      if (options.onLive) options.onLive(parsed, readings, skipped);
      for (const r of readings) {
        const key = `${c.name}|${r.indicator}`;
        if (c.stream && lastKept[key] !== undefined && ms - lastKept[key] < minInterval) continue;
        lastKept[key] = ms;
        onReading(r);
      }
    });
    // A characteristic that will not start (for example a cuff that needs pairing first) is skipped; if none starts,
    // the connection is closed below, so a half-open device is never left behind.
    try { await ch.startNotifications(); subscribed.push(c.name); } catch { /* try the next one */ }
  }
  if (!subscribed.length) {
    try { device.gatt.disconnect(); } catch { /* already gone */ }
    throw new Error(`The device has no standard ${k.label} measurement.`);
  }
  device.addEventListener('gattserverdisconnected', () => { if (options.onDisconnect) options.onDisconnect(); });
  return {
    kind,
    name: device.name || k.label,
    characteristics: subscribed,
    disconnect() { try { if (device.gatt.connected) device.gatt.disconnect(); } catch { /* already gone */ } },
  };
}
