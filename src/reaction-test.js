// The 3-minute reaction test (F3), modelled on NASA's Reaction Self Test, the PVT-B that astronauts have used
// on the ISS since 2009 as a personal aid for fatigue (Dinges et al., NASA 2009; Basner et al., Acta
// Astronautica 2011). PVT-B as published: a counter appears after a random wait and counts up in milliseconds;
// the person presses as fast as possible; the response time shows for 1 s; waits vary from 1 to 4 s (the 1-s
// feedback included); a response of 355 ms or more is a lapse; a press with no counter, or under 100 ms, is a
// false start; 30 s without a response counts as a lapse of 30 s.
// The result is compared only with the person's own earlier runs (NASA compares WinSCAT with each astronaut's
// own pre-flight baseline, OCHMO-TB-016). Browser timing is less exact than lab hardware (Bridges et al.,
// PeerJ 2020), so runs are compared on the same computer only. Not a fitness-for-duty test.
// The scoring is pure (no DOM) so Node can test it; runReactionTest() draws the full-screen test.
// Code generated by Claude (Anthropic), an AI system. The "slower" threshold is a placeholder: the team decides.
import { h, fill, btn, supIcon, badge, sourceLine, openOverlay, SRC, BADGE } from './support.js';

const DAY = 24 * 60 * 60 * 1000;
const msOf = (t) => (t instanceof Date ? t.getTime() : typeof t === 'number' ? t : new Date(t).getTime());

export const RT_RULES = {
  fullS: 180, // the 3-minute test
  demoS: 30, // the 30-second demo for judges
  waitMinMs: 1000, // from one response to the next counter, the 1-s feedback included (PVT-B: 1 to 4 s)
  waitMaxMs: 4000,
  feedbackMs: 1000, // the response time shows for 1 s
  lapseMs: 355, // PVT-B lapse: 355 ms or more
  falseStartMs: 100, // under 100 ms counts as a false start
  timeoutMs: 30000, // no response for 30 s: a lapse of 30 s
};

// Placeholder for "clearly slower than your own earlier runs". Not from a study: the team decides.
export const COMPARE_RULE = {
  slowerPct: 10,
  fasterPct: 10,
  placeholder: true,
  text: "Slower or faster means a median at least 10% away from the earlier runs it is compared with. Placeholder: the team's open decision.",
};

export const SAY = "Modelled on NASA's Reaction Self Test. Compare only with yourself; not a fitness-for-duty test.";

export function median(list) {
  const xs = (list || []).filter(Number.isFinite).sort((a, b) => a - b);
  if (!xs.length) return null;
  const mid = Math.floor(xs.length / 2);
  return xs.length % 2 ? xs[mid] : (xs[mid - 1] + xs[mid]) / 2;
}

// trials: [{ rt }] for responses, [{ falseStart: true }] for presses with no counter, [{ rt, timeout: true }]
// for 30 s without a response. Returns { median, lapses, falseStarts, count, durationS, mode, score }:
// median of the valid response times in ms (lapses included, false starts not), the number of lapses
// (355 ms or more), of false starts (no counter, or under 100 ms), of valid responses, and the PVT-B
// performance score: 100% minus lapses and false starts relative to valid responses and false starts.
export function scoreRun(trials, { durationS = RT_RULES.fullS, mode = 'full' } = {}, rules = RT_RULES) {
  const list = Array.isArray(trials) ? trials.filter((x) => x && typeof x === 'object') : [];
  const early = (x) => x.falseStart === true || (Number.isFinite(x.rt) && x.rt < rules.falseStartMs);
  const valid = list.filter((x) => !early(x) && Number.isFinite(x.rt));
  const falseStarts = list.filter(early).length;
  const lapses = valid.filter((x) => x.rt >= rules.lapseMs).length;
  const m = median(valid.map((x) => x.rt));
  const all = valid.length + falseStarts;
  return {
    median: m === null ? null : Math.round(m),
    lapses,
    falseStarts,
    count: valid.length,
    durationS,
    mode,
    score: all ? Math.round(100 * (1 - (lapses + falseStarts) / all)) : null,
  };
}

// The test as a small machine with the clock passed in, so it runs the same in a browser and in a test.
// start(t) once; poll(t) on every frame returns what the screen shows; press(t) for each Space or tap.
export function createSession({ mode = 'full', durationS = null, rng = Math.random, rules = RT_RULES } = {}) {
  const lengthS = Number.isFinite(durationS) && durationS > 0 ? durationS : (mode === 'demo' ? rules.demoS : rules.fullS);
  const dur = lengthS * 1000;
  const trials = [];
  let phase = 'ready'; // ready, wait, stimulus, done
  let startAt = 0;
  let endAt = 0;
  let onset = 0;
  let shownAt = 0;
  let feedback = null; // { kind: 'rt' | 'early' | 'timeout', ms, until }
  const nextWait = () => rules.waitMinMs + Math.min(1, Math.max(0, rng())) * (rules.waitMaxMs - rules.waitMinMs);
  const view = (t) => ({
    phase,
    counterMs: phase === 'stimulus' ? Math.max(0, Math.floor(t - shownAt)) : null,
    feedback: feedback && t < feedback.until ? feedback : null,
    leftMs: Math.max(0, endAt - t),
    progress: dur ? Math.min(1, Math.max(0, (t - startAt) / dur)) : 1,
  });
  return {
    get phase() { return phase; },
    get trials() { return trials.map((x) => ({ ...x })); },
    start(t) {
      startAt = t;
      endAt = t + dur;
      onset = t + nextWait();
      phase = 'wait';
      feedback = null;
      trials.length = 0;
      return view(t);
    },
    poll(t) {
      if (phase === 'wait') {
        if (t >= endAt) phase = 'done'; // no counter starts after the time is up
        else if (t >= onset) { phase = 'stimulus'; shownAt = t; }
      }
      if (phase === 'stimulus' && t - shownAt >= rules.timeoutMs) {
        trials.push({ rt: rules.timeoutMs, timeout: true });
        feedback = { kind: 'timeout', ms: rules.timeoutMs, until: t + rules.feedbackMs };
        onset = t + nextWait();
        phase = t >= endAt ? 'done' : 'wait';
      }
      return view(t);
    },
    press(t) {
      if (phase === 'wait' && t >= endAt) { phase = 'done'; return null; }
      if (phase === 'wait') {
        trials.push({ falseStart: true });
        feedback = { kind: 'early', ms: null, until: t + rules.feedbackMs };
        onset = t + nextWait();
        return { kind: 'early' };
      }
      if (phase === 'stimulus') {
        const rt = t - shownAt;
        if (rt < rules.falseStartMs) {
          trials.push({ falseStart: true, rt });
          feedback = { kind: 'early', ms: null, until: t + rules.feedbackMs };
        } else {
          trials.push({ rt });
          feedback = { kind: 'rt', ms: Math.round(rt), until: t + rules.feedbackMs };
        }
        onset = t + nextWait();
        phase = 'wait';
        return { kind: rt < rules.falseStartMs ? 'early' : 'rt', rt };
      }
      return null;
    },
    result() {
      return scoreRun(trials, { durationS: lengthS, mode }, rules);
    },
  };
}

// Compares a result only with the same person's own earlier runs of the same length. Runs marked
// beforeFlight: true are the baseline when there are any (as NASA does with WinSCAT), otherwise all earlier
// runs. Returns { state: 'none' | 'first' | 'similar' | 'slower' | 'faster', runs, basis, baseline, diffMs,
// diffPct, lapses, baselineLapses, attention, placeholder, text }. attention: true only for "slower", which
// the screen may show as the blue "attention" level, never more.
export function compareToOwn(result, earlier = [], rule = COMPARE_RULE) {
  const modeOf = (r) => (r && r.mode) || 'full';
  if (!result || !Number.isFinite(result.median)) {
    return { state: 'none', runs: 0, basis: null, attention: false, placeholder: true, text: 'This run has no reaction times, so there is nothing to compare.' };
  }
  const same = (Array.isArray(earlier) ? earlier : []).filter((r) => r && r !== result && Number.isFinite(r.median) && r.median > 0 && modeOf(r) === modeOf(result));
  const before = same.filter((r) => r.beforeFlight === true);
  const base = before.length ? before : same;
  // Made-up example runs are never passed off as the person's own.
  const madeUp = base.length > 0 && base.every((r) => r.example === true);
  const basis = `${madeUp ? 'the made-up example' : 'your'} ${before.length ? 'runs from before flight' : 'earlier runs'}`;
  const length = modeOf(result) === 'demo' ? '30-second' : '3-minute';
  if (!base.length) {
    return { state: 'first', runs: 0, basis: null, attention: false, placeholder: true, text: `This is your first ${length} run: there is nothing of your own to compare with yet.` };
  }
  const baseline = median(base.map((r) => r.median));
  const diffMs = result.median - baseline;
  const diffPct = (100 * diffMs) / baseline;
  const state = diffPct >= rule.slowerPct ? 'slower' : diffPct <= -rule.fasterPct ? 'faster' : 'similar';
  const head = { slower: 'Slower than', similar: 'About the same as', faster: 'Faster than' }[state];
  const n = base.length;
  const text = [
    `${head} ${basis}: median ${result.median} ms against ${Math.round(baseline)} ms (${n} ${n === 1 ? 'run' : 'runs'}).`,
    state === 'slower' ? 'In ISS astronauts, nights under 6 hours of sleep went with slower responses. One run is one data point.' : '',
    n === 1 ? 'There is only one earlier run, so compare with care.' : '',
  ].filter(Boolean).join(' ');
  return {
    state, runs: n, basis, baseline: Math.round(baseline), diffMs: Math.round(diffMs), diffPct: Math.round(diffPct),
    lapses: result.lapses, baselineLapses: median(base.map((r) => (Number.isFinite(r.lapses) ? r.lapses : 0))),
    attention: state === 'slower', placeholder: true, text,
  };
}

// Made-up earlier runs for the example crew (marked example: true), so the comparison can be shown in a demo:
// three 3-minute runs and two 30-second runs before launch, with medians near 305 ms, a plausible result for a
// rested person pressing a keyboard in a browser (Claude's choice of example numbers, not from a study).
export function exampleEarlierRuns(launch = Date.now()) {
  const L = msOf(launch);
  const run = (daysBefore, med, lapses, falseStarts, count, mode) => ({
    time: new Date(L - daysBefore * DAY).toISOString(), median: med, lapses, falseStarts, count,
    durationS: mode === 'demo' ? RT_RULES.demoS : RT_RULES.fullS, mode,
    score: Math.round(100 * (1 - (lapses + falseStarts) / (count + falseStarts))), beforeFlight: true, example: true,
  });
  return [run(60, 305, 2, 1, 60, 'full'), run(30, 298, 1, 0, 61, 'full'), run(14, 312, 2, 1, 59, 'full'), run(30, 300, 0, 0, 10, 'demo'), run(14, 310, 1, 1, 9, 'demo')];
}

// The moment of a key press or tap on the page's clock; the event's own time is closer than "now".
const stamp = (e) => {
  const n = performance.now();
  const t = e && e.timeStamp;
  return Number.isFinite(t) && t > 0 && t <= n + 1 && n - t < 1000 ? t : n;
};
const clock = (ms) => { const s = Math.ceil(ms / 1000); return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`; };

// The full-screen test. mode: 'full' (3 minutes) or 'demo' (30 seconds). earlier: the person's own earlier
// results, for the comparison on the result screen. onDone(result) when the person saves the result, with
// { median, lapses, falseStarts, count, durationS, mode, score, time }; onCancel(reason) when it closes
// without one ('cancelled', 'discarded'). Space or a tap answers; Esc stops at any time. Returns { close }.
export function runReactionTest({ mode = 'full', onDone, onCancel, earlier = [], rng = Math.random, durationS = null } = {}) {
  const demo = mode === 'demo';
  const lengthS = Number.isFinite(durationS) && durationS > 0 ? durationS : (demo ? RT_RULES.demoS : RT_RULES.fullS);
  const lengthWord = lengthS % 60 === 0 ? `${lengthS / 60}-minute` : `${lengthS}-second`;
  const lengthText = `${lengthWord} ${demo ? 'demo' : 'test'}`;
  let session = null;
  let screen = 'intro';
  let raf = 0;
  let shownSecond = -1;
  let closed = false;
  let result = null;

  const cancel = (reason) => { stop(); if (closed) return; layer.close(); closed = true; cleanup(); if (typeof onCancel === 'function') onCancel(reason); };
  const press = (e) => {
    if (screen !== 'test' || !session) return;
    session.press(stamp(e));
    paint(session.poll(performance.now()));
  };
  const layer = openOverlay({
    cls: 'sup-rt',
    labelledby: 'sup-rt-title',
    onEscape: () => cancel('cancelled'),
    onKey: (e) => {
      if (screen !== 'test') return false;
      if (e.key === ' ' || e.code === 'Space' || e.key === 'Spacebar') {
        e.preventDefault();
        e.stopPropagation();
        if (!e.repeat) press(e);
        return true;
      }
      return false;
    },
  });
  const panel = h('div', { class: 'sup-rt-panel' });
  layer.root.append(panel);

  const counter = h('span', { class: 'sup-rt-counter mono' });
  const box = h('div', { class: 'sup-rt-box', tabindex: '0', role: 'button', 'aria-label': 'Response box: press Space or tap here when the counter appears' }, counter);
  box.addEventListener('pointerdown', (e) => { e.preventDefault(); box.focus({ preventScroll: true }); press(e); });
  const left = h('span', { class: 'sup-rt-left mono' });
  const bar = h('span', {});

  const paint = (v) => {
    box.classList.toggle('on', v.phase === 'stimulus');
    if (v.phase === 'stimulus') counter.textContent = String(v.counterMs);
    else if (v.feedback && v.feedback.kind === 'rt') counter.textContent = `${v.feedback.ms} ms`;
    else if (v.feedback && v.feedback.kind === 'early') counter.textContent = 'Too soon';
    else if (v.feedback && v.feedback.kind === 'timeout') counter.textContent = 'No response';
    else counter.textContent = '';
    box.classList.toggle('feedback', v.phase !== 'stimulus' && Boolean(v.feedback));
    const sec = Math.ceil(v.leftMs / 1000);
    if (sec !== shownSecond) {
      shownSecond = sec;
      left.textContent = `${clock(v.leftMs)} left`;
      bar.style.width = `${Math.round(v.progress * 100)}%`;
    }
  };
  const frame = (ts) => {
    if (screen !== 'test' || !session) return;
    const v = session.poll(ts);
    paint(v);
    if (v.phase === 'done') finish();
    else raf = requestAnimationFrame(frame);
  };
  const stop = () => { cancelAnimationFrame(raf); raf = 0; };
  const interrupted = () => {
    if (screen !== 'test') return;
    stop();
    session = null;
    screen = 'stopped';
    fill(panel,
      h('h2', { id: 'sup-rt-title' }, 'The test stopped'),
      h('p', {}, 'The window was hidden or lost focus, so this run does not count. Start again when you are ready.'),
      h('div', { class: 'actions' }, btn('primary', 'Start again', () => begin(), 'play'), btn('secondary', 'Close', () => cancel('cancelled'))));
    panel.querySelector('button').focus();
  };
  const onHide = () => { if (document.visibilityState === 'hidden') interrupted(); };
  const onBlur = () => interrupted();
  document.addEventListener('visibilitychange', onHide);
  window.addEventListener('blur', onBlur);
  const cleanup = () => { document.removeEventListener('visibilitychange', onHide); window.removeEventListener('blur', onBlur); };

  const begin = () => {
    screen = 'test';
    shownSecond = -1;
    session = createSession({ mode, durationS, rng });
    fill(panel,
      h('h2', { id: 'sup-rt-title', class: 'sup-rt-small' }, `Reaction test, ${lengthText}`),
      box,
      h('div', { class: 'sup-rt-meta' }, left, h('div', { class: 'sup-rt-bar', 'aria-hidden': 'true' }, bar)),
      h('p', { class: 'note' }, 'Press Space or tap the box when the counter appears. Esc stops.'),
      h('div', { class: 'actions' }, btn('secondary small', 'Stop', () => cancel('cancelled'), 'square')));
    box.focus({ preventScroll: true });
    paint(session.start(performance.now()));
    raf = requestAnimationFrame(frame);
  };

  const finish = () => {
    stop();
    screen = 'result';
    result = { ...session.result(), time: new Date().toISOString() };
    const cmp = compareToOwn(result, earlier);
    const rows = [
      ['Slow responses (355 ms or more)', String(result.lapses)],
      ['Too-early presses', String(result.falseStarts)],
      ['Responses', String(result.count)],
      ['Score by the PVT-B formula (slow and early presses lower it)', result.score === null ? 'none' : `${result.score}%`],
    ];
    fill(panel,
      h('h2', { id: 'sup-rt-title' }, 'Your result'),
      h('div', { class: 'sup-rt-result' },
        h('b', { class: 'mono' }, result.median === null ? 'none' : String(result.median)),
        result.median === null ? null : h('span', {}, 'ms'),
        h('span', { class: 'sup-rt-label' }, `median reaction time, ${lengthText}`)),
      h('dl', { class: 'sup-rt-rows' }, rows.map(([k, v]) => h('div', {}, h('dt', {}, k), h('dd', { class: 'mono' }, v)))),
      h('p', { class: `sup-rt-compare ${cmp.attention ? 'lvc1' : ''}` }, cmp.attention ? supIcon('info', { size: 18 }) : null, cmp.text),
      h('p', { class: 'sup-rt-say' }, SAY),
      h('p', { class: 'note' }, COMPARE_RULE.text),
      h('div', { class: 'actions' },
        btn('primary', 'Save my result', () => { if (closed) return; layer.close(); closed = true; cleanup(); if (typeof onDone === 'function') onDone(result); }, 'check'),
        btn('secondary', 'Do not save', () => cancel('discarded'))));
    panel.querySelector('.btn.primary').focus();
  };

  fill(panel,
    h('div', { class: 'sup-head' }, supIcon('timer', { size: 24 }), h('h2', { id: 'sup-rt-title' }, demo ? `Reaction test: ${lengthWord} demo` : `${lengthWord} reaction test`)),
    h('p', {}, 'When a counter appears in the box, press Space or tap the box as fast as you can. It comes at random moments, every 1 to 4 seconds. Do not press before it appears.'),
    h('p', { class: 'sup-rt-say' }, SAY),
    h('p', { class: 'note' }, 'Use the same computer each time: browser timing is less exact than lab hardware. Esc stops at any time.'),
    h('div', { class: 'actions' }, btn('primary', 'Start', () => begin(), 'play'), btn('secondary', 'Cancel', () => cancel('cancelled'))),
    h('p', {}, badge(BADGE.iss)),
    sourceLine(SRC.rst2009, SRC.pvtb2011));
  panel.querySelector('.btn.primary').focus();

  return {
    close() { if (closed) return; stop(); layer.close(); closed = true; cleanup(); if (typeof onCancel === 'function') onCancel('closed'); },
  };
}
