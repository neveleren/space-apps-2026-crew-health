// The crew's own mission, for a real flight or an analog such as HERA: a name, a launch date and a landing date,
// set in Settings while the example flight is off and kept on this device only. The status line counts the days
// from it (FD for flight day, L- before launch and R+ after return, as NASA's tables and OSDR's Inspiration4 files
// do), and About shows it. With no mission set, no flight day is shown. The mission can also hold the dates of its
// critical tasks (a spacewalk, a docking, robotic arm work, or another one), each a GMT date and start time between
// launch and landing: Coming up lists them, and Today shows the readiness card before each (src/readiness.js).
// Pure functions, so the automatic checks run them in Node. Code generated by Claude (Anthropic), an AI system.

const DAY = 24 * 60 * 60 * 1000;
const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const TIME = /^([01]\d|2[0-3]):([0-5]\d)$/;
export const MISSION_RULES = Object.freeze({ nameMax: 60, defaultName: 'Our mission', tasksMax: 20, taskNameMax: 60 });
// The kinds of critical task a mission can hold; their names and icons are in src/readiness.js (TASK_KINDS).
export const TASK_KIND_KEYS = Object.freeze(['spacewalk', 'docking', 'robotics', 'other']);

// A calendar day written as YYYY-MM-DD that really exists (no 31 June).
function realDay(s) {
  const m = DATE.exec(String(s || ''));
  if (!m) return false;
  const d = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])));
  return d.getUTCFullYear() === Number(m[1]) && d.getUTCMonth() === Number(m[2]) - 1 && d.getUTCDate() === Number(m[3]);
}
const dayNumber = (ms) => Math.floor(ms / DAY); // GMT days since 1 Jan 1970
const dayOf = (s) => dayNumber(Date.parse(`${s}T00:00:00Z`));
const msOf = (t) => (t instanceof Date ? t.getTime() : typeof t === 'number' ? t : new Date(t).getTime());

// Why these fields cannot be saved as the mission, or null when they can.
export function missionProblem({ name = '', launch = '', landing = '' } = {}) {
  if (String(name).trim().length > MISSION_RULES.nameMax) return `The name can have at most ${MISSION_RULES.nameMax} characters.`;
  if (!realDay(launch)) return 'Choose the launch date.';
  if (!realDay(landing)) return 'Choose the landing date.';
  if (dayOf(landing) < dayOf(launch)) return 'The landing cannot be before the launch.';
  return null;
}

// Why this critical task cannot be saved with the mission m, or null when it can. A task is { kind, title, date, time }:
// one of TASK_KIND_KEYS, an optional short name, the GMT date as YYYY-MM-DD and the GMT start as HH:MM, from launch
// day to landing day.
export function taskProblem(t, m = null) {
  if (!t || typeof t !== 'object') return 'Choose the task.';
  if (!TASK_KIND_KEYS.includes(t.kind)) return 'Choose what kind of task it is.';
  if (String(t.title || '').trim().length > MISSION_RULES.taskNameMax) return `The name of the task can have at most ${MISSION_RULES.taskNameMax} characters.`;
  if (!realDay(t.date)) return 'Choose the date of the task.';
  if (!TIME.test(String(t.time || ''))) return 'Choose the start time of the task (GMT).';
  if (m && realDay(m.launch) && realDay(m.landing) && (dayOf(t.date) < dayOf(m.launch) || dayOf(t.date) > dayOf(m.landing))) return 'The task must fall between launch and landing.';
  return null;
}
const taskStart = (t) => `${t.date}T${t.time}:00Z`;
const cleanTask = (t) => (t && typeof t === 'object' ? { kind: String(t.kind || ''), title: String(t.title || '').trim(), date: String(t.date || ''), time: String(t.time || '') } : null);

// A saved mission, checked again when it is read back: { name, launch, landing } or null, with tasks: the critical
// tasks that pass taskProblem, in time order, at most MISSION_RULES.tasksMax, only when there are any.
export function readMission(raw) {
  if (!raw || typeof raw !== 'object') return null;
  const m = { name: String(raw.name || '').trim(), launch: String(raw.launch || ''), landing: String(raw.landing || '') };
  if (missionProblem(m)) return null;
  const tasks = (Array.isArray(raw.tasks) ? raw.tasks : []).map(cleanTask).filter((t) => t && !taskProblem(t, m))
    .sort((a, b) => Date.parse(taskStart(a)) - Date.parse(taskStart(b))).slice(0, MISSION_RULES.tasksMax);
  return tasks.length ? { ...m, tasks } : m;
}

// The mission as the screen's mission object. Midday GMT is used for both dates, so a date never shows as the
// day before in a time zone west of Greenwich; "today" is now. Its critical tasks get their start as a GMT time.
export function missionTimes(m, now = Date.now()) {
  const tasks = (m.tasks || []).map((t, i) => ({ id: `own-${i}`, kind: t.kind, title: t.title || '', start: taskStart(t), crew: null, example: false }));
  return { name: m.name || MISSION_RULES.defaultName, launch: `${m.launch}T12:00:00Z`, landing: `${m.landing}T12:00:00Z`, today: new Date(msOf(now)).toISOString(), own: true, tasks };
}

// The day count for the status line, by GMT calendar days: launch day is flight day 1 and the landing day is the
// last flight day. Before launch it counts down (L-3: 3 days to launch), after landing it counts up (R+2).
export function flightDay(m, now = Date.now()) {
  if (!m) return null;
  const today = dayNumber(msOf(now));
  const launch = dayOf(m.launch);
  const landing = dayOf(m.landing);
  if (!Number.isFinite(today) || !Number.isFinite(launch) || !Number.isFinite(landing)) return null;
  if (today < launch) { const n = launch - today; return { kind: 'before', n, short: `L-${n}`, words: `${n} ${n === 1 ? 'day' : 'days'} to launch` }; }
  if (today > landing) { const n = today - landing; return { kind: 'after', n, short: `R+${n}`, words: `${n} ${n === 1 ? 'day' : 'days'} after landing` }; }
  const n = today - launch + 1;
  return { kind: 'flight', n, short: `FD ${n}`, words: `Flight day ${n}` };
}

// A date of the mission in words, in GMT: "1 Jun 2026".
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
export function missionDay(s) {
  const m = DATE.exec(String(s || ''));
  return m ? `${Number(m[3])} ${MONTHS[Number(m[2]) - 1]} ${m[1]}` : '';
}
