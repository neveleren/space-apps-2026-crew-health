// The medical record screen: draws what src/medrecord.js builds, in the crew screen's own classes (index.html): a card
// for who and which mission, today's levels and alerts, a list of the sections with their counts, then each section,
// newest first, and the sections this prototype does not hold. Read only: every item opens where it came from (a
// measure's page, a blood value, Messages, the cycle card), through the callbacks crew.js passes in. Every level has
// its icon and its word, never colour alone (NASA-STD-3001 Vol 2, Appendix F); private parts carry a word and a lock.
// Every control drawn here has a data-fk key, so the crew screen's keepFocus() finds it again after a redraw (the "?"
// buttons come from src/explain.js and have none). Back from a page opened here returns the keyboard to the very item
// that was pressed (recordReturnKey), not to the first item of the same measure (WCAG 2.4.3).
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".
import { icon } from './icons.js';
import { supIcon, fmtDay } from './support.js';
import { gmtText } from './quicklog.js';
import { LEVEL, LEVEL_WORD } from './state-levels.js';
import { RECORD_RULES } from './medrecord.js';

const LEVEL_ICON = ['circle-check', 'info', 'triangle-alert', 'octagon-alert'];
const LV = ['lv0', 'lv1', 'lv2', 'lv3'];
const cap = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);
const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const SECTION_ICON = { vitals: 'heart-pulse', measures: 'activity', labs: 'test-tube', eyes: 'eye', medicines: 'pill', symptoms: 'stethoscope', alerts: 'bell', encounters: 'message-square', mind: 'brain', cycle: 'calendar-heart', documents: 'file-json-2' };

function h(tag, props = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v === undefined || v === null || v === false) continue;
    if (k === 'class') node.className = v;
    else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2), v);
    else node.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children.flat()) {
    if (c === null || c === undefined || c === false) continue;
    node.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return node;
}
const btn = (kind, label, onclick, ic = null, extra = {}) => h('button', { type: 'button', class: `btn ${kind}`, onclick, ...extra }, ic ? icon(ic, { size: 18 }) : null, label);
const when = (t) => (t ? gmtText(t) : '');
const chip = (lv, text) => h('span', { class: `chip ${LV[lv]}`, 'data-tip': 't:level' }, icon(LEVEL_ICON[lv], { size: 16 }), text);
const privateTag = (note) => h('span', { class: 'rec-private', title: note }, supIcon('lock', { size: 16 }), 'Private');

// "Show all" of a long list stays open across redraws, for the person who opened it; resetRecordView() forgets it.
const opened = new Map();
// The key (data-fk) of the control last pressed on the record: several items can open the same measure page (the
// SpO2 row of Vital signs and a red limit of SpO2 under Alerts, a blood value in each draw), and Back goes to the one
// that was pressed. Noted in the capture phase, before the press opens the page; once per host.
let pressed = null;
const listening = new WeakSet();
export const recordReturnKey = () => pressed;
export function resetRecordView() { opened.clear(); pressed = null; }

// Print the record, or save it as a PDF: every list and every blood draw open, then back as they were after printing.
export function printRecord(host, { personId = null, print = () => window.print(), after = () => {} } = {}) {
  const before = new Set(opened.get(personId) || []);
  for (const d of host.querySelectorAll('details')) d.open = true;
  for (const l of host.querySelectorAll('.rec-folded')) l.classList.remove('rec-folded');
  window.addEventListener('afterprint', () => { opened.set(personId, before); after(); }, { once: true });
  print();
}

// drawRecord(host, model, on): on = { personId, initials, tip(key, label), pinNote (a node or null), measure(indicator),
// blood(code), complex(indicator), messages(), cycle(), fhir(), copy(), connection(id), print() }.
export function drawRecord(host, model, on = {}) {
  if (!listening.has(host)) {
    listening.add(host);
    host.addEventListener('click', (e) => {
      const x = e.target && e.target.closest ? e.target.closest('[data-fk]') : null;
      if (x && host.contains(x)) pressed = x.dataset.fk;
    }, true);
  }
  const tip = typeof on.tip === 'function' ? on.tip : () => null;
  const open = opened.get(on.personId) || new Set();
  opened.set(on.personId, open);
  const go = (link) => {
    if (!link) return;
    if (link.to === 'measure' && on.measure) on.measure(link.indicator);
    else if (link.to === 'blood' && on.blood) on.blood(link.code);
    else if (link.to === 'complex' && on.complex) on.complex(link.indicator);
    else if (link.to === 'cycle' && on.cycle) on.cycle();
    else if (link.to === 'messages' && on.messages) on.messages();
  };
  const jump = (id) => {
    const head = host.querySelector(`#rec-${id}-h`);
    if (!head) return;
    head.scrollIntoView({ block: 'start' });
    head.focus({ preventScroll: true });
  };

  // ---------- who, and today ----------
  const hd = model.header;
  const idCard = h('section', { class: 'card rec-id', 'aria-labelledby': 'rec-who' },
    h('div', { class: 'rec-who' }, h('span', { class: 'rec-avatar', 'aria-hidden': 'true' }, on.initials || ''), h('div', {}, h('h2', { id: 'rec-who' }, hd.name), h('p', { class: 'muted' }, hd.kindText))),
    h('dl', { class: 'rec-dl' }, ...hd.facts.flatMap(([k, v]) => [h('dt', {}, k), h('dd', {}, v)])),
    on.pinNote || null);

  const t = model.today;
  let todayCard = null;
  if (t && t.real) {
    todayCard = h('section', { class: `card rec-today ${t.outNow ? 'lv1' : ''}`, 'aria-labelledby': 'rec-today-h' },
      h('h2', { id: 'rec-today-h' }, 'Today'),
      h('p', { class: 'rec-sentence' }, t.sentence),
      h('div', { class: 'chips' }, t.outNow ? chip(LEVEL.ATTENTION, `Outside the lab range in the last test: ${t.outNow}`) : h('span', { class: 'chip neutral' }, icon('circle-check', { size: 16 }), 'All within the lab range in the last test')),
      t.lastDraw ? h('p', { class: 'note' }, `The last test: ${t.lastDraw}.`) : null);
  } else if (t) {
    const top = Math.max(t.body || 0, t.mind || 0, t.ship || 0);
    const chips = [];
    if (t.ship) chips.push(chip(t.ship, `Ship: ${LEVEL_WORD[t.ship]}`));
    if (t.body) chips.push(chip(t.body, `Body: ${LEVEL_WORD[t.body]}`));
    if (t.mind) chips.push(chip(t.mind, `Mind: ${LEVEL_WORD[t.mind]}`));
    for (const s of t.stale || []) chips.push(h('span', { class: 'chip stale' }, icon('clock', { size: 16 }), s));
    const alerts = t.alerts || [];
    const shown = alerts.slice(0, 5);
    todayCard = h('section', { class: `card rec-today ${LV[top]}`, 'aria-labelledby': 'rec-today-h' },
      h('h2', { id: 'rec-today-h' }, 'Today'),
      h('p', { class: 'rec-sentence' }, t.sentence),
      chips.length ? h('div', { class: 'chips' }, ...chips) : null,
      alerts.length ? h('ul', { class: 'reasons' }, ...shown.map((a) => h('li', {}, h('button', { type: 'button', class: 'reason', 'data-fk': `rec:alert:${a.id}`, 'data-ind': a.indicator || null, onclick: () => (a.indicator && on.measure ? on.measure(a.indicator) : go({ to: 'messages' })) },
        icon(LEVEL_ICON[a.level], { size: 20, cls: `lvc${a.level}`, label: LEVEL_WORD[a.level] }),
        h('span', { class: 'what' }, h('b', {}, a.title), h('span', {}, `${LEVEL_WORD[a.level] ? cap(LEVEL_WORD[a.level]) : ''} · ${a.system || ''} · ${when(a.time)}`)),
        icon('chevron-right', { size: 18, cls: 'chev' }))))) : h('p', { class: 'muted' }, 'No active alert.'),
      alerts.length ? h('div', { class: 'actions' }, btn('secondary small', alerts.length > shown.length ? `All ${alerts.length} in Messages` : 'What to do: Messages', () => go({ to: 'messages' }), 'bell', { 'data-fk': 'rec:to-messages' })) : null);
  }

  // ---------- the list of sections ----------
  const sections = model.sections || [];
  const toc = h('nav', { class: 'rec-toc', 'aria-label': 'Sections of the record' },
    ...sections.map((s) => h('button', { type: 'button', 'data-fk': `rec:toc:${s.id}`, onclick: () => jump(s.id) }, icon(SECTION_ICON[s.id] || 'list', { size: 16 }), s.title, h('span', { class: 'rec-count' }, h('span', { class: 'sr-only' }, ', '), String(s.count)))),
    h('button', { type: 'button', 'data-fk': 'rec:toc:missing', onclick: () => jump('missing') }, icon('ban', { size: 16 }), 'Not in this prototype', h('span', { class: 'rec-count' }, h('span', { class: 'sr-only' }, ', '), String(model.notHeld.items.length))));

  // ---------- rows ----------
  const measureRow = (it) => {
    const isWord = !/^[0-9.,/% +-]+$/.test(String(it.value));
    const long = isWord && String(it.value).length > 16 ? 'long' : '';
    const arrow = it.out === 'below' || it.out === 'above' ? icon(it.out === 'below' ? 'arrow-down' : 'arrow-up', { size: 16, stroke: 2.4, label: it.out === 'below' ? 'below the normal range' : 'above the normal range' }) : null;
    const tint = it.level && it.out ? `lvc${it.level}` : '';
    const line = [it.verdict, when(it.time), it.source, plural(it.count, 'reading')].filter(Boolean).join(' · ');
    const row = h('button', { type: 'button', class: `row ${it.level ? LV[it.level] : ''}`, 'data-ind': it.indicator, 'data-fk': `rec:${it.key}`, 'data-tip': on.personId ? `m:${it.indicator}:${on.personId}` : null, onclick: () => go(it.link) },
      h('b', { class: 'r-name' }, it.title),
      h('span', { class: `r-num ${isWord ? 'word' : ''} ${long} ${it.unit ? '' : 'nounit'} ${tint}` }, it.value, arrow),
      it.unit ? h('span', { class: 'r-unit' }, it.unit) : null,
      h('span', { class: 'r-time text' }, line),
      it.level ? h('span', { class: `r-state lvc${it.level}` }, icon(LEVEL_ICON[it.level], { size: 14 }), cap(LEVEL_WORD[it.level])) : null,
      icon('chevron-right', { size: 18, cls: 'chev' }));
    return h('div', { class: 'row-wrap' }, row, on.personId ? tip(`m:${it.indicator}:${on.personId}`, it.title) : null);
  };
  const entryItem = (it, extra) => {
    const mark = it.level ? icon(LEVEL_ICON[it.level], { size: 20, cls: `lvc${it.level}`, label: LEVEL_WORD[it.level] }) : icon(it.icon || 'info', { size: 20, cls: 'muted' });
    const meta = [when(it.time), it.source].filter(Boolean).join(' · ');
    const what = h('span', { class: 'what' },
      it.tag ? h('span', { class: 'rec-tag' }, it.tag) : null,
      h('b', {}, it.title),
      it.detail ? h('span', {}, it.detail) : null,
      it.out === 'below' || it.out === 'above' ? h('span', {}, icon(it.out === 'below' ? 'arrow-down' : 'arrow-up', { size: 14, stroke: 2.4 }), it.out === 'below' ? ' Below the normal range' : ' Above the normal range') : null,
      meta ? h('span', { class: 'mono rec-meta' }, meta) : null);
    const inner = it.link
      ? h('button', { type: 'button', class: 'reason rec-item', 'data-ind': it.link.indicator || null, 'data-fk': `rec:${it.key}`, onclick: () => go(it.link) }, mark, what, icon('chevron-right', { size: 18, cls: 'chev' }))
      : h('div', { class: 'reason rec-item static' }, mark, what);
    return h('li', { class: extra ? 'rec-extra' : null }, inner);
  };
  // A long list shows its newest entries first; "Show all" opens the rest in place, so the keyboard stays on the button.
  const entryList = (s) => {
    const n = RECORD_RULES.listShown;
    const folded = s.items.length > n && !open.has(s.id);
    const list = h('ul', { class: `reasons rec-list ${folded ? 'rec-folded' : ''}` }, ...s.items.map((it, i) => entryItem(it, i >= n)));
    const more = s.items.length > n ? h('button', { type: 'button', class: 'link', 'data-fk': `rec:more:${s.id}`, 'aria-expanded': String(!folded), onclick: (e) => {
      const nowOpen = list.classList.contains('rec-folded');
      list.classList.toggle('rec-folded', !nowOpen);
      if (nowOpen) open.add(s.id); else open.delete(s.id);
      e.currentTarget.setAttribute('aria-expanded', String(nowOpen));
      e.currentTarget.textContent = nowOpen ? `Show the newest ${n}` : `Show all ${s.items.length}`;
    } }, folded ? `Show all ${s.items.length}` : `Show the newest ${n}`) : null;
    return [h('div', { class: 'rec-box' }, list), more];
  };
  const drawItem = (d) => {
    const rows = d.groups.map((g) => h('div', { class: 'rec-draw-group' },
      h('h3', {}, g.title),
      h('div', { class: 'rows' }, ...g.values.map((v) => {
        const range = `Lab range ${v.min === null ? '' : v.min} to ${v.max === null ? '' : v.max} ${v.units}`.replace(/\s+/g, ' ').trim();
        const kids = [
          h('b', { class: 'r-name' }, v.name),
          h('span', { class: `r-num ${v.units ? '' : 'nounit'} ${v.out ? 'lvc1' : ''}` }, String(v.value), v.out ? icon(v.out === 'below' ? 'arrow-down' : 'arrow-up', { size: 16, stroke: 2.4, label: v.out === 'below' ? 'below the lab range' : 'above the lab range' }) : null),
          v.units ? h('span', { class: 'r-unit' }, v.units) : null,
          h('span', { class: 'r-time text' }, range),
          v.out ? h('span', { class: 'r-state lvc1' }, icon('info', { size: 14 }), v.out === 'below' ? 'Below the lab range' : 'Above the lab range') : null,
        ];
        if (!d.link) return h('div', { class: 'row-wrap' }, h('div', { class: `row static ${v.out ? 'lv1' : ''}` }, ...kids));
        return h('div', { class: 'row-wrap' },
          h('button', { type: 'button', class: `row ${v.out ? 'lv1' : ''}`, 'data-ind': `blood:${v.code}`, 'data-fk': `rec:${d.key}:${v.code}`, 'data-tip': on.personId ? `b:${v.code}:${on.personId}` : null, onclick: () => on.blood && on.blood(v.code) }, ...kids, icon('chevron-right', { size: 18, cls: 'chev' })),
          on.personId ? tip(`b:${v.code}:${on.personId}`, v.name) : null);
      }))));
    const isOpen = open.has(`draw:${d.key}`) || d === model.sections.find((s) => s.id === 'labs').items[0];
    const box = h('details', { class: 'more rec-draw', open: isOpen ? true : null, ontoggle: (e) => { if (e.currentTarget.open) open.add(`draw:${d.key}`); else open.delete(`draw:${d.key}`); } },
      h('summary', { 'data-fk': `rec:${d.key}` }, icon('chevron-right', { size: 18 }), h('span', {}, h('b', {}, d.title), h('span', { class: 'rec-meta' }, ` · ${fmtDay(d.time)} · ${plural(d.values.length, 'value')}, ${d.outCount} outside the lab range`))),
      h('div', {}, h('p', { class: 'note' }, d.source), ...rows));
    return box;
  };
  const docItem = (d) => h('div', { class: 'rec-doc' },
    h('p', {}, h('b', {}, d.title)),
    h('p', { class: d.unavailable ? 'muted' : '' }, d.detail),
    d.links ? h('p', {}, ...d.links.flatMap((l, i) => [i ? ' · ' : '', h('a', { href: l.url, target: '_blank', rel: 'noopener' }, l.name)])) : null,
    d.action ? h('div', { class: 'actions' }, btn('secondary small', d.action, () => (d.id === 'fhir' ? on.fhir && on.fhir() : on.copy && on.copy()), d.id === 'fhir' ? 'file-json-2' : 'send', { 'data-fk': `rec:${d.key}` })) : null);

  // ---------- one section ----------
  const section = (s) => {
    const head = h('div', { class: 'group-head' },
      h('h2', { id: `rec-${s.id}-h`, tabindex: '-1' }, s.title, ' ', h('span', { class: 'rec-count' }, h('span', { class: 'sr-only' }, ', '), String(s.count))),
      s.private ? privateTag(model.privateNote) : null);
    const parts = [head, h('p', { class: 'note' }, s.about)];
    if (s.private) parts.push(h('p', { class: 'note rec-private-note' }, model.privateNote));
    if (s.facts && s.facts.length) parts.push(h('div', { class: 'card rec-facts' }, h('div', { class: 'prose' }, ...s.facts.map((x) => h('p', {}, x)))));
    if (!s.items.length) parts.push(h('p', { class: 'rec-empty' }, s.empty || 'Nothing yet.'));
    else if (s.items[0].kind === 'measure') parts.push(h('div', { class: 'rows' }, ...s.items.map(measureRow)));
    else if (s.items[0].kind === 'draw') parts.push(h('div', { class: 'rec-draws' }, ...s.items.map(drawItem)));
    else if (s.items[0].kind === 'doc') parts.push(h('div', { class: 'rec-docs' }, ...s.items.map(docItem)));
    else parts.push(...entryList(s));
    if (s.table && s.table.length) {
      parts.push(h('details', { class: 'more' },
        h('summary', { 'data-fk': `rec:table:${s.id}` }, icon('chevron-right', { size: 18 }), `Daily check-ins, the last ${RECORD_RULES.mindDays} days`),
        // The table scrolls inside its frame, so the frame takes the keyboard too (WCAG 2.1.1).
        h('div', {}, h('div', { class: 'table-wrap', tabindex: '0', role: 'region', 'aria-label': 'Daily check-ins, a table that scrolls', 'data-fk': `rec:tablewrap:${s.id}` }, h('table', {},
          h('caption', { class: 'sr-only' }, `Daily check-ins of the last ${RECORD_RULES.mindDays} days, newest first`),
          h('thead', {}, h('tr', {}, ...['Day (GMT)', 'Mood', 'Energy', 'Sleep', 'Low day'].map((x) => h('th', { scope: 'col' }, x)))),
          h('tbody', {}, ...s.table.map((r) => h('tr', {}, h('td', {}, fmtDay(`${r.day}T12:00:00Z`)), h('td', {}, r.mood ? cap(r.mood) : '-'), h('td', {}, r.energy || '-'), h('td', {}, r.sleep || '-'), h('td', {}, r.low ? 'Yes' : 'No')))))),
        h('p', { class: 'note' }, 'Energy: 1 fully alert, 7 completely exhausted (Samn-Perelli). A low day is a bad mood or energy at 5 or more, the mind rule\'s own drafts.'))));
    }
    if (s.note) parts.push(h('p', { class: 'note' }, s.note));
    if (s.id === 'documents' && on.print) parts.push(h('div', { class: 'actions rec-print' }, btn('secondary small', 'Print or save as PDF', () => on.print(), 'file-json-2', { 'data-fk': 'rec:print' })));
    return h('section', { class: `group rec-sec ${s.private ? 'rec-is-private' : ''}`, id: `rec-${s.id}`, 'aria-labelledby': `rec-${s.id}-h` }, ...parts);
  };

  // ---------- what this prototype does not hold ----------
  const nh = model.notHeld;
  const conn = nh.connection;
  const missing = h('section', { class: 'group rec-sec', id: 'rec-missing', 'aria-labelledby': 'rec-missing-h' },
    h('div', { class: 'group-head' }, h('h2', { id: 'rec-missing-h', tabindex: '-1' }, 'Not in this prototype ', tip('t:recordmissing', 'what is not in this prototype'), ' ', h('span', { class: 'rec-count' }, h('span', { class: 'sr-only' }, ', '), String(nh.items.length)))),
    h('p', { class: 'note' }, 'A full medical card also holds these. They are listed with the reason, instead of being left out.'),
    h('div', { class: 'rec-box' }, h('ul', { class: 'reasons rec-list' }, ...nh.items.map((x) => h('li', {}, h('div', { class: 'reason rec-item static', 'data-missing': x.id },
      icon('ban', { size: 20, cls: 'lvc-off' }),
      h('span', { class: 'what' }, h('b', {}, x.title), h('span', {}, x.what), h('span', { class: 'rec-meta' }, nh.text))))))),
    conn ? h('div', { class: 'rec-doc' },
      h('p', {}, h('b', {}, `Planned: ${conn.name}`), ' ', tip(`c:${conn.id}`, conn.name)),
      h('p', {}, conn.how),
      h('div', { class: 'actions' }, btn('secondary small', 'Show it in Settings, Connections', () => on.connection && on.connection(conn.id), 'settings', { 'data-fk': 'rec:connection' }))) : null);

  const src = model.sources;
  const sources = h('p', { class: 'note rec-sources' }, 'Built after the patient medical card of Ukraine\'s e-health system, as apps like Helsi show it, and the HL7 International Patient Summary: ',
    ...[src.ehealth, src.helsi, src.helsiResults, src.ips, src.ipsEmpty].flatMap((x, i) => [i ? '; ' : '', h('a', { href: x.url, target: '_blank', rel: 'noopener' }, x.name)]), '.');

  host.replaceChildren(...[
    h('div', { class: 'screen-head' },
      h('h1', { id: 'rec-title', tabindex: '-1' }, 'Medical record ', tip('t:record', 'the medical record')),
      h('p', {}, 'Everything this program holds about you, in one place. Read only: press an item to open where it came from.')),
    idCard, todayCard, toc, ...sections.map(section), missing, sources,
  ].filter(Boolean));
  return host;
}
