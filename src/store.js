// Where the page keeps what happened, so that a reload does not wipe it.
// What is kept is the list of events: every reading, every periodic review and every message to a doctor, with
// its time, the person and the position of the switches. On open, the page sends them through the
// machine again in time order, so the journal, the history and the piles come back exactly.
// 1. Our own simple server (serve.mjs): plain files, one per person, named by id, in app/data.
//    NASA asks ISS research software to keep data on the station server in plain files,
//    with no personal information in file names.
// 2. If the page is opened without that server, the browser's own storage on this computer.
// 3. If that is blocked too, memory only, and the page says that nothing is saved.
// Whose events: the crew screen opens the store for one person, openStore({ person }), and gets only that
// person's events plus the ship's cabin readings. The ISS crew code of conduct (14 CFR 1214.403) says other
// crewmembers may not use a crewmember's medical information without consent. The technical view opens it for
// everyone, openStore() or openStore({ all: true }): the engineering view, which a real deployment would restrict.
// Code generated by Claude (Anthropic), an AI system.

const KEY = 'jff-health-events-v1';
const SHIP_ID = 'ship';
const PERSON_ID = /^[a-z0-9][a-z0-9-]{0,31}$/;

// Our own server runs on the computer itself (http://127.0.0.1 or localhost). A static copy on the web
// (for example GitHub Pages, served over https) has no server, so it goes straight to the browser's storage.
const ownServer = () => typeof location !== 'undefined' && (location.protocol === 'http:' || location.hostname === 'localhost' || location.hostname === '127.0.0.1');
// Full addresses, so the same code also runs in Node for the automatic checks. fetch keeps its default mode
// ("cors"): under Referrer-Policy no-referrer a "same-origin" mode request would send Origin "null", which the
// server refuses.
const at = (path) => new URL(path, location.href).href;

export async function openStore({ person = null } = {}) {
  if (person !== null && (typeof person !== 'string' || !PERSON_ID.test(person))) throw new TypeError('person must be an id such as crew-1');
  const scope = person ? { person } : { all: true };
  // A crewmate's alarm line is for everyone; the rest of their record is not.
  const inScope = (e) => Boolean(scope.all || (e && (e.person === scope.person || e.person === SHIP_ID || e.kind === 'alarm')));
  try {
    if (!ownServer()) throw new Error('no server on a static copy');
    const query = scope.all ? 'all=1' : `person=${encodeURIComponent(person)}`;
    const res = await fetch(at(`./api/events?${query}`), { headers: { Accept: 'application/json' }, cache: 'no-store' });
    const type = res.headers.get('content-type') || '';
    if (res.ok && type.includes('application/json')) {
      const events = await res.json();
      if (Array.isArray(events)) return serverStore(events.filter(inScope), scope, inScope);
    }
  } catch {
    // no server of ours: fall through to the browser
  }
  try {
    const raw = localStorage.getItem(KEY);
    const all = raw ? JSON.parse(raw) : [];
    if (Array.isArray(all)) return browserStore(all, scope, inScope);
  } catch {
    // browser storage blocked: fall through to memory
  }
  return memoryStore(scope, inScope);
}

// What every store tells the screen: where it keeps things, and whose events it holds.
const about = (kind, scope) => ({ kind, scope: scope.all ? 'all' : 'person', person: scope.person || null });

function serverStore(events, scope, inScope) {
  const ask = scope.all ? 'all=1' : `person=${encodeURIComponent(scope.person)}`;
  return {
    ...about('server', scope),
    events,
    // Resolves with what the server says about a message to a doctor ({ outbox: { id, file, status, ... } }),
    // or null for other events.
    async append(event) {
      if (inScope(event)) events.push(event);
      const res = await fetch(at('./api/events'), {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
        body: JSON.stringify(event),
      });
      if (!res.ok) {
        let why = '';
        try { why = (await res.json()).error || ''; } catch { /* no reason given */ }
        throw new Error(`not saved: ${res.status}${why ? ` (${why})` : ''}`);
      }
      return res.status === 201 ? res.json() : null;
    },
    // The messages that wait in data/outbox for the downlink, without their sealed text.
    async outbox() {
      const res = await fetch(at(`./api/outbox?${ask}`), { headers: { Accept: 'application/json' }, cache: 'no-store' });
      if (!res.ok) throw new Error(`outbox not readable: ${res.status}`);
      return res.json();
    },
  };
}

// The browser keeps everyone's events under one key, so a person's view is a filter of that list, and saving
// writes the whole list back: the other people's events stay.
function browserStore(all, scope, inScope) {
  const events = all.filter(inScope);
  const store = {
    ...about('browser', scope),
    events,
    async append(event) {
      all.push(event);
      if (inScope(event)) events.push(event);
      try {
        localStorage.setItem(KEY, JSON.stringify(all));
      } catch {
        store.kind = 'memory';
        throw new Error('not saved: browser storage is full or blocked');
      }
      return null;
    },
    async outbox() {
      return []; // a static copy has no outbox: messages stay in this browser
    },
  };
  return store;
}

function memoryStore(scope, inScope) {
  const events = [];
  return {
    ...about('memory', scope),
    events,
    async append(event) {
      if (inScope(event)) events.push(event);
      return null;
    },
    async outbox() {
      return [];
    },
  };
}
