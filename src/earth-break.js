export const BREATH = { inS: 4, outS: 6 };
// fadeS: the crossfade between two scenes, for the picture and the sound. volume: the calm starting level, 0 to 1
// (TO CONFIRM: 50 percent). soundFadeS: how fast the sound goes quiet when the break stops. soundPadS: each sound
// file carries this much of its loop's own end before the loop and of its own start after it (see loopPoints).
export const BREAK_RULES = { durationS: 180, fadeS: 2, volume: 0.5, volumeStep: 0.05, soundFadeS: 1.5, prefetchS: 8, soundPadS: 0.5 };
export const FEELINGS = [['better', 'Better'], ['same', 'Same'], ['worse', 'Worse']];

// Where the breath is at ms after the start: phase 'in' or 'out', progress 0 to 1 within the phase, the circle's
// scale (0.6 when empty, 1 when full, eased) and the whole seconds left in this phase.
export function breathAt(ms, breath = BREATH) {
  const inMs = breath.inS * 1000;
  const outMs = breath.outS * 1000;
  const cycle = inMs + outMs;
  const t = ((ms % cycle) + cycle) % cycle;
  const ease = (p) => 0.5 - 0.5 * Math.cos(Math.PI * p);
  if (t < inMs) {
    const p = t / inMs;
    return { phase: 'in', progress: p, scale: 0.6 + 0.4 * ease(p), secondsLeft: Math.ceil((inMs - t) / 1000) };
  }
  const p = (t - inMs) / outMs;
  return { phase: 'out', progress: p, scale: 1 - 0.4 * ease(p), secondsLeft: Math.ceil((outMs - (t - inMs)) / 1000) };
}

// Which scene the mix shows at ms after the start, when count scenes share durationMs equally; -1 when there is none.
export function sceneAt(ms, count, durationMs) {
  if (!(count > 0) || !(durationMs > 0)) return -1;
  return Math.min(count - 1, Math.max(0, Math.floor(ms / (durationMs / count))));
}

// The person's choice: 'mix' (the scenes take turns) or the index of one scene, which then stays until the end
// or until the mix is chosen again. Anything else falls back to the mix.
export function chooseScene(choice, count) {
  const i = Number(choice);
  if (choice !== 'mix' && choice !== null && choice !== '' && Number.isInteger(i) && i >= 0 && i < count) return { mode: 'one', index: i };
  return { mode: 'mix' };
}

// The scene on the screen at ms for a choice made with chooseScene.
export function sceneFor(pick, ms, count, durationMs) {
  if (pick && pick.mode === 'one' && pick.index >= 0 && pick.index < count) return pick.index;
  return sceneAt(ms, count, durationMs);
}

// The next scene the mix will show and when it starts, so its sound can be loaded in time; null after the last.
export function nextSceneAt(ms, count, durationMs) {
  const i = sceneAt(ms, count, durationMs);
  if (i < 0 || i >= count - 1) return null;
  return { index: i + 1, startMs: ((i + 1) * durationMs) / count };
}

// A volume between 0 and 1 in whole percent; anything that is not a number gives the calm starting level.
export function clampVolume(v, fallback = BREAK_RULES.volume) {
  const n = Number(v);
  if (v === null || v === undefined || v === '' || !Number.isFinite(n)) return fallback;
  return Math.round(Math.min(1, Math.max(0, n)) * 100) / 100;
}

// The level the sound plays at: nothing when muted, else the volume.
export function soundLevel({ volume = BREAK_RULES.volume, muted = false } = {}) {
  return muted ? 0 : clampVolume(volume);
}

// What a screen reader says for the volume slider.
export function volumeText({ volume = BREAK_RULES.volume, muted = false } = {}) {
  const pct = `${Math.round(clampVolume(volume) * 100)} percent`;
  return muted ? `${pct}, muted` : pct;
}

// The part of a decoded sound to loop: from the first to the last sample louder than the threshold, in seconds,
// so the silence an MP3 encoder adds at both ends never makes a gap in the loop. channels: Float32Array per channel.
export function loopBounds(channels, sampleRate, threshold = 1e-4) {
  const list = (Array.isArray(channels) ? channels : []).filter((c) => c && typeof c.length === 'number' && c.length);
  if (!list.length || !(sampleRate > 0)) return null;
  const n = Math.min(...list.map((c) => c.length));
  const loud = (i) => list.some((c) => Math.abs(c[i]) > threshold);
  let first = 0;
  while (first < n && !loud(first)) first += 1;
  if (first >= n) return null;
  let last = n - 1;
  while (last > first && !loud(last)) last -= 1;
  return { start: first / sampleRate, end: (last + 1) / sampleRate };
}

// Where a sound loops, in seconds: inside the sound (loopBounds) and padS in from each end. The padding repeats the
// loop's own sound, so the step from the loop's end back to its start is as smooth as any other moment, and the
// edge effects of decoding and resampling stay outside the loop. null when the sound is too short to loop.
export function loopPoints(channels, sampleRate, padS = BREAK_RULES.soundPadS) {
  const b = loopBounds(channels, sampleRate);
  if (!b) return null;
  const start = b.start + padS;
  const end = b.end - padS;
  return end - start >= 1 ? { start, end } : null;
}

// The credit line on the screen for one scene.
export function creditText(scene) {
  if (!scene) return '';
  return `${scene.label}. Video: ${scene.by.video} (Pexels). Sound: ${scene.by.sound} (Freesound, CC0).`;
}

// The quiet line when files of the scene on the screen did not load: what is missing, what shows instead, and
// that the break goes on. failed: { video, poster, sound } for this scene; still: reduce motion is on (no video).
export function problemText(scene, failed = {}, still = false) {
  if (!scene) return '';
  const name = scene.label.toLowerCase();
  const parts = [];
  if (!still && failed.video && failed.poster) parts.push(`The ${name} video and its still picture did not load.`);
  else if (!still && failed.video) parts.push(`The ${name} video did not load, so its still picture shows instead.`);
  else if (still && failed.poster) parts.push(`The ${name} picture did not load.`);
  if (failed.sound) parts.push(`The ${name} sound did not load.`);
  return parts.length ? `${parts.join(' ')} The break goes on.` : '';
}

const clock = (ms) => { const s = Math.max(0, Math.ceil(ms / 1000)); return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`; };
const reducedMotion = () => { try { return window.matchMedia('(prefers-reduced-motion: reduce)').matches; } catch { return false; } };

// The sound: one looping recording per scene through the Web Audio API, which loops without a gap and fades
// between scenes. Each file is fetched from this program's own address and decoded once; only the scene playing
// and the next one are kept. onProblem(file) when a file cannot be fetched or decoded, onPlay(file) when it plays.
// Returns null when the browser has no Web Audio.
function createSound({ base, fadeS, onProblem, onPlay }) {
  let AC = null;
  try { AC = window.AudioContext || window.webkitAudioContext || null; } catch { AC = null; }
  if (!AC) return null;
  let ctx;
  try { ctx = new AC(); } catch { return null; }
  const master = ctx.createGain();
  master.gain.value = 0;
  master.connect(ctx.destination);
  const buffers = new Map();
  let current = null;
  let token = 0;
  let closed = false;
  const decode = (data) => new Promise((resolve, reject) => {
    const p = ctx.decodeAudioData(data, resolve, reject);
    if (p && typeof p.then === 'function') p.then(resolve, reject);
  });
  const load = (file) => {
    if (!buffers.has(file)) {
      const p = fetch(`${base}${file}`).then((r) => { if (!r.ok) throw new Error(`status ${r.status}`); return r.arrayBuffer(); }).then(decode);
      buffers.set(file, p);
      p.catch(() => { if (buffers.get(file) === p) buffers.delete(file); });
    }
    return buffers.get(file);
  };
  const fadeOut = (c, s = fadeS) => {
    if (!c) return;
    const now = ctx.currentTime;
    try {
      c.gain.gain.cancelScheduledValues(now);
      c.gain.gain.setValueAtTime(c.gain.gain.value, now);
      c.gain.gain.linearRampToValueAtTime(0, now + s);
      c.src.stop(now + s + 0.05);
    } catch { /* already stopped */ }
  };
  return {
    load,
    play(file, keep = []) {
      const t = (token += 1);
      for (const f of [...buffers.keys()]) if (f !== file && !keep.includes(f)) buffers.delete(f);
      load(file).then((buf) => {
        if (closed || t !== token) return;
        const src = ctx.createBufferSource();
        src.buffer = buf;
        src.loop = true;
        const ch = [];
        for (let i = 0; i < buf.numberOfChannels; i += 1) ch.push(buf.getChannelData(i));
        const b = loopPoints(ch, buf.sampleRate);
        if (b) { src.loopStart = b.start; src.loopEnd = b.end; }
        const gain = ctx.createGain();
        const now = ctx.currentTime;
        gain.gain.setValueAtTime(0, now);
        gain.gain.linearRampToValueAtTime(1, now + fadeS);
        src.connect(gain);
        gain.connect(master);
        src.start(now, b ? b.start : 0);
        fadeOut(current);
        current = { src, gain };
        if (typeof onPlay === 'function') onPlay(file);
      }).catch(() => {
        if (closed || t !== token) return;
        fadeOut(current);
        current = null;
        if (typeof onProblem === 'function') onProblem(file);
      });
    },
    level(v, rampS = 0.15) {
      if (closed) return;
      const now = ctx.currentTime;
      master.gain.cancelScheduledValues(now);
      master.gain.setValueAtTime(master.gain.value, now);
      master.gain.linearRampToValueAtTime(v, now + rampS);
    },
    // Wakes the sound up after a key or a press, when the browser held it back until the person did something.
    resume() { if (!closed && ctx.state === 'suspended') ctx.resume().catch(() => {}); },
    state: () => ctx.state,
    fadeAll(s) { token += 1; fadeOut(current, s); current = null; },
    close() {
      if (closed) return;
      closed = true;
      token += 1;
      try { if (current) current.src.stop(); } catch { /* already stopped */ }
      current = null;
      buffers.clear();
      ctx.close().catch(() => {});
    },
  };
}

// Opens the break at once. onDone({ feeling: 'better' | 'same' | 'worse' | null, completed, seconds, time })
// after the question (null when the person skips it); onCancel({ seconds }) when Esc closes it. base: where the
// media files are. sound: false leaves the sound out. Returns { close, state }: state() says what shows and what failed.
export function runEarthBreak({ onDone, onCancel, durationS = BREAK_RULES.durationS, base = './assets/breathe/', scenes = BREAK_SCENES, sound: withSound = true } = {}) {
  const still = reducedMotion();
  const dur = Math.max(10, Number(durationS) || BREAK_RULES.durationS) * 1000;
  const list = (Array.isArray(scenes) ? scenes : []).filter((s) => s && s.video && s.poster);
  const fadeMs = BREAK_RULES.fadeS * 1000;
  let start = performance.now();
  let raf = 0;
  let closed = false;
  let asked = false;
  let shown = -1;
  let front = 0;
  let videoToken = 0;
  let lastPhase = '';
  let lastSecond = -1;
  let lastLeft = -1;
  let elapsedAtStop = 0;
  let pick = { mode: 'mix' };
  let volume = BREAK_RULES.volume;
  let muted = false;
  let prefetched = -1;
  const failed = { video: new Set(), poster: new Set(), sound: new Set() };

  // One quiet line for what did not load, for the scene on the screen only (role status: read out once, politely).
  const statusLine = h('p', { class: 'sup-status sup-eb-status', role: 'status', 'aria-live': 'polite' });
  let general = '';
  const refreshStatus = () => {
    const s = list[shown];
    const text = [general, s ? problemText(s, { video: failed.video.has(s.id), poster: failed.poster.has(s.id), sound: failed.sound.has(s.id) }, still) : ''].filter(Boolean).join(' ');
    if (statusLine.textContent !== text) statusLine.textContent = text;
  };
  const sceneOf = (file, key) => list.find((s) => s[key] === String(file || '').split('/').pop());
  const mark = (kind, file, key, bad) => { const s = sceneOf(file, key); if (!s) return; if (bad) failed[kind].add(s.id); else failed[kind].delete(s.id); refreshStatus(); };
  const sound = withSound ? createSound({
    base,
    fadeS: BREAK_RULES.fadeS,
    onProblem: (file) => mark('sound', file, 'sound', true),
    onPlay: (file) => mark('sound', file, 'sound', false),
  }) : null;
  if (withSound && !sound) general = 'Sound cannot play in this browser. The break goes on without it.';

  const stopMedia = () => {
    for (const v of vids) { try { v.pause(); v.removeAttribute('src'); v.load(); } catch { /* nothing to stop */ } }
    if (sound) sound.close();
  };
  const close = () => { if (closed) return; closed = true; cancelAnimationFrame(raf); stopMedia(); layer.close(); };
  const layer = openOverlay({
    cls: `sup-eb${still ? ' still' : ''}`,
    labelledby: 'sup-eb-title',
    onEscape: () => { const seconds = Math.round((asked ? elapsedAtStop : performance.now() - start) / 1000); close(); if (typeof onCancel === 'function') onCancel({ seconds }); },
  });

  // The picture: the scene's still frame underneath, and two videos above it that crossfade from one scene to
  // the next. With reduce motion there are no videos, only the still frame.
  const poster = h('img', { class: 'sup-eb-poster', alt: '', decoding: 'async' });
  const vids = still ? [] : [0, 1].map(() => {
    const v = h('video', { class: 'sup-eb-video', muted: true, loop: true, playsinline: true, preload: 'auto', disablepictureinpicture: true, 'aria-hidden': 'true', tabindex: '-1' });
    v.muted = true;
    v.defaultMuted = true;
    return v;
  });
  const sceneBox = h('div', { class: 'sup-eb-scene', role: 'img', 'aria-label': '' }, poster, vids);
  const credit = h('p', { class: 'sup-eb-credit' });
  const circle = h('div', { class: 'sup-eb-circle', 'aria-hidden': 'true' });
  const word = h('p', { class: 'sup-eb-word' });
  const count = h('p', { class: 'sup-eb-count mono', 'aria-hidden': 'true' });
  const left = h('span', { class: 'sup-eb-left mono' });
  const stopBtn = btn('secondary small', 'Stop', () => ask(false), 'square');
  const pacer = h('div', { class: 'sup-eb-pacer' },
    still ? null : circle,
    word,
    still ? count : null,
    h('p', { class: 'sup-eb-how' }, 'Breathe in for 4 seconds, out for 6. Your own pace is fine too.'));
  const top = h('div', { class: 'sup-eb-top' },
    h('div', {}, h('h2', { id: 'sup-eb-title' }, '3-minute Earth break'), h('p', {}, 'Flat screen, not VR. Real video and sound, recorded on Earth.')),
    h('div', { class: 'sup-eb-top-right' }, left, stopBtn));

  // The controls: the scene (the mix or one scene), and the sound (mute, volume).
  const sceneBtns = new Map();
  const choose = (choice) => {
    if (sound) sound.resume();
    pick = chooseScene(choice, list.length);
    paintScenes();
    if (!asked && !closed) showScene(sceneFor(pick, performance.now() - start, list.length, dur));
  };
  const chip = (key, label) => {
    const b = h('button', { type: 'button', class: 'sup-eb-chip', 'aria-pressed': 'false', dataset: { scene: key }, onclick: () => choose(key) }, h('span', { class: 'sup-dot', 'aria-hidden': 'true' }), label);
    sceneBtns.set(key, b);
    return b;
  };
  const scenesGroup = h('div', { class: 'sup-eb-scenes', role: 'group', 'aria-labelledby': 'sup-eb-scene-label' },
    h('span', { class: 'sup-eb-label', id: 'sup-eb-scene-label' }, 'Scene'),
    chip('mix', 'Mix'),
    list.map((s, i) => chip(String(i), s.label)));
  const muteBtn = h('button', { type: 'button', class: 'btn secondary small sup-eb-mute', 'aria-pressed': 'false', onclick: () => setMuted(!muted) }, supIcon('volume-2', { size: 18 }), 'Mute sound');
  const slider = h('input', { type: 'range', id: 'sup-eb-volume', class: 'sup-eb-volume', min: '0', max: '100', step: String(Math.round(BREAK_RULES.volumeStep * 100)), value: String(Math.round(volume * 100)), 'aria-valuetext': volumeText({ volume, muted }) });
  const volOut = h('span', { class: 'sup-eb-volume-out mono', 'aria-hidden': 'true' });
  slider.addEventListener('input', () => setVolume(Number(slider.value) / 100));
  const soundRow = h('div', { class: 'sup-eb-sound' }, muteBtn, h('label', { class: 'sup-eb-label', for: 'sup-eb-volume' }, 'Volume'), slider, volOut);
  const controls = h('div', { class: 'sup-eb-controls', role: 'group', 'aria-label': 'Scene and sound' }, scenesGroup, sound ? soundRow : null, statusLine);
  const head = h('div', { class: 'sup-eb-head' }, top, controls);
  layer.root.append(sceneBox, head, pacer, credit);
  // Some browsers hold sound back until the person presses something; any key or press here wakes it up.
  layer.root.addEventListener('pointerdown', () => { if (sound) sound.resume(); });
  layer.root.addEventListener('keydown', () => { if (sound) sound.resume(); });

  function paintScenes() {
    for (const [key, b] of sceneBtns) {
      const on = key === 'mix' ? pick.mode === 'mix' : pick.mode === 'one' && String(pick.index) === key;
      b.setAttribute('aria-pressed', String(on));
      b.classList.toggle('now', key !== 'mix' && String(shown) === key);
    }
  }
  function paintSound() {
    muteBtn.setAttribute('aria-pressed', String(muted));
    muteBtn.firstChild.replaceWith(supIcon(muted ? 'volume-x' : 'volume-2', { size: 18 }));
    slider.setAttribute('aria-valuetext', volumeText({ volume, muted }));
    volOut.textContent = muted ? 'Muted' : `${Math.round(volume * 100)}%`;
    if (sound && !asked) sound.level(soundLevel({ volume, muted }));
  }
  function setMuted(on) {
    if (sound) sound.resume();
    muted = Boolean(on);
    paintSound();
  }
  function setVolume(v) {
    if (sound) sound.resume();
    volume = clampVolume(v, volume);
    if (muted) muted = false; // moving the volume turns the sound back on
    paintSound();
  }

  poster.addEventListener('error', () => {
    if (!poster.getAttribute('src')) return;
    poster.classList.add('failed');
    if (!vids.some((v) => v.classList.contains('shown'))) sceneBox.classList.add('missing');
    mark('poster', poster.getAttribute('src'), 'poster', true);
  });
  poster.addEventListener('load', () => { poster.classList.remove('failed'); sceneBox.classList.remove('missing'); mark('poster', poster.getAttribute('src'), 'poster', false); });

  const playVideo = (s) => {
    const token = (videoToken += 1);
    const next = vids[1 - front];
    const prev = vids[front];
    const ready = () => {
      if (token !== videoToken || closed || asked) return;
      next.classList.add('shown');
      prev.classList.remove('shown');
      front = 1 - front;
      sceneBox.classList.remove('missing');
      if (failed.video.delete(s.id)) refreshStatus();
      setTimeout(() => { if (token === videoToken && !closed) { try { prev.pause(); prev.removeAttribute('src'); prev.load(); } catch { /* nothing to stop */ } } }, fadeMs + 200);
    };
    const fail = () => {
      if (token !== videoToken || closed) return;
      failed.video.add(s.id);
      for (const v of vids) { v.classList.remove('shown'); try { v.pause(); } catch { /* nothing to stop */ } }
      if (poster.classList.contains('failed')) sceneBox.classList.add('missing');
      refreshStatus();
    };
    next.onplaying = () => { next.onplaying = null; ready(); };
    next.onerror = () => { next.onerror = null; fail(); };
    next.src = `${base}${s.video}`;
    const p = next.play();
    if (p && typeof p.catch === 'function') p.catch((e) => { if (e && e.name === 'NotAllowedError') fail(); });
  };

  function showScene(i) {
    if (i < 0 || i === shown || !list[i]) return;
    shown = i;
    const s = list[i];
    poster.classList.remove('failed');
    poster.src = `${base}${s.poster}`;
    sceneBox.setAttribute('aria-label', s.alt);
    credit.textContent = creditText(s);
    paintScenes();
    refreshStatus();
    if (!still) playVideo(s);
    if (sound && s.sound) {
      const nxt = pick.mode === 'mix' ? list[i + 1] : null;
      sound.play(s.sound, nxt && nxt.sound ? [nxt.sound] : []);
    }
  }

  // In the mix, the next scene's sound and still frame are loaded a few seconds before it starts.
  const prefetch = (t) => {
    if (pick.mode !== 'mix') return;
    const n = nextSceneAt(t, list.length, dur);
    if (!n || n.index === prefetched || n.startMs - t > BREAK_RULES.prefetchS * 1000) return;
    prefetched = n.index;
    const s = list[n.index];
    if (sound && s.sound) sound.load(s.sound).catch(() => {});
    const pre = new Image();
    pre.src = `${base}${s.poster}`;
  };

  const frame = (now) => {
    if (closed || asked) return;
    const t = now - start;
    if (t >= dur) { ask(true); return; }
    const b = breathAt(t);
    if (!still) circle.style.transform = `scale(${b.scale.toFixed(3)})`;
    if (b.phase !== lastPhase) { lastPhase = b.phase; word.textContent = b.phase === 'in' ? 'Breathe in' : 'Breathe out'; }
    if (still && b.secondsLeft !== lastSecond) { lastSecond = b.secondsLeft; count.textContent = String(b.secondsLeft); }
    const sec = Math.ceil((dur - t) / 1000);
    if (sec !== lastLeft) { lastLeft = sec; left.textContent = `${clock(dur - t)} left`; }
    showScene(sceneFor(pick, t, list.length, dur));
    prefetch(t);
    raf = requestAnimationFrame(frame);
  };

  const finish = (feeling) => {
    if (closed) return;
    const out = { feeling, completed: elapsedAtStop >= dur - 1000, seconds: Math.round(Math.min(elapsedAtStop, dur) / 1000), time: new Date().toISOString() };
    close();
    if (typeof onDone === 'function') onDone(out);
  };

  function ask(completed) {
    if (asked || closed) return;
    asked = true;
    elapsedAtStop = completed ? dur : performance.now() - start;
    cancelAnimationFrame(raf);
    // The break is over: the sound fades out and the picture holds still while the question is open.
    if (sound) sound.fadeAll(BREAK_RULES.soundFadeS);
    for (const v of vids) { try { v.pause(); } catch { /* nothing to stop */ } }
    pacer.hidden = true;
    stopBtn.hidden = true;
    controls.hidden = true;
    left.textContent = completed ? 'Done' : 'Stopped';
    const box = h('div', { class: 'sup-eb-ask', role: 'group', 'aria-labelledby': 'sup-eb-ask-title' },
      h('h2', { id: 'sup-eb-ask-title' }, 'How do you feel now?'),
      h('div', { class: 'actions' }, FEELINGS.map(([k, label]) => btn('secondary', label, () => finish(k)))),
      h('button', { type: 'button', class: 'link', onclick: () => finish(null) }, 'Skip'),
      h('p', { class: 'note' }, 'Your answer is kept in this browser only, and no screen shows it.'),
      h('p', {}, badge(BADGE.nasa)),
      sourceLine(SRC.vr2017, SRC.vr2026, SRC.breath2023));
    layer.root.append(box);
    box.querySelector('button').focus();
  }

  word.textContent = 'Breathe in';
  lastPhase = 'in';
  if (still) { count.textContent = String(BREATH.inS); lastSecond = BREATH.inS; }
  left.textContent = `${clock(dur)} left`;
  paintSound();
  if (sound) sound.level(soundLevel({ volume, muted }), BREAK_RULES.fadeS);
  showScene(sceneFor(pick, 0, list.length, dur));
  paintScenes();
  stopBtn.focus();
  start = performance.now();
  raf = requestAnimationFrame(frame);

  return {
    close() { if (closed) return; const seconds = Math.round((performance.now() - start) / 1000); close(); if (typeof onCancel === 'function') onCancel({ seconds }); },
    // For the automatic checks: what is on the screen and what failed to load.
    state: () => ({ scene: list[shown] ? list[shown].id : null, pick: { ...pick }, volume, muted, still, sound: sound ? sound.state() : 'none', failed: { video: [...failed.video], poster: [...failed.poster], sound: [...failed.sound] } }),
  };
}
