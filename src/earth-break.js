// The 3-minute Earth break (F7): NASA photographs of Earth taken from the ISS, a slow crossfade, and a circle
// that paces slow breathing (in 4 s, out 6 s), then "How do you feel now? Better / Same / Worse".
// Why: astronauts call watching Earth from the cupola restorative (NASA HRP evidence report, 2025); crews
// beyond the Moon will not see Earth up close; nature scenes lowered negative feelings in NASA-funded studies
// (Anderson et al. 2017; Abbott et al. 2026); breathing with long, slow exhales for 5 minutes a day helped mood
// (Balban et al. 2023). This is a flat screen, not VR, and says so. With "reduce motion" set on the device
// there is no crossfade and no moving circle: one still photo and a text pacer.
// Photos: NASA, public domain in the United States, used without NASA logos and without implying endorsement
// (NASA media guidelines); see assets/earth/CREDITS.md. Nothing is recorded; the answer goes to onDone only.
// Code generated by Claude (Anthropic), an AI system.
