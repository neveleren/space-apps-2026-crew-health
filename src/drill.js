// The drill switch, for an analog test such as NASA's HERA, whose mission plans list medical drills and emergency
// drills among the crew's tasks (Vessey, Cromwell and Platts, NASA, 2017). While a drill is on, everything new on the
// crew screen carries the drill's mark (the time the drill started), the screen says DRILL, and alarms sound and go to
// the crew and the doctor as usual, with the word DRILL, because that is what a drill tests. Drill events never count
// in the levels, the medical record or the summaries for the doctor: the screen judges the person by a machine that
// never sees them (src/crew.js rebuild), and a second machine with the drill's readings is used only for the drill's
// own alarms. NASA-STD-3001 Vol 2 Rev F asks for an explicit command to change between simulation, test and
// operational mode [V2 10153]: the drill is such a test mode, turned on and off by hand in Settings.
// Every rule here is a draft for the team and the flight surgeons.
// Code generated by Claude (Anthropic), an AI system.

export const DRILL_RULES = Object.freeze({
  // The drill ends by itself after this long, so it is never left on by mistake (then real readings would be kept
  // out of the record). No public source gives this time: a draft, and the team's open decision.
  maxMinutes: 60,
  draft: true,
  sourceNote: 'No public source gives this time: a draft, the team decides.',
});

