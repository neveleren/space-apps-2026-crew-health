// ---------- "Bring back a copy" ----------
// Which lines of a saved copy may come back: the person's own and the ship's events that pass the server's own check
// (src/security.js, with the rule against times from the future). Messages to a doctor and crew alarm lines stay
// out, so an old message is never sealed into the outbox again and an old alarm never reaches the crew again.
export function restorePlan(text, { person, ship = 'ship', have = [], now = Date.now(), check = eventProblem } = {}) {
  const known = new Set([...have].map((e) => (typeof e === 'string' ? e : eventKey(e))));
  const plan = { add: [], unreadable: 0, others: 0, messages: 0, alarms: 0, known: 0, refused: [] };
  String(text || '').split(/\r?\n/).forEach((line, i) => {
    if (!line.trim()) return;
    let e;
    try { e = JSON.parse(line); } catch { plan.unreadable += 1; return; }
    if (!e || typeof e !== 'object' || Array.isArray(e) || !e.kind || !e.person || !e.time) { plan.unreadable += 1; return; }
    if (e.person !== person && e.person !== ship) { plan.others += 1; return; }
    if (e.kind === 'report') { plan.messages += 1; return; }
    if (e.kind === 'alarm') { plan.alarms += 1; return; }
    const why = check(e, { now });
    if (why) { plan.refused.push({ line: i + 1, why }); return; }
    const k = eventKey(e);
    if (known.has(k)) { plan.known += 1; return; }
    known.add(k);
    plan.add.push(e);
  });
  return plan;
}

// The reason a save failed, in a few words: the server's own reason when it gave one.
export function shortReason(why) {
  const s = String(why || '');
  const m = /\((.+)\)\s*$/.exec(s);
  if (m) return m[1];
  if (/failed to fetch|network|load failed|fetch/i.test(s)) return 'the station computer did not answer';
  return s.replace(/^not saved:\s*/, '') || 'unknown reason';
}
