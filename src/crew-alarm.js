// The countdown of the camera question "Are you okay?".
export function askTimerText(secondsLeft, ship = {}) {
  if (!(secondsLeft > 0)) return 'Alerting your crewmates now.';
  const n = Math.ceil(secondsLeft);
  if (ship.doctorOnBoard) return `No answer in ${n} s: your crewmates and the doctor on board will be alerted.`;
  if (ship.linkToEarth) return `No answer in ${n} s: your crewmates and the doctor on Earth will be alerted.`;
  return `No answer in ${n} s: your crewmates will be alerted; the doctor gets the message when the link is back.`;
}
