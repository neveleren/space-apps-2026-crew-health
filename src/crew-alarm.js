// A new line is written only when the set of urgent signs changes: a new sign, one that is over, or an all clear.
// tokens: the signs urgent now, by the words that name them in a line ("Blood oxygen (SpO2)", "Help key", "camera").
// universe: every token a line can hold. A line that is open (not a clear) and names exactly these signs stays.
export function needsNewLine(last, tokens, universe) {
  const open = Boolean(last && last.alarm && !last.alarm.clear);
  if (!tokens.length) return open;
  if (!open) return true;
  const named = new Set((universe || []).filter((u) => last.alarm.text.includes(u)));
  return tokens.length !== named.size || tokens.some((t) => !named.has(t));
}

// The automatic message to the doctor when an urgent alarm is raised or ends: what happened and when, written by the
// program, which says so. what: the sentences about the signs.
export function alarmReportText({ name, gmt, what = [], clear = false, crew = '' }) {
  const head = `Automatic message from the Crew Health Console (written by the program, not by ${name}).`;
  const body = (Array.isArray(what) ? what : [what]).filter(Boolean).join(' ');
  return [head, clear ? `All clear for the urgent alarm of ${name}, GMT ${gmt}.` : `Urgent alarm for ${name}, GMT ${gmt}.`, body, crew].filter(Boolean).join(' ').slice(0, 6000);
}

// ---------- what happened to a save, in words ----------
// A message: 'queued' (sealed in the outbox for Earth), 'onboard' (saved for the doctor on board), 'local' (a copy
// without the station server), 'waiting' (kept in this browser until the station server answers), 'server' (saved
// there, no outbox answer), 'unsent' (not saved).
export function messageStatus(res, { to, storeKind }) {
  if (!res || !res.ok) return 'unsent';
  if (res.waiting) return 'waiting';
  if (storeKind !== 'server') return 'local';
  if (to === 'doctor-onboard') return 'onboard';
  const st = res.answer && res.answer.outbox && res.answer.outbox.status;
  return st === 'queued' ? 'queued' : st ? String(st) : 'server';
}
// A crew line: 'shared' (on the station server, so every open crew screen gets it), 'local', 'waiting', 'unsent'.
export function lineStatus(res, { storeKind }) {
  if (!res || !res.ok) return 'unsent';
  if (res.waiting) return 'waiting';
  return storeKind === 'server' ? 'shared' : 'local';
}
// An earlier message read back at sign-in, from the outbox listing of the station server (GET /api/outbox).
export function statusFromOutbox(report, items) {
  if (!report || !report.report) return 'server';
  if (report.report.to === 'doctor-onboard') return 'onboard';
  const hit = (items || []).find((m) => m && m.time === report.time && m.to === report.report.to);
  return hit && hit.status ? String(hit.status) : 'server';
}

// What the screen may say about the doctor for an urgent alarm, from what really happened to the automatic message.
// With no doctor on board and no link it never says that a doctor has been called (FS-04).
export function doctorWords(status, ship = {}) {
  switch (status) {
    case 'onboard': return 'The doctor on board has been called: the message is saved on the station computer.';
    case 'queued': return ship.linkToEarth ? 'The doctor on Earth has been called: the message is sealed in the outbox for the next downlink.' : 'There is no link to Earth: the message to the doctor waits in the outbox and goes when the link is back. Until then the crew on board is alerted.';
    case 'sent': return 'The message to the doctor on Earth has gone with the downlink.';
    case 'local': return 'This copy runs without the station server: the message to the doctor is saved on this computer only and is not sent. Tell the crew medical officer.';
    case 'waiting': return 'The message to the doctor is not on the station computer yet: it is kept in this browser and sent as soon as the computer takes it. Tell the crew in person now.';
    case 'server': return 'The message to the doctor is saved on the station server.';
    case 'unsent': return 'The message to the doctor was NOT saved. Tell the crew medical officer, or use "Message the doctor".';
    default: return 'No message about this alarm reached a doctor: use "Message the doctor".';
  }
}
