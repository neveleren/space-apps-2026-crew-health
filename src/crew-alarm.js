// The crew alarm and the saving rules of the crew screen, as plain functions the checks can run without a browser:
// which crewmate line each screen shows, when a new line is written, the automatic message to the doctor, what a
// number typed by hand is, which lines of a saved copy may come back, and what the screen may say about a call for
// help. The team's idea: speak up only when something is really wrong, and then tell the crew and the doctor.
// The rule here is never to say that help was called when it was not: every sentence follows what really happened
// to the saved line and the message (NASA-STD-3001 Vol 2 Rev F asks that emergencies are seen and heard, 10114).
// The waits and windows in ALARM_RULES are Claude's drafts: the team and the flight surgeons decide.
// Code generated by Claude (Anthropic), an AI system.
import { eventProblem } from './security.js';

const HOUR = 60 * 60 * 1000;
const ALARM_CHARS = 200; // the longest crew line the server keeps (src/security.js)

export const ALARM_RULES = Object.freeze({
  pollSeconds: 15, // every open crew screen asks the station computer for new crew lines this often (draft)
  lineHours: 24, // a crewmate's line stays until it is cleared, at most this long; the camera rule also uses 24 h (draft)
  repeatSeconds: 4, // an urgent alarm repeats its warning tone this often until someone acknowledges it (draft)
  voiceEvery: 4, // ... and speaks its line every this many repeats (draft)
  retrySeconds: 5, // a call for help that the station computer did not take is tried again after this long (draft)
  draft: true,
});

// The initials on the sign-in cards and on the who button: T, E, C3, C4, and I1 to I4 for the Inspiration4
// participants, so no two people on the sign-in screen share them.
export function initialsOf(p) {
  if (!p) return '';
  if (p.real) return `I${String(p.code || '').replace(/^C0*/i, '') || '?'}`;
  const name = String(p.name || '');
  const n = /(\d+)$/.exec(name);
  return n ? `C${n[1]}` : name.slice(0, 1).toUpperCase();
}

// A number typed by hand: digits with at most one decimal point or comma, so "2,8" is 2.8 and never 28.
// An empty field or anything else is null: the screen saves nothing and asks for a number.
export function typedNumber(text) {
  const s = String(text ?? '').trim();
  if (!/^-?\d+([.,]\d+)?$/.test(s)) return null;
  const v = Number(s.replace(',', '.'));
  return Number.isFinite(v) ? v : null;
}

// Two events are the same when kind, person, time and what they carry match; the server sends back its cleaned
// copy, so only the parts it keeps are compared.
export function eventKey(e) {
  if (!e || typeof e !== 'object') return '';
  let body = [];
  if (e.kind === 'alarm') body = [e.alarm && e.alarm.text, Boolean(e.alarm && e.alarm.clear)];
  else if (e.kind === 'reading') body = [e.reading && e.reading.indicator, e.reading && e.reading.source, e.reading && e.reading.value];
  else if (e.kind === 'report') body = [e.report && e.report.to, e.report && e.report.text];
  else if (e.kind === 'alert') body = [e.alert && e.alert.id, e.alert && e.alert.step]; // the alert log (src/alert-log.js)
  return `${e.kind}|${e.person}|${e.time}|${JSON.stringify(body)}`;
}

// What a new look at the station computer brings that this screen does not have yet: crew alarm lines (anyone's)
// and the ship's readings, nothing else of anyone's record.
export function newShared(fetched, have, { ship = 'ship' } = {}) {
  const known = new Set((have || []).map(eventKey));
  const out = [];
  for (const e of Array.isArray(fetched) ? fetched : []) {
    if (!e || typeof e !== 'object' || !(e.kind === 'alarm' || e.person === ship)) continue;
    const k = eventKey(e);
    if (known.has(k)) continue;
    known.add(k);
    out.push(e);
  }
  return out;
}

// The lines a crew screen shows: each person's latest crew line of the last lineHours hours, unless that latest line
// is an all clear ("Tom is okay: false alarm"). The viewer's own lines are left out. Newest first.
export function crewLines(events, { viewer = null, now = Date.now(), hours = ALARM_RULES.lineHours } = {}) {
  const latest = new Map();
  for (const e of events || []) {
    if (!e || e.kind !== 'alarm' || !e.alarm || typeof e.alarm.text !== 'string' || e.person === viewer) continue;
    const t = Date.parse(e.time);
    if (!Number.isFinite(t)) continue;
    const age = now - t;
    if (age > hours * HOUR || age < -HOUR) continue;
    const prev = latest.get(e.person);
    if (!prev || t >= Date.parse(prev.time)) latest.set(e.person, e);
  }
  return [...latest.values()].filter((e) => !e.alarm.clear).sort((a, b) => Date.parse(b.time) - Date.parse(a.time));
}

// Since when the alarm of one item has been on, in milliseconds, so the screen finds the crew line and the message
// written for it: for a red limit the first reading of the current run outside the range (the same sign measured
// again, by hand or by a device once a minute, is the same alarm, and gets no new line), for the camera and the Help
// key the alarm's own time; 0 when the item has no time.
export function alarmSince(it) {
  const m = it && it.m;
  const t = (m && (m.runFrom || (m.last && m.last.time))) || (it && it.time) || null;
  const v = t instanceof Date ? t.getTime() : t ? Date.parse(t) : NaN;
  return Number.isFinite(v) ? v : 0;
}

// The latest crew line of one person (an alarm or an all clear), or null.
export function latestLine(events, person, { now = Date.now(), hours = ALARM_RULES.lineHours } = {}) {
  let best = null;
  for (const e of events || []) {
    if (!e || e.kind !== 'alarm' || e.person !== person || !e.alarm) continue;
    const t = Date.parse(e.time);
    if (!Number.isFinite(t) || now - t > hours * HOUR || t - now > HOUR) continue;
    if (!best || t >= Date.parse(best.time)) best = e;
  }
  return best;
}

const fit = (text) => (text.length <= ALARM_CHARS ? text : `${text.slice(0, ALARM_CHARS - 4).replace(/[;,: ]+\S*$/, '')} ...`);

// The crew line of an urgent alarm. The Help key names the person who pressed it, so responders go to that screen:
// "Tom pressed the Help key." Otherwise "Tom needs help now: Blood oxygen (SpO2) 85 %."
export function alarmText(name, { helpKey = false, signs = [] } = {}) {
  const list = (signs || []).filter(Boolean);
  if (helpKey) return fit(list.length ? `${name} pressed the Help key and needs help now: ${list.join('; ')}.` : `${name} pressed the Help key.`);
  return fit(`${name} needs help now: ${list.join('; ') || 'an alarm was raised'}.`);
}
export const falseAlarmText = (name) => fit(`${name} is okay: false alarm`);
export const allClearText = (name, what = '') => fit(`${name} is no longer urgent${what ? `: ${what}` : ''}`);
