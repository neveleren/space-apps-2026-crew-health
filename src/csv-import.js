// Import readings from a file (CSV): a time column and a value column become readings of one measure.
// Three device exports are recognised by their headers; any other file returns its column list, so the screen can ask
// the person which columns to use. Every value passes the same plausibility limits as typing a reading in by hand.
//
// What is documented and what is guessed (said again in docs/INTEGRATIONS.md):
// - Hexoskin shirt: the CSV time column counts 256ths of a second since 1 Jan 1970 GMT (divide by 256), one row a
//   second, columns breathing rate, minute ventilation, sleep position, activity, heart rate, cadence. Documented:
//   https://support.hexoskin.com/understanding-my-data-in-the-csv-file and
//   https://support.hexoskin.com/understand-and-convert-hexoskin-timestamps . The exact header spelling is not shown
//   there, so headers are matched loosely ("heart_rate [bpm]", "Heart Rate (bpm)" and similar).
// - Astroskin (the commercial twin of the ISS Bio-Monitor shirt): time in 1000ths of a second ("time [s/1000]"),
//   columns breathing rate, SPO2, PTT, minute ventilation, systolic pressure, sleep position, activity, heart rate,
//   cadence. Documented: https://support.hexoskin.com/en/astroskin/understanding-my-data-in-the-csv-file-astroskin
// - Philips Actiware (Actiwatch sleep watches, worn by ISS crews): exports are comma-separated ASCII files
//   (Actiware user guide, https://www.philips.com/c-dam/b2bhc/master/sites/actigraphy/solutions/Actiware/actiware-user-guide.pdf).
//   The statistics columns (Interval Type, Start Date, Start Time, End Date, End Time, Duration, Sleep Time in minutes)
//   are named in the guide's "Statistics Tab"; the epoch-by-epoch columns (Line, Date, Time, Activity, Sleep/Wake with
//   0 = sleep, Interval Status) in its "Data List Tab" and in the open-source reader pyActigraphy
//   (https://github.com/ghammad/pyActigraphy/blob/master/pyActigraphy/io/rpx/multilang.py, section "Epoch-by-Epoch Data").
//   The layout of the sections in one file is guessed from those two sources.
// - Svantek sound dosimeters (SV 102A+, worn by ISS crews; SvanPC++ exports to CSV, https://svantek.com/products/svanpc-software/):
//   no public description of the columns was found, so the match (a column named LAeq and a date or time column) is a guess.
// Times without a time zone are read as GMT, the time the ISS runs on.
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".
