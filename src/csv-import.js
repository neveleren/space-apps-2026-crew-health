// ---------- CSV text into a table ----------
// RFC 4180 style: quoted fields, "" inside quotes, line breaks inside quotes, CRLF or LF.
// The separator is guessed from the first lines (comma, semicolon or tab); a semicolon file may use decimal commas.
function splitTable(text, delimiter) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  let wasQuoted = false;
  const end = () => { row.push(wasQuoted ? field : field.trim()); field = ''; wasQuoted = false; };
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') { if (text[i + 1] === '"') { field += '"'; i += 1; } else quoted = false; } else field += ch;
    } else if (ch === '"' && field.trim() === '') { quoted = true; wasQuoted = true; field = ''; }
    else if (ch === delimiter) end();
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      end();
      rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== '' || row.length) { end(); rows.push(row); }
  return rows;
}

function guessDelimiter(text) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim()).slice(0, 30);
  let best = ',';
  let bestScore = -1;
  for (const d of [',', ';', '\t']) {
    const counts = lines.map((l) => l.replace(/"[^"]*"/g, '').split(d).length - 1);
    const score = counts.reduce((a, b) => a + b, 0);
    if (score > bestScore) { best = d; bestScore = score; }
  }
  return best;
}

const blank = (row) => row.every((c) => c === '');
const isNum = (s) => /^[-+]?(\d+[.,]?\d*|[.,]\d+)([eE][-+]?\d+)?$/.test(String(s).trim());

// Numbers as written in the file: "36.6", "36,6" in a semicolon file, "1e3". Empty or text: NaN.
export function toNumber(s, decimalComma = false) {
  const t = String(s ?? '').trim();
  if (!t || !isNum(t)) return NaN;
  return Number(decimalComma ? t.replace(',', '.') : t);
}

function rowsUnder(table, headerIndex) {
  const header = table[headerIndex].map((h, i, all) => {
    const name = h || `Column ${i + 1}`;
    const before = all.slice(0, i).filter((x) => (x || '') === (h || '')).length;
    return before ? `${name} (${before + 1})` : name;
  });
  const rows = [];
  for (let i = headerIndex + 1; i < table.length; i += 1) {
    const r = table[i];
    if (blank(r)) {
      // A blank line ends this table when another section starts after it.
      const next = table.slice(i + 1).find((x) => !blank(x));
      if (next && next.filter((c) => c !== '').length <= 1) break;
      continue;
    }
    if (r.filter((c) => c !== '').length === 1 && !isNum(r.find((c) => c !== ''))) break; // a section title
    const obj = { _line: i + 1 };
    header.forEach((name, k) => { obj[name] = r[k] ?? ''; });
    rows.push(obj);
  }
  return { header, rows };
}

// The header is the first line with at least two names (not numbers) that is followed by a line with numbers.
function findHeader(table) {
  for (let i = 0; i < table.length; i += 1) {
    const cells = table[i].filter((c) => c !== '');
    if (cells.length < 2 || cells.filter(isNum).length > cells.length / 2) continue;
    const next = table.slice(i + 1).find((r) => !blank(r));
    if (next && next.some((c) => isNum(c))) return i;
  }
  return table.findIndex((r) => !blank(r));
}

// parseCsv(text) -> { delimiter, decimalComma, table (all lines as arrays), headerIndex, columns, rows }
// rows are objects keyed by column name, with _line (1-based line in the file).
export function parseCsv(text, { delimiter = null } = {}) {
  const clean = String(text ?? '').replace(/^\uFEFF/, '');
  const d = delimiter || guessDelimiter(clean);
  const table = splitTable(clean, d).map((r) => {
    const copy = [...r];
    while (copy.length > 1 && copy[copy.length - 1] === '') copy.pop(); // trailing separators
    return copy;
  });
  const decimalComma = d === ';' && table.some((r) => r.some((c) => /^[-+]?\d+,\d+$/.test(c)));
  const headerIndex = findHeader(table);
  const { header, rows } = headerIndex >= 0 ? rowsUnder(table, headerIndex) : { header: [], rows: [] };
  // The rows carry the decimal comma setting, so mapReadings(result.rows, choice) after the column picker reads
  // "64,5" as 64.5 without the screen passing it on.
  Object.defineProperty(rows, 'decimalComma', { value: decimalComma, enumerable: false });
  return { delimiter: d, decimalComma, table, headerIndex, columns: header, rows };
}

// ---------- times ----------
const MONTH = { jan: 1, feb: 2, mar: 3, apr: 4, may: 5, jun: 6, jul: 7, aug: 8, sep: 9, oct: 10, nov: 11, dec: 12 };

// One time cell (and an optional date cell) into milliseconds since 1970, GMT. unit: 's/256' (Hexoskin),
// 's/1000' or 'ms' (Astroskin, Unix milliseconds), 's' (Unix seconds). dayFirst: true for 14/11/2026, false for
// 11/14/2026, null to decide from the numbers (a part above 12 settles it; otherwise month first).
export function parseTime(value, { date = null, unit = null, dayFirst = null } = {}) {
  const raw = String(value ?? '').trim();
  if (unit) {
    const n = toNumber(raw);
    if (!Number.isFinite(n)) return NaN;
    if (unit === 's/256') return Math.round((n / 256) * 1000);
    if (unit === 's/1000' || unit === 'ms') return Math.round(n);
    if (unit === 's') return Math.round(n * 1000);
  }
  const s = date ? `${String(date).trim()} ${raw}`.trim() : raw;
  let m = s.match(/^(\d{4})-(\d{1,2})-(\d{1,2})(?:[T ]+(\d{1,2}):(\d{2})(?::(\d{2})(?:[.,](\d+))?)?)?\s*(Z|[+-]\d{2}:?\d{2})?$/i);
  if (m) {
    const ms = m[7] ? Number(`0.${m[7]}`) * 1000 : 0;
    let t = Date.UTC(+m[1], +m[2] - 1, +m[3], +(m[4] || 0), +(m[5] || 0), +(m[6] || 0), ms);
    if (m[8] && m[8].toUpperCase() !== 'Z') {
      const off = m[8].replace(':', '');
      t -= (off[0] === '-' ? -1 : 1) * (Number(off.slice(1, 3)) * 60 + Number(off.slice(3, 5))) * 60000;
    }
    return t;
  }
  m = s.match(/^(\d{1,2})[/.-](\d{1,2})[/.-](\d{2,4})(?:[ T]+(\d{1,2}):(\d{2})(?::(\d{2}))?(?:[.,]\d+)?\s*([AaPp][Mm])?)?$/);
  if (m) {
    const a = +m[1];
    const b = +m[2];
    const first = dayFirst === null ? a > 12 : dayFirst; // undecided and both 12 or less: month first
    const day = first ? a : b;
    const month = first ? b : a;
    let year = +m[3];
    if (year < 100) year += 2000;
    let hours = +(m[4] || 0);
    if (m[7]) { const pm = m[7].toLowerCase() === 'pm'; if (hours === 12) hours = pm ? 12 : 0; else if (pm) hours += 12; }
    if (month < 1 || month > 12 || day < 1 || day > 31) return NaN;
    return Date.UTC(year, month - 1, day, hours, +(m[5] || 0), +(m[6] || 0));
  }
  m = s.match(/^(\d{1,2})[ -]([A-Za-z]{3})[A-Za-z]*[ -](\d{4})(?:[ T]+(\d{1,2}):(\d{2})(?::(\d{2}))?)?$/);
  if (m && MONTH[m[2].toLowerCase()]) return Date.UTC(+m[3], MONTH[m[2].toLowerCase()] - 1, +m[1], +(m[4] || 0), +(m[5] || 0), +(m[6] || 0));
  if (/^\d{9,13}(\.\d+)?$/.test(s)) { const n = Number(s); return n >= 1e12 ? Math.round(n) : Math.round(n * 1000); }
  return NaN;
}

// The day and month order of a whole column, so one file is never read two ways (10/11 as October and 13/11 as
// November): a first number above 12 anywhere means day first, a second number above 12 means month first, and
// dates written with dots (14.11.2026) are day first. null when the column does not say; parseTime then reads
// month first.
export function guessDayFirst(values) {
  let monthFirst = false;
  let dots = false;
  for (const v of values || []) {
    const m = String(v ?? '').trim().match(/^(\d{1,2})([/.-])(\d{1,2})\2\d{2,4}(?!\d)/);
    if (!m) continue;
    if (+m[1] > 12) return true;
    if (+m[3] > 12) monthFirst = true;
    if (m[2] === '.') dots = true;
  }
  if (monthFirst) return false;
  return dots ? true : null;
}

// ---------- units ----------
// Into the unit of the program's cell. Pressure factors from NIST SP 811 Appendix B.8: 1 torr = 133.3224 Pa,
// 1 mmHg = 133.3224 Pa, 1 psi = 6.894757 kPa
// (https://www.nist.gov/pml/special-publication-811/nist-guide-si-appendix-b-conversion-factors/nist-guide-si-appendix-b8).
const norm = (u) => String(u || '').toLowerCase().replace(/[\s()[\]]/g, '').replace('°', 'deg').replace('\u00BA', 'deg');
const SAME = (v) => v;
const C_FROM_F = (v) => Number((((v - 32) * 5) / 9).toFixed(2));
const UNITS = {
  pulse: { bpm: SAME, '/min': SAME, 'beats/min': SAME, 'beats/minute': SAME },
  resp: { 'breaths/min': SAME, rpm: SAME, '/min': SAME, 'respirations/minute': SAME },
  spo2: { '%': SAME, percent: SAME },
  temp: { degc: SAME, c: SAME, cel: SAME, degf: C_FROM_F, f: C_FROM_F },
  cabinTemp: { degc: SAME, c: SAME, cel: SAME, degf: C_FROM_F, f: C_FROM_F },
  sleep: { h: SAME, hours: SAME, min: (v) => v / 60, minutes: (v) => v / 60, s: (v) => v / 3600 },
  fluid: { ml: SAME, 'ml/day': SAME, 'ml/d': SAME, l: (v) => v * 1000 },
  cabinPressure: { kpa: SAME, torr: (v) => v * 0.1333224, mmhg: (v) => v * 0.1333224, psi: (v) => v * 6.894757, psia: (v) => v * 6.894757, hpa: (v) => v / 10, mbar: (v) => v / 10 },
  co2: { mmhg: SAME, torr: SAME, kpa: (v) => v / 0.1333224 },
  cabinO2: { mmhg: SAME, torr: SAME, kpa: (v) => v / 0.1333224 },
  noise: { dba: SAME }, // A-weighted only: an unweighted dB level is a different quantity
};

export function convertUnit(indicator, value, unit) {
  const v = Number(value);
  const cellUnit = unitOf[indicator];
  if (!unit || norm(unit) === norm(cellUnit)) return { value: v };
  const table = UNITS[indicator] || {};
  const f = table[norm(unit)];
  if (!f) return { error: `cannot turn ${unit} into ${cellUnit || 'this measure'}` };
  return { value: f(v) };
}

const round = (v, d = 2) => Number(Number(v).toFixed(d));

// ---------- rows into readings ----------
// mapReadings(rows, { timeColumn, valueColumn, indicator, unit }) and options:
// dateColumn (a separate date cell), timeUnit ('s/256', 's/1000', 's'), dayFirst, every (milliseconds: keep one
// reading per period, the mean of that period, as the Bluetooth heart rate keeps one a minute), aggregate
// ('energy-mean-day' for sound levels: the energy average of each GMT day), source (the source id saved with each
// reading), person, decimalComma (by default the setting parseCsv gave the rows). Without dayFirst, the order of
// day and month is decided once for the whole column (guessDayFirst). Returns { readings, rejected: [{ line, value,
// reason }], notes }.
export function mapReadings(rows, opts = {}) {
  const { timeColumn, valueColumn, indicator, unit = null, dateColumn = null, timeUnit = null, dayFirst = null, every = 0, aggregate = null, source = 'csv-import', person = null, decimalComma = Boolean(rows && rows.decimalComma) } = opts;
  const notes = [];
  const rejected = [];
  if (!indicator || !unitOf[indicator]) return { readings: [], rejected, notes: [`"${indicator}" is not a number measure of the program.`] };
  if (!timeColumn || !valueColumn) return { readings: [], rejected, notes: ['Choose a time column and a value column.'] };
  const order = dayFirst !== null || timeUnit ? dayFirst : guessDayFirst(rows.map((r) => (dateColumn ? r[dateColumn] : r[timeColumn])));
  const points = [];
  for (const row of rows) {
    const line = row._line;
    const rawValue = row[valueColumn];
    const t = parseTime(row[timeColumn], { date: dateColumn ? row[dateColumn] : null, unit: timeUnit, dayFirst: order });
    if (!Number.isFinite(t)) { rejected.push({ line, value: row[timeColumn], reason: 'the time cannot be read' }); continue; }
    const n = toNumber(rawValue, decimalComma);
    if (!Number.isFinite(n)) { if (String(rawValue ?? '').trim() !== '') rejected.push({ line, value: rawValue, reason: 'not a number' }); continue; }
    const c = convertUnit(indicator, n, unit);
    if (c.error) return { readings: [], rejected, notes: [`${c.error}.`] };
    if (!isPlausible(indicator, c.value)) { rejected.push({ line, value: rawValue, reason: `outside the plausibility limits ${PLAUSIBLE[indicator] ? PLAUSIBLE[indicator].join(' to ') : ''} ${unitOf[indicator]}`.trim() }); continue; }
    points.push({ t, v: c.value });
  }
  points.sort((a, b) => a.t - b.t);
  let kept = points;
  if (aggregate === 'energy-mean-day') {
    const days = new Map();
    for (const p of points) { const k = Math.floor(p.t / 86400000); if (!days.has(k)) days.set(k, []); days.get(k).push(p); }
    // LAeq over a period is the energy average of the levels: 10 log10(mean(10^(L/10))).
    kept = [...days.values()].map((list) => ({ t: list[list.length - 1].t, v: 10 * Math.log10(list.reduce((s, p) => s + 10 ** (p.v / 10), 0) / list.length), n: list.length }));
    notes.push('Sound levels: one value per GMT day, the energy average of that day\'s logged levels. The program\'s norm is for the 16-hour work period, which this average does not pick out.');
  } else if (every > 0) {
    const buckets = new Map();
    for (const p of points) { const k = Math.floor(p.t / every); if (!buckets.has(k)) buckets.set(k, []); buckets.get(k).push(p); }
    kept = [...buckets.values()].map((list) => ({ t: list[list.length - 1].t, v: list.reduce((s, p) => s + p.v, 0) / list.length, n: list.length }));
    if (kept.length < points.length) notes.push(`One reading per ${every >= 60000 ? `${every / 60000} min` : `${every / 1000} s`}: the mean of the values in it (${points.length} values became ${kept.length} readings).`);
  }
  const owner = ownerFor(indicator, person);
  const readings = kept.map((p) => ({ source, indicator, value: round(p.v, indicator === 'sleep' ? 2 : 1), unit: unitOf[indicator], time: new Date(p.t).toISOString(), ...(owner ? { person: owner } : {}) }));
  if (rejected.length) notes.push(rejected.length === 1 ? '1 value was left out (see the list).' : `${rejected.length} values were left out (see the list).`);
  return { readings, rejected, notes };
}

