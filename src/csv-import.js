// Shirt exports: one row a second, so one reading a minute is kept (the mean of that minute).
function shirt(id, name, timeUnit, measures, documented, sources) {
  return {
    id,
    name,
    documented,
    sources,
    find(parsed) {
      const t = parsed.columns[0] || '';
      if (!(timeUnit === 's/256' ? /s\/256/i : /s\/1000/i).test(t)) return null;
      const found = measures.map((m) => ({ ...m, column: col(parsed.columns, m.re) })).filter((m) => m.column);
      return found.length ? { parsed, found, timeColumn: t } : null;
    },
    extract({ parsed, found, timeColumn }) {
      const out = { readings: [], rejected: [], notes: [] };
      for (const m of found) {
        const r = mapReadings(parsed.rows, { timeColumn, valueColumn: m.column, indicator: m.indicator, timeUnit, every: 60000, source: `csv-${id}`, decimalComma: parsed.decimalComma });
        out.readings.push(...r.readings);
        out.rejected.push(...r.rejected);
        out.notes.push(...r.notes.map((n) => `${m.column}: ${n}`));
      }
      return out;
    },
  };
}

