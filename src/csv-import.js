export const PLAUSIBLE = { pulse: [20, 250], glucose: [10, 600], temp: [30, 44], spo2: [50, 100], sleep: [0, 16], resp: [3, 70], fluid: [0, 10000], bodyMass: [60, 120], eyePressure: [2, 70], hearing: [-10, 120], radiation: [0, 2000], vo2max: [5, 90], strength: [5, 500], co2: [0, 30], cabinTemp: [5, 45], cabinO2: [50, 300], cabinPressure: [0, 120], noise: [20, 140] };

export function isPlausible(indicator, value) {
  if (indicator === 'bp') {
    const sys = Number(value && value.sys);
    const dia = Number(value && value.dia);
    return sys >= 50 && sys <= 300 && dia >= 20 && dia <= 200 && sys > dia; // as in crew.js
  }
  const v = Number(value);
  const r = PLAUSIBLE[indicator];
  return Number.isFinite(v) && (!r || (v >= r[0] && v <= r[1]));
}

