// sourceInfo(sourceId, { example }) -> { key, origin, label, standard, text, thisValue }
// origin: device | import | feed | typed | dataset | simulated | example | unknown.
export function sourceInfo(id, { example = false } = {}) {
  if (example) return { key: 'example', origin: 'example', label: 'Example flight generator of the program (made-up data)', standard: null, text: TEXT.example, thisValue: 'Made-up example data, shaped like published flight studies' };
  const known = KNOWN_SOURCES[id];
  if (known) return { key: id, ...known, text: TEXT[known.origin] };
  const sim = SOURCES.find((s) => s.id === id);
  if (sim) return { key: id, origin: 'simulated', label: `${sim.label} (simulated)`, standard: null, text: TEXT.simulated, thisValue: `Entered on the technical view from a simulated "${sim.label}"` };
  return { key: `unknown:${id}`, origin: 'unknown', label: id ? `Source "${id}"` : 'Unknown source', standard: null, text: TEXT.unknown, thisValue: null };
}

// Readings of any connector into events in the app's saved shape, each with its own time:
// { v: 1, kind: 'reading', time, person, state, reading: { source, indicator, value } }.
export function toEvents(readings, { person = null, state = {} } = {}) {
  return (readings || []).map((r) => ({ v: 1, kind: 'reading', time: r.time || new Date().toISOString(), person: r.person || person, state: { ...state }, reading: { source: r.source, indicator: r.indicator, value: r.value } }));
}

// Leaves out readings already saved (same person, source, measure and time), so reading a feed twice adds nothing.
export function onlyNew(readings, events, person = null) {
  const have = new Set((events || []).filter((e) => e.kind === 'reading' && e.reading).map((e) => `${e.person}|${e.reading.source}|${e.reading.indicator}|${new Date(e.time).toISOString()}`));
  return (readings || []).filter((r) => !have.has(`${r.person || person}|${r.source}|${r.indicator}|${new Date(r.time).toISOString()}`));
}

// ---------- drawing ----------
function h(tag, props = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v === undefined || v === null || v === false) continue;
    if (k === 'class') node.className = v;
    else if (k === 'style') node.setAttribute('style', v);
    else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2), v);
    else node.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children.flat()) {
    if (c === null || c === undefined || c === false) continue;
    node.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return node;
}
const btn = (label, onclick, ic = null, extra = {}) => h('button', { type: 'button', class: 'btn secondary small', onclick, ...extra }, ic ? icon(ic, { size: 18 }) : null, label);

export const chipFor = (status) => h('span', { class: `chip ${CHIP[status][0]}` }, icon(CHIP[status][1], { size: 16 }), STATUS_WORDS[status]);

// The text of a row's "?": what, how, what it needs, a caveat, what was tested tonight, and the sources as links.
// To show it, crew.js tipContent() answers keys "c:<id>" with connectionTip(id).
export function connectionTip(id) {
  const c = CONNECTIONS.find((x) => x.id === id);
  if (!c) return null;
  const line = (label, text) => (text ? h('p', {}, h('b', {}, `${label}: `), text) : null);
  return h('div', {},
    h('p', { class: 'tp-title' }, `${c.name}: ${STATUS_WORDS[c.status]}`),
    h('p', {}, c.what),
    line('How', c.how),
    line('Needs', c.needs ? c.needs.replace(/^needs /, '') : null),
    c.earthDemo ? line('Earth demo', 'needs the internet, off by default; the program works the same without it.') : null,
    line('Note', c.note),
    line('Tested', c.tested),
    h('p', {}, h('b', {}, 'Sources: '), ...c.sources.flatMap((s, i) => [i ? '; ' : '', h('a', { href: s.url, target: '_blank', rel: 'noopener' }, s.title)])));
}

function control(c, ctx) {
  const a = c.action;
  if (!a) return null;
  const blocked = c.personal && ctx.state.real ? true : null;
  if (a.type === 'connect') {
    const kids = a.buttons.map((b) => {
      const on = ctx.state.connected && ctx.state.connected[b.kind];
      return btn(on ? (b.connected || `${b.label} connected`) : b.label, () => ctx.onConnect(b.kind), 'bluetooth', { disabled: blocked || (ctx.state.busy && ctx.state.busy[b.kind]) ? true : null, 'aria-pressed': on ? 'true' : null });
    });
    // Several buttons get a line of their own under the text (see row()), so the name keeps its width on a phone.
    return kids.length === 1 ? kids[0] : h('span', { class: 'conn-actions', style: 'grid-column:1 / -1;display:flex;flex-wrap:wrap;gap:8px' }, ...kids);
  }
  if (a.type === 'open') return btn(a.label, () => ctx.onConnect(a.kind), a.kind === 'ical' ? 'calendar' : 'file-json-2', { disabled: blocked });
  if (a.type === 'link') return h('a', { href: a.href, target: '_blank', rel: 'noopener' }, a.label);
  if (a.type === 'import') {
    return h('label', { class: 'btn secondary small', 'aria-disabled': blocked ? 'true' : null }, icon('file-json-2', { size: 18 }), a.label,
      h('input', { type: 'file', accept: a.accept, hidden: true, disabled: blocked, onchange: (e) => { const f = e.target.files && e.target.files[0]; e.target.value = ''; if (f) ctx.onImport(f); } }));
  }
  if (a.type === 'toggle') {
    const on = Boolean(ctx.state.on && ctx.state.on[c.id]);
    const word = h('span', { class: 'word', 'aria-hidden': 'true' }, on ? 'On' : 'Off');
    return h('span', { class: 'switch-ctl' }, word, h('input', { type: 'checkbox', role: 'switch', class: 'switch', id: `conn-${c.id}`, checked: on ? true : null, onchange: (e) => { word.textContent = e.target.checked ? 'On' : 'Off'; ctx.onToggle(c.id, e.target.checked); } }));
  }
  return null;
}

function row(c, ctx) {
  const live = ctx.state.live && ctx.state.live[c.id];
  const sub = [
    h('small', {}, live || c.what),
    c.earthDemo ? h('small', {}, 'Earth demo, needs the internet. Off by default.') : null,
    c.needs ? h('small', {}, c.needs.charAt(0).toUpperCase() + c.needs.slice(1)) : null,
  ];
  const toggle = c.action && c.action.type === 'toggle';
  const label = h(toggle ? 'label' : 'span', { class: 'label', for: toggle ? `conn-${c.id}` : null }, h('span', {}, `${c.name} `, chipFor(c.status)), ...sub);
  const ctl = control(c, ctx);
  const ownLine = ctl && ctl.className === 'conn-actions';
  return h('div', { class: 'switch-row', 'data-conn': c.id }, label, h('span', { class: 'switch-ctl' }, ctx.tip(c), ownLine ? null : ctl), ownLine ? ctl : null);
}

// Draws the Connections list into host (for example the Connections card of Settings).
// state: { real (the signed-in person is a real Inspiration4 participant: personal rows are disabled),
//          on: { isslive, spaceweather } (Earth demo switches, both off by default),
//          connected: { 'heart-rate', thermometer, 'blood-pressure', 'pulse-oximeter' } (true when connected),
//          busy: { kind: true } while connecting, live: { id: 'text' } (replaces the row's line, e.g. "72 bpm") }
// onToggle(id, on) for the Earth demo switches, onImport(file) for the CSV row, onConnect(kind) for
// 'heart-rate' | 'thermometer' | 'blood-pressure' | 'pulse-oximeter' | 'fhir' | 'ical'.
// tipKey(id) gives the "?" key (default "c:<id>"); crew.js tipContent() should answer it with connectionTip(id).
export function renderConnections(host, { state = {}, onToggle = () => {}, onImport = () => {}, onConnect = () => {}, tipKey = (id) => `c:${id}` } = {}) {
  const ctx = { state, onToggle, onImport, onConnect, tip: (c) => tipButton(tipKey(c.id), c.name) };
  const groups = [
    { status: 'working', title: 'Working now', open: true },
    { status: 'simulated', title: 'Simulated', open: false },
    { status: 'planned', title: 'Planned, needs a partner', open: false },
  ];
  const nodes = [h('p', { class: 'note' }, 'No NASA system is connected. Working rows work now; simulated rows are imitated; planned rows name who must agree.')];
  for (const g of groups) {
    const rows = CONNECTIONS.filter((c) => c.status === g.status).map((c) => row(c, ctx));
    if (g.open) nodes.push(h('div', { class: 'conn-group' }, ...rows));
    else nodes.push(h('details', { class: 'more' }, h('summary', {}, icon('chevron-right', { size: 18 }), `${g.title} (${rows.length})`), h('div', {}, ...rows)));
  }
  host.replaceChildren(...nodes);
  return host;
}

// For a file that is not a known export: choose the time column, the value column and the measure.
// onPick({ timeColumn, valueColumn, indicator, unit }) then goes to mapReadings(result.rows, choice).
export function columnPicker(columns, { onPick, measures = IMPORTABLE } = {}) {
  const select = (id, label, options) => h('label', { class: 'log-field' }, h('span', {}, label), h('select', { id }, ...options.map(([v, t]) => h('option', { value: v }, t))));
  const cols = columns.map((c) => [c, c]);
  const form = h('div', { class: 'log-form' },
    select('imp-time', 'Time column', cols),
    select('imp-value', 'Value column', cols.length > 1 ? [...cols.slice(1), cols[0]] : cols),
    select('imp-measure', 'Measure', measures.map((m) => [m.indicator, `${m.label} (${m.unit})`])),
    h('label', { class: 'log-field' }, h('span', {}, 'Unit in the file'), h('input', { id: 'imp-unit', type: 'text', placeholder: 'leave empty if it is the same' })));
  form.append(btn('Import', () => {
    const val = (id) => form.querySelector(`#${id}`).value;
    onPick({ timeColumn: val('imp-time'), valueColumn: val('imp-value'), indicator: val('imp-measure'), unit: val('imp-unit').trim() || null });
  }, 'check'));
  return form;
}
