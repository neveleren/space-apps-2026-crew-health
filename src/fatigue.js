// The energy question of the daily check-in: the Samn-Perelli seven-point fatigue scale. The person picks the one
// statement that fits; 1 is fully alert and 7 is completely exhausted, so a higher number means more fatigue.
// Scale: Samn and Perelli, USAF School of Aerospace Medicine, 1982 (report SAM-TR-82-21, DTIC ADA125319). The
// statements are in the words of UK CAA Paper 2005/04, Issue 2, December 2007, Appendix B (its semicolons written as
// commas); the 1982 form says "Extremely Peppy" in statement 1 and ends statement 7 with "Ready to Drop". The CAA paper
// gives a group mean of level five as an example of a moderately high level (p. 49). The 1982 report links the steps to
// performance only as a hypothesis (its Tables 1 and 2): 5 is the first step of moderate fatigue, "flying duty
// permissible but not recommended unless urgent". The team chose this scale on 15 Nov 2026, in place of the two
// answers "energetic" and "sluggish". Code generated by Claude (Anthropic), an AI system.

export const FATIGUE_SOURCE = Object.freeze({ name: 'Samn-Perelli fatigue scale, UK CAA Paper 2005/04 (2007)', url: 'https://caa.co.uk/publication/download/13058' });

export const FATIGUE_STEPS = Object.freeze([
  { step: 1, short: 'Fully alert', text: 'Fully alert, wide awake, extremely energetic' },
  { step: 2, short: 'Very lively', text: 'Very lively, responsive, but not at peak' },
  { step: 3, short: 'Okay', text: 'Okay, somewhat fresh' },
  { step: 4, short: 'A little tired', text: 'A little tired, less than fresh' },
  { step: 5, short: 'Moderately tired', text: 'Moderately tired, let down' },
  { step: 6, short: 'Extremely tired', text: 'Extremely tired, very difficult to concentrate' },
  { step: 7, short: 'Completely exhausted', text: 'Completely exhausted, unable to function effectively' },
].map(Object.freeze));

// A day counts as a low-energy day for the mind rule from this step on: a draft, the team's open decision. Step 5 is
// where the 1982 report puts the start of moderate fatigue, as a hypothesis.
export const FATIGUE_RULE = Object.freeze({ lowFrom: 5, draft: true, source: FATIGUE_SOURCE });

// The step of an answer, 1 to 7. Records saved before the scale said "energetic" or "sluggish": they are read as
// steps 2 and 5, so an old "sluggish" day still counts as low. Anything else is no step.
export function fatigueStep(value) {
  if (value === 'energetic') return 2;
  if (value === 'sluggish') return 5;
  const n = typeof value === 'number' ? value : typeof value === 'string' && /^\s*[1-7]\s*$/.test(value) ? Number(value) : NaN;
  return Number.isInteger(n) && n >= 1 && n <= 7 ? n : NaN;
}

export const isLowEnergy = (value) => fatigueStep(value) >= FATIGUE_RULE.lowFrom;

// "5 of 7: moderately tired"; an old record keeps its own word next to the step it is read as.
export function fatigueWords(value) {
  const n = fatigueStep(value);
  if (!Number.isFinite(n)) return String(value ?? '');
  const words = `${n} of 7: ${FATIGUE_STEPS[n - 1].short.toLowerCase()}`;
  return typeof value === 'string' && /[a-z]/i.test(value) ? `${value} (read as ${words})` : words;
}
