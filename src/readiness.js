// Readiness before hard work (review finding PO-9; the team's choice of 15 Nov 2026): the mission's critical tasks (a
// spacewalk, a docking, robotic arm work) and, in the hours before one starts, the three things the app already holds
// about the person, put together on one card: last night's sleep, the medicines taken that can make a person sleepy
// (the kit list's sleep medicines and its sedation notes), and the 3-minute reaction test against the person's own
// earlier runs. Every rule here is a DRAFT for the team and the flight surgeons, and the screen says so. The card
// decides nothing and never blocks work: it shows the facts, asks for the reaction test after a short night or a sleep
// medicine, and offers to tell the flight surgeon. Nothing here is sent or saved by itself. Pure functions, so the
// automatic checks run them in Node.
// Sources, each opened by Claude on 15 Nov 2026 (what each one supports is said where it is used):
// - NASA-STD-3001 Volume 1 Revision C (2023), [V1 4006];
// - Jones et al., Sleep 2022: 24 astronauts on six-month ISS missions;
// - Barger et al., Lancet Neurology 2014: sleep before shuttle spacewalks;
// - the FDA label of AMBIEN (zolpidem tartrate), revised 2/2022, as published on DailyMed;
// - NCCIH, "Melatonin: What You Need To Know", last updated May 2024;
// - NASA's ISS medical kit list of 9 Apr 2015 (its sleep group and sedation notes are data in src/config.js).
// Code generated by Claude (Anthropic), an AI system.
import { CELLS } from './config.js';
import { compareToOwn } from './reaction-test.js';
import { amountText, gmtText } from './quicklog.js';

const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const ms = (t) => (t instanceof Date ? t.getTime() : typeof t === 'number' ? t : Date.parse(t));
const iso = (t) => new Date(ms(t)).toISOString();

export const READINESS_SOURCES = Object.freeze({
  std1: { name: 'NASA-STD-3001 Vol 1 Rev C, 2023, [V1 4006]', url: 'https://www.nasa.gov/wp-content/uploads/2023/11/nasa-std-3001-vol-1-rev-c-with-signature.pdf' },
  jones2022: { name: 'Jones et al., Sleep, 2022', url: 'https://pmc.ncbi.nlm.nih.gov/articles/PMC8919197/' },
  barger2014: { name: 'Barger et al., Lancet Neurology, 2014', url: 'https://pmc.ncbi.nlm.nih.gov/articles/PMC4188436/' },
  zolpidem: { name: 'FDA label of AMBIEN (zolpidem), revised 2/2022, on DailyMed', url: 'https://dailymed.nlm.nih.gov/dailymed/drugInfo.cfm?setid=c36cadf4-65a4-4466-b409-c82020b42452' },
  melatonin: { name: 'NCCIH, Melatonin: What You Need To Know, 2024', url: 'https://www.nccih.nih.gov/health/melatonin-what-you-need-to-know' },
  kit2015: { name: 'NASA ISS medical kit list, 9 Apr 2015', url: 'https://www.governmentattic.org/19docs/NASA-ISSmedicalEmergManual_2016.pdf' },
});

// The rules of the card, all drafts for the team and the flight surgeons.
export const READINESS_RULES = Object.freeze({
  // The card shows from this many hours before the start, so the night before is inside it: Barger et al. (2014)
  // looked at the night before each shuttle spacewalk. The length itself is the team's open decision.
  windowHours: 24,
  // A night of this many hours or less counts as short. Jones et al. (2022), ISS: "PVT-B response speed was
  // significantly slower when sleep duration was ≤6 h"; Barger et al. (2014): on more than half of the nights before
  // shuttle spacewalks (41 of 80) crewmembers slept less than 6 hours.
  shortNightHours: 6,
  // The FDA label of zolpidem: "Tell patients to wait for at least 8 hours after dosing before driving or engaging in
  // other activities requiring full mental alertness."
  labelHours: 8,
  // Coming up lists the critical tasks of this many next days.
  listDays: 14,
  draft: true,
});

// The kinds of critical task. NASA's crew health standard: "In-mission Fitness-for-Duty technical requirements shall be
// guided by the nature of mission-associated critical operations (such as, but not limited to, vehicle control,
// robotic operations, and EVAs)" ([V1 4006]). A docking stands for vehicle control here. Icons from src/icons.js.
export const TASK_KINDS = Object.freeze({
  spacewalk: Object.freeze({ label: 'Spacewalk', icon: 'orbit', the: 'the spacewalk' }),
  docking: Object.freeze({ label: 'Docking', icon: 'rocket', the: 'the docking' }),
  robotics: Object.freeze({ label: 'Robotic arm work', icon: 'cpu', the: 'the robotic arm work' }),
  other: Object.freeze({ label: 'Critical task', icon: 'flag', the: 'the task' }),
});
const kindOf = (t) => TASK_KINDS[t && t.kind] || TASK_KINDS.other;
export const taskName = (t) => (t && t.title ? t.title : kindOf(t).label);
// "the spacewalk", or "the task" with its own name for a named task of another kind.
export const taskThe = (t) => (t && t.title && (!t.kind || t.kind === 'other') ? `the task "${t.title}"` : kindOf(t).the);

// MADE UP for the example flight, like everything in src/demo-crew.js: three critical tasks, on flight days counted
// from launch (the example's today is flight day 167; landing is on day 193). hour: hours after the start of that
// flight day, so the spacewalk starts about 14 hours after the example's today and its readiness card shows at once.
// crew: who does the task; null means the whole crew.
export const EXAMPLE_TASKS = Object.freeze([
  { id: 'example-spacewalk', kind: 'spacewalk', title: 'Spacewalk', phrase: 'a spacewalk', day: 168, hour: 2, crew: ['crew-1', 'crew-2'] },
  { id: 'example-robotics', kind: 'robotics', title: 'Robotic arm session', phrase: 'a robotic arm session', day: 171, hour: 5, crew: ['crew-3'] },
  { id: 'example-docking', kind: 'docking', title: 'Docking of a crew ship', phrase: 'the docking of a crew ship', day: 175, hour: 4, crew: null },
].map(Object.freeze));

// The example's tasks with their start as a GMT time: { id, kind, title, start, crew, example: true, day }.
export function exampleTasks(launch, list = EXAMPLE_TASKS) {
  const L = ms(launch);
  return list.map((t) => ({ id: t.id, kind: t.kind, title: t.title, start: iso(L + (t.day - 1) * DAY + t.hour * HOUR), crew: t.crew ? [...t.crew] : null, example: true, day: t.day }));
}

// The same tasks as items of the mission calendar of the mind tools (src/support.js renderCalendar).
export function calendarItems(list = EXAMPLE_TASKS) {
  return list.map((t) => ({ day: t.day, kind: 'task', task: t.kind, icon: kindOf(t).icon, title: `${t.title} (critical task)`, phrase: t.phrase, example: true }));
}

// One person's tasks in time order: a task with no crew list is everyone's.
export function tasksFor(tasks, personId) {
  return (Array.isArray(tasks) ? tasks : [])
    .filter((t) => t && Number.isFinite(ms(t.start)) && (!Array.isArray(t.crew) || t.crew.includes(personId)))
    .sort((a, b) => ms(a.start) - ms(b.start));
}

// The tasks that start after now and within `days` days, in time order.
export function upcomingTasks(tasks, now, days = READINESS_RULES.listDays) {
  const t0 = ms(now);
  return (Array.isArray(tasks) ? tasks : []).filter((t) => t && ms(t.start) > t0 && ms(t.start) - t0 <= days * DAY).sort((a, b) => ms(a.start) - ms(b.start));
}

// The next task that has not started yet, or null.
export function nextTask(tasks, now) {
  const t0 = ms(now);
  return (Array.isArray(tasks) ? tasks : []).filter((t) => t && ms(t.start) > t0).sort((a, b) => ms(a.start) - ms(b.start))[0] || null;
}

// Is the readiness card due: the task starts within the window. Once the task has started, the card is gone.
export function readinessDue(task, now, rules = READINESS_RULES) {
  if (!task) return false;
  const d = ms(task.start) - ms(now);
  return d > 0 && d <= rules.windowHours * HOUR;
}

// When a logged medicine was taken: its takenAt when the entry has one, otherwise the time of the entry
// (the same reading as src/quicklog.js).
function takenMs(x) {
  const at = x && x.value && typeof x.value.takenAt === 'string' ? Date.parse(x.value.takenAt) : NaN;
  return Number.isFinite(at) ? at : ms(x && x.time);
}

const KIT = (CELLS.find((c) => c.indicator === 'medicines') || { kit: [] }).kit;

// What a public source says about a medicine the card lists. The kit list's own note is quoted for the others.
export const MEDICINE_NOTES = Object.freeze({
  zolpidem: Object.freeze({ text: 'Its FDA label says: "Tell patients to wait for at least 8 hours after dosing before driving or engaging in other activities requiring full mental alertness." It adds that impairment "can be present despite feeling fully awake."', src: READINESS_SOURCES.zolpidem }),
  melatonin: Object.freeze({ text: 'Melatonin has no FDA drug label: in the United States it is a dietary supplement. In short-term studies only mild side effects were reported, sleepiness among them (NCCIH, 2024).', src: READINESS_SOURCES.melatonin }),
});

// Everything the card shows before one task, for one person, at now. The inputs are as the machine keeps them:
//   sleep: the history of 'sleep' (hours a night); quality: of 'sleepQuality' (1 to 7, the morning check-in);
//   medicines: of 'medicines'; runs: the person's reaction test results ({ median, mode, time, ... }: their own and, with
//   the example flight, the made-up earlier ones of src/reaction-test.js).
// Parts, each with a level (0: nothing to tell, 1: attention, "worth telling your flight surgeon"):
//   sleep: the latest night logged in the 24 hours before now: 'none', 'ok' or 'short';
//   medicines: the kit list's sleep medicines and the medicines with its sedation note, taken from windowHours before
//     the start until now: 'none' or 'taken', each with how many hours before the start;
//   reaction: the latest reaction test of that window against the person's own earlier runs (compareToOwn): 'none',
//     'first', 'similar', 'faster' or 'slower'.
// askTest: a short night or such a medicine, and no reaction test after it yet. level: the highest part; never more
// than attention, and the card never stops the task.
export function readiness({ task, now, sleep = [], quality = [], medicines = [], runs = [], kit = KIT, rules = READINESS_RULES } = {}) {
  const start = ms(task.start);
  const t0 = ms(now);
  const from = start - rules.windowHours * HOUR;
  const within = (x, a, b) => x && Number.isFinite(ms(x.time)) && ms(x.time) >= a && ms(x.time) <= b;
  const newest = (list) => [...list].sort((a, b) => ms(a.time) - ms(b.time)).slice(-1)[0] || null;

  const night = newest((sleep || []).filter((x) => within(x, t0 - DAY, t0) && Number.isFinite(Number(x.value))));
  const rate = newest((quality || []).filter((x) => within(x, t0 - DAY, t0) && Number.isFinite(Number(x.value))));
  const hours = night ? Number(night.value) : null;
  const short = hours !== null && hours <= rules.shortNightHours;
  const sleepPart = { state: night ? (short ? 'short' : 'ok') : 'none', level: short ? 1 : 0, hours, time: night ? iso(night.time) : null, rating: rate ? Number(rate.value) : null };

  const byKey = new Map((kit || []).map((k) => [k.key, k]));
  const meds = (medicines || [])
    .map((x) => ({ x, k: x && x.value && typeof x.value === 'object' ? byKey.get(x.value.medicine) : undefined, t: takenMs(x) }))
    .filter(({ x, k, t }) => k && (k.sleepMed || k.sedating) && Number(x.value.amount) > 0 && Number.isFinite(t) && t >= from && t <= t0)
    .sort((a, b) => a.t - b.t)
    .map(({ x, k, t }) => ({
      key: k.key, name: k.name, strength: k.strength, amount: Number(x.value.amount), unit: x.value.unit || k.unit, taken: iso(t),
      hoursBefore: (start - t) / HOUR, sleepMed: Boolean(k.sleepMed), sedating: Boolean(k.sedating), kitNote: k.kitNote || null,
      underLabel: k.key === 'zolpidem' && (start - t) / HOUR < rules.labelHours,
    }));
  const medPart = { state: meds.length ? 'taken' : 'none', level: meds.length ? 1 : 0, list: meds };

  const mine = (runs || []).filter((r) => r && Number.isFinite(r.median) && Number.isFinite(ms(r.time)));
  const last = newest(mine.filter((r) => ms(r.time) >= from && ms(r.time) <= t0));
  const cmp = last ? compareToOwn(last, mine) : null;
  const reactionPart = { state: cmp ? cmp.state : 'none', level: cmp && cmp.attention ? 1 : 0, run: last, compare: cmp };

  const after = Math.max(short ? ms(night.time) : -Infinity, ...meds.map((m) => ms(m.taken)));
  const askTest = (short || meds.length > 0) && !(last && ms(last.time) >= after);
  return {
    task, start: iso(start), from: iso(from), hoursTo: Math.max(0, (start - t0) / HOUR),
    sleep: sleepPart, medicines: medPart, reaction: reactionPart, askTest,
    level: Math.max(sleepPart.level, medPart.level, reactionPart.level), draft: true,
  };
}

// "in 14 hours", "in 40 minutes", "in 3 days".
export function startsIn(hours) {
  if (hours < 1) { const m = Math.max(1, Math.round(hours * 60)); return `in ${m} ${m === 1 ? 'minute' : 'minutes'}`; }
  if (hours < 48) { const h = Math.round(hours); return `in ${h} ${h === 1 ? 'hour' : 'hours'}`; }
  const d = Math.round(hours / 24);
  return `in ${d} days`;
}
// The same for a list that also shows the task's GMT date (Coming up): from 2 days on it counts GMT calendar days, as
// the status line does, so "in 7 days" always matches the date next to it.
export function startsInAt(start, now) {
  const hours = (ms(start) - ms(now)) / HOUR;
  if (hours < 48) return startsIn(hours);
  return `in ${Math.floor(ms(start) / DAY) - Math.floor(ms(now) / DAY)} days`;
}
const hoursText = (h) => { const r = Math.round(h * 10) / 10; return `${r} ${r === 1 ? 'hour' : 'hours'}`; };
const fmtNum = (v) => String(Math.round(Number(v) * 10) / 10);

// One medicine of the card in plain words, with what its source says.
export function medicineText(m) {
  const head = `${m.name} ${m.strength}, ${amountText(m.amount, m.unit)}, taken ${gmtText(m.taken)}, ${hoursText(Math.max(0, m.hoursBefore))} before the start.`;
  const note = MEDICINE_NOTES[m.key];
  const label = m.underLabel ? ` That is less than the ${READINESS_RULES.labelHours} hours its FDA label asks for.` : '';
  if (note) return `${head}${label} ${note.text}`;
  return m.kitNote ? `${head} The kit list says: "${m.kitNote}"` : head;
}

// The card's lines, in plain words, each with its level and sources: sleep, medicines, reaction test.
export function readinessLines(r, rules = READINESS_RULES) {
  const S = READINESS_SOURCES;
  const s = r.sleep;
  const rated = s.rating ? ` Sleep rated ${s.rating} of 7 in the check-in.` : '';
  const sleepLine = s.state === 'none'
    ? { key: 'sleep', level: 0, title: "Last night's sleep", text: `No hours of sleep logged in the last 24 hours.${rated}`, src: [] }
    : s.state === 'short'
      ? { key: 'sleep', level: 1, title: "Last night's sleep: a short night", text: `${fmtNum(s.hours)} hours (logged ${gmtText(s.time)}): ${rules.shortNightHours} hours or less counts as a short night here (a draft).${rated} On the ISS, the reaction test was slower after nights of 6 hours or less (Jones et al., 2022).`, src: [S.jones2022] }
      : { key: 'sleep', level: 0, title: "Last night's sleep", text: `${fmtNum(s.hours)} hours (logged ${gmtText(s.time)}).${rated}`, src: [] };
  const m = r.medicines;
  const medLine = m.state === 'none'
    ? { key: 'medicines', level: 0, title: 'Medicines that can make you sleepy', text: `None logged since ${gmtText(r.from)}, ${rules.windowHours} hours before the start: no sleep medicine from the kit list and no medicine with its note "May cause sedation and impair performance."`, src: [S.kit2015] }
    : { key: 'medicines', level: 1, title: m.list.some((x) => x.sleepMed) ? 'A sleep medicine before the task' : 'A medicine that can make you sleepy', text: `${m.list.map(medicineText).join(' ')} Worth telling your flight surgeon before the task (a draft rule).`, src: [S.kit2015, ...m.list.map((x) => (MEDICINE_NOTES[x.key] || {}).src).filter(Boolean)] };
  const c = r.reaction;
  const after = r.sleep.state === 'short' ? 'a short night' : r.medicines.list.some((x) => x.sleepMed) ? 'a sleep medicine' : 'a medicine that can make you sleepy';
  const ask = r.askTest ? ` After ${after}, a run now shows how you compare with yourself.` : '';
  const reactionLine = c.state === 'none'
    ? { key: 'reaction', level: 0, title: 'Reaction test', text: `No reaction test since ${gmtText(r.from)}, ${rules.windowHours} hours before the start.${ask} It compares you only with your own earlier runs; it is not a fitness-for-duty test.`, src: [S.jones2022] }
    : { key: 'reaction', level: c.level, title: c.state === 'slower' ? 'Reaction test: slower than before' : 'Reaction test', text: `Run of ${gmtText(c.run.time)}${c.run.mode === 'demo' ? ' (the 30-second demo)' : ''}: ${c.compare.text}${c.state === 'slower' ? ' Worth telling your flight surgeon before the task (a draft rule).' : ''}${ask}`, src: [S.jones2022] };
  return [sleepLine, medLine, reactionLine];
}

// The draft of a message to the flight surgeon: the person reads and changes it before anything is sent.
export function readinessMessage(r, { name = '', when = '' } = {}) {
  const t = r.task;
  const lines = [`Before ${taskThe(t)}${t.example ? ' (a made-up example task)' : ''}, which starts ${gmtText(r.start)}${when ? ` (${when})` : ''}${name ? `, from ${name}'s readiness card` : ''}:`];
  const s = r.sleep;
  lines.push(s.state === 'none' ? "- Last night's sleep: no hours logged in the last 24 hours." : `- Last night's sleep: ${fmtNum(s.hours)} hours (${gmtText(s.time)})${s.state === 'short' ? `, a short night (${READINESS_RULES.shortNightHours} hours or less, a draft rule)` : ''}${s.rating ? `, rated ${s.rating} of 7` : ''}.`);
  lines.push(r.medicines.state === 'none' ? `- Medicines that can make me sleepy, since ${gmtText(r.from)}: none logged.`
    : `- Medicines that can make me sleepy, since ${gmtText(r.from)}: ${r.medicines.list.map((m) => `${m.name} ${m.strength}, ${amountText(m.amount, m.unit)}, taken ${gmtText(m.taken)}`).join('; ')}.`);
  const c = r.reaction;
  lines.push(c.state === 'none' ? `- Reaction test: none since ${gmtText(r.from)}.` : `- Reaction test of ${gmtText(c.run.time)}: ${c.compare.text}`);
  lines.push('', 'The readiness card is a draft check of the program; it does not decide whether I do the task.', '');
  return lines.join('\n');
}
