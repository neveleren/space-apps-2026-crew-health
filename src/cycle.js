// The menstrual cycle, in the team's words "like Flo, but for astronauts", with its link to the mind.
// Only facts with a checked source are used as flags:
// - doctors on Earth treat the menstrual cycle as a vital sign (American College of Obstetricians and Gynecologists);
// - a check-up is advised if cycles are consistently longer than 45 days or there is no period for 3 months
//   (Endocrine Society guideline on functional hypothalamic amenorrhea);
// - many astronauts choose to suppress periods with hormones; it is a personal decision with the flight surgeon
//   (NASA oral histories of Anna Fisher and others).
// The prediction of the next period is a plain average of the last cycles, not a medical model.
// Code generated by Claude (Anthropic), an AI system.

const DAY = 24 * 60 * 60 * 1000;
const ms = (t) => (t instanceof Date ? t.getTime() : new Date(t).getTime());
export const CYCLE_RULES = { longCycleDays: 45, noPeriodDays: 90, cyclesForAverage: 6 };

// events: the person's cycle log [{ time, value }] with values period_start, period_end,
// suppression_on, suppression_off.
export function cycleSummary(events, now) {
  const list = [...events].filter((e) => Number.isFinite(ms(e.time))).sort((a, b) => ms(a.time) - ms(b.time));
  const last = (pred) => [...list].reverse().find(pred);
  const sup = last((e) => e.value === 'suppression_on' || e.value === 'suppression_off');
  const suppressed = Boolean(sup && sup.value === 'suppression_on');
  const starts = list.filter((e) => e.value === 'period_start').map((e) => ms(e.time));
  const ends = list.filter((e) => e.value === 'period_end').map((e) => ms(e.time));
  const lengths = [];
  for (let i = 1; i < starts.length; i += 1) lengths.push(Math.round((starts[i] - starts[i - 1]) / DAY));
  const recent = lengths.slice(-CYCLE_RULES.cyclesForAverage);
  const average = recent.length ? Math.round(recent.reduce((a, b) => a + b, 0) / recent.length) : null;
  const periodDays = starts.map((s) => {
    const end = ends.find((e) => e >= s);
    return end !== undefined ? Math.round((end - s) / DAY) + 1 : null;
  }).filter((d) => d !== null && d > 0 && d < 15);
  const lastStart = starts.length ? starts[starts.length - 1] : null;
  const t = ms(now);
  const cycleDay = lastStart !== null && t >= lastStart ? Math.floor((t - lastStart) / DAY) + 1 : null;
  const nextExpected = !suppressed && average && lastStart !== null ? new Date(lastStart + average * DAY) : null;
  const flags = [];
  if (!suppressed) {
    const lastTwo = lengths.slice(-2);
    if (lastTwo.length === 2 && lastTwo.every((d) => d > CYCLE_RULES.longCycleDays)) flags.push('long-cycles');
    if (lastStart !== null && t - lastStart > CYCLE_RULES.noPeriodDays * DAY) flags.push('no-period');
  }
  return {
    suppressed,
    starts,
    lengths,
    average,
    periodDays: periodDays.length ? Math.round(periodDays.slice(-CYCLE_RULES.cyclesForAverage).reduce((a, b) => a + b, 0) / Math.min(periodDays.length, CYCLE_RULES.cyclesForAverage)) : null,
    lastStart: lastStart !== null ? new Date(lastStart) : null,
    cycleDay,
    nextExpected,
    flags,
  };
}

// The team's link between cycle and mind: how the person's own low check-ins fall across the cycle.
// Only counts of the person's own days; no conclusion is drawn.
export const PHASES = [[1, 7], [8, 14], [15, 21], [22, 99]];
export function lowDaysByPhase(starts, lowDays) {
  const out = PHASES.map(([from, to]) => ({ from, to, low: 0, days: 0 }));
  if (!starts.length) return out;
  const sorted = [...starts].sort((a, b) => a - b);
  for (const [day, isLow] of lowDays) {
    const t = ms(day);
    const start = [...sorted].reverse().find((s) => s <= t);
    if (start === undefined) continue;
    const cd = Math.floor((t - start) / DAY) + 1;
    const phase = out.find((p) => cd >= p.from && cd <= p.to);
    if (!phase) continue;
    phase.days += 1;
    if (isLow) phase.low += 1;
  }
  return out;
}
