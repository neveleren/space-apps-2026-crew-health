// The menstrual cycle, in the team's words "like Flo, but for astronauts", with its link to the mind.
// Only facts with a checked source are used as flags:
// - doctors on Earth treat the menstrual cycle as a vital sign (American College of Obstetricians and Gynecologists);
// - a check-up is advised if cycles are consistently longer than 45 days or there is no period for 3 months
//   (Endocrine Society guideline on functional hypothalamic amenorrhea);
// - many astronauts choose to suppress periods with hormones; it is a personal decision with the flight surgeon
//   (NASA oral histories of Anna Fisher and others);
// - a normal cycle is typically 21 to 35 days and a normal period lasts up to 7 days; a cycle length that varies by
//   more than 7 to 9 days counts as abnormal (ACOG patient FAQ095, reviewed August 2025). The larger 9 is used here;
// - bleeding or spotting between periods is listed among the kinds of abnormal uterine bleeding (ACOG FAQ095); spotting
//   is "usually harmless", and "if bleeding between periods occurs regularly and/or is accompanied by pain or other
//   symptoms" a health care provider should be contacted (Flo help centre, 2021). A draft flag.
// The periods come from the day-by-day log (src/cycle-log.js), which still reads the old start and end buttons.
// A cycle length is not counted across a time of suppression, and after suppression the 3 months of "no period"
// count from the day it ended (drafts). The prediction of the next period is a plain average of the last cycles,
// not a medical model.
// Code generated by Claude (Anthropic), an AI system.
import { readLog, periodsOf, spottingApart, bleedingSummary, suppressedOn, dayOf, dayWords, addDays, daysBetween, LOG_RULES, PATTERN_WORDS } from './cycle-log.js';

const DAY = 24 * 60 * 60 * 1000;
const ms = (t) => (t instanceof Date ? t.getTime() : new Date(t).getTime());
export const CYCLE_RULES = { longCycleDays: 45, noPeriodDays: 90, cyclesForAverage: 6, normalMin: 21, normalMax: 35, periodMax: 7, varyMax: 9 };
const mean = (list) => Math.round(list.reduce((a, b) => a + b, 0) / list.length);

// events: the person's cycle log [{ time, value }]: the days of the log ({ day, flow, symptoms }) and the old values
// period_start, period_end, suppression_on, suppression_off.
// Returns the summary the card shows: suppressed now, the period starts (ms), the cycle lengths counted, their plain
// average, the average period length, the last start, today's cycle day, the next expected start, the flags; and
// for the log itself the periods (each with its cycle length or why it is not counted), the spotting apart from
// periods and the bleeding while suppressed.
export function cycleSummary(events, now) {
  const log = readLog(events);
  const t = ms(now);
  const today = dayOf(t);
  const suppressed = today !== null && suppressedOn(today, log.suppression);
  const periods = periodsOf(log, t);
  // The times periods were suppressed. Switched on and off again on the same GMT day (a tap undone) does not count.
  const stretches = [];
  for (const s of log.suppression) {
    const open = stretches.length && stretches[stretches.length - 1].offAt === undefined ? stretches[stretches.length - 1] : null;
    if (s.on && !open) stretches.push({ day: s.day, at: s.at, offAt: undefined, offDay: null });
    if (!s.on && open) { open.offAt = s.at; open.offDay = s.day; }
  }
  const real = stretches.filter((x) => x.offDay !== x.day);
  const lengths = [];
  for (let i = 1; i < periods.length; i += 1) {
    const a = periods[i - 1];
    const b = periods[i];
    a.acrossSuppression = real.some((x) => x.day > a.start && x.day <= b.start);
    // Calendar days from one first day of bleeding to the next (ACOG FAQ095).
    a.cycle = a.acrossSuppression ? null : daysBetween(a.start, b.start);
    if (a.cycle !== null) lengths.push(a.cycle);
  }
  const recent = lengths.slice(-CYCLE_RULES.cyclesForAverage);
  const average = recent.length ? mean(recent) : null;
  const known = periods.filter((p) => p.length !== null).map((p) => p.length);
  const last = periods.length ? periods[periods.length - 1] : null;
  const lastStart = last ? last.startAt : null;
  // Suppression switched on after the last period: the cycle starts again only when it ends, so "no period" counts
  // from the day it was switched off, and there is no cycle day and no estimate until a new period is logged.
  const after = last ? real.filter((x) => x.at >= last.startAt || x.day > last.start) : [];
  const suppressedSince = after.length > 0;
  const offAt = suppressedSince ? after[after.length - 1].offAt : undefined;
  const since = lastStart === null ? null : suppressedSince ? (offAt !== undefined ? offAt : null) : lastStart;
  const cycleDay = lastStart !== null && !suppressedSince && t >= lastStart ? Math.floor((t - lastStart) / DAY) + 1 : null;
  const nextExpected = !suppressed && !suppressedSince && average && lastStart !== null ? new Date(lastStart + average * DAY) : null;
  const apart = spottingApart(log).filter((e) => today !== null && e.last >= addDays(today, -(LOG_RULES.referenceDays - 1)));
  const flags = [];
  if (!suppressed) {
    const lastTwo = lengths.slice(-2);
    if (lastTwo.length === 2 && lastTwo.every((d) => d > CYCLE_RULES.longCycleDays)) flags.push('long-cycles');
    if (since !== null && t - since > CYCLE_RULES.noPeriodDays * DAY) flags.push('no-period');
    const lastLength = lengths[lengths.length - 1];
    if (lastLength !== undefined && (lastLength < CYCLE_RULES.normalMin || lastLength > CYCLE_RULES.normalMax)) flags.push('cycle-outside-range');
    if (recent.length >= 3 && Math.max(...recent) - Math.min(...recent) > CYCLE_RULES.varyMax) flags.push('cycle-varies');
    // The last period: still going (its days so far), else its length, else (an old start with no end) the one before.
    const lastKnown = [...periods].reverse().find((p) => p.length !== null);
    const lastPeriod = !last ? null : last.ongoing ? last.soFar : last.length !== null ? last.length : lastKnown ? lastKnown.length : null;
    if (lastPeriod !== null && lastPeriod > CYCLE_RULES.periodMax) flags.push('long-period');
    if (apart.length) flags.push('between-periods');
  }
  return {
    suppressed,
    starts: periods.map((p) => p.startAt),
    lengths,
    average,
    periodDays: known.length ? mean(known.slice(-CYCLE_RULES.cyclesForAverage)) : null,
    lastStart: lastStart !== null ? new Date(lastStart) : null,
    cycleDay,
    nextExpected,
    flags,
    periods,
    spottingApart: apart,
    since: since !== null ? new Date(since) : null,
    suppressedSince,
    bleeding: bleedingSummary(log, t),
    log,
  };
}

// The summary in plain sentences for the card, flags first after the cycle day. s: cycleSummary(...).
export function cycleFacts(s) {
  const facts = [];
  const date = (d) => dayWords(dayOf(d));
  // An estimate that has already passed says so, in days: a plain average is often off by a few.
  const late = s.nextExpected && s.cycleDay && s.average ? s.cycleDay - 1 - s.average : 0;
  const ago = late > 0 ? ` (${late} ${late === 1 ? 'day' : 'days'} ago)` : '';
  if (s.suppressed) facts.push("You chose to suppress your periods. Many astronauts do; the choice is yours and your flight surgeon's.");
  else if (s.cycleDay) facts.push(`Cycle day ${s.cycleDay}${s.average ? ` · average cycle ${s.average} days` : ''}${s.periodDays ? ` · period about ${s.periodDays} days` : ''}${s.nextExpected ? ` · next period expected around ${date(s.nextExpected)}${ago}` : ''}.`);
  else if (s.suppressedSince && s.since) facts.push(`You stopped suppressing your periods on ${date(s.since)}. No period logged since then.`);
  else facts.push('No period logged yet.');
  if (s.flags.includes('long-cycles')) facts.push(`The last cycles were longer than ${CYCLE_RULES.longCycleDays} days. The Endocrine Society advises a check-up when cycles are consistently that long.`);
  if (s.flags.includes('no-period')) facts.push('No period for more than 3 months. The Endocrine Society advises a check-up, after other causes are ruled out.');
  if (s.flags.includes('cycle-outside-range')) facts.push(`The last cycle was outside the usual ${CYCLE_RULES.normalMin} to ${CYCLE_RULES.normalMax} days (ACOG).`);
  if (s.flags.includes('cycle-varies')) facts.push(`Your recent cycles differ by more than ${CYCLE_RULES.varyMax} days; ACOG counts that as irregular.`);
  if (s.flags.includes('long-period')) facts.push(`Your last period has more than ${CYCLE_RULES.periodMax} days of bleeding logged; ACOG counts bleeding that lasts more than ${CYCLE_RULES.periodMax} days as abnormal.`);
  if (s.flags.includes('between-periods')) {
    const e = s.spottingApart[s.spottingApart.length - 1];
    facts.push(`You logged spotting apart from your periods, last on ${dayWords(e.last)}. ACOG lists bleeding or spotting between periods as abnormal bleeding. Flo's help says spotting is usually harmless, and advises seeing a health care provider when bleeding between periods happens regularly or comes with pain: on board, your flight surgeon (a draft flag).`);
  }
  const b = s.bleeding;
  if (b && b.suppressedDays > 0 && (s.suppressed || b.bleedingDays + b.spottingDays > 0)) {
    const count = b.bleedingDays + b.spottingDays;
    const span = b.full ? `over the last ${b.days} days` : `on ${b.suppressedDays} of the last ${b.days} days`;
    facts.push(count
      ? `Bleeding while suppressed (${span}): ${b.bleedingDays} ${b.bleedingDays === 1 ? 'day' : 'days'} of bleeding and ${b.spottingDays} of spotting, in ${b.episodes} ${b.episodes === 1 ? 'episode' : 'episodes'}${b.pattern ? `; ${PATTERN_WORDS[b.pattern]}` : ''}${b.prolonged ? `; one lasted more than ${LOG_RULES.prolongedDays} days` : ''}.`
      : `No bleeding or spotting logged while suppressed (${span}).`);
  }
  return facts;
}

// The team's link between cycle and mind: how the person's own low check-ins fall across the cycle.
// Only counts of the person's own days; no conclusion is drawn.
export const PHASES = [[1, 7], [8, 14], [15, 21], [22, 99]];
export function lowDaysByPhase(starts, lowDays) {
  const out = PHASES.map(([from, to]) => ({ from, to, low: 0, days: 0 }));
  if (!starts.length) return out;
  const sorted = [...starts].sort((a, b) => a - b);
  for (const [day, isLow] of lowDays) {
    const t = ms(day);
    const start = [...sorted].reverse().find((s) => s <= t);
    if (start === undefined) continue;
    const cd = Math.floor((t - start) / DAY) + 1;
    const phase = out.find((p) => cd >= p.from && cd <= p.to);
    if (!phase) continue;
    phase.days += 1;
    if (isLow) phase.low += 1;
  }
  return out;
}
