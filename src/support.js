// A full-screen layer for the reaction test and the Earth break: it keeps the keyboard inside, Esc calls
// onEscape (and goes no further, so the side sheet under it stays open), onKey(e) may handle a key first by
// returning true. close() puts the focus back where it was.
export function openOverlay({ cls = '', labelledby = null, label = null, onEscape, onKey } = {}) {
  hideTip();
  const back = document.activeElement;
  const root = h('div', { class: `sup sup-overlay ${cls}`.trim(), role: 'dialog', 'aria-modal': 'true', 'aria-labelledby': labelledby, 'aria-label': labelledby ? null : label });
  const focusables = () => [...root.querySelectorAll('button, a[href], input, textarea, select, [tabindex]:not([tabindex="-1"])')]
    .filter((x) => !x.disabled && !x.closest('[hidden]') && x.getClientRects().length);
  const keydown = (e) => {
    // A dialog opened on top of this layer (the crew screen's camera question "Are you okay?") keeps its own
    // keys: Tab, Space and Esc there must reach its buttons, not this layer.
    const t = e.target;
    if (t instanceof Node && t !== document.body && t !== document.documentElement && !root.contains(t)) return;
    if (e.key === 'Escape' || e.key === 'Esc') {
      e.preventDefault();
      e.stopPropagation();
      if (typeof onEscape === 'function') onEscape(e);
      return;
    }
    if (typeof onKey === 'function' && onKey(e)) return;
    if (e.key === 'Tab') {
      const f = focusables();
      if (!f.length) { e.preventDefault(); return; }
      const i = f.indexOf(document.activeElement);
      if (e.shiftKey && i <= 0) { e.preventDefault(); f[f.length - 1].focus(); } else if (!e.shiftKey && (i === -1 || i === f.length - 1)) { e.preventDefault(); f[0].focus(); }
    }
  };
  window.addEventListener('keydown', keydown, true);
  document.documentElement.classList.add('sup-noscroll');
  document.body.append(root);
  let closed = false;
  return {
    root,
    close() {
      if (closed) return;
      closed = true;
      window.removeEventListener('keydown', keydown, true);
      root.remove();
      if (!document.querySelector('.sup-overlay')) document.documentElement.classList.remove('sup-noscroll');
      if (back && document.contains(back) && typeof back.focus === 'function') back.focus();
    },
  };
}

