// Orders the cards for this moment. signals: { topic: 'home' or null, lowMood, lowEnergy, poorSleep }.
// A matching topic counts double; ties keep the list's own order. Nothing is ever hidden, only ordered.
export function pickTips(signals = {}, tips = MIND_TIPS) {
  const keys = new Set();
  if (signals.topic) keys.add(`topic:${signals.topic}`);
  for (const k of ['lowMood', 'lowEnergy', 'poorSleep']) if (signals[k]) keys.add(k);
  const score = (tip) => tip.for.reduce((s, k) => s + (keys.has(k) ? (k.startsWith('topic:') ? 2 : 1) : 0), 0);
  return tips.map((tip, i) => ({ tip, i, s: score(tip) })).sort((a, b) => b.s - a.s || a.i - b.i).map((x) => x.tip);
}

