// F9. Problem solving in five steps. onSave(worksheet) with { id, time, problem, better, options, plan,
// checkBack: 'YYYY-MM-DD', review }. worksheet: an earlier one to continue, or null for a new one.
export function renderSteps(host, { onSave, worksheet = null, now } = {}) {
  prep(host, 'sup-steps-box');
  const msg = status();
  const sid = Object.fromEntries([...STEPS.map((s) => s.key), 'date'].map((k) => [k, uid(`s-${k}`)]));
  const boxes = Object.fromEntries(STEPS.slice(0, 4).map((s) => [s.key, h('textarea', { class: 'sup-textarea', id: sid[s.key], rows: '3', maxlength: '2000' })]));
  const review = h('textarea', { class: 'sup-textarea', id: sid.review, rows: '3', maxlength: '2000' });
  const date = h('input', { type: 'date', class: 'sup-date', id: sid.date });
  let id = null;
  const fillFrom = (w) => {
    id = w && w.id ? w.id : null;
    for (const s of STEPS.slice(0, 4)) boxes[s.key].value = w ? String(w[s.key] || '') : '';
    review.value = w ? String(w.review || '') : '';
    const base = nowOf(now).getTime();
    date.value = w && /^\d{4}-\d{2}-\d{2}$/.test(String(w.checkBack || '')) ? w.checkBack : dayKey(base + 7 * DAY);
  };
  const save = async () => {
    const sheet = { id: id || makeId('ps'), time: nowOf(now).toISOString(), ...Object.fromEntries(STEPS.slice(0, 4).map((s) => [s.key, boxes[s.key].value.trim()])), checkBack: date.value, review: review.value.trim() };
    if (!sheet.problem) { msg.textContent = 'Start with step 1: name the problem.'; boxes.problem.focus(); return; }
    try {
      await asPromise(onSave, sheet);
      id = sheet.id;
      msg.textContent = `Saved for you only.${sheet.checkBack ? ` Check back on ${fmtDay(`${sheet.checkBack}T12:00:00Z`)}.` : ''}`;
    } catch {
      msg.textContent = 'Could not save. Your text is still here.';
    }
  };
  fill(host,
    h('div', { class: 'sup-head' }, h('h2', {}, 'Work through it in 5 steps'), tipBtn('steps', 'the five steps')),
    h('p', { class: 'note' }, 'A worksheet that works with the AI off. Saved only for you. When the AI is on, it follows the same steps.'),
    h('ol', { class: 'sup-steps' }, STEPS.map((s, i) => h('li', { class: 'sup-step' },
      h('span', { class: 'sup-step-n', 'aria-hidden': 'true' }, String(i + 1)),
      h('div', { class: 'sup-step-body' },
        h('label', { class: 'sup-label', for: s.key === 'review' ? sid.date : sid[s.key] }, s.title),
        h('p', { class: 'note' }, s.hint),
        s.key === 'review'
          ? [h('div', { class: 'sup-date-row' }, h('span', { 'aria-hidden': 'true' }, 'Check back on'), date), h('label', { class: 'sup-label sup-sub', for: sid.review }, 'How did it go? (on that day)'), review]
          : boxes[s.key])))),
    h('div', { class: 'actions' }, btn('primary', 'Save', save, 'check'), btn('secondary', 'Start a new one', () => { fillFrom(null); msg.textContent = 'A new, empty worksheet.'; boxes.problem.focus(); })),
    msg,
    h('p', { class: 'note' }, 'Draft wording, to be reviewed by a psychologist before use. A worksheet, not a treatment.'),
    h('p', {}, badge(BADGE.nasa)),
    sourceLine(SRC.pst2017, SRC.smartop2013));
  fillFrom(worksheet);
  return { load(w) { fillFrom(w); } };
}

// F8. The mission calendar as a list. flightDay: today's flight day. onOpen(item) when the person opens
// today's message or package (the screen shows its content; in the example there is none).
const KIND_ICON = { milestone: 'flag', message: 'mail', package: 'gift' };
export function renderCalendar(host, { flightDay, calendar = MISSION_CALENDAR, onOpen } = {}) {
  prep(host, 'sup-calendar');
  const day = Math.floor(Number(flightDay));
  const items = [...calendar].sort((a, b) => a.day - b.day);
  const line = nextUp(day, items);
  const row = (x) => {
    const past = x.day < day;
    const today = x.day === day;
    const state = past ? (x.kind === 'milestone' ? 'Passed' : 'Opened') : today ? (x.kind === 'milestone' ? 'Today' : 'Opens today') : (x.kind === 'milestone' ? 'Ahead' : `Opens on flight day ${x.day}`);
    return h('li', { class: `sup-cal-item ${past ? 'past' : today ? 'today' : 'ahead'}` },
      h('span', { class: 'sup-cal-icon', 'aria-hidden': 'true' }, supIcon(KIND_ICON[x.kind] || 'calendar', { size: 20 })),
      h('span', { class: 'sup-cal-day mono' }, `Day ${x.day}`),
      h('span', { class: 'sup-cal-title' }, x.title),
      today && x.kind !== 'milestone' && typeof onOpen === 'function'
        ? btn('secondary small', 'Open', () => onOpen(x), 'gift')
        : h('span', { class: 'sup-cal-state' }, !past && !today && x.kind !== 'milestone' ? supIcon('lock', { size: 14 }) : null, state));
  };
  fill(host,
    h('div', { class: 'sup-head' }, h('h2', {}, 'Mission calendar'), items.some((x) => x.example) ? exampleTag() : null, tipBtn('calendar', 'the mission calendar')),
    line ? h('p', { class: 'sup-nextup' }, supIcon('calendar', { size: 18 }), line) : null,
    h('ul', { class: 'sup-cal' }, items.map(row)),
    h('p', { class: 'note' }, 'Loaded before flight with your family. Messages stay closed until their day and belong to you and your family.'),
    h('p', {}, badge(BADGE.iss)),
    sourceLine(SRC.hrp2025, SRC.jscBhp));
  return { line };
}
