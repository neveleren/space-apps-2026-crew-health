// The placeholder rule. The real numbers are the team's open decision, and the screen says so.
export const TOPIC_RULE = {
  minDays: 3,
  windowDays: 7,
  placeholder: true,
  text: "A topic marked on 3 or more of the last 7 days is named in the AI offer. Placeholder rule: the team's open decision.",
};

// One check-in record: { time, topics: ['home', ...] } or a reading { time, value } whose value is a list of
// topic ids (or labels), one id, or ids joined by commas.
function topicsOf(rec) {
  const v = rec.topics ?? rec.value;
  const list = Array.isArray(v) ? v : typeof v === 'string' ? v.split(',') : [];
  return list.map((x) => TOPIC_BY_KEY.get(String(x).trim().toLowerCase())).filter(Boolean).map((t) => t.id);
}

// How many of the last `windowDays` GMT days (today included) each topic was marked on. The last check-in of a
// day counts (records with the same time are one check-in); "Nothing in particular" is never counted.
// Sorted: most days first, then the most recently marked, then the order of CHECKIN_TOPICS.
export function topicCounts(history, now, windowDays = TOPIC_RULE.windowDays) {
  const end = msOf(now);
  if (!Number.isFinite(end) || !Array.isArray(history)) return [];
  const today = Date.UTC(new Date(end).getUTCFullYear(), new Date(end).getUTCMonth(), new Date(end).getUTCDate());
  const from = today - (windowDays - 1) * DAY;
  const byDay = new Map();
  for (const rec of history) {
    if (!rec || typeof rec !== 'object') continue;
    const t = msOf(rec.time);
    if (!Number.isFinite(t) || t > end || t < from) continue;
    const day = dayKey(t);
    const cur = byDay.get(day);
    if (!cur || t > cur.t) byDay.set(day, { t, ids: new Set(topicsOf(rec)) });
    else if (t === cur.t) for (const id of topicsOf(rec)) cur.ids.add(id);
  }
  const days = new Map();
  const last = new Map();
  for (const { t, ids } of byDay.values()) {
    for (const id of ids) {
      if (id === 'nothing') continue;
      days.set(id, (days.get(id) || 0) + 1);
      last.set(id, Math.max(last.get(id) || 0, t));
    }
  }
  const order = (id) => CHECKIN_TOPICS.findIndex((x) => x.id === id);
  return [...days.keys()]
    .sort((a, b) => days.get(b) - days.get(a) || last.get(b) - last.get(a) || order(a) - order(b))
    .map((id) => ({ ...TOPIC_BY_KEY.get(id), days: days.get(id), lastTime: new Date(last.get(id)).toISOString(), windowDays }));
}

// The topic to name in the AI offer, or null. history: the person's check-in records; now: a Date, ms or ISO.
export function topicSignal(history, now, rule = TOPIC_RULE) {
  const top = topicCounts(history, now, rule.windowDays).find((x) => x.days >= rule.minDays);
  if (!top) return null;
  return { id: top.id, label: top.label, phrase: top.phrase, days: top.days, windowDays: rule.windowDays, minDays: rule.minDays, placeholder: true };
}

