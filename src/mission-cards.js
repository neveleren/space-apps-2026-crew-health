// ---------- the critical tasks of the crew's own mission, in Settings ----------
// mission: the saved mission ({ name, launch, landing, tasks? }). onSave(tasks) saves the new list and redraws.
export function taskFields({ mission, onSave }) {
  const tasks = mission.tasks || [];
  const kind = h('select', { id: 'mt-kind' }, ...TASK_KIND_KEYS.map((k) => h('option', { value: k }, TASK_KINDS[k].label)));
  const title = h('input', { id: 'mt-title', type: 'text', maxlength: String(MISSION_RULES.taskNameMax), autocomplete: 'off', placeholder: 'Optional' });
  const date = h('input', { id: 'mt-date', type: 'date', min: mission.launch, max: mission.landing });
  const time = h('input', { id: 'mt-time', type: 'time', step: '60' });
  const status = h('p', { class: 'note', id: 'mt-status', role: 'status' });
  const add = () => {
    const t = { kind: kind.value, title: title.value.trim(), date: date.value, time: time.value };
    const why = tasks.length >= MISSION_RULES.tasksMax ? `A mission can hold at most ${MISSION_RULES.tasksMax} critical tasks.` : taskProblem(t, mission);
    if (why) { status.textContent = why; return; }
    onSave([...tasks, t], `Added: ${t.title || TASK_KINDS[t.kind].label}, ${missionDay(t.date)}, ${t.time} GMT.`);
  };
  const named = (t) => `${t.title || TASK_KINDS[t.kind].label}, ${missionDay(t.date)}, ${t.time} GMT`;
  return h('div', { class: 'mission-tasks' },
    h('p', {}, h('b', {}, 'Critical tasks'), ' ', tipButton('phase:tasks', 'critical tasks'), ' ', h('span', { class: 'muted' }, `A spacewalk, a docking, robotic arm work or another one, with its GMT date and start. Today shows a readiness card in the ${READINESS_RULES.windowHours} hours before each (a draft).`)),
    tasks.length ? h('ul', { class: 'due' }, ...tasks.map((t, i) => h('li', {}, supIcon(TASK_KINDS[t.kind].icon, { size: 18 }), h('span', {}, named(t)),
      btn('secondary small', 'Remove', () => onSave(tasks.filter((x, j) => j !== i), `Removed: ${named(t)}.`), 'x', { 'aria-label': `Remove ${named(t)}`, 'data-fk': `mission:remove:${i}` })))) : h('p', { class: 'note' }, 'No critical tasks yet.'),
    h('div', { class: 'log-form' },
      h('label', { class: 'log-field' }, h('span', {}, 'Kind'), kind),
      h('label', { class: 'log-field' }, h('span', {}, 'Name'), title),
      h('label', { class: 'log-field' }, h('span', {}, 'Date (GMT)'), date),
      h('label', { class: 'log-field' }, h('span', {}, 'Start (GMT)'), time),
      btn('primary small', 'Add the task', add, 'check', { 'data-fk': 'mission:add-task' })),
    status);
}

// ---------- the "?" cards ----------
const tipLinks = (list) => h('p', {}, h('b', {}, 'Sources: '), ...list.flatMap((s, i) => [i ? '; ' : '', h('a', { href: s.url, target: '_blank', rel: 'noopener' }, s.name)]));
export function phaseTip(key) {
  const R = READINESS_SOURCES;
  const L = LANDING_SOURCES;
  const card = (title, lines, sources) => h('div', {}, h('p', { class: 'tp-title' }, title), ...lines.map((x) => h('p', {}, x)), sources.length ? tipLinks(sources) : null);
  if (key === 'readiness') {
    return card('The readiness card', [
      `In the ${READINESS_RULES.windowHours} hours before a critical task it puts together what the app already holds about you: last night's sleep, the medicines that can make you sleepy, and the reaction test against your own earlier runs.`,
      `Drafts for the team and the flight surgeons: ${READINESS_RULES.windowHours} hours before the start; a short night is ${READINESS_RULES.shortNightHours} hours or less (on the ISS the reaction test was slower after such nights); the medicines are the kit list's sleep medicines and those with its note "May cause sedation and impair performance."; zolpidem's FDA label asks for at least ${READINESS_RULES.labelHours} hours between a dose and work that needs full alertness.`,
      'Why these three: before shuttle spacewalks, crewmembers slept less than 6 hours on more than half of the nights, and sleep medicine was reported on 60% of the nights before spacewalks (Barger et al., 2014). In an ISS study, astronauts took the reaction test more often before and after spacewalks (Jones et al., 2022).',
      'After a short night or such a medicine it asks for the reaction test. It is never more than attention, it never stops the task, and nothing is sent unless you send it. NASA names vehicle control, robotic operations and EVAs as critical operations.',
    ], [R.std1, R.jones2022, R.barger2014, R.zolpidem, R.melatonin, R.kit2015]);
  }
  if (key === 'landing') {
    return card('Getting ready for landing', [
      `From ${LANDING_RULES.nearDays} days before landing (a draft): aerobic capacity and strength against NASA's ${LANDING_RULES.minPercent}% of your pre-flight level, with the straight line to the landing day; your exercise minutes of the last ${LANDING_RULES.exerciseWeeks} weeks; the eye exam 30 days before return; and what to expect on return.`,
      'The line is a straight line through your flight tests, not a medical model. Exercise is recorded, not judged: each prescription is personal.',
    ], [L.std1, L.eyes2018, L.mtb004]);
  }
  if (key === 'recovery') {
    return card('Back on Earth (R+)', [
      'R+3 means 3 days after landing. After landing there is no forecast to landing any more: the measures with a pre-flight level show how far back you are, and reconditioning aims at your pre-flight level.',
      'Flight surgeons follow crew for the first 30 to 45 days. The check-in, the sleep log and the reaction test go on, as they did in an ISS study before, during and after flight.',
    ], [L.std1, L.mtb004, L.jones2022]);
  }
  if (key === 'tasks') {
    return card('Critical tasks', [
      'NASA names vehicle control, robotic operations and EVAs as critical operations. Add yours with their GMT date and start time; they are kept on this device only, with the mission.',
      `Coming up lists those of the next ${READINESS_RULES.listDays} days, and Today shows the readiness card in the ${READINESS_RULES.windowHours} hours before each (drafts). Everyone signed in on this device sees the mission's tasks.`,
    ], [R.std1]);
  }
  return null;
}

// The words for a task in Coming up: "Spacewalk, GMT 320/02:00 (critical task)".
export const comingUpText = (t) => `${cap(taskName(t))}, ${gmtText(t.start)} (critical task${t.example ? ', made-up example' : ''})`;
// One row of the Coming up list for a task, in the list's own layout: icon, words, when.
export function comingUpItem(t, now) {
  return h('li', { class: 'task' }, supIcon((TASK_KINDS[t.kind] || TASK_KINDS.other).icon, { size: 18 }), h('span', {}, comingUpText(t)), h('span', { class: 'when' }, startsInAt(t.start, now)));
}
