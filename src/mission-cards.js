// The cards of the mission's phases on Today, drawn from src/readiness.js and src/landing.js: the readiness card in
// the hours before a critical task, "Getting ready for landing" in the last weeks of flight, "Back on Earth" after
// landing (R+), and a plain note when no mission is set. Also the critical tasks of the crew's own mission in Settings
// and the "?" cards of all of these. This module only draws: every button calls back into the crew screen, and nothing
// is sent or saved from here. Display rules after NASA-STD-3001 Vol 2 Appendix F: a level has its colour, its icon and
// its word, never colour alone; plain words. Code generated by Claude (Anthropic), an AI system.
import { h, fill, btn, supIcon } from './support.js';
import { tipButton } from './explain.js';
import { LEVEL_WORD } from './state-levels.js';
import { READINESS_RULES, READINESS_SOURCES, TASK_KINDS, taskName, taskThe, readinessLines, startsIn, startsInAt } from './readiness.js';
import { LANDING_RULES, LANDING_SOURCES, fmtDay } from './landing.js';
import { TASK_KIND_KEYS, MISSION_RULES, taskProblem, missionDay } from './mission.js';
import { gmtText } from './quicklog.js';

const LEVEL_ICON = ['circle-check', 'info', 'triangle-alert', 'octagon-alert'];
const ROW_ICON = { vo2max: 'heart', strength: 'dumbbell', exercise: 'flame', eyes: 'eye', bodyMass: 'scale', pulse: 'heart-pulse', sleep: 'moon', medicines: 'pill', reaction: 'zap' };
// The measure a row opens; Back on its page returns the keyboard to the row (data-back, src/crew.js backButton).
const ROW_OPENS = { eyes: 'octChange' };
const cap = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);

// The card's host on Today: made once, right after the element `after`, so the cards keep their order.
export function cardHost(id, after) {
  let el = document.getElementById(id);
  if (!el) {
    el = h('section', { class: 'card phase-card', id, 'aria-labelledby': `${id}-title`, hidden: true });
    after.after(el);
  }
  return el;
}
export const hideCard = (id) => { const el = document.getElementById(id); if (el) { el.hidden = true; el.replaceChildren(); } };

const chip = (lv, text) => h('span', { class: `chip lv${lv}` }, supIcon(LEVEL_ICON[lv], { size: 16 }), text);
const exampleChip = () => h('span', { class: 'chip neutral' }, 'Made-up example');
const links = (list) => (list && list.length ? h('small', { class: 'phase-src' }, 'Source: ', ...list.flatMap((s, i) => [i ? '; ' : '', h('a', { href: s.url, target: '_blank', rel: 'noopener' }, s.name)])) : null);
// The head of a card: its title, the level chip when there is something to tell, the example chip, the "?" button.
const head = (id, title, { level = 0, label = '', example = false, tip = null } = {}) => h('div', { class: 'checkin-row phase-head' },
  h('h2', { id: `${id}-title` }, title, tip ? tipButton(tip[0], tip[1]) : null),
  level || example ? h('span', { class: 'chips' }, level ? chip(level, `${label}: ${LEVEL_WORD[level]}`) : null, example ? exampleChip() : null) : null);

// One line of a card: the level icon and word when there is something to tell, otherwise the measure's own icon.
function line({ key, level = 0, title, text, src = [] }, onOpen = null) {
  const mark = level
    ? supIcon(LEVEL_ICON[level], { size: 20, cls: `lvc${level}`, label: LEVEL_WORD[level] })
    : supIcon(ROW_ICON[key] || 'circle-check', { size: 20, cls: 'lvc-off' });
  const what = h('span', { class: 'what' }, h('b', {}, title, level ? h('strong', { class: `lvc${level}` }, ` · ${LEVEL_WORD[level]}`) : null), h('span', {}, text), links(src));
  if (typeof onOpen !== 'function') return h('li', {}, h('div', { class: 'reason static', 'data-key': key }, mark, what));
  return h('li', {}, h('button', { type: 'button', class: 'reason', 'data-key': key, 'data-fk': `phase:${key}`, 'data-back': ROW_OPENS[key] || key, onclick: () => onOpen(key) }, mark, what, supIcon('chevron-right', { size: 18, cls: 'chev' })));
}
const factsBox = (facts, title = 'What to expect on return') => h('details', { class: 'more phase-more' },
  h('summary', {}, supIcon('chevron-right', { size: 18 }), title),
  h('div', {}, h('ul', { class: 'phase-facts' }, ...facts.map((f) => h('li', {}, f.text, ' ', links(f.src))))));

// ---------- readiness before a critical task ----------
// r: readiness() of src/readiness.js. on: { test(), demo(), tell(), sleep() }.
export function renderReadinessCard(host, { r, on = {} }) {
  const t = r.task;
  const lines = readinessLines(r);
  const sleepMissing = r.sleep.state === 'none';
  fill(host,
    head('phase-readiness', `Before ${taskThe(t)}`, { level: r.level, label: 'Readiness', example: t.example, tip: ['phase:readiness', 'the readiness card'] }),
    h('p', { class: 'sub' }, `${taskName(t)}${t.example ? ' (made-up example)' : ''} starts ${gmtText(r.start)}, ${startsIn(r.hoursTo)}. What the app holds about you for it:`),
    h('ul', { class: 'reasons phase-lines' }, ...lines.map((l) => line(l))),
    h('div', { class: 'actions' },
      btn(r.askTest ? 'primary' : 'secondary', 'Take the reaction test now', () => on.test && on.test(), 'zap', { 'data-fk': 'phase:test' }),
      btn('secondary small', 'Try a 30-second demo', () => on.demo && on.demo(), null, { 'data-fk': 'phase:demo' }),
      sleepMissing ? btn('secondary small', "Log last night's sleep", () => on.sleep && on.sleep(), 'moon', { 'data-fk': 'phase:sleep' }) : null,
      // One clear next step: the reaction test when it is asked for, otherwise telling the flight surgeon.
      btn(r.level && !r.askTest ? 'primary' : 'secondary', 'Tell the flight surgeon', () => on.tell && on.tell(), 'stethoscope', { 'data-fk': 'phase:tell' })),
    h('p', { class: 'note' }, `A draft check for the team and the flight surgeons; every rule on it is a draft. It never stops the task: your flight surgeon and mission control decide. Nothing is sent unless you press Send in the message.`));
  host.className = `card phase-card${r.level ? ` lv${r.level}` : ''}`;
  host.hidden = false;
}

// ---------- getting ready for landing ----------
// prep: landingPrep() of src/landing.js. onOpen(key): open the measure behind a row.
export function renderLandingCard(host, { prep, example = false, onOpen }) {
  const rowsOpen = { vo2max: 'vo2max', strength: 'strength', exercise: 'exercise', ...ROW_OPENS };
  fill(host,
    head('phase-landing', 'Getting ready for landing', { level: prep.level, label: 'Landing', example, tip: ['phase:landing', 'getting ready for landing'] }),
    h('p', { class: 'sub' }, `Landing on ${fmtDay(prep.landing)}, ${prep.daysToLanding === 0 ? 'today' : prep.daysToLanding === 1 ? 'tomorrow' : `in ${prep.daysToLanding} days`}. What landing needs from you:`),
    h('ul', { class: 'reasons phase-lines' }, ...prep.rows.map((r) => line({ ...r, src: [] }, rowsOpen[r.key] ? () => onOpen(rowsOpen[r.key]) : null))),
    factsBox(prep.expect),
    h('p', { class: 'note' }, `A draft for the team and the flight surgeons: this card shows from ${LANDING_RULES.nearDays} days before landing, when NASA's last eye exam in flight falls. NASA's line for aerobic capacity and strength is ${LANDING_RULES.minPercent}% of the pre-flight level (NASA-STD-3001 Vol 1).`));
  host.className = `card phase-card${prep.level ? ` lv${prep.level}` : ''}`;
  host.hidden = false;
}

// ---------- back on Earth: R+ ----------
// rec: recovery() of src/landing.js. checkedIn: the daily check-in is done today. on: { checkin(), sleep(), open(key) }.
export function renderRecoveryCard(host, { rec, checkedIn = false, on = {} }) {
  const s = rec.sleep;
  fill(host,
    head('phase-landing', `Back on Earth: day ${rec.n} after landing (R+${rec.n})`, { tip: ['phase:recovery', 'the time after landing'] }),
    h('p', { class: 'sub' }, `Landed on ${fmtDay(rec.landing)}. Flight surgeons follow crew for the first 30 to 45 days after landing (NASA, 2025).`),
    h('p', {}, h('b', {}, 'Keep going')),
    h('ul', { class: 'due' },
      h('li', {}, supIcon(checkedIn ? 'circle-check' : 'calendar', { size: 18 }), h('span', {}, checkedIn ? 'Daily check-in: done today.' : 'Daily check-in: not yet today.', checkedIn ? null : [' ', btn('secondary small', 'Check in now', () => on.checkin && on.checkin(), null, { 'data-fk': 'phase:checkin' })]), h('span', { class: 'when' }, '')),
      h('li', {}, supIcon('moon', { size: 18 }), h('span', {}, s ? `Sleep last night: ${Math.round(s.hours * 10) / 10} hours (logged ${gmtText(s.time)}).` : 'Sleep last night: not logged yet.', s ? null : [' ', btn('secondary small', "Log last night's sleep", () => on.sleep && on.sleep(), null, { 'data-fk': 'phase:sleep' })]), h('span', { class: 'when' }, ''))),
    h('p', {}, h('b', {}, 'Recovery against your pre-flight levels')),
    h('ul', { class: 'reasons phase-lines' }, ...rec.rows.map((r) => line(r, () => on.open && on.open(r.key)))),
    factsBox(rec.expect, 'What to expect after landing'),
    h('p', { class: 'note' }, 'Information, not judged here: each reading still meets its own normal range and red limits. An ISS study followed sleep and the reaction test before, during and after six-month missions (Jones et al., 2022), so the check-in, the sleep log and the reaction test go on after landing.'));
  host.className = 'card phase-card';
  host.hidden = false;
}

