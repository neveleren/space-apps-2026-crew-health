// Where the mission is now. none: no launch and landing to work with (the example flight off, no mission set);
// before: days to launch; flight: days to landing, near when landing is within LANDING_RULES.nearDays; after: n days
// after landing, R+n. All by GMT calendar days, as on the status line: the landing day itself is 0 days to landing
// ("today"), and the count always matches the landing date shown next to it.
export function missionPhase(mission, now, rules = LANDING_RULES) {
  if (!hasMissionDates(mission)) return { kind: 'none' };
  const t = ms(now);
  const L = ms(mission.launch);
  const R = ms(mission.landing);
  if (dayNum(t) < dayNum(L)) return { kind: 'before', days: dayNum(L) - dayNum(t) };
  if (dayNum(t) > dayNum(R)) { const n = dayNum(t) - dayNum(R); return { kind: 'after', n, short: `R+${n}`, landing: iso(R) }; }
  const daysToLanding = dayNum(R) - dayNum(t);
  return { kind: 'flight', daysToLanding, near: daysToLanding <= rules.nearDays, landing: iso(R) };
}

const baseOf = (person, cell) => Number(person && person.baselines ? person.baselines[cell.baselineKey] : NaN);
const levelText = (person, base, unit) => `${fmt(base)} ${unit}${person && person.real ? '' : ' (a made-up example level)'}`;
const readable = (list) => list.filter((x) => x && Number.isFinite(Number(x.value)) && x.context !== 'exercise');

// Aerobic capacity or strength against NASA's 80%: the last test in flight, its share of the pre-flight level, and where
// the straight line through the flight tests reaches on the landing day. The level follows src/state-levels.js: below
// the line is "needs action", a line that crosses it before landing is "attention".
function eightyRow(cell, ctx, rules) {
  const { machine, person, mission, now } = ctx;
  const title = cell.indicator === 'vo2max' ? 'Aerobic capacity' : 'Muscle strength';
  const base = baseOf(person, cell);
  const row = { key: cell.indicator, title, level: LEVEL.FINE };
  if (!(base > 0)) return { ...row, state: 'no-base', text: 'No pre-flight level is set for you, so there is nothing to compare with.' };
  const m = measureState({ machine, person, cell, mission, now });
  const flight = readable(m.list).filter((x) => ms(x.time) >= ms(mission.launch) && ms(x.time) <= ms(mission.landing));
  const last = flight[flight.length - 1] || null;
  if (!last) {
    return { ...row, state: 'none', base, text: cell.indicator === 'strength'
      ? `No strength test in flight. NASA tests strength before flight and within 5 to 7 days of landing ([V1 4025]). Your pre-flight level here: ${levelText(person, base, cell.unit)}.`
      : `No test in flight yet. Your pre-flight level here: ${levelText(person, base, cell.unit)}.` };
  }
  // Shares to one decimal, so a line just under 80% never reads as "about 80%".
  const share = (v) => Math.round((1000 * v) / base) / 10;
  const pct = share(Number(last.value));
  const fc = m.forecast;
  const atPct = fc && fc.line && Number.isFinite(fc.atLanding) ? share(fc.atLanding) : null;
  const cross = fc && fc.crossing && !fc.crossing.already ? fc.crossing : null;
  let text = `Last test ${fmt(last.value)} ${cell.unit} (${gmtText(last.time)}): ${pct}% of your pre-flight level of ${levelText(person, base, cell.unit)}. NASA's line is ${rules.minPercent}% ([V1 ${cell.indicator === 'vo2max' ? '4003' : '4024'}]).`;
  let level = LEVEL.FINE;
  let state = 'ok';
  if (last.status === STATUS.OUT) { text += ' This test is below it: repeat the test, and show the result to the doctor.'; level = LEVEL.ACTION; state = 'below'; }
  else if (cross && fc.crossedBeforeNow) { text += ` If the straight line through your flight tests holds, it passed ${rules.minPercent}% around ${fmtDay(cross.date)}, after the last test: a new test is needed.`; level = LEVEL.ATTENTION; state = 'crossing'; }
  else if (cross) { text += ` If the straight line through your flight tests holds, it reaches ${rules.minPercent}% around ${fmtDay(cross.date)}, before landing${atPct !== null ? `: about ${atPct}% on the landing day` : ''}.`; level = LEVEL.ATTENTION; state = 'crossing'; }
  else if (atPct !== null) text += ` The straight line through your flight tests stays above it up to landing: about ${atPct}% on the landing day.`;
  else text += ' There are too few tests in flight for a line to landing: tests on at least three different days are needed.';
  if (cross || atPct !== null) text += ' The line is not a medical model.';
  return { ...row, level, state, base, value: Number(last.value), pct, atPct, crossing: cross ? iso(cross.date) : null, time: iso(last.time), text };
}

// Exercise minutes a week, newest week first: the 7 days up to now, the 7 before, and so on.
export function weeklyMinutes(list, now, weeks = LANDING_RULES.exerciseWeeks) {
  const t0 = ms(now);
  const xs = readableAll(list);
  const out = [];
  for (let w = 0; w < weeks; w += 1) {
    const to = t0 - w * 7 * DAY;
    const from = to - 7 * DAY;
    const mine = xs.filter((x) => ms(x.time) > from && ms(x.time) <= to);
    out.push({ from: iso(from), to: iso(to), minutes: Math.round(mine.reduce((s, x) => s + Number(x.value), 0)), days: new Set(mine.map((x) => dayNum(x.time))).size });
  }
  return out;
}
function readableAll(list) { return (Array.isArray(list) ? list : []).filter((x) => x && Number.isFinite(Number(x.value)) && Number.isFinite(ms(x.time))); }

function exerciseRow(cell, ctx, rules) {
  const { machine, person, mission, now } = ctx;
  const list = readableAll(machine.history(person.id, 'exercise'));
  const weeks = weeklyMinutes(list, now, rules.exerciseWeeks);
  const row = { key: 'exercise', title: `Exercise, the last ${rules.exerciseWeeks} weeks`, level: LEVEL.FINE, weeks };
  if (!weeks.some((w) => w.minutes > 0)) return { ...row, state: 'none', text: `No exercise minutes logged in the last ${rules.exerciseWeeks} weeks.` };
  const flight = list.filter((x) => ms(x.time) >= ms(mission.launch) && ms(x.time) <= ms(now));
  const flightWeeks = (ms(now) - ms(mission.launch)) / (7 * DAY);
  const avg = flightWeeks >= 2 ? Math.round(flight.reduce((s, x) => s + Number(x.value), 0) / flightWeeks) : null;
  const text = `Minutes a week, newest week first: ${weeks.map((w) => w.minutes).join(', ')}.${avg !== null ? ` Your average in flight so far: ${avg} minutes a week.` : ''} Recorded, not judged: each exercise prescription is personal.`;
  return { ...row, state: 'logged', average: avg, text, unit: cell ? cell.unit : 'min/day' };
}

// The eye exam 30 days before return (NASA JSC, 2018): done (an OCT result of that time), scanned (a scan, no result yet),
// due (still ahead) or late (the day is past and no scan is recorded). The level of a result follows NASA's two lines
// as the OCT cell holds them: 20 micrometres or more the earliest sign of SANS, 55 or more clinically concerning.
export function preLandingEyeExam({ machine, person, mission, now, cells = [], rules = LANDING_RULES }) {
  const due = ms(mission.landing) - rules.eyeExamDaysBefore * DAY;
  const since = due - rules.eyeExamEarlyDays * DAY;
  const at = (ind) => readableOrAny(machine.history(person.id, ind)).filter((x) => ms(x.time) >= since && ms(x.time) <= ms(now));
  const results = at('octChange');
  const scans = at('octScan');
  const oct = cells.find((c) => c.indicator === 'octChange');
  const lines = oct && Array.isArray(oct.thresholds) ? oct.thresholds : [{ min: 20, text: 'earliest indication of SANS' }, { min: 55, text: 'clinically concerning SANS' }];
  const row = { key: 'eyes', title: 'Eye exam before landing', level: LEVEL.FINE, due: iso(due) };
  if (results.length) {
    const r = results[results.length - 1];
    const v = Number(r.value);
    const over = [...lines].sort((a, b) => b.min - a.min).find((l) => v >= l.min);
    return { ...row, state: 'done', value: v, time: iso(r.time), level: over ? (over.min >= 55 ? LEVEL.ACTION : LEVEL.ATTENTION) : LEVEL.FINE,
      text: `Done: OCT result of ${gmtText(r.time)}, retinal thickness change ${v > 0 ? '+' : ''}${fmt(v)} µm, ${over ? `at or above NASA's ${over.min} µm line, the ${over.text}` : `below NASA's ${lines[0].min} µm line, the ${lines[0].text}`} (a draft line here).` };
  }
  if (scans.length) return { ...row, state: 'scanned', time: iso(scans[scans.length - 1].time), text: `OCT scan of ${gmtText(scans[scans.length - 1].time)}; the thickness change measured from it is not in yet.` };
  if (ms(now) < due) return { ...row, state: 'due', text: `Due around ${fmtDay(due)}, 30 days before landing: NASA's schedule for US crew holds eye tests then, the OCT scan of the retina among them (NASA JSC, 2018).` };
  return { ...row, state: 'late', text: `Due since ${fmtDay(due)}, 30 days before landing; no OCT scan is recorded since then.` };
}
function readableOrAny(list) { return (Array.isArray(list) ? list : []).filter((x) => x && Number.isFinite(ms(x.time))); }

// Everything the "Getting ready for landing" card shows, or null when landing is not near (or there is no mission).
export function landingPrep({ machine, person, cells, mission, now, rules = LANDING_RULES }) {
  const phase = missionPhase(mission, now, rules);
  if (phase.kind !== 'flight' || !phase.near) return null;
  const ctx = { machine, person, mission, now };
  const cell = (ind) => cells.find((c) => c.indicator === ind);
  const rows = [
    cell('vo2max') ? eightyRow(cell('vo2max'), ctx, rules) : null,
    cell('strength') ? eightyRow(cell('strength'), ctx, rules) : null,
    exerciseRow(cell('exercise'), ctx, rules),
    preLandingEyeExam({ ...ctx, cells, rules }),
  ].filter(Boolean);
  return { phase, landing: iso(mission.landing), daysToLanding: phase.daysToLanding, rows, level: Math.max(LEVEL.FINE, ...rows.map((r) => r.level)), expect: RETURN_FACTS, draft: true };
}

const median = (xs) => { const s = [...xs].sort((a, b) => a - b); const n = s.length; return n ? (n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2) : null; };

// After landing: each measure with a pre-flight level against it, from the readings since landing. Information only:
// nothing here raises a level (the measures' own norms and red limits still do, on their own rows).
export function recovery({ machine, person, cells, mission, now, rules = LANDING_RULES }) {
  const phase = missionPhase(mission, now, rules);
  if (phase.kind !== 'after') return null;
  const landing = ms(mission.landing);
  const launch = ms(mission.launch);
  const rOf = (t) => Math.max(0, dayNum(t) - dayNum(landing));
  const cell = (ind) => cells.find((c) => c.indicator === ind);
  const hist = (ind) => readable(machine.history(person.id, ind));
  const rows = [];
  for (const ind of ['vo2max', 'strength']) {
    const c = cell(ind);
    if (!c) continue;
    const base = baseOf(person, c);
    const list = hist(ind);
    const after = list.filter((x) => ms(x.time) > landing);
    const lastAfter = after[after.length - 1] || null;
    const lastFlight = list.filter((x) => ms(x.time) >= launch && ms(x.time) <= landing).slice(-1)[0] || null;
    const title = ind === 'vo2max' ? 'Aerobic capacity' : 'Muscle strength';
    const req = ind === 'vo2max' ? '4004' : '4025';
    if (!(base > 0)) { rows.push({ key: ind, title, state: 'no-base', text: 'No pre-flight level is set for you, so there is nothing to compare with.' }); continue; }
    const pctOf = (x) => Math.round((100 * Number(x.value)) / base);
    rows.push(lastAfter
      ? { key: ind, title, state: 'since', pct: pctOf(lastAfter), value: Number(lastAfter.value), time: iso(lastAfter.time), base,
        text: `Since landing: ${fmt(lastAfter.value)} ${c.unit} (${gmtText(lastAfter.time)}, R+${rOf(lastAfter.time)}), ${pctOf(lastAfter)}% of your pre-flight level of ${levelText(person, base, c.unit)}.${lastFlight ? ` Last test in flight: ${pctOf(lastFlight)}%.` : ''} Reconditioning aims at your pre-flight level ([V1 ${req}]).` }
      : { key: ind, title, state: 'none', base, text: `No test since landing yet. NASA tests it within 5 to 7 days of landing, and reconditioning aims at your pre-flight level of ${levelText(person, base, c.unit)} ([V1 ${req}]).` });
  }
  if (cell('bodyMass')) {
    const after = hist('bodyMass').filter((x) => ms(x.time) > landing);
    const x = after[after.length - 1];
    rows.push(x ? { key: 'bodyMass', title: 'Body mass', state: 'since', value: Number(x.value), time: iso(x.time), text: `Since landing: ${fmt(x.value)}% of your pre-flight mass (${gmtText(x.time)}, R+${rOf(x.time)}).` }
      : { key: 'bodyMass', title: 'Body mass', state: 'none', text: 'No reading since landing yet; it is compared with your own pre-flight mass.' });
  }
  if (cell('pulse')) {
    const list = hist('pulse');
    const before = list.filter((x) => ms(x.time) < launch).map((x) => Number(x.value));
    const after = list.filter((x) => ms(x.time) > landing);
    const x = after[after.length - 1];
    const pre = median(before);
    const preText = pre !== null ? ` Before flight: about ${Math.round(pre)} bpm (the middle of ${before.length} ${before.length === 1 ? 'reading' : 'readings'}).` : ' No reading from before flight to compare with.';
    rows.push(x ? { key: 'pulse', title: 'Heart rate at rest', state: 'since', value: Number(x.value), time: iso(x.time), pre, text: `Since landing: ${fmt(x.value)} bpm (${gmtText(x.time)}, R+${rOf(x.time)}).${preText}` }
      : { key: 'pulse', title: 'Heart rate at rest', state: 'none', pre, text: `No reading since landing yet.${preText}` });
  }
  const night = hist('sleep').filter((x) => ms(x.time) <= ms(now) && ms(now) - ms(x.time) <= DAY).slice(-1)[0] || null;
  return { phase, n: phase.n, landing: iso(landing), rows, sleep: night ? { hours: Number(night.value), time: iso(night.time) } : null, expect: RETURN_FACTS, draft: true };
}

// One line for a measure's page after landing: its recovery row, or, for another measure with a forecast, that the
// forecast to landing ended at landing. null when the mission is not past its landing.
export function recoveryLine(indicator, rec) {
  if (!rec) return null;
  const row = rec.rows.find((r) => r.key === indicator);
  if (row) return `${row.title}, back on Earth: ${row.text}`;
  return `Back on Earth since ${fmtDay(rec.landing)} (R+${rec.n}): the forecast to landing ended at landing, so no line is drawn.`;
}
