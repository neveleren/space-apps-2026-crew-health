// Getting ready for landing, and the time after it (review finding PO-10; the team's choice of 15 Nov 2026).
// In flight, from LANDING_RULES.nearDays before landing, one card gathers what landing needs: aerobic capacity and
// strength against NASA's 80% of the pre-flight level, with the straight-line forecast to the landing day (the cells and
// src/state-levels.js already hold both), the exercise minutes of the last weeks, the eye exam 30 days before return,
// and what to expect on return. After landing the phase goes on (R+): the daily check-in and the sleep log stay, and the
// measures with a pre-flight level show recovery against it, instead of a forecast that stops at landing.
// Every window here is a DRAFT for the team and the flight surgeons, and the screen says so. Pure functions, so the
// automatic checks run them in Node.
// Sources, each opened by Claude on 15 Nov 2026:
// - NASA-STD-3001 Volume 1 Revision C (2023): [V1 4003] in-mission aerobic capacity "at or above 80% of the pre-mission
//   capacity"; [V1 4024] strength "at or above 80% of baseline values"; [V1 4004] and [V1 4025] post-mission
//   reconditioning aimed at the pre-mission values, with VO2max and strength evaluated "within 5-7 days of landing" and
//   "a daily schedule of prescribed" reconditioning exercises; [V1 3017] reconditioning "starts with crew egress at
//   landing";
// - NASA OCHMO-MTB-004 Rev A (25 Sep 2025), "Pre-landing Assessments": terrestrial readaptation motion sickness after
//   return; "Most TRMS clears in 2-3 days but crew are monitored for the first 30-45 days"; the higher risk of fainting
//   and the dizziness, nausea and unstable gait on return (the brief quotes ESA, 2018);
// - NASA JSC (Brunstetter, 13 June 2018): eye tests on flight day 30, flight day 90 and 30 days before return (R-30)
//   for US crew, and "Astronaut eyes have always been eval'd pre- & post-flight";
// - Jones et al., Sleep 2022: sleep and the reaction test followed "before, during, and after" six-month ISS missions.
// Code generated by Claude (Anthropic), an AI system.
import { STATUS } from './engine.js';
import { measureState, hasMissionDates, LEVEL } from './state-levels.js';
import { gmtText } from './quicklog.js';

const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const ms = (t) => (t instanceof Date ? t.getTime() : typeof t === 'number' ? t : Date.parse(t));
const iso = (t) => new Date(ms(t)).toISOString();
const dayNum = (t) => Math.floor(ms(t) / DAY); // GMT days, as the status line counts them (src/mission.js)
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
// A GMT date in words: "10 Dec 2026".
export const fmtDay = (t) => { const d = new Date(ms(t)); return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]} ${d.getUTCFullYear()}`; };
const fmt = (v) => String(Math.round(Number(v) * 10) / 10);

export const LANDING_SOURCES = Object.freeze({
  std1: { name: 'NASA-STD-3001 Vol 1 Rev C, 2023', url: 'https://www.nasa.gov/wp-content/uploads/2023/11/nasa-std-3001-vol-1-rev-c-with-signature.pdf' },
  mtb004: { name: 'NASA OCHMO-MTB-004 Rev A, 2025', url: 'https://www.nasa.gov/wp-content/uploads/2025/09/ochmo-mtb-004-space-adaptation-sickness-sas.pdf' },
  eyes2018: { name: 'NASA JSC, 2018', url: 'https://ntrs.nasa.gov/api/citations/20180004916/downloads/20180004916.pdf' },
  jones2022: { name: 'Jones et al., Sleep, 2022', url: 'https://pmc.ncbi.nlm.nih.gov/articles/PMC8919197/' },
});

export const LANDING_RULES = Object.freeze({
  // DRAFT: the card shows from this many days before landing, when NASA's last eye exam in flight falls (R-30).
  nearDays: 30,
  // NASA's schedule for US crew: eye tests 30 days before return (NASA JSC, 2018).
  eyeExamDaysBefore: 30,
  // DRAFT: an OCT scan up to this many days before that day counts as the pre-landing exam.
  eyeExamEarlyDays: 7,
  // DRAFT: the exercise minutes of this many last weeks, week by week.
  exerciseWeeks: 4,
  // NASA-STD-3001 Vol 1 Rev C [V1 4003] and [V1 4024]: at or above 80% of the pre-flight level.
  minPercent: 80,
  // NASA's brief: crew are monitored for the first 30 to 45 days after landing (OCHMO-MTB-004 Rev A).
  watchDays: 45,
  draft: true,
});

