// Camera demonstration. The laptop camera gives frames; Google's MediaPipe models find body points
// (pose) and face shape scores (blendshapes) right here in the browser; the rules in camera-rules.js
// turn them into the camera events the machine already knows: "sleeping" and "chest_grab".
// Nothing leaves the computer and no video is kept: only the events go into the machine.
// All model and program files are on this computer (vendor/mediapipe), so it works with no internet.
// Google's model cards say these models are not meant for decisions a human life depends on, so this
// shows how camera rules can feed the machine; it is not a medical device.
// Code generated by Claude (Anthropic), an AI system.
import { FilesetResolver, PoseLandmarker, FaceLandmarker } from '../vendor/mediapipe/vision_bundle.mjs';
import { RULES, POINT, chestBox, handOnChest, eyesClosed, stillness, holdTimer } from './camera-rules.js';

const BASE = new URL('../vendor/mediapipe/', import.meta.url).href;

async function makeModels(delegate) {
  const files = await FilesetResolver.forVisionTasks(`${BASE}wasm`);
  const base = (model) => ({ modelAssetPath: `${BASE}models/${model}`, delegate });
  const pose = await PoseLandmarker.createFromOptions(files, { baseOptions: base('pose_landmarker_lite.task'), runningMode: 'VIDEO', numPoses: 1 });
  const face = await FaceLandmarker.createFromOptions(files, { baseOptions: base('face_landmarker.task'), runningMode: 'VIDEO', numFaces: 1, outputFaceBlendshapes: true });
  return { pose, face };
}

// Starts the camera and the rules. Returns a function that stops everything and lets the camera go.
// onStatus gets { person, hand, eyes, still, chestHeld, sleepHeld } several times a second;
// onEvent gets 'chest_grab' or 'sleeping' once per event.
export async function startCamera({ video, canvas, onStatus, onEvent }) {
  if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) throw new Error('this browser does not give access to the camera');
  const stream = await navigator.mediaDevices.getUserMedia({ video: { width: { ideal: 640 }, height: { ideal: 480 }, facingMode: 'user' }, audio: false });
  let models;
  try {
    try {
      models = await makeModels('GPU');
    } catch {
      models = await makeModels('CPU'); // no usable graphics card: the processor does the work, slower
    }
  } catch (err) {
    stream.getTracks().forEach((track) => track.stop());
    throw err;
  }
  video.srcObject = stream;
  await video.play();

  const ctx = canvas.getContext('2d');
  const chest = holdTimer(RULES.chestSeconds);
  const sleep = holdTimer(RULES.sleepSeconds);
  const still = stillness();
  let frame = 0;
  let lastFace = null;
  let lastTime = -1;
  let running = true;
  let raf = 0;
  const color = getComputedStyle(document.documentElement).getPropertyValue('--series-1').trim() || '#2a78d6';

  const step = () => {
    if (!running) return;
    raf = requestAnimationFrame(step);
    if (video.readyState < 2) return;
    const t = performance.now();
    if (t <= lastTime) return;
    lastTime = t;
    frame += 1;
    const poseResult = models.pose.detectForVideo(video, t);
    if (frame % 2 === 0) lastFace = models.face.detectForVideo(video, t);
    const points = poseResult.landmarks && poseResult.landmarks[0];
    const shapes = lastFace && lastFace.faceBlendshapes && lastFace.faceBlendshapes[0] ? lastFace.faceBlendshapes[0].categories : null;

    const hand = handOnChest(points);
    const eyes = eyesClosed(shapes);
    const calm = still.update(points ? points[POINT.nose] : null, t);
    const c = chest.update(hand, t);
    const s = sleep.update(eyes && calm, t);
    if (c.fire) onEvent('chest_grab');
    if (s.fire) onEvent('sleeping');
    onStatus({ person: Boolean(points), hand, eyes, still: calm, chestHeld: c.held, sleepHeld: s.held });

    // Draw the found points and the chest area over the picture. Nothing is saved.
    if (canvas.width !== video.videoWidth) canvas.width = video.videoWidth;
    if (canvas.height !== video.videoHeight) canvas.height = video.videoHeight;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    if (!points) return;
    const box = chestBox(points);
    if (box) {
      ctx.strokeStyle = hand ? '#ec835a' : color;
      ctx.lineWidth = 2;
      ctx.setLineDash([6, 4]);
      ctx.strokeRect(box.x0 * canvas.width, box.y0 * canvas.height, (box.x1 - box.x0) * canvas.width, (box.y1 - box.y0) * canvas.height);
      ctx.setLineDash([]);
    }
    ctx.fillStyle = color;
    for (const p of points.slice(0, 25)) {
      if (p.visibility !== undefined && p.visibility < 0.5) continue;
      ctx.beginPath();
      ctx.arc(p.x * canvas.width, p.y * canvas.height, 4, 0, Math.PI * 2);
      ctx.fill();
    }
  };
  raf = requestAnimationFrame(step);

  return () => {
    running = false;
    cancelAnimationFrame(raf);
    stream.getTracks().forEach((track) => track.stop());
    video.srcObject = null;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    models.pose.close();
    models.face.close();
  };
}
