// "Add to plan": the program's scheduled items as an iCalendar file (IETF RFC 5545,
// https://www.rfc-editor.org/rfc/rfc5545), the plain calendar format that calendar programs and planning tools
// import. Times are written in UTC (GMT), the time the ISS runs on. The ISS crew plan itself is built in NASA's
// Score and read in OPTIMIS Viewer (NASA, 2019: https://ntrs.nasa.gov/api/citations/20190027148/downloads/20190027148.pdf);
// a live link to them is planned and needs NASA. This file is what a planner could import today.
// Rules used, by RFC 5545 section: 3.1 lines end with CRLF and are folded at 75 octets with CRLF and one space;
// 3.3.11 text escapes backslash, semicolon, comma and line breaks; 3.3.5 UTC date-time form 19980119T070000Z;
// 3.3.6 durations such as PT30M; 3.3.10 RRULE; 3.6.1 a VEVENT needs UID and DTSTAMP, and DTSTART when the
// calendar has no METHOD; 3.7.3 and 3.7.4 PRODID and VERSION:2.0 are required in VCALENDAR.
// Code generated by Claude (Anthropic), an AI system. Idea and decisions: the human member of team "Just For Fun".

const CRLF = '\r\n';

export function escapeText(s) {
  return String(s ?? '').replace(/\\/g, '\\\\').replace(/;/g, '\\;').replace(/,/g, '\\,').replace(/\r\n|\r|\n/g, '\\n');
}

// Folds a content line at 75 octets (UTF-8), never inside a character.
export function foldLine(line) {
  const enc = new TextEncoder();
  const parts = [];
  let cur = '';
  let curBytes = 0;
  for (const ch of line) {
    const b = enc.encode(ch).length;
    const limit = parts.length ? 74 : 75; // a continuation line starts with one space
    if (curBytes + b > limit) { parts.push(cur); cur = ''; curBytes = 0; }
    cur += ch;
    curBytes += b;
  }
  parts.push(cur);
  return parts.join(`${CRLF} `);
}

const two = (n) => String(n).padStart(2, '0');
export function utcStamp(t) {
  const d = new Date(t);
  if (!Number.isFinite(d.getTime())) throw new RangeError(`not a time: ${t}`);
  return `${d.getUTCFullYear()}${two(d.getUTCMonth() + 1)}${two(d.getUTCDate())}T${two(d.getUTCHours())}${two(d.getUTCMinutes())}${two(d.getUTCSeconds())}Z`;
}

// Minutes (a number) or an RFC 5545 duration string ("PT45M", "P1D") into a duration value.
export function duration(d) {
  if (typeof d === 'string') {
    if (!/^[+-]?P(\d+W|(\d+D)?(T(\d+H)?(\d+M)?(\d+S)?)?)$/.test(d) || d === 'P' || d.endsWith('T')) throw new RangeError(`not an RFC 5545 duration: ${d}`);
    return d;
  }
  const min = Math.round(Number(d));
  if (!Number.isFinite(min) || min <= 0) throw new RangeError(`not a duration in minutes: ${d}`);
  const days = Math.floor(min / 1440);
  const h = Math.floor((min % 1440) / 60);
  const m = min % 60;
  return `P${days ? `${days}D` : ''}${h || m ? `T${h ? `${h}H` : ''}${m ? `${m}M` : ''}` : ''}`;
}

// A stable id from the item, so importing the file again updates the same events instead of adding copies.
function stableUid(item, i) {
  let h = 0x811c9dc5; // FNV-1a, 32 bits
  for (const ch of `${item.title}|${new Date(item.start).toISOString()}|${i}`) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return `${h.toString(16).padStart(8, '0')}-${i}@crew-health-console`;
}

const FREQ = { day: 'DAILY', week: 'WEEKLY', month: 'MONTHLY' };
function rrule(r) {
  if (!r) return null;
  const freq = FREQ[r.unit];
  if (!freq) throw new RangeError(`repeat unit must be day, week or month: ${r.unit}`);
  const parts = [`FREQ=${freq}`];
  if (r.every && r.every > 1) parts.push(`INTERVAL=${Math.round(r.every)}`);
  if (r.count) parts.push(`COUNT=${Math.round(r.count)}`);
  else if (r.until) parts.push(`UNTIL=${utcStamp(r.until)}`);
  return `RRULE:${parts.join(';')}`;
}

// items: [{ title, start, duration (minutes or "PT30M"), description?, location?, uid?, repeat?: { every, unit:
// 'day' | 'week' | 'month', count? or until? } }]. Returns the file's text, CRLF line ends.
export function toICalendar(items, { name = 'Crew health plan', now = new Date() } = {}) {
  const lines = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Team Just For Fun//Crew Health Console//EN',
    'CALSCALE:GREGORIAN',
    `X-WR-CALNAME:${escapeText(name)}`,
  ];
  const stamp = utcStamp(now);
  (items || []).forEach((item, i) => {
    if (!item || !item.title) throw new TypeError(`item ${i + 1} has no title`);
    const start = utcStamp(item.start);
    lines.push('BEGIN:VEVENT');
    lines.push(`UID:${escapeText(item.uid || stableUid(item, i))}`);
    lines.push(`DTSTAMP:${stamp}`);
    lines.push(`DTSTART:${start}`);
    lines.push(`DURATION:${duration(item.duration ?? 30)}`);
    lines.push(`SUMMARY:${escapeText(item.title)}`);
    if (item.description) lines.push(`DESCRIPTION:${escapeText(item.description)}`);
    if (item.location) lines.push(`LOCATION:${escapeText(item.location)}`);
    const rule = rrule(item.repeat);
    if (rule) lines.push(rule);
    lines.push('END:VEVENT');
  });
  lines.push('END:VCALENDAR');
  return lines.map(foldLine).join(CRLF) + CRLF;
}

