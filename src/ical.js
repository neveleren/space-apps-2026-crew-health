// Drafts of the program's own repeating items, for "Add to plan". The two-week review follows the team's idea of a
// planned review (for example every two weeks); the thinking test follows NASA's monthly comparison with the
// pre-flight result (NASA OCHMO-TB-016: https://www.nasa.gov/wp-content/uploads/2023/12/ochmo-tb-016-behavioral-health.pdf).
// Times of day and lengths are placeholders for the team to set.
export function planDrafts({ from = new Date(), until = null, hourGmt = 9 } = {}) {
  const day = new Date(from);
  const start = Date.UTC(day.getUTCFullYear(), day.getUTCMonth(), day.getUTCDate() + 1, hourGmt, 0, 0);
  const end = until ? { until } : { count: 6 };
  return [
    { title: 'Health check-in review (every two weeks)', start, duration: 15, description: 'Look at the daily check-ins of the last two weeks (mood, energy, sleep). Draft time: the team sets it.', repeat: { every: 14, unit: 'day', ...end } },
    { title: 'Thinking test (once a month)', start: start + 2 * 3600000, duration: 20, description: 'Monthly thinking test, compared with the result before flight. Draft time: the team sets it.', repeat: { every: 1, unit: 'month', ...end } },
  ];
}
