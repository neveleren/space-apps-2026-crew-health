// Three NASA rules the app quoted but did not use (the NASA-style review of 15 Nov 2026, PO-11), as plain functions
// for the screens: the cabin CO2 around a logged headache, with its 7-day average; body mass against the loss levels
// of NASA's nutrition report; hearing judged by its shift from the person's own pre-flight test.
// The numbers live in the cells (src/config.js) and the judging in the machine (src/engine.js); this module reads
// them and puts them in plain words, lines for the charts and facts for the pages. Every threshold is a DRAFT for the
// team and the flight surgeons. Each source below was opened and checked by Claude on 15 Nov 2026:
// - NASA-STD-3001 Vol 2 Rev F [V2 6004] (PDF page 53): "The system shall limit the average one-hour CO2 partial
//   pressure (ppCO2) in the habitable volume to no more than 3 mmHg."
// - Law et al., J Occup Environ Med 2014 (abstract), and NASA OCHMO-TB-004 Rev D (2026), page 5: "For each 1-mm Hg
//   increase in CO(2), the odds of a crew member reporting a headache doubled. To keep the risk of headache below 1%,
//   average 7-day CO(2) would need to be maintained below 2.5 mm Hg".
// - NASA HRP evidence report on nutrition (Smith, Zwart and Heer, 2015), pages 111 and 112: many crewmembers "lost
//   more than 5% of preflight body mass, an amount worthy of concern"; "a loss of 10% of body mass is clinically
//   significant".
// - NASA JSC, ICES-2015-239 (2015), page 12: "a 10 dB average shift or more of hearing thresholds in the high
//   frequencies of 2000, 3000 and 4000 Hz since preflight audiometric tests", found in "less than 5% of ISS
//   crewmembers". WHO World report on hearing (2021), Table 1.3: normal hearing is below 20 dB, for the better-ear
//   average at 500, 1000, 2000 and 4000 Hz. Coste and Robinette, NASA (2024): on-orbit tests show a low-tone shift
//   (250 and 500 Hz) in 40% of tests and 60% of crewmembers.
// Code generated by Claude (Anthropic), an AI system. Idea and logic: the human member of team "Just For Fun".
import { CELLS } from './config.js';
import { gmtText } from './quicklog.js';

const cellOf = (indicator) => CELLS.find((c) => c.indicator === indicator);
const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const ms = (t) => (t instanceof Date ? t.getTime() : new Date(t).getTime());
const iso = (t) => new Date(ms(t)).toISOString();
const one = (v) => String(Math.round(Number(v) * 10) / 10);
const num = (v) => (typeof v === 'number' ? v : typeof v === 'string' && v.trim() !== '' ? Number(v) : NaN);
// How long before: "3 h", "less than 1 h", "2 days".
export function agoText(hours) {
  if (!Number.isFinite(hours) || hours < 1) return 'less than 1 h';
  return hours < 48 ? `${Math.round(hours)} h` : `${Math.floor(hours / 24)} days`;
}

// The sources this module quotes, for the links on the screens (the same ones the cells cite).
export const RULE_SOURCES = {
  co2Limit: { name: 'NASA-STD-3001 Vol 2 Rev F [V2 6004]', url: 'https://www.nasa.gov/wp-content/uploads/2025/05/nasa-std-3001-vol-2.pdf' },
  nutrition: { name: 'NASA HRP nutrition report, 2015', url: 'https://ntrs.nasa.gov/api/citations/20150000512/downloads/20150000512.pdf' },
};

// ---------- cabin CO2 around a headache ----------
// Drafts of this app: how long a logged headache shows its cabin CO2 on Today, and how many headaches the symptom
// page lists with theirs.
export const CO2_RULES = { todayHours: 24, listMax: 5, draft: true };

// The link between the two measures, as config.js keeps it on the symptom cell (Law et al., 2014).
export function co2Link(cell = cellOf('symptoms')) {
  return ((cell && cell.links) || []).find((l) => l.symptom === 'headache' && l.measure === 'co2') || null;
}

// The ship's CO2 readings at or before a time: the latest one, and the average of those in the link's last days
// (7). list: the ship's CO2 history ({ time, value }). Returns null for a time that cannot be read.
//   { at, latest: { value, time, hoursBefore, overLimit } | null, average: { value, count, days, from, to, notBelowLine } | null,
//     limit (3 mmHg, a one-hour average), line (2.5 mmHg, a 7-day average), days }
export function co2Around(list, at, { link = co2Link(), co2 = cellOf('co2') } = {}) {
  const t = ms(at);
  if (!Number.isFinite(t)) return null;
  const days = (link && link.days) || 7;
  const line = link && Number.isFinite(link.below) ? link.below : null;
  const limit = co2.norm.max;
  const before = (Array.isArray(list) ? list : [])
    .map((x) => ({ t: ms(x && x.time), v: num(x && x.value) }))
    .filter((x) => Number.isFinite(x.t) && Number.isFinite(x.v) && x.t <= t)
    .sort((a, b) => a.t - b.t);
  const last = before[before.length - 1] || null;
  const week = before.filter((x) => x.t > t - days * DAY);
  const mean = week.length ? week.reduce((s, x) => s + x.v, 0) / week.length : null;
  return {
    at: iso(t),
    latest: last ? { value: last.v, time: iso(last.t), hoursBefore: (t - last.t) / HOUR, overLimit: last.v > limit } : null,
    average: mean === null ? null : { value: Math.round(mean * 100) / 100, count: week.length, days, from: iso(week[0].t), to: iso(week[week.length - 1].t), notBelowLine: line !== null && mean >= line },
    limit, line, days,
  };
}

// One short phrase for a list, a draft message or Today: "cabin CO2 before it 3.4 mmHg (latest, GMT 319/01:00, 4 h
// before), 7-day average 2.7 mmHg; NASA's limit is 3 mmHg as a one-hour average".
export function co2Short(ctx) {
  if (!ctx || (!ctx.latest && !ctx.average)) return `no cabin CO2 reading in the ${ctx ? ctx.days : 7} days before it`;
  const parts = [];
  if (ctx.latest) parts.push(`${one(ctx.latest.value)} mmHg (latest, ${gmtText(ctx.latest.time)}, ${agoText(ctx.latest.hoursBefore)} before)`);
  if (ctx.average) parts.push(`${ctx.days}-day average ${one(ctx.average.value)} mmHg`);
  return `cabin CO2 before it ${parts.join(', ')}; NASA's limit is ${ctx.limit} mmHg as a one-hour average`;
}

// The full words for the symptom page: what was measured, what it is compared with, and the sources' words.
export function co2Words(ctx, link = co2Link()) {
  if (!ctx) return [];
  const out = [];
  if (!ctx.latest) out.push(`No cabin CO2 reading before it.`);
  else out.push(`Latest cabin CO2 before it: ${one(ctx.latest.value)} mmHg at ${gmtText(ctx.latest.time)}, ${agoText(ctx.latest.hoursBefore)} before${ctx.latest.overLimit ? `, above NASA's limit of ${ctx.limit} mmHg (a limit on the one-hour average; this is a single reading)` : ''}.`);
  if (ctx.average) out.push(`${ctx.days}-day average: ${one(ctx.average.value)} mmHg from ${ctx.average.count} ${ctx.average.count === 1 ? 'reading' : 'readings'}${ctx.line === null ? '' : ctx.average.notBelowLine ? `, not below ${ctx.line} mmHg` : `, below ${ctx.line} mmHg`}.`);
  else if (ctx.latest) out.push(`No cabin CO2 reading in the ${ctx.days} days before it, so there is no ${ctx.days}-day average.`);
  return out;
}

// The latest headache of the last CO2_RULES.todayHours hours, with the cabin CO2 before it, for Today; or null.
// symptoms: the person's symptom history; co2: the ship's CO2 history.
export function headacheToday(symptoms, co2, now, { link = co2Link(), hours = CO2_RULES.todayHours } = {}) {
  if (!link) return null;
  const t0 = ms(now);
  const recent = (Array.isArray(symptoms) ? symptoms : []).filter((x) => x && x.value && x.value.symptom === link.symptom && t0 - ms(x.time) <= hours * HOUR && ms(x.time) <= t0);
  const last = recent.sort((a, b) => ms(a.time) - ms(b.time))[recent.length - 1];
  return last ? { entry: last, co2: co2Around(co2, last.time, { link }) } : null;
}

// The latest headaches (CO2_RULES.listMax), newest first, each with the cabin CO2 before it, for the symptom page.
export function headacheList(symptoms, co2, { link = co2Link(), max = CO2_RULES.listMax } = {}) {
  if (!link) return [];
  return (Array.isArray(symptoms) ? symptoms : [])
    .filter((x) => x && x.value && x.value.symptom === link.symptom && Number.isFinite(ms(x.time)))
    .sort((a, b) => ms(b.time) - ms(a.time))
    .slice(0, max)
    .map((x) => ({ entry: x, co2: co2Around(co2, x.time, { link }) }));
}

// ---------- body mass against the loss levels of NASA's nutrition report ----------
// The value is a share of the person's own pre-flight mass (100 = no change). The levels come from the cell: its
// band ends at a loss of 5% (norm.min 95) and its red limit is a loss of 10% (90), both drafts.
export function massLevels(cell = cellOf('bodyMass')) {
  const red = (cell.red || [])[0];
  return { concernBelow: cell.norm.min, significantAt: red ? red.value : null, src: RULE_SOURCES.nutrition };
}

// The two reference lines for the chart.
export function massLines(cell = cellOf('bodyMass')) {
  const m = massLevels(cell);
  return [
    { v: m.concernBelow, label: `Loss over ${one(100 - m.concernBelow)}%: worthy of concern (NASA, draft)` },
    ...(m.significantAt === null ? [] : [{ v: m.significantAt, label: `Loss of ${one(100 - m.significantAt)}%: clinically significant (NASA, draft)` }]),
  ];
}

// The last reading in words, against the two levels; null for a value that cannot be read.
export function massWords(value, cell = cellOf('bodyMass')) {
  const v = num(value);
  if (!Number.isFinite(v)) return null;
  const m = massLevels(cell);
  const concern = one(100 - m.concernBelow);
  const significant = m.significantAt === null ? null : one(100 - m.significantAt);
  const loss = Math.round((100 - v) * 10) / 10;
  const head = loss > 0 ? `Your last reading is ${one(v)}% of your pre-flight mass: a loss of ${one(loss)}%.`
    : loss < 0 ? `Your last reading is ${one(v)}% of your pre-flight mass: ${one(-loss)}% above it.` : 'Your last reading is the same as your pre-flight mass.';
  const where = significant !== null && v <= m.significantAt ? ` That is a loss of ${significant}% or more, which NASA's nutrition report calls clinically significant.`
    : v < m.concernBelow ? ` That is more than ${concern}%, which NASA's nutrition report calls worthy of concern.` : '';
  const levels = ` NASA's nutrition report calls a loss of more than ${concern}% of pre-flight mass worthy of concern${significant === null ? '' : `, and a loss of ${significant}% clinically significant`}.`;
  return `${head}${where || levels} The lines on the chart, at ${one(m.concernBelow)}%${significant === null ? '' : ` and ${one(m.significantAt)}%`}, are drafts here.`;
}

// ---------- hearing: the shift from the person's own pre-flight test ----------
// The machine keeps, on each reading taken after launch, the pre-flight test it was compared with (baseline,
// baselineTime) and the shift (engine.js, norm type 'baseline-shift').
export function hearingRule(cell = cellOf('hearing')) {
  const f = cell.norm.fallback || {};
  return { shiftAtLeast: cell.norm.shiftAtLeast, whoBelow: f.max ?? null };
}

// The latest reading and the pre-flight test it was compared with; baseline null when none is on record.
export function hearingState(list) {
  const all = Array.isArray(list) ? list : [];
  const last = all[all.length - 1] || null;
  const based = all.filter((x) => Number.isFinite(x.baseline));
  const ref = based[based.length - 1] || null;
  return { last, baseline: ref ? ref.baseline : null, baselineTime: ref ? ref.baselineTime : null, shift: last && Number.isFinite(last.shift) ? last.shift : null };
}

// The normal range in words, as the screens write ranges ("below 22 dB HL, ...").
export function hearingRangeText(list, cell = cellOf('hearing')) {
  const rule = hearingRule(cell);
  const s = hearingState(list);
  if (s.baseline === null) return `below ${rule.whoBelow} dB HL (WHO; no pre-flight test on record to compare with)`;
  return `below ${one(s.baseline + rule.shiftAtLeast)} dB HL, less than ${rule.shiftAtLeast} dB above your pre-flight test of ${one(s.baseline)} dB HL`;
}

// The band of the chart: below the pre-flight test plus the shift, or below WHO's 20 dB without a test.
export function hearingBand(list, cell = cellOf('hearing')) {
  const rule = hearingRule(cell);
  const s = hearingState(list);
  return { min: null, max: s.baseline === null ? rule.whoBelow : s.baseline + rule.shiftAtLeast };
}

// The chart lines: NASA's shift line, and WHO's 20 dB as the second reference while it is not right next to it.
export function hearingLines(list, cell = cellOf('hearing')) {
  const rule = hearingRule(cell);
  const s = hearingState(list);
  if (s.baseline === null) return rule.whoBelow === null ? [] : [{ v: rule.whoBelow, label: `WHO: normal hearing below ${rule.whoBelow} dB (no pre-flight test on record)` }];
  const nasa = s.baseline + rule.shiftAtLeast;
  const out = [{ v: nasa, label: `NASA: ${rule.shiftAtLeast} dB above your pre-flight test (draft)` }];
  if (rule.whoBelow !== null && Math.abs(rule.whoBelow - nasa) >= 4) out.push({ v: rule.whoBelow, label: `WHO: ${rule.whoBelow} dB, a second reference` });
  return out;
}

// The facts for the measure page, in plain words.
export function hearingWords(list, cell = cellOf('hearing')) {
  const rule = hearingRule(cell);
  const s = hearingState(list);
  const out = [];
  out.push(`This value is the average of your hearing thresholds at 2000, 3000 and 4000 Hz. NASA counts an average shift of ${rule.shiftAtLeast} dB or more at these tones since the pre-flight hearing test as a mission-related shift; in ISS crews fewer than 5% had one (NASA JSC, 2015). Here it is a draft rule.`);
  if (s.baseline === null) {
    out.push(`No pre-flight test is on record, so there is nothing of your own to compare with: the reading is compared with WHO's ${rule.whoBelow} dB for now, the second reference.`);
  } else {
    out.push(`Your pre-flight test: ${one(s.baseline)} dB HL, ${gmtText(s.baselineTime)}, the latest test before launch.`);
    if (s.last && s.shift !== null) {
      const words = s.shift > 0 ? `${one(s.shift)} dB above it` : s.shift < 0 ? `${one(-s.shift)} dB below it` : 'the same as it';
      out.push(`Your last test, ${one(num(s.last.value))} dB HL, is ${words}${s.shift >= rule.shiftAtLeast ? `: a shift of ${rule.shiftAtLeast} dB or more, which NASA counts as a mission-related shift` : ''}.`);
    }
  }
  if (rule.whoBelow !== null) out.push(`WHO calls hearing normal below ${rule.whoBelow} dB, for a different average (500 to 4000 Hz, better ear), so it is only a second reference here.`);
  out.push('A 2024 NASA poster reports a shift at the low tones (250 and 500 Hz) in 60% of crewmembers tested on orbit: this 2000 to 4000 Hz average does not show such a shift.');
  return out;
}
